#!/usr/bin/env bash
# The generator's text for a definition that is not `plain` (`kcore gen --as-not-plain`), built.
# No package of the examples is outside `plain`, so the branch is taken by the switch, on two texts,
# into .lake/not-plain (ignored), each built (gen/build.sh: one module a process, one thread, 12 GiB
# memory scope): peano with `--core` (namespace NotPlainPeano), and prio with `--wf` and its
# certificates (namespace NotPlainPrio). Checked: no `plain_defn`, `obl_nil` or `obligations_nil`
# is stated; `sound_at_of` and `complete_at_of` are `KCore.sound_at` and `KCore.complete_at`; prio's
# `sound` and `complete` take the obligations (`hob : Obligations defn`); peano's `_defn` statements
# take the owed conditions (`how`), its `sound_at_of` the pinned `hw` and `hc`, its `complete_at_of`
# `hc`; and peano's modules other than FnHyp and FnHyp.Owed are those of its plain text. Natively,
# on f2-examples/myint (coreOK, not plain, nothing owed and no fact named): `obl_nil` is stated and no
# name ends in `_of`.
# Usage: test/not-plain.sh   (from anywhere; the library and `kcore` built first)
set -u
K=$(cd "$(dirname "$0")/.." && pwd); cd "$K"
P=.lake/not-plain/peano; Q=.lake/not-plain/peano-plain
rm -rf "$P" "$Q"; mkdir -p .lake/not-plain
gen/gen.sh examples/peano/Peano/definition.kore "$P" NotPlainPeano --core --as-not-plain \
  > .lake/not-plain/peano-gen.log 2>&1 || { cat .lake/not-plain/peano-gen.log; exit 1; }
gen/gen.sh examples/peano/Peano/definition.kore "$Q" NotPlainPeano --core \
  > .lake/not-plain/peano-plain-gen.log 2>&1 || { cat .lake/not-plain/peano-plain-gen.log; exit 1; }
F=$P/NotPlainPeano/FnHyp.lean
fail=0
grep -q 'plain_defn\|plain_withHooks_defn\|theorem obl_nil' "$F" && { echo "not-plain: $F states plain_defn or obl_nil"; fail=1; }
grep -q 'KCore.sound_at _ ' "$F" || { echo "not-plain: sound_at is not KCore.sound_at"; fail=1; }
grep -q 'KCore.complete_at _ ' "$F" || { echo "not-plain: complete_at is not KCore.complete_at"; fail=1; }
grep -q '(how : OwedH H)' "$F" || { echo "not-plain: the _defn statements take no owed conditions (how)"; fail=1; }
grep -q "(hw : ∀ r' ∈" "$F" || { echo "not-plain: sound_at_of takes no hw"; fail=1; }
[ "$(grep -c '(hc : ∀ fn ∈' "$F")" = 2 ] || { echo "not-plain: sound_at_of and complete_at_of do not both take hc"; fail=1; }
d=$(diff -rq -I 'Generated by .kcore gen' -x .lake "$P" "$Q" | grep -v "NotPlainPeano/FnHyp.lean" | grep -v "NotPlainPeano/FnHyp: Owed.lean" \
  | grep -v "peano/modules.txt and")
[ -z "$d" ] || { echo "not-plain: modules other than FnHyp differ: $d"; fail=1; }
[ -z "$(diff <(grep -v 'FnHyp.Owed' "$P/modules.txt") "$Q/modules.txt")" ] || { echo "not-plain: the module lists differ by more than FnHyp.Owed"; fail=1; }
M=.lake/not-plain/myint; rm -rf "$M"
gen/gen.sh f2-examples/myint.kompile.kore "$M" NotPlainMyint --core \
  > .lake/not-plain/myint-gen.log 2>&1 || { cat .lake/not-plain/myint-gen.log; exit 1; }
G=$M/NotPlainMyint/FnHyp.lean
grep -q 'plain_defn' "$G" && { echo "not-plain: myint states plain_defn"; fail=1; }
grep -q 'theorem obl_nil : Obl := FnFacts.of_nil' "$G" || { echo "not-plain: myint states no obl_nil"; fail=1; }
grep -q 'theorem [a-z_]*_of \|(how :' "$G" && { echo "not-plain: myint states an _of name or takes how"; fail=1; }
[ $fail = 0 ] || exit 1
R=.lake/not-plain/prio; rm -rf "$R"
gen/gen.sh examples/prio/Prio/definition.kore "$R" NotPlainPrio --wf --as-not-plain \
  --cert goD=examples/runs/prio-goD.cert.json --cert goB=examples/runs/prio-goB.cert.json \
  > .lake/not-plain/prio-gen.log 2>&1 || { cat .lake/not-plain/prio-gen.log; exit 1; }
grep -q 'obligations_nil\|plain_defn\|theorem obl_nil' -r "$R/NotPlainPrio" && { echo "not-plain: prio states obligations_nil, plain_defn or obl_nil"; fail=1; }
grep -q 'theorem sound (hob : Obligations defn)' "$R/NotPlainPrio/Sound.lean" || { echo "not-plain: prio's sound takes no obligations"; fail=1; }
grep -q 'KCore.sound_at _ ' "$R/NotPlainPrio/FnHyp.lean" || { echo "not-plain: prio's sound_at is not KCore.sound_at"; fail=1; }
[ $fail = 0 ] || exit 1
gen/build.sh "$P" || exit 1
gen/build.sh "$R" || exit 1
echo "not-plain on peano and prio: ok"
