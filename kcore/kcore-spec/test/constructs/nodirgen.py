def demangle(n):
    """A KORE symbol name with kompile's `Lbl` prefix dropped and its quoted runs of 4-character codes
    decoded (`'Unds'` is `_`)."""
    s = n[3:] if n.startswith("Lbl") else n
    out, parts = [], s.split("'")
    for j, part in enumerate(parts):
        if j % 2 == 0:
            out.append(part)
        else:
            if len(part) % 4 or any(part[i:i + 4] not in CODES for i in range(0, len(part), 4)):
                return s
            out.append("".join(CODES[part[i:i + 4]] for i in range(0, len(part), 4)))
    return "".join(out)


def pretty(n):
    """A symbol's K name: its label up to `_MODULE_`, without an argument list `(_,_)`."""
    s = demangle(n)
    m = re.match(r"^(.+?)_([A-Z][A-Z0-9-]*)_", s)
    if m:
        s = m[1]
    s = re.sub(r"\([_,]*\)$", "", s)
    return s


def enum(xs):
    xs = list(xs)
    return xs[0] if len(xs) == 1 else ", ".join(xs[:-1]) + " and " + xs[-1]


