def unl_why(why, d):
    """The probe's reason a sentence of the class is not listed, its symbol by its K name."""
    m = re.match(r"an equation of (\S+) that is no initializer's", why)
    if m and m[1] in d["consts"]:
        return (f"the equation of `{pretty(m[1])}`, a constant of `order` whose equation the model reads, but no "
                "initializer's, projection's or getter's, the equations `nodSentEqB` takes")
    return re.sub(r"\bLbl\S*?(?=,| |$)", lambda x: f"`{pretty(x[0])}`", why)


