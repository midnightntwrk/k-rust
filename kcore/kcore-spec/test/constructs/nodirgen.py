def config(name):
    return (tomllib.load(open(CONF, "rb")) if os.path.exists(CONF) else {}).get(name, {})


def data_of(name):
    text = os.path.join(KS, f"f2-examples/{name}.kompile.kore")
    if not os.path.exists(text):
        raise Refused(f"{name}: no text f2-examples/{name}.kompile.kore")
    cls, co = tie_data(name)
    d = probe(name, text, cls, co)
    d.update(cls=cls, co=co)
    bad = [k for k in CHECKS if not d["chk"].get(k)]
    if bad:
        raise Refused(f"{name}: checks false or not printed on the data: {bad}")
    if d["H"].get("scanCompose") != "true":
        raise Refused(f"{name}: the sentences' scans do not append to the module's")
    if not d["eqIdx"] and not d["fun"] and not d["fs"] and not d["fv"]:
        raise Refused(f"{name}: no sentence of the class is one the instance takes")
    d["inits"] = [n for n in d["order"] if n not in d["consts"]]
    kore = open(text).read()
    d["hooked"] = all(re.search(r"^\s*hooked-symbol " + re.escape(x[0]) + r"\{", kore, re.M) for x in d["fs"] + d["fv"])
    return d


def self_test():
    assert pretty("Lbl'Unds'-Map'UndsUnds'MAP'Unds'Map'Unds'Map'Unds'Map") == "_-Map_"
    assert pretty("Lbl'Unds-LT-Eqls'Map'UndsUnds'MAP'Unds'Bool'Unds'Map'Unds'Map") == "_<=Map_"
    assert pretty("LblupdateMap'LParUndsCommUndsRParUnds'MAP'Unds'Map'Unds'Map'Unds'Map") == "updateMap"
    assert pretty("Lbl'Hash'stdin'Unds'K-IO'Unds'Int") == "#stdin"
    assert blocks(70, 273) == 3 and blocks(22, 66) == 2 and blocks(10, 67) == 6 and blocks(13, 202) == 15
    assert blocks(5, 0) == 0 and blocks(5, 5) == 0 and blocks(5, 6) == 1
    assert layout_cuts(300, [(120, 190)]) == [50, 100, 120, 155, 190, 200, 250]
    assert walk_term(1, [0]) == "List.Sublist.refl _"
    assert walk_term(3, [0, 1]) == "drop <| keep <| List.Sublist.refl _"
    assert walk_term(4, [1, 3]) == "keep <| drop <| first"
    assert walk_term(5, [4]) == "first"
    try:
        walk_term(5, [5])
        raise AssertionError("a kept block outside the blocks accepted")
    except Refused:
        pass
    try:
        layout_cuts(300, [(120, 190)], [50, 100, 150])
        raise AssertionError("cuts that split a run's bound accepted")
    except Refused:
        pass
    # the acceptance control: rdr-config-deep's file from its text and its tie, byte for byte
    name = "rdr-config-deep"
    got = generate(name, data_of(name), config(name))
    want = open(os.path.join(KS, f"test/GenEqsNodir{tiegen.camel(name)}.lean")).read()
    if got != want:
        import difflib
        sys.stdout.writelines(list(difflib.unified_diff(want.splitlines(True), got.splitlines(True), "landed",
                                                        "generated"))[:80])
        print(f"nodirgen self-test: {name}: the generated file differs from the landed one")
        return 1
    print(f"nodirgen self-test: ok ({name}: test/GenEqsNodir{tiegen.camel(name)}.lean regenerated byte for byte)")
    return 0


def main(argv):
    if argv == ["--self-test"]:
        return self_test()
    if not argv or argv[0].startswith("-"):
        print(__doc__, file=sys.stderr)
        return 2
    name = argv[0]
    out = argv[argv.index("--out") + 1] if "--out" in argv else os.path.join(KS, "test")
    d = data_of(name)
    t = generate(name, d, config(name))
    if "--print" in argv:
        sys.stdout.write(t)
    else:
        p = os.path.join(out, f"GenEqsNodir{tiegen.camel(name)}.lean")
        open(p, "w").write(t)
        print(f"wrote {p}: {len(d['listed'])} of the class's {len(d['cls'])} sentences listed"
              + (f"; not listed: {', '.join(str(i) for i, _ in d['unl'])}" if d["unl"] else ""))
    return 0


