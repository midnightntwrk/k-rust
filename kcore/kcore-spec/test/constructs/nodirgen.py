# The tie, the probe

def tie_data(name):
    """The tie's no-direction class and its `callOrder` (test/Tie<Fixture>.lean)."""
    p = os.path.join(KS, f"test/Tie{tiegen.camel(name)}.lean")
    if not os.path.exists(p):
        raise Refused(f"{name}: no tie test/Tie{tiegen.camel(name)}.lean")
    t = open(p).read()
    m = re.search(r'\("no direction", \[([\d,\s]*)\]\)', t)
    co = re.search(r"^def callOrder : List Nat := \[([^\]]*)\]", t, re.M)
    if not m or not co:
        raise Refused(f"{name}: the tie states no no-direction class or no callOrder")
    return [int(x) for x in re.findall(r"\d+", m[1])], [int(x) for x in re.findall(r"\d+", re.sub(r"/-.*?-/", "", co[1]))]


def probe(name, text, cls, co):
    src = (PROBE_LEAN.replace("@PATH@", os.path.abspath(text)).replace("@CLASS@", f"({cls} : List Nat)")
           .replace("@CALLORDER@", f"({co} : List Nat)"))
    with tempfile.TemporaryDirectory(prefix="nodirgen-") as d:
        f = os.path.join(d, "Probe.lean")
        open(f, "w").write(src)
        env = dict(os.environ, LEAN_NUM_THREADS="1")
        r = subprocess.run(tiegen.WRAP + ["timeout", os.environ.get("NODIRGEN_PROBE_TIMEOUT", "900"), "lake", "env",
                                          "lean", "-j1", f], cwd=KS, env=env, capture_output=True, text=True)
    if r.returncode != 0:
        raise Refused(f"{name}: the probe fails: {(r.stdout + r.stderr).strip()[-800:]}")
    return parse_probe(r.stdout)


def parse_probe(out):
    p = dict(H={}, consts=[], order=[], runs=[], eqn=[], others=[], eqIdx=[], fun=[], fs=[], fv=[], unl=[], tbl=[],
             chk={}, gsym=None)
    for l in out.split("\n"):
        tag, _, rest = l.partition(" ")
        if tag == "H":
            k, _, v = rest.partition(" ")
            p["H"][k] = v
        elif tag == "CONST":
            p["consts"].append(rest)
        elif tag == "ORDER":
            p["order"].append(rest)
        elif tag == "RUN":
            a, b = rest.split()
            p["runs"].append((int(a), int(b)))
        elif tag == "EQN":
            pos, idx, kind, fn = rest.split(" ", 3)
            p["eqn"].append(dict(pos=int(pos), idx=int(idx), kind=kind, fn=fn))
        elif tag == "OTHER":
            p["others"].append(rest)
        elif tag == "EQIDX":
            p["eqIdx"].append(int(rest))
        elif tag == "FUN":
            i, _, L = rest.partition(" ")
            p["fun"].append((int(i), L))
        elif tag == "FS":
            m = re.fullmatch(r"(\S+) (\d+) \[([\d, ]*)\]", rest)
            p["fs"].append((m[1], int(m[2]), [int(x) for x in re.findall(r"\d+", m[3])]))
        elif tag == "FV":
            m = re.fullmatch(r"(\S+) (\d+) \[([\d, ]*)\] (.*)", rest)
            p["fv"].append((m[1], int(m[2]), [int(x) for x in re.findall(r"\d+", m[3])], m[4]))
        elif tag == "UNL":
            i, _, why = rest.partition("\t")
            p["unl"].append((int(i), why))
        elif tag == "TBL":
            n, _, v = rest.partition("\t")
            p["tbl"].append((n, v))
        elif tag == "GSYM":
            p["gsym"] = rest
        elif tag == "CHK":
            k, _, v = rest.partition(" ")
            p["chk"][k] = v == "true"
    return p


