def L(xs):
    return "[" + ", ".join(map(str, xs)) + "]"


def Q(xs):
    return "[" + ", ".join('"%s"' % x for x in xs) + "]"


def nest(xs, op):
    s = xs[0]
    for i, x in enumerate(xs[1:]):
        s = f"({s}){op}{x}" if i > 0 else f"{s}{op}{x}"
    return s


def chain(ix):
    return " ++ ".join(f"stage.scan{i}.eqs" for i in ix)


def ranges_of(xs):
    out = []
    for x in sorted(xs):
        if out and out[-1][1] == x - 1:
            out[-1][1] = x
        else:
            out.append([x, x])
    return out


def listed_range(listed):
    terms = []
    for a, b in ranges_of(listed):
        if b - a >= 2:
            terms.append(f"({a} ≤ i && i ≤ {b})")
        else:
            terms += [f"i == {x}" for x in range(a, b + 1)]
    lines, cur = [], "def listedRange (i : Nat) : Bool := "
    for j, t in enumerate(terms):
        piece = t + (" ||" if j < len(terms) - 1 else "")
        if cur.strip() and not cur.endswith(":= ") and len(cur) + len(piece) > 120:
            lines.append(cur.rstrip())
            cur = "  "
        cur += piece + " "
    lines.append(cur.rstrip())
    return "\n".join(lines)


