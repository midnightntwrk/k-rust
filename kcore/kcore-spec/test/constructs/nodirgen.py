#!/usr/bin/env python3
"""nodirgen.py: the no-direction instance of a construct fixture's kompiled text, written as a Lean test.

Usage (from anywhere; the library built first):
  python3 -I test/constructs/nodirgen.py FIXTURE [--out DIR] [--print]
  python3 -I test/constructs/nodirgen.py --self-test   (rdr-config-deep regenerated byte for byte)
  (the probe, a run of the Lean definitions on the text, is stopped after $NODIRGEN_PROBE_TIMEOUT
  seconds, 900 by default, and runs under the 12G scope with one Lean thread)

For FIXTURE, whose text f2-examples/FIXTURE.kompile.kore and tie test/Tie<Fixture>.lean exist, it
writes test/GenEqsNodir<Fixture>.lean (into DIR with --out; to stdout with --print): one model of
the theory, for every interpretation H of the parameters, in which each sentence of the tie's
no-direction class (`classes`, "no direction") that one of the instance's checks takes holds:

- the equations `nodSentEqB` takes (a cell initializer's, the counter's getter, a projection);
- the constants' `functional` axioms `nodSentFunB` takes (the constants of `order`);
- the `functional` axioms of symbols Γ lacks and the text gives no equation: such a symbol is given
  its first argument where that is of its sort (`fs`, `nodSentFunAtB`), else the value `false` of
  `Bool` or `0` of `Int` (`fv`, `nodSentFunValB`).

The class's other sentences are not listed; the header says which and why. The probe computes the
sentences' classes, the literals (`order`, `others`, `tblL`, `gSymCodes`, `sents`) and evaluates
every check of the file on them by compiled code; the generator refuses where one is false, so a file
it writes elaborates unless a decision runs out of memory or time.

The layout (KcoreSpec/GenEqsNodirTbl.lean, GenEqsNodirFunLacked.lean; findings/work/tie-cost-analysis.md
section 4.2):
- the user module is cut into blocks of STEP sentences (`kore_term … cut`), and at the bounds of the
  runs of sentences whose equations the model reads (the listed equations and those of `order`'s
  constants, joined across sentences that give no equation); a run longer than STEP is cut into
  near-equal blocks. `eqsN` is the runs' blocks' equations, a sublist of `S.eqs` (`eqsN_sub`): the
  blocks are walked once, each one's equations dropped or kept by a step matched on `Scan.append`
  (`walk_term`), and only the kept blocks are re-associated as `eqsN` nests them, so the proof is
  linear in the number of blocks and raises no budget;
- the names are compared with Γ's by codes (`gSymCodes`, `lacked_codes`), the names' sorts are read
  from a table checked once (`tblL`, `tbl_ok`, `nodR_eq_tbl`);
- each decision over a list is cut into blocks of n entries (`decide_all_blocks n k`, k the number of
  full blocks before the last), n = BUDGET // (the length of the scan each entry pays for): Γ's
  symbols for `listed_absent`, `order` for the table and the sorts, `order` squared for the
  initializers' equations (the tree below each cell), the names for the projections'. The budgets
  are those of rdr-config-deep's file, whose blocks were measured (findings/work/rcd/rnd-summary.txt).

test/constructs/nodirgen.toml records, per fixture, what the data do not give: `cuts` (the cut list,
in place of the computed one), `header` (the file's header, in place of the generated one), `about`
(the text's configuration, for the generated header), `lacked` (how the docs name the symbols of
`fs` and `fv`), `env_note` (the instance's reason for not stating `envOf m S = .ok E`).
"""
