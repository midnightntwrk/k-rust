# ---------------------------------------------------------------- the add-module mode

def names_lists():
    """The library's added names, as BuiltinNames.lean numbers them."""
    t = open("KcoreSpec/BuiltinNames.lean").read()
    def grab(name):
        m = re.search(r"def " + name + r" : List String :=\s*\[(.*?)\]\n", t, re.S)
        return re.findall(r'"([^"]*)"', m.group(1))
    return grab("newSortNames"), grab("newSymNames")


def uncomment(raw):
    """A sentence of K's text without kompile's `//` comments (outside string literals)."""
    out = []
    for l in raw.split("\n"):
        q, i, cut = False, 0, len(l)
        while i < len(l):
            ch = l[i]
            if q and ch == "\\": i += 2; continue
            if ch == '"': q = not q
            elif not q and l.startswith("//", i): cut = i; break
            i += 1
        s = l[:cut].rstrip()
        if s or not l.strip(): out.append(s)
    return "\n".join(out).rstrip("\n") + "\n"


def k_source(s):
    """K's builtin FILE and the path of a sentence of K's text located in K's builtin directory."""
    sr = src(s)
    m = re.match(r"^(.*/include/kframework/builtin/)([^/]+)$", sr) if sr else None
    return (m.group(2), sr) if m else (None, sr)


def data_rows():
    """The committed rows of BuiltinData.modules, as text, with each row's name, file and first line."""
    t = open("KcoreSpec/BuiltinData.lean").read()
    i = t.index(":= [\n", t.index("def modules :")) + len(":= [\n")
    j = t.index("]\n\n/-- The SHA-256")
    body = t[i:j]
    starts = [m.start() for m in re.finditer(r'^  \("', body, re.M)]
    rows = []
    for k, s in enumerate(starts):
        r = body[s:starts[k + 1] if k + 1 < len(starts) else len(body)].rstrip()
        r = r[:-1] if r.endswith(",") else r
        h = re.match(r'  \("([^"]+)", "krust-builtin://([^"]+)", (\d+), (\d+), \[([0-9, ]*)\]', r)
        rows.append((h.group(1), h.group(2), int(h.group(3)), [int(x) for x in h.group(5).split(",") if x.strip()], r))
    return rows


def kore_blocks(path):
    """The module blocks of a library text: its header line, then (name, text) per module."""
    t = open(path).read()
    head, rest = t.split("\n", 1)
    blocks = []
    for m in re.finditer(r"^module (\S+)\n.*?^endmodule \[\]\n", rest, re.S | re.M):
        blocks.append((m.group(1), m.group(0)))
    if "".join(b for _, b in blocks) != rest: raise SystemExit(f"{path}: not a sequence of module blocks")
    return head + "\n", blocks


def add(name, path):
    if name not in APPENDED: raise SystemExit(f"--add {name}: not a module of APPENDED")
    reg_sorts, reg_syms = reg_lists()
    new_sorts, new_syms = names_lists()
    app_sorts, app_syms = APPENDED[name][0], appended_syms(name)
    # the numbers are BuiltinNames.lean's, the module's names last, in `APPENDED`'s order
    if new_sorts[len(new_sorts) - len(app_sorts):] != app_sorts or new_syms[len(new_syms) - len(app_syms):] != app_syms:
        raise SystemExit(f"--add {name}: BuiltinNames.lean does not end with its names of APPENDED")
    all_sorts = reg_sorts + new_sorts
    sort_no = {X: i for i, X in enumerate(all_sorts)}
    sym_no = {x: i for i, x in enumerate(reg_syms + new_syms)}
    rows = [r for r in data_rows() if r[0] != name]
    head, blocks = kore_blocks("prelude/builtin.kore")
    head_a, blocks_a = kore_blocks("prelude/builtin-arg.kore")
    if [b[0] for b in blocks] != ["KERNEL"] + [r[0] for r in data_rows()] or [b[0] for b in blocks_a] != [b[0] for b in blocks]:
        raise SystemExit("the committed texts' modules are not the rows'")
    blocks = [b for b in blocks if b[0] != name]
    blocks_a = [b for b in blocks_a if b[0] != name]
    base = set()
    for _, b in blocks:
        cur = None
        for l in b.split("\n")[1:]:
            if KW.match(l) or l.startswith("endmodule"):
                if cur is not None: base.add("".join(cur.split()))
                cur = l
            elif cur is not None: cur += l
    # K's text: the module's sentences; the other builtin modules' declarations are the library's
    sent, gens, where, checked = [], OrderedDict(), None, 0
    for raw in user_module(path):
        raw = plain(uncomment(raw))
        f, sr = k_source(raw)
        if f is None:
            gens.setdefault(norm(raw), raw)
            continue
        if f not in FILES: raise SystemExit(f"{sr}: not a file of the library")
        l = line(raw)
        mod = [(n, a, b) for n, a, b in ranges_of(sr) if a <= l <= b]
        if len(mod) != 1: raise SystemExit(f"no module of {sr}:{l}")
        raw = raw.replace(f"Source({sr})", f"Source(krust-builtin://{f})")
        if mod[0][0] == name:
            if where not in (None, (f, sr) + mod[0][1:]): raise SystemExit(f"module {name} in two files")
            where = (f, sr) + mod[0][1:]
            sent.append((norm(raw), raw))
        elif re.match(r"^  (sort|hooked-sort|symbol|hooked-symbol)\b", raw):
            if "".join(raw.split()) not in base:
                raise SystemExit(f"{path}: a declaration of module {mod[0][0]} is not the library's: {norm(raw)[:300]}")
            checked += 1
    if where is None: raise SystemExit(f"{path}: no sentence of module {name}")
    f, kpath, a, b = where
    klines = open(kpath).read().split("\n")[a - 1:b]
    if open(builtin_dir() + f).read().split("\n")[a - 1:b] != klines:
        raise SystemExit(f"module {name}: lines {a}-{b} of {kpath} and of krust's {f} differ")
    m = (f, name, a, b)
    check_appended(name, sent, gens)
    gen_n = list(gens)
    decls = OrderedDict((d["name"], d) for d in (decl(raw) for _, raw in sent) if d and not d["params"])
    declared = [SORTD.match(n).group(2) for n, _ in sent if SORTD.match(n) and not SORTD.match(n).group(3)]
    plain_sorts = [SORTD.match(n).group(2) for n in gens if SORTD.match(n) and n.endswith("[]")]
    ss = declared + [X for X in plain_sorts if X in app_sorts and X not in declared]
    if sorted(ss) != sorted(app_sorts): raise SystemExit(f"module {name}: sorts {ss}, APPENDED {app_sorts}")
    below = [X for X in ss if below_kitem(X, gen_n)]
    if sorted(below) != sorted(APPENDED_PREDS.get(name, [])):
        raise SystemExit(f"module {name}: sorts below KItem {below}, APPENDED_PREDS {APPENDED_PREDS.get(name, [])}")
    own = set(ss) | set(decls) | KERNEL_NAMES
    stored = [gens[n] for n in gen_n if LAW.search(n) and names(n) <= own and names(n) & set(decls)]
    def sig(d):
        return f"⟨{sym_no[d['name']]}, [{', '.join(str(sort_no[x]) for x in d['args'])}], {sort_no[d['res']]}⟩"
    lib = {X for r in rows for X in r[3]} | {sort_no[X] for X in ss}
    row = module_row(m, sent, ss, below, list(decls.values()), sort_no, sig, reg_syms, total_names(gen_n, decls),
                     {X: sort_uids(X, gen_n) for X in below}, gen_n, lambda X: X in sort_no and sort_no[X] in lib)
    # at its place by (file, line)
    at = len([r for r in rows if (FILES.index(r[1]), r[2]) < (FILES.index(f), a)])
    rows.insert(at, (name, f, a, [], row))
    for p, hd, bs, form in [("prelude/builtin.kore", head, blocks, plain), ("prelude/builtin-arg.kore", head_a, blocks_a, arg)]:
        text = f"module {name}\n" + "".join(form(raw) for _, raw in sent) + "".join(form(raw) for raw in stored) + "endmodule []\n"
        bs = bs[:at + 1] + [(name, text)] + bs[at + 1:]
        open(p, "w").write(hd + "".join(t for _, t in bs))
    write_data([r[4] for r in rows])
    print(f"--add {name}: {len(sent)} sentences of {f} {a}-{b}, {len(stored)} stored generated, row {at} of {len(rows)}; "
          f"{checked} declarations of other modules checked against the library", file=sys.stderr)


if __name__ == "__main__":
    if sys.argv[1:2] == ["--add"]:
        if len(sys.argv) != 4: raise SystemExit("usage: extract_builtin.py --add MODULE KORE")
        add(sys.argv[2], sys.argv[3])
    else:
        main(sys.argv[1:])
