# The sorts below KItem of each `APPENDED` module, in its sorts' order: each one's `isX` and
# `project:X` are numbered after the module's symbols (the add-module mode checks the list against
# the sorts K's text puts below KItem)
APPENDED_PREDS = {"RANGEMAP": ["Range", "RangeMap"]}


def appended_syms(name):
    """The numbered symbols of the `APPENDED` module `name`, in their order."""
    return APPENDED[name][1] + [n for X in APPENDED_PREDS.get(name, []) for n in (is_l(X), pr_l(X))]


def appended_names(texts, gens):
    """The sorts and symbols of the `APPENDED` modules, in their order, checked against the
    declarations of each module an input holds."""
    sorts, syms = [], []
    for name, (ss, ys) in APPENDED.items():
        sorts += ss; syms += ys
        ms = [m for m in texts if m[1] == name]
        if not ms:
            print(f"appended module {name}: in no input, its names only (add it with --add)", file=sys.stderr)
            continue
        check_appended(name, texts[ms[0]], gens)
    return sorts, syms


def check_appended(name, sent, gens):
    """The module's declarations are exactly its names of `APPENDED`."""
    ss, ys = APPENDED[name]
    decl_syms = [d["name"] for d in (decl(raw) for _, raw in sent) if d and not d["params"]]
    if sorted(decl_syms) != sorted(ys):
        raise SystemExit(f"appended module {name}: declares {sorted(set(decl_syms) ^ set(ys))} not as listed")
    named = {a for _, raw in sent for d in [decl(raw)] if d for a in d["args"] + [d["res"]]}
    decl_sorts = {SORTD.match(n).group(2) for n, _ in sent if SORTD.match(n)}
    placeless = {SORTD.match(n).group(2) for n in gens if SORTD.match(n) and n.endswith("[]")}
    for X in ss:
        if X not in decl_sorts and not (X in placeless and X in named):
            raise SystemExit(f"appended module {name}: sort {X} not its own")
    if not decl_sorts <= set(ss): raise SystemExit(f"appended module {name}: sorts {decl_sorts - set(ss)} not listed")




is_l = lambda X: "Lblis" + X
pr_l = lambda X: "Lblproject'Coln'" + X
KERNEL_NAMES = {"K", "KItem", "kseq", "dotk", "inj", "append", "LblisK", "LblisKItem", "Lblproject'Coln'K",
                "Lblproject'Coln'KItem", "Lbl'Hash'KConfigValue", "Lbl'Hash'unboxKConfigValue"}
LAW = re.compile(r"\[(assoc|unit|idem)\{\}\(\)\]")
UID = re.compile(r'UNIQUE\'Unds\'ID\{\}\("([0-9a-f]+)"\)')


def names(n):
    return set(re.findall(r"\bSort([A-Za-z0-9']+)\{", n)) | set(re.findall(r"\b(Lbl[^{\s(]*)\{", n)) | \
           set(re.findall(r"\b(kseq|dotk|inj|append)\{", n))


def sort_uids(X, gen_n):
    """The ids of X's generated `project:X`, `isX` true and `isX` false equations (whitespace aside)."""
    flat = [("".join(n.split()), n) for n in gen_n]
    def uid_of(pat, what, optional=False):
        pat = "".join(pat.split())
        for f, n in flat:
            if pat in f:
                m = UID.search(n)
                if m: return m.group(1)
        if optional: return ""
        raise SystemExit(f"no uid for {what} of {X}")
    return (uid_of(f"\\equals{{Sort{X}{{}}, R}}( {pr_l(X)}{{}}(X0:SortK{{}})", "project", True),
            uid_of(f"\\equals{{SortBool{{}}, R}}( {is_l(X)}{{}}(X0:SortK{{}}), \\and{{SortBool{{}}}}(\\dv{{SortBool{{}}}}(\"true\")", "isTrue"),
            uid_of(f"\\equals{{SortBool{{}}, R}}( {is_l(X)}{{}}(X0:SortK{{}}), \\and{{SortBool{{}}}}(\\dv{{SortBool{{}}}}(\"false\")", "isFalse"))


def below_kitem(X, gen_n):
    return any(f"[subsort{{Sort{X}{{}}, SortKItem{{}}}}()]" in n for n in gen_n)


def total_names(gen_n, decls):
    totals = set()
    for n in gen_n:
        if n.endswith("[functional{}()]"):
            for x in re.findall(r"\b(Lbl[^{\s(]*)\{", n):
                if x in decls: totals.add(x)
    return totals


def module_row(m, sent, ss, below, ds, sort_no, sig, reg_syms, totals, uids, gen_n, lib_sort):
    """The module's row of BuiltinData.modules: `sent` its sentences, `ss` its sorts, `ds` its
    declarations; `lib_sort X`: X is a sort of the library."""
    f, name, a, b = m
    bl = [X for X in ss if X in below]
    tok = [X for X in ss if X in ("Id", "String")]
    byt = [X for X in ss if X == "Bytes"]
    subs = []
    for n in gen_n:
        mm = re.search(r"\[subsort\{Sort([A-Za-z0-9]+)\{\}, Sort([A-Za-z0-9]+)\{\}\}\(\)\]", n)
        if mm and lib_sort(mm.group(1)) and mm.group(2) in ss:
            pair = (sort_no[mm.group(1)], sort_no[mm.group(2)])
            if pair not in subs: subs.append(pair)
    if name in DECLARED_SUBSORTS:
        keep = [(sort_no[x], sort_no[y]) for x, y in DECLARED_SUBSORTS[name]]
        if not set(keep) <= set(subs): raise SystemExit(f"{name}: declared subsorts {set(keep) - set(subs)} not extracted")
        subs = [x for x in subs if x in keep]
    ctors = [sig(d) for d in ds if "constructor" in attr_names(d["attrs"])]
    # the registry's are interpreted or without meaning; Builtins.libParams drops the interpreted
    params = [sig(d) for d in ds if "constructor" not in attr_names(d["attrs"]) and d["name"] not in reg_syms]
    tots = [sig(d) for d in ds if d["name"] in totals and "constructor" not in attr_names(d["attrs"])]
    us = [f'({sort_no[X]}, "{uids[X][0]}", "{uids[X][1]}", "{uids[X][2]}")' for X in bl]
    declared = {SORTD.match(nn).group(2) for nn, _ in sent if SORTD.match(nn)}
    pl = [X for X in ss if X not in declared]
    dvs = [X for X in ss if any(nn.startswith(("sort Sort" + X + "{}", "hooked-sort Sort" + X + "{}")) and "hasDomainValues" in nn
                                for nn, _ in sent)]
    num = lambda xs: ", ".join(str(sort_no[X]) for X in xs)
    return (f'  ("{name}", "krust-builtin://{f}", {a}, {b}, [{num(ss)}], [{num(pl)}], [{num(dvs)}], [{num(bl)}], '
            f'[{num(tok)}], [{num(byt)}], [{", ".join(f"({x}, {y})" for x, y in subs)}],\n    [{", ".join(ctors)}],\n'
            f'    [{", ".join(params)}],\n    [{", ".join(tots)}],\n    [{", ".join(us)}])')


def main(paths):
    reg_sorts, reg_syms = reg_lists()
    texts = OrderedDict()  # (file, module) -> list of (norm, raw)
    gens = OrderedDict()   # norm -> raw, generated sentences of the first input
    for i, p in enumerate(paths):
        seen = OrderedDict()
        for raw in user_module(p):
            raw = plain(raw)
            m = module_of(raw)
            if m is None:
                gens.setdefault(norm(raw), raw)
                continue
            seen.setdefault(m, []).append((norm(raw), raw))
        for m, ss in seen.items():
            if m in texts:
                if [a for a, _ in texts[m]] != [a for a, _ in ss]:
                    raise SystemExit(f"{p}: module {m[1]} differs from an earlier input")
            else:
                texts[m] = ss
    app_sorts, app_syms = appended_names(texts, gens)
    mods = sorted(texts, key=lambda m: (FILES.index(m[0]), m[2]))

    # the library's sorts and symbols
    sort_mod, sym_mod, decls, pdecls, psorts = OrderedDict(), OrderedDict(), OrderedDict(), OrderedDict(), set()
    for m in mods:
        for n, raw in texts[m]:
            sm = SORTD.match(n)
            if sm and not sm.group(3): sort_mod.setdefault(sm.group(2), m)
            if sm and sm.group(3): psorts.add(sm.group(2))  # with sort parameters (MInt)
            d = decl(raw)
            if d and not d["params"]:
                sym_mod.setdefault(d["name"], m); decls[d["name"]] = d
            pm = PDECL.match(n)
            if pm:
                pdecls.setdefault(pm.group(2), m)  # with sort parameters: not numbered
    # a plain sort the text declares without location: the module of the first declaration that
    # names it
    plain_sorts = [SORTD.match(n).group(2) for n in gens if SORTD.match(n) and n.endswith("[]")]
    for X in plain_sorts:
        for name, d in decls.items():
            if X in d["args"] + [d["res"]] and X not in sort_mod:
                sort_mod[X] = sym_mod[name]
    lib_sorts = list(sort_mod)
    gen_n = list(gens)
    below = [X for X in lib_sorts if below_kitem(X, gen_n)]
    lib_names = set(lib_sorts) | set(decls) | {is_l(X) for X in below} | {pr_l(X) for X in below} | KERNEL_NAMES
    selectors = {name for n in gen_n for name in re.findall(r"\b(Lblproject'ColnHash'[^{\s(]*)\{", n)}
    lib_names |= selectors | set(pdecls) | psorts
    # the generated sentences: user, emit's, or stored
    stored = OrderedDict((m, []) for m in mods)
    kernel = []
    emitted = []
    for n in gen_n:
        raw = gens[n]
        ns = names(n)
        if not ns <= lib_names:
            continue  # the definition's own, or the configuration's
        if n.startswith("import "):
            kernel.append(raw); continue
        if LAW.search(n) or "\\ceil{SortMap{}, Q0}" in n:
            owner = [sym_mod[x] for x in ns if x in sym_mod]
            stored[owner[0]].append(raw); continue
        par = [x for x in ns if x in pdecls]
        if par:
            # about a symbol with sort parameters (`ite`), which the core does not number
            stored[pdecls[par[0]]].append(raw); continue
        sel = [x for x in ns if x in selectors]
        if sel:
            # K-IO's selectors: owned by the constructor they select from
            c = re.match(r"Lblproject'ColnHash'(.*)'Coln'", sel[0]).group(1)
            stored[sym_mod["Lbl'Hash'" + c]].append(raw); continue
        if ns & {"LblisK", "LblisKItem", "Lblproject'Coln'K", "Lblproject'Coln'KItem", "Lbl'Hash'unboxKConfigValue"} or \
                (ns - {"K", "KItem", "inj", "kseq", "dotk"}) <= {"Lbl'Hash'KConfigValue"}:
            kernel.append(raw); continue
        emitted.append(n)
    # numbers: the modules' names but `APPENDED`'s, in their order, then `APPENDED`'s
    new_sorts = [X for X in lib_sorts if X not in reg_sorts and X not in app_sorts]
    all_sorts = reg_sorts + new_sorts
    sort_no = {X: i for i, X in enumerate(all_sorts)}
    new_syms = []
    for X in new_sorts:
        if X in below: new_syms += [is_l(X), pr_l(X)]
    for name, d in decls.items():
        if name not in reg_syms and name not in app_syms: new_syms.append(name)
    new_sorts += [X for X in app_sorts if X not in reg_sorts]
    new_syms += [x for name in APPENDED for x in appended_syms(name) if x not in reg_syms]
    all_sorts = reg_sorts + new_sorts
    sort_no = {X: i for i, X in enumerate(all_sorts)}
    all_syms = reg_syms + new_syms
    sym_no = {x: i for i, x in enumerate(all_syms)}
    def sig(d):
        return f"⟨{sym_no[d['name']]}, [{', '.join(str(sort_no[a]) for a in d['args'])}], {sort_no[d['res']]}⟩"
    uids = {X: sort_uids(X, gen_n) for X in below}
    totals = total_names(gen_n, decls)
    write_kore(mods, texts, stored, kernel)
    app_preds = [X for name in APPENDED for X in APPENDED_PREDS.get(name, [])]
    write_names(new_sorts, new_syms, [X for X in new_sorts if X in below and X not in app_sorts] + app_preds,
                sort_no, sym_no)
    rows = [module_row(m, texts[m], [X for X, mm in sort_mod.items() if mm == m], below,
                       [d for x, d in decls.items() if sym_mod[x] == m], sort_no, sig, reg_syms, totals, uids, gen_n,
                       lambda X: X in sort_mod) for m in mods]
    write_data(rows)
    print(f"{len(mods)} modules, {sum(len(texts[m]) for m in mods)} sentences, {sum(len(v) for v in stored.values())} "
          f"stored generated, {len(kernel)} kernel, {len(emitted)} generated by emit; {len(new_sorts)} new sorts, "
          f"{len(new_syms)} new symbols", file=sys.stderr)


def write_kore(mods, texts, stored, kernel):
    for path, form in [("prelude/builtin.kore", plain), ("prelude/builtin-arg.kore", arg)]:
        with open(path, "w") as o:
            o.write("[]\n")
            o.write("module KERNEL\n")
            for raw in kernel: o.write(form(raw))
            o.write("endmodule []\n")
            for m in mods:
                o.write(f"module {m[1]}\n")
                for _, raw in texts[m]: o.write(form(raw))
                for raw in stored[m]: o.write(form(raw))
                o.write("endmodule []\n")


def write_names(new_sorts, new_syms, pred_sorts, sort_no, sym_no):
    N = []
    N.append("/-\n  KCore. The names of the sorts and symbols the builtin library adds to the registry, generated by")
    N.append("  prelude/extract_builtin.py; not edited by hand (FLOAT's symbols, after INT-COMMON's, as")
    N.append("  BuiltinData.lean says). Frozen layer; imports nothing but Init.\n-/")
    N.append("set_option autoImplicit false\n\nnamespace KCore.BuiltinNames\n")
    N.append(f"/-- How many sorts the library adds (numbered from 21). -/\ndef nNewSorts : Nat := {len(new_sorts)}\n")
    N.append(f"/-- How many symbols the library adds (numbered from 173). -/\ndef nNewSyms : Nat := {len(new_syms)}\n")
    w = N.append
    w("/-- The names of the sorts the library adds to the registry's, numbered from 21. -/")
