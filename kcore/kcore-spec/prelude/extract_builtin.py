"""The builtin library, by K module, from krust's KORE of probe definitions.

krust writes every module a definition imports, its own and the builtin ones, into one KORE module.
A builtin sentence carries `Source(krust-builtin://FILE)` and a `Location`; the K module that
declares it is the module of FILE whose line range holds the location (krust's embedded copies,
crates/k-rust/builtin). Every other sentence is generated by kompile from the signature, or is the
definition's own.

Writes
- prelude/builtin.kore: one KORE module per K module, holding the module's sentences as krust
  writes them (its declarations and its hand-written axioms), and the generated sentences that
  are not schematic in the signature: the `KERNEL` module (what every definition holds: the
  K and KItem predicates and projections, `#KConfigValue`, `import K`) and, inside their module,
  the collection axioms of LIST, SET and MAP (assoc, unit, idem) and K-IO's selectors;
- KcoreSpec/BuiltinData.lean: the library's numbers (the registry's, then the sorts and symbols the
  library adds) and each module's declarations as numbers.

Everything else kompile generates for a builtin sort, constructor or total symbol is `emit`'s
(KcoreSpec/Emit.lean): the sort's declaration, `isX`, `project:X`, the subsorts, the constructor
axioms, the functional axioms. The library is the union of the inputs' modules; inputs holding a
module must agree on its text. The inputs, in this order, from findings/work/p23 (none tracked;
probe/compile.sh and kevm.sh write them): probe/out/kryp/definition.kore,
probe/out/bytesp/definition.kore, kevm-out/kore/definition.kore, and krust's KORE of a definition
that imports FLOAT (the committed FLOAT text is krust's KORE of wasm-semantics). RANGEMAP is then
added by the add-module mode (below).

A module's subsorts are those into one of its sorts from a library sort, whichever module declares
them; where an input's own productions add some, `DECLARED_SUBSORTS` holds the ones K's file
declares for the module, and only those are kept.

A module of `APPENDED` is numbered after every other, its sorts and symbols in the order listed
there, then the generated `isX` and `project:X` of each of its sorts below KItem
(`APPENDED_PREDS`), as every other library sort below KItem has them. Where an input holds
it, the listed names must be exactly its declarations, and it is a module of the library like any
other (a row of BuiltinData.lean, a text in builtin.kore, at its place in its file); where none
does, only its names are written.

The add-module mode, `--add MODULE KORE`, adds one module to the committed data from K's own
kompile of a definition that imports it (prelude/add-rangemap.sh: RANGEMAP). The committed
BuiltinData.lean rows and the module texts of builtin.kore and builtin-arg.kore are carried over
unread, and BuiltinNames.lean is not written: the module's names must be the registry's already
(`APPENDED`), with the numbers BuiltinNames.lean gives them. A builtin sentence of K's text has
`Source(.../include/kframework/builtin/FILE)`; it is stored with `Source(krust-builtin://FILE)`,
the library's spelling, in K's layout, without kompile's `//` comments. The module is found by
line range in that K's FILE, whose lines of the module must be those of krust's copy. Only the
named module is taken: every declaration of the input's other builtin modules must be the
library's already, whitespace aside (their rule axioms differ from krust's in the `Location` only,
and are not read). A second run gives the same files.

Usage: python3 -I prelude/extract_builtin.py KORE...             (from kcore-spec)
       python3 -I prelude/extract_builtin.py --add MODULE KORE  (from kcore-spec)
krust's copies of K's files are read from K_RUST/crates/k-rust/builtin (K_RUST: the k-rust
checkout, by default the one holding this file, else the main checkout under $HOME)."""
import re, sys
from collections import OrderedDict

KW = re.compile(r"^  (sort|hooked-sort|symbol|hooked-symbol|axiom|claim|import|alias)\b")
import os
FILES = ["kast.md", "domains.md", "json.md"]


def builtin_dir():
    """krust's copies of K's builtin files: in $K_RUST, or in the nearest directory above this file
    that holds crates/k-rust/builtin (the k-rust checkout)."""
    if os.environ.get("K_RUST"):
        roots = [os.environ["K_RUST"]]
    else:
        d, roots = os.path.dirname(os.path.abspath(__file__)), []
        while d != os.path.dirname(d):
            d = os.path.dirname(d); roots.append(d)
    for r in roots:
        d = os.path.join(r, "crates/k-rust/builtin/")
        if os.path.isdir(d): return d
    raise SystemExit("no crates/k-rust/builtin in $K_RUST or a directory above " + os.path.dirname(os.path.abspath(__file__)))
norm = lambda s: " ".join(s.split())
# kompile writes an argument-less `simplification` as `simplification{}("")` when some sentence of
# the definition gives the attribute an argument (INT-KORE's `simplification(51)`), and as
# `simplification{}()` otherwise: the library holds both forms (builtin.kore, builtin-arg.kore)
plain = lambda raw: raw.replace('simplification{}("")', 'simplification{}()')
arg = lambda raw: raw.replace('simplification{}()', 'simplification{}("")')


def user_module(path):
    mods, cur = [], None
    for line in open(path):
        if line.startswith("module "):
            cur = []
        elif line.startswith("endmodule"):
            mods.append(cur); cur = None
        elif cur is not None:
            if KW.match(line): cur.append(line)
            elif cur: cur[-1] += line
    return mods[-1]


def ranges(path):
    rs, cur = [], None
    for i, l in enumerate(open(path), 1):
        m = re.match(r"^module ([A-Z0-9-]+)", l)
        if m: cur = (m.group(1), i)
        elif l.startswith("endmodule") and cur: rs.append((cur[0], cur[1], i)); cur = None
    return rs


_RANGES = {}


def ranges_of(path):
    if path not in _RANGES: _RANGES[path] = ranges(path)
    return _RANGES[path]


def src(s):
    m = re.search(r'Source\{\}\(\s*"Source\(([^)]*)\)"\s*\)', s); return m.group(1) if m else None


def line(s):
    m = re.search(r'Location\{\}\(\s*"Location\((\d+),', s); return int(m.group(1)) if m else None


def module_of(s):
    sr = src(s)
    if sr is None or not sr.startswith("krust-builtin://"): return None
    f = sr[len("krust-builtin://"):]
    l = line(s)
    for n, a, b in ranges_of(builtin_dir() + f):
        if a <= l <= b: return (f, n, a, b)
    raise SystemExit(f"no module of {f}:{l}")


DECL = re.compile(r"^(hooked-symbol|symbol) (\S+?)\{([^}]*)\}\(([^)]*)\) : (\S+?)\{\} \[(.*)\]$")
PDECL = re.compile(r"^(hooked-symbol|symbol) (\S+?)\{([^}]+)\}\(")
SORTD = re.compile(r"^(hooked-sort|sort) Sort(\S+?)\{([^}]*)\}")


def decl(s):
    m = DECL.match(norm(s))
    if not m: return None
    kind, name, sv, args, res, attrs = m.groups()
    args = [a.strip() for a in args.split(",") if a.strip()]
    return dict(kind=kind, name=name, params=sv, args=[a[4:-2] for a in args], res=res[4:], attrs=attrs)


def attr_names(attrs):
    return re.findall(r"([A-Za-z'0-9-]+)\{[^}]*\}\(", attrs)


def reg_lists():
    t = open("KcoreSpec/FixedSignature.lean").read()
    def grab(name):
        m = re.search(r"def " + name + r" : List String :=\s*\[(.*?)\]", t, re.S)
        return re.findall(r'"([^"]*)"', m.group(1))
    return grab("regSortNames"), grab("regSymNames")


