#!/usr/bin/env bash
# Regenerate the libraries and relation files of k2lean's demos and build the demos, in this
# checkout: the libraries go to k2lean/generated/, the relation files into the demos (git ignores
# both, except each library's open lists and hand module). The demos:
#   ImpRel        the KRS IMP port (k/krs-imp) is bisimilar to kimp (`k2lean relate`, `Bisim.lean`)
#   ImpTypes      kimp is type-sound for the K type checker k/imp-typing.k
#   ImpMut        a mutant of kimp (k/kimp-mutant) diverges from kimp
#   KrsImpTyping  every KRS IMP rule preserves the declared cell type `env: Map<Id, Value>`
#   SimpleEnv     (heavy only) a kind 2 invariant of SIMPLE: every environment maps into the store
#   PeanoRel, CellMapRel  the generator's fixtures peano and cellmap (../tests/fixtures) are each
#                 bisimilar to themselves under two namespaces (`k2lean relate`, `Bisim.lean`)
# ImpRel, ImpTypes and KrsImpTyping also have `Preserve.lean`, the preservation theorem proved with
# the prelude's invariant core and `k2l_preserve`; ImpRel has `CollTest.lean`, tests of the
# collection preservation lemmas; ImpTypes has `PreservesOf.lean`, `preservation` through the
# generated `KImp.Step.preserves_of`, and the generated `KImp.init` against the generated
# `ImpTypes.init`. ImpTypes' type soundness is generated by `k2lean soundness` around one hand
# module: `Typing.lean` (generated: the runtime typing), `Store.lean` (hand-written: the store
# typing and the cases of the rules that read or write the store) and `Soundness.lean` (generated:
# preservation, progress, `soundness`). The generator calls are in ../tests/libs.sh,
# shared with the gate (../tests/gate.sh), which checks the same outputs in a work tree of its own.
#
#   k2lean/demos/regen.sh [light|heavy]      (default light)
#
# light generates kimp, krsimp, kmut, imptypes and the fixture libraries and builds six projects (a clean build took
# 780 s wall and 2,000 s of CPU on a shared 32-CPU host); heavy also generates SIMPLE and builds
# SimpleEnv (about 500 s more).
#
# Environment:
#   KRUST=FILE          krust (default target/release/krust of this checkout)
#   K_BUILTIN=DIR       K's builtin modules (default k/k-distribution/include/kframework/builtin,
#                       the K sources of README.md, "Compatibility evidence")
#   KIMP=DIR            kimp's K sources (default imp-semantics/src/kimp/kdist/imp-semantics)
#   SD=DIR              SIMPLE's K sources, for heavy (default
#                       k/pyk/regression-new/pl-tutorial/2_languages/1_simple/1_untyped)
#   DEMOS_SCRATCH=DIR   compiled KORE, build logs and timing tables (default target/k2lean-demos)
#   CLEAN=1             delete the `.lake` of every library and project first (a clean build)
#   RESET_OPEN=1        empty each library's open-obligations.txt first, so every equation proof is
#                       attempted again; the lists are tracked, so review their diff afterwards
#   DEMOS_RESULTS=DIR   also copy the timing tables and the `k2l_preserve` lines there
#
# k/krs-imp/*.kore is the KRS IMP port (`krs/tests/imp/rust-definition`) as `krs build` compiled
# it on 2026-10-23 (definition.kore md5 7ab05924e9a2d8f71e8ee37bfd9129b7). It is kept here because
# the port has changed since (k-rust 70e12ba80, 12fe33e21), so a rebuild would relate a different
# definition.
#
# Outputs: generated/{kimp,krsimp,kmut,imptypes[,simple]} (libraries), demos/*/ (the generated
# `Bisim.lean`, `Tr.lean`, `correspondence.toml`), build logs and times in DEMOS_SCRATCH:
# times.tsv (each `lake build`), modules.tsv (each project module, as lake reports it),
# preserve.txt (each `k2l_preserve` result).
set -euo pipefail
TIER=${1:-light}
case $TIER in light|heavy) ;; *) sed -n '2,/^set -euo/p' "$0" | sed '$d; s/^# \{0,1\}//'; exit 2 ;; esac
D=$(cd "$(dirname "$0")" && pwd)
K2=$(dirname "$D")
R=$(dirname "$K2")
S=${DEMOS_SCRATCH:-$R/target/k2lean-demos}
KRUST=${KRUST:-$R/target/release/krust}
BUILTIN=${K_BUILTIN:-$R/k/k-distribution/include/kframework/builtin}
KIMP=${KIMP:-$R/imp-semantics/src/kimp/kdist/imp-semantics}
SD=${SD:-$R/k/pyk/regression-new/pl-tutorial/2_languages/1_simple/1_untyped}
export KRUST BUILTIN KIMP SD
RT=$K2/tests/rtime.py
GEN=$K2/generated
mkdir -p "$S"
[ -x "$KRUST" ] || { echo "regen.sh: needs krust at $KRUST (set KRUST)" >&2; exit 2; }
[ -d "$BUILTIN" ] || { echo "regen.sh: needs K's builtin modules at $BUILTIN (set K_BUILTIN)" >&2; exit 2; }
[ -d "$KIMP" ] || { echo "regen.sh: needs kimp's sources at $KIMP (set KIMP)" >&2; exit 2; }
command -v lake > /dev/null || { echo "regen.sh: needs lake (elan) on PATH" >&2; exit 2; }
times=$S/times.tsv
printf 'target\twall_s\tcpu_s\tpeak_rss_mib\tload_at_start\n' > "$times"
timed() { # NAME LOG COMMAND...: run, append its rtime line to $times; fail on a nonzero exit
  local n=$1 log=$2; shift 2
  local l; l=$(cut -d' ' -f1-3 /proc/loadavg)
  local rc=0; "$RT" "$@" > "$log" 2>&1 || rc=$?
  sed -n "s|^rtime: wall \([0-9.]*\) s, cpu \([0-9.]*\) s, max child rss \([0-9]*\) MiB.*|$n\t\1\t\2\t\3\t$l|p" "$log" >> "$times"
  return $rc
}

# the generator calls, shared with tests/gate.sh; they read DEMOS, KRS, G and GEN
# shellcheck source=../tests/libs.sh
. "$K2/tests/libs.sh"
export DEMOS=$D KRS=$D/k/krs-imp GEN
kore_dir() { echo "$S/kore/$1"; }

# 1. compiled KORE (krust): kimp and its lemma module, the type checker, the mutant, SIMPLE
kores=(kimp kimp-verif imp-typing kmut)
[ "$TIER" = heavy ] && kores+=(simple)
for k in "${kores[@]}"; do libs_kcompile "$k" > "$S/kcompile-$k.log" 2>&1 || { tail -5 "$S/kcompile-$k.log"; exit 1; }; done

# 2. the generator
cargo build --release --locked -p k2lean --manifest-path "$R/Cargo.toml"
G=${CARGO_TARGET_DIR:-$R/target}/release/k2lean

# 3. the libraries; a failed K-equation proof becomes an open obligation (`open-from-log`), then
#    the library is regenerated and rebuilt
gen() { # dir: the generator call for one library (tests/libs.sh)
  libs_gen "$1" 2> "$S/gen-$1.log"
}
lib() { # dir name
  local d=$1 n=$2
  mkdir -p "$GEN/$d"; touch "$GEN/$d/open-obligations.txt"
  [ "${RESET_OPEN:-0}" = 1 ] && : > "$GEN/$d/open-obligations.txt"
  gen "$d"
  [ "${CLEAN:-0}" = 1 ] && rm -rf "$GEN/$d/.lake"
  if ! (cd "$GEN/$d" && timed "$d:Equations" "$S/build-$d-eqns.log" lake build "$n.Equations"); then
    "$G" open-from-log "$GEN/$d/$n/Equations.lean" "$S/build-$d-eqns.log" "$GEN/$d/open-obligations.txt"
    gen "$d"
  fi
  (cd "$GEN/$d" && timed "$d" "$S/build-$d.log" lake build "$n") || { grep -E '^error' "$S/build-$d.log" | head; exit 1; }
  # the library's axiom guard (`#k2l_assert_axioms` over every proved theorem)
  (cd "$GEN/$d" && timed "$d:guard" "$S/build-$d-guard.log" lake build "${n}Test.Axioms") || { grep -E '^error' "$S/build-$d-guard.log" | head; exit 1; }
  echo "$d: $(wc -l < "$GEN/$d/open-obligations.txt") open obligations, $(grep -c 'depends on axioms' "$S/build-$d-guard.log") theorems under the guard"
}
lib kimp KImp
lib krsimp KrsImp
lib kmut KMut
lib imptypes KImpTypes
lib freekey FreeKey
# the two sides of each fixture self-relation; the demo's build builds them as far as it needs
for d in peano peanob cellmap cellmapb; do mkdir -p "$GEN/$d"; touch "$GEN/$d/open-obligations.txt"; gen "$d"; done
if [ "$TIER" = heavy ]; then lib simple KSimple; fi

# 4. the relations (generated files of ImpRel, ImpTypes, ImpMut, PeanoRel, CellMapRel) and the
#    soundness modules of ImpTypes
for ns in ImpRel ImpTypes ImpMut PeanoRel CellMapRel; do libs_relate "$ns" > "$S/relate-$ns.log" 2>&1 || { tail -5 "$S/relate-$ns.log"; exit 1; }; done
# the generated modules of ImpTypes' type-soundness proof (`k2lean soundness`)
libs_soundness ImpTypes > "$S/soundness-ImpTypes.log" 2>&1 || { tail -5 "$S/soundness-ImpTypes.log"; exit 1; }

# 5. the projects; the axiom guards are `#k2l_assert_axioms` commands inside them, so a build
#    that passes has checked them; `sorry` is rejected below
printf 'module\tbuild\n' > "$S/modules.tsv"
: > "$S/preserve.txt"
projects=(ImpRel ImpTypes ImpMut KrsImpTyping PeanoRel CellMapRel)
[ "$TIER" = heavy ] && projects+=(SimpleEnv)
for p in "${projects[@]}"; do
  [ "${CLEAN:-0}" = 1 ] && rm -rf "$D/$p/.lake"
  (cd "$D/$p" && timed "$p" "$S/build-$p.log" lake build) || { grep -E '^error' "$S/build-$p.log" | head; exit 1; }
  if grep -q "declaration uses 'sorry'" "$S/build-$p.log"; then echo "$p: sorry" >&2; exit 1; fi
  sed -n "s|.* Built \($p\.[A-Za-z]*\) (\(.*\))\$|\1\t\2|p" "$S/build-$p.log" >> "$S/modules.tsv"
  grep -o 'k2l_preserve: .*' "$S/build-$p.log" | sed "s|^|$p: |" >> "$S/preserve.txt" || true
  echo "$p: built"
done
column -t -s "$(printf '\t')" "$times"
column -t -s "$(printf '\t')" "$S/modules.tsv"
cat "$S/preserve.txt"
if [ -n "${DEMOS_RESULTS:-}" ]; then
  mkdir -p "$DEMOS_RESULTS"
  cp "$times" "$DEMOS_RESULTS/demos-times.tsv"
  cp "$S/modules.tsv" "$DEMOS_RESULTS/demos-modules.tsv"
  cp "$S/preserve.txt" "$DEMOS_RESULTS/demos-preserve.txt"
fi
