//! Rewrite rules with priorities stratified by rank.
//!
//! At a configuration, only the applicable rules of the first rank (in priority order) at which
//! some rule applies are used; a lower rank is used only where no rule of a higher rank matches
//! with a true requires. So:
//! - `App i c`: a rule of rank `i` applies at `c` (match ∧ requires; one constructor per rule);
//! - `Step0 i c c'`: a rule of rank `i` rewrites `c` to `c'`, ignoring the other ranks;
//! - `Step c c'`: one constructor per rule, whose hypotheses include `¬ App j lhs` for every
//!   higher rank `j`. `App` is defined before `Step`, so the negation is a positive occurrence.

use crate::index::CtorInfo;
use crate::lower::L;
use crate::names;
use crate::rules::{Rule, ctor_args, ctor_sig, display_name};

fn rank_of(r: &Rule, prios: &[i64]) -> usize {
    prios.iter().position(|p| *p == r.priority).unwrap()
}

/// `∀ j, j < i → ¬ App j lhs`, or nothing at rank 0.
fn hpri(i: usize, lhs: &str) -> String {
    if i == 0 {
        String::new()
    } else {
        format!("\n      (hpri : ∀ j, j < {i} → ¬ App j {lhs})")
    }
}

pub fn emit_rules(rules: &[Rule], prios: &[i64], top: &str, ns: &str, info: &CtorInfo) -> String {
    let k = prios.len();
    let mut o = format!(
        "import {ns}.Functions\n\n/-! Generated by k2lean from compiled KORE; do not edit.\n\n\
Rewrite rules with priorities, stratified by rank ({k} ranks: priorities {prios:?}).\n\
`App i c`: a rule of rank `i` applies at `c`. `Step0 i c c'`: a rule of rank `i` rewrites `c` to\n\
`c'`, ignoring the other ranks. `Step c c'`: one constructor per rewrite axiom, which also\n\
requires that no rule of a higher rank applies. -/\n\nset_option linter.unusedSimpArgs false\nset_option linter.unusedVariables false\nset_option maxHeartbeats 0\nset_option maxRecDepth 100000\n\nnamespace {ns}\n\nopen KPrelude\n\n"
    );
    o.push_str(&format!("inductive App : Nat → {top} → Prop where\n"));
    for r in rules {
        let i = rank_of(r, prios);
        o.push_str(&format!(
            "  | {}{} :\n      App {i} {}\n",
            r.lean,
            ctor_sig(&r.app),
            r.app.index.render_arg()
        ));
    }
    o.push_str(&format!(
        "\ninductive Step0 : Nat → {top} → {top} → Prop where\n"
    ));
    for r in rules {
        let i = rank_of(r, prios);
        o.push_str(&format!(
            "  | {}{} :\n      Step0 {i} {}\n        {}\n",
            r.lean,
            ctor_sig(&r.step),
            r.step.index.render_arg(),
            r.rhs.subst(&r.step.subst).render_arg()
        ));
    }
    o.push_str(&format!("\ninductive Step : {top} → {top} → Prop where\n"));
    for r in rules {
        let i = rank_of(r, prios);
        let lhs = r.step.index.render_arg();
        o.push_str(&format!(
            "  /-- {} (priority {}) -/\n  | {}{}{} :\n      Step {lhs}\n        {}\n",
            crate::rules::doc(r),
            r.priority,
            r.lean,
            ctor_sig(&r.step),
            hpri(i, &lhs),
            r.rhs.subst(&r.step.subst).render_arg()
        ));
    }
    o.push_str("\nnamespace Rules\n\n");
    for r in rules {
        let i = rank_of(r, prios);
        o.push_str(&format!(
            "def {} (c : {top}) : RuleResult (App {i}) (Step0 {i}) c :=\n{}\n",
            r.lean, r.exec
        ));
    }
    o.push_str("end Rules\n\n");
    for (pos, r) in rules.iter().enumerate() {
        let i = rank_of(r, prios);
        o.push_str(&format!(
            "def R.{} : Rule {top} (App {i}) (Step0 {i}) := ⟨{}, {pos}, Rules.{}⟩\n",
            r.lean,
            names::string_lit(&display_name(r)),
            r.lean
        ));
    }
    for i in 0..k {
        let rs: Vec<&Rule> = rules.iter().filter(|r| rank_of(r, prios) == i).collect();
        let items: Vec<String> = rs.iter().map(|r| format!("  R.{}", r.lean)).collect();
        o.push_str(&format!(
            "\n/-- The rules of rank {i} (priority {}), in `krun`'s order. -/\ndef rules{i} : List (Rule {top} (App {i}) (Step0 {i})) := [\n{}]\n",
            prios[i],
            items.join(",\n")
        ));
        let lhs: Vec<&L> = rs.iter().map(|r| &r.app.index).collect();
        let tree = crate::index::build(&lhs, info);
        let names: Vec<String> = rs.iter().map(|r| format!("R.{}", r.lean)).collect();
        o.push_str(&format!(
            "\ndef bucketOf{i} (c : {top}) : List (Rule {top} (App {i}) (Step0 {i})) :=\n{}",
            crate::index::emit(&tree, &names, info, 2)
        ));
    }
    let mut body = format!("firstDefined (bucketOf{} c) c none", k - 1);
    for i in (0..k - 1).rev() {
        body = format!("orStuck (firstDefined (bucketOf{i} c) c none) (fun _ => {body})");
    }
    o.push_str(&format!(
        "\n/-- One step as `krun` takes it: the first rank at which a rule applies, and there the first\nrule whose result is defined. -/\ndef step (c : {top}) : Outcome {top} :=\n  {body}\n\n\
/-- `run fuel c`: at most `fuel` steps from `c`. -/\ndef run (fuel : Nat) (c : {top}) : RunResult {top} := KPrelude.run step fuel c 0\n\nend {ns}\n"
    ));
    o
}

/// `match j, hj with | 0, _ => p0 | … | _ + i, hj => absurd hj (by omega)`: the higher ranks.
fn below(i: usize, proofs: &dyn Fn(usize) -> String) -> String {
    if i == 0 {
        return "(fun j hj => absurd hj (Nat.not_lt_zero j))".into();
    }
    let mut arms = String::new();
    for j in 0..i {
        arms.push_str(&format!(" | {j}, _ => {}", proofs(j)));
    }
    format!("(fun j hj => match j, hj with{arms} | _ + {i}, hj => absurd hj (by omega))")
}

pub fn emit_adequacy(
    rules: &[Rule],
    prios: &[i64],
    top: &str,
    ns: &str,
    info: &CtorInfo,
) -> String {
    let k = prios.len();
    let mut o = format!(
        "import {ns}.Rules\nimport KPrelude.Tactic\n\n/-! Generated by k2lean; do not edit.\n\nAdequacy of the executable step with respect to `Step` and `App`, with priority ranks. -/\n\n\
set_option linter.unusedSimpArgs false\nset_option linter.unusedVariables false\nset_option maxHeartbeats 0\nset_option maxRecDepth 100000\n\nnamespace {ns}\n\nopen KPrelude\n\n"
    );
    // the per-rule closer is the one of `rules::emit_adequacy` (see there)
    for r in rules {
        let rule = format!("Rules.{}", r.lean);
        let s_rhs = r.rhs.subst(&r.step.subst).render_arg();
        o.push_str(&format!(
            "theorem {rule}.complete{} :\n    ({rule} {}).next? = some {s_rhs} := by\n{}",
            ctor_sig(&r.step),
            r.step.index.render_arg(),
            crate::rules::adequacy_tactic(&rule)
        ));
        o.push_str(&format!(
            "theorem {rule}.applies{} :\n    ({rule} {}).applies = true := by\n{}",
            ctor_sig(&r.app),
            r.app.index.render_arg(),
            crate::rules::adequacy_tactic(&rule)
        ));
    }
    // every rule is in its rank's bucket of its own left-hand side
    for i in 0..k {
        let rs: Vec<&Rule> = rules.iter().filter(|r| rank_of(r, prios) == i).collect();
        crate::rules::emit_mem(&mut o, &rs, &format!("bucketOf{i}"), info);
    }
    o.push_str(&format!("theorem Step0.app {{i : Nat}} {{c c' : {top}}} (h : Step0 i c c') : App i c := by\n  cases h with\n"));
    for r in rules {
        o.push_str(&format!(
            "  | {} {} => exact App.{} {}\n",
            r.lean,
            ctor_args(&r.step).join(" "),
            r.lean,
            ctor_args(&r.app).join(" ")
        ));
    }
    o.push_str(&format!(
        "\n/-- A rank-`i` step where no higher rank applies is a `Step`. -/\ntheorem Step0.lift {{i : Nat}} {{c c' : {top}}} (h : Step0 i c c') (hi : ∀ j, j < i → ¬ App j c) : Step c c' := by\n  cases h with\n"
    ));
    for r in rules {
        let i = rank_of(r, prios);
        let args = ctor_args(&r.step).join(" ");
        if i == 0 {
            o.push_str(&format!(
                "  | {} {args} => exact Step.{} {args}\n",
                r.lean, r.lean
            ));
        } else {
            o.push_str(&format!(
                "  | {} {args} => exact Step.{} {args} hi\n",
                r.lean, r.lean
            ));
        }
    }
    o.push_str(&format!(
        "\ntheorem Step.base {{c c' : {top}}} (h : Step c c') : ∃ i, Step0 i c c' ∧ ∀ j, j < i → ¬ App j c := by\n  cases h with\n"
    ));
    for r in rules {
        let i = rank_of(r, prios);
        let args = ctor_args(&r.step).join(" ");
        if i == 0 {
            o.push_str(&format!("  | {} {args} => exact ⟨0, Step0.{} {args}, fun j hj => absurd hj (Nat.not_lt_zero j)⟩\n", r.lean, r.lean));
        } else {
            o.push_str(&format!(
                "  | {} {args} hpri => exact ⟨{i}, Step0.{} {args}, hpri⟩\n",
                r.lean, r.lean
            ));
        }
    }
    for i in 0..k {
        let rs: Vec<&Rule> = rules.iter().filter(|r| rank_of(r, prios) == i).collect();
        o.push_str(&format!(
            "\ntheorem rules{i}_complete {{c c' : {top}}} (h : Step0 {i} c c') : ∃ r ∈ bucketOf{i} c, (r.run c).next? = some c' := by\n  cases h with\n"
        ));
        for r in &rs {
            let args = ctor_args(&r.step).join(" ");
            o.push_str(&format!(
                "  | {0} {args} => exact ⟨R.{0}, Rules.{0}.memS {args}, Rules.{0}.complete {args}⟩\n",
                r.lean
            ));
        }
        o.push_str(&format!(
            "\ntheorem rules{i}_applies {{c : {top}}} (h : App {i} c) : ∃ r ∈ bucketOf{i} c, (r.run c).applies = true := by\n  cases h with\n"
        ));
        for r in &rs {
            let args = ctor_args(&r.app).join(" ");
            o.push_str(&format!(
                "  | {0} {args} => exact ⟨R.{0}, Rules.{0}.mem {args}, Rules.{0}.applies {args}⟩\n",
                r.lean
            ));
        }
        o.push_str(&format!(
            r#"
/-- No rule of rank {i} applies exactly when its bucket is stuck. -/
theorem rank{i}_stuck {{c : {top}}} (h : firstDefined (bucketOf{i} c) c none = .stuck) : ¬ App {i} c := by
  intro ha
  obtain ⟨r, hm, hr⟩ := rules{i}_applies ha
  have := firstDefined_stuck (bucketOf{i} c) c h r hm
  rw [hr] at this
  exact Bool.noConfusion this

theorem rank{i}_none {{c : {top}}} (h : ¬ App {i} c) : firstDefined (bucketOf{i} c) c none = .stuck :=
  firstDefined_of_none _ c (fun r _ => by
    cases e : (r.run c).applies
    · rfl
    · exact absurd (RuleResult.app_of_applies (fun _ hs => Step0.app hs) e) h)
"#
        ));
    }
    // step_sound: peel the ranks
    let mut sound = format!(
        "\n/-- Soundness of the executable step. -/\ntheorem step_sound {{c c' : {top}}} (h : step c = .next c') : Step c c' := by\n  unfold step at h\n"
    );
    for i in 0..k {
        let prev = |j: usize| format!("rank{j}_stuck s{j}");
        if i + 1 < k {
            sound.push_str(&format!(
                "  rcases orStuck_next h with h{i} | ⟨s{i}, h⟩\n  · exact Step0.lift (firstDefined_sound _ c none c' h{i}) {}\n  try simp only [] at h\n",
                below(i, &prev)
            ));
        } else {
            sound.push_str(&format!(
                "  exact Step0.lift (firstDefined_sound _ c none c' h) {}\n",
                below(i, &prev)
            ));
        }
    }
    o.push_str(&sound);
    // step_progress
    o.push_str(&format!(
        "\n/-- If some rule has a successor, the step function takes a step. -/\ntheorem step_progress {{c c' : {top}}} (h : Step c c') : ∃ c'', step c = .next c'' := by\n  obtain ⟨i, h0, hhi⟩ := Step.base h\n  match i, h0, hhi with\n"
    ));
    for i in 0..k {
        let mut rws = Vec::new();
        for j in 0..i {
            rws.push(format!("rank{j}_none (hhi {j} (by omega))"));
        }
        let rw = if rws.is_empty() {
            String::new()
        } else {
            format!("rw [{}]; ", rws.join(", "))
        };
        o.push_str(&format!(
            "  | {i}, h0, hhi =>\n    obtain ⟨r, hm, hr⟩ := rules{i}_complete h0\n    obtain ⟨c'', hc⟩ := firstDefined_next_of_mem (bucketOf{i} c) c none r c' hm hr\n    refine ⟨c'', ?_⟩\n    unfold step; {rw}simp only [orStuck_of_stuck, hc, orStuck]\n"
        ));
    }
    o.push_str(&format!("  | _ + {k}, h0, _ => cases h0\n"));
    // step_stuck
    let mut stuck = format!(
        "\n/-- A stuck configuration: no rule of any rank applies. -/\ntheorem step_stuck {{c : {top}}} (h : step c = .stuck) : ∀ i, ¬ App i c := by\n  unfold step at h\n"
    );
    for i in 0..k {
        if i + 1 < k {
            stuck.push_str(&format!(
                "  obtain ⟨s{i}, h⟩ := orStuck_stuck h\n  try simp only [] at h\n"
            ));
        } else {
            stuck.push_str(&format!("  have s{i} := h\n"));
        }
    }
    stuck.push_str("  intro i ha\n  match i, ha with\n");
    for i in 0..k {
        stuck.push_str(&format!("  | {i}, ha => exact rank{i}_stuck s{i} ha\n"));
    }
    stuck.push_str(&format!("  | _ + {k}, ha => cases ha\n"));
    o.push_str(&stuck);
    o.push_str(&format!(
        r#"
theorem stuck_no_step {{c : {top}}} (h : step c = .stuck) (c' : {top}) : ¬ Step c c' := fun hs => by
  obtain ⟨i, h0, _⟩ := Step.base hs
  exact step_stuck h i (Step0.app h0)

/-- Runs are `Step` derivations. -/
theorem run_sound (fuel : Nat) (c : {top}) :
    StepsN Step (run fuel c).steps c (run fuel c).config := by
  have := (KPrelude.run_sound (step := step) (R := Step) (I := fun _ => True)
    (fun _ _ _ h => step_sound h) (fun _ _ _ _ => trivial) fuel c 0 trivial).1
  simpa [run] using this

end {ns}
"#
    ));
    o
}

pub fn emit_determinism(top: &str, ns: &str, unfold: &[String]) -> String {
    format!(
        "import {ns}.Adequacy\n\n/-! Generated by k2lean; do not edit. Determinism of `Step` with priority ranks: within a\n\
rank by case analysis on pairs of rules, across ranks because the lower rank's `Step` excludes\n\
the higher rank's `App`. -/\n\nset_option maxHeartbeats 0\nset_option maxRecDepth 100000\n\nnamespace {ns}\n\nopen KPrelude\n\n\
theorem Step0.deterministic {{i : Nat}} {{c c₁ c₂ : {top}}} (h₁ : Step0 i c c₁) (h₂ : Step0 i c c₂) : c₁ = c₂ := by\n  cases h₁ <;> cases h₂ <;> k2l_map_facts <;> (try simp_all [{u}]) <;>\n    (repeat' (k2l_split_hyps <;> (try simp_all [{u}])))\n\n\
theorem Step.deterministic {{c c₁ c₂ : {top}}} (h₁ : Step c c₁) (h₂ : Step c c₂) : c₁ = c₂ := by\n  obtain ⟨i, a₁, hi⟩ := Step.base h₁\n  obtain ⟨j, a₂, hj⟩ := Step.base h₂\n  rcases Nat.lt_trichotomy i j with h | rfl | h\n  · exact absurd (Step0.app a₁) (hj i h)\n  · exact Step0.deterministic a₁ a₂\n  · exact absurd (Step0.app a₂) (hi j h)\n\n\
/-- With determinism, the executable step is complete. -/\ntheorem step_complete {{c c' : {top}}} (h : Step c c') : step c = .next c' := by\n  obtain ⟨c'', hc⟩ := step_progress h\n  rw [hc, Step.deterministic (step_sound hc) h]\n\n\
theorem step_iff {{c c' : {top}}} : step c = .next c' ↔ Step c c' := ⟨step_sound, step_complete⟩\n\nend {ns}\n",
        u = unfold.join(", ")
    )
}
