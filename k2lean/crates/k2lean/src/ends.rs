//! Every run ends, in an acceptable ending (SND-21): `NS/Ends.lean`, the composition of a
//! library's three facts, written when it has all three: its kind 1 invariant (`--invariant`),
//! progress to a step under it (`--progress`, `progress_step`), and a measure every rule lowers
//! (`--measure`, `Measure.terminates`).
//!
//! From a configuration that satisfies the invariant and where the measure is defined, no run is
//! infinite (`Measure.terminates`), so every run reaches a configuration that does not step
//! (`KPrelude.Ends.Every`); the invariant holds there (`Invariant.preserved`), so `progress_step`
//! makes it an ending, or one of `progress_step`'s outcomes, since its step is impossible
//! (`KPrelude.Ends.every_of_progress`). The outcomes stay in the statement, which therefore says no
//! more than its parts: with none, every run ends in an ending.
//!
//! `ends_init` states it from the initial configuration, by `Invariant.init_holds` (its hypotheses,
//! where it has some, become this theorem's). The measure's definedness is a hypothesis of both,
//! unless the measure is defined at every configuration (`Measure.defined`): its generated
//! function is not partial, or a proved lemma gives every call of it a value (its nonnegativity
//! as a simplification, `f(_) >=Int 0 => true`, or its totality, `Total.f`).

use crate::eqns::Stated;
use crate::invariants::InitSig;
use std::collections::BTreeSet;

pub struct Inputs<'a> {
    pub ns: &'a str,
    pub top: &'a str,
    /// `progress_step`'s outcomes beside an ending and a step (`Undefined`, `Progress.Refuted`…).
    pub outcomes: &'a [String],
    /// `--measure-invariant`: `Measure.terminates` takes the invariant too.
    pub measure_inv: bool,
    /// The proof of `Measure.defined`, where the measure is defined everywhere.
    pub defined: Option<String>,
    /// `Invariant.init_holds`'s signature, where it is stated.
    pub init: Option<&'a InitSig>,
}

/// The proof of `Measure.defined` from a proved lemma about a call of the measure's function `f`
/// (its Lean name) at any argument, `(Option.bind (f X) g) = some b`: its totality (`Total.f`) or
/// a simplification of it such as `f(_) >=Int 0 => true`, which a measure states for its
/// nonnegativity. Such a call has a value, so the measure, that call at a cell of the
/// configuration, is defined at every configuration.
pub fn defined_by_lemma(f: &str, stated: &[Stated], open: &BTreeSet<String>) -> Option<String> {
    let l = stated.iter().find(|s| {
        if !(s.name.starts_with("Simp.") || s.name.starts_with("Total.")) || open.contains(&s.name)
        {
            return false;
        }
        // one binder `(X : S)`, no hypothesis, and the call of `f` at it
        let st = s.statement.trim_start();
        let Some((binder, body)) = st.split_once(") :") else {
            return false;
        };
        let Some((x, _)) = binder.strip_prefix('(').and_then(|b| b.split_once(" : ")) else {
            return false;
        };
        !binder.contains(')')
            && !body.contains('→')
            && body
                .trim_start()
                .starts_with(&format!("(Option.bind ({f} {x}) "))
            && body.trim_end().ends_with("= some true")
    })?;
    Some(format!(
        "by\n  simp only [Measure.value]\n  exact KPrelude.Measure.isSome_of_bind ({} _)",
        l.name
    ))
}

/// The first line of the module's documentation, by which `remove_generated` knows it.
const HEADER: &str = "/-! Generated by k2lean (`gen --progress --measure`); do not edit.";

/// Remove `path` if it is a generated `Ends.lean` (of an earlier generation that had all three
/// facts); a file of that name that `gen` did not write is kept.
pub fn remove_generated(path: &std::path::Path) {
    if std::fs::read_to_string(path).is_ok_and(|t| t.contains(HEADER)) {
        let _ = std::fs::remove_file(path);
    }
}

/// `Ends.lean`.
pub fn emit(i: &Inputs) -> String {
    let (ns, top) = (i.ns, i.top);
    let res = std::iter::once("Ending e".to_string())
        .chain(i.outcomes.iter().map(|o| format!("{o} e")))
        .collect::<Vec<_>>()
        .join(" ∨ ");
    let what = if i.outcomes.is_empty() {
        "an acceptable ending (`Ending`)".to_string()
    } else {
        format!(
            "an acceptable ending (`Ending`) or at an outcome of `progress_step` ({})",
            i.outcomes
                .iter()
                .map(|o| format!("`{o}`"))
                .collect::<Vec<_>>()
                .join(", ")
        )
    };
    let mut t = format!(
        "import {ns}.Defined\nimport {ns}.Measure\nimport KPrelude.Ends\n\n\
{HEADER}\n\n\
Every run ends, in an acceptable ending (SND-21): from a configuration that satisfies `Invariant`, where\n\
the measure is defined, no run is infinite (`Measure.terminates`), so every run reaches a configuration\n\
that does not step; the invariant holds there, and `progress_step` makes it {what}. -/\n\n\
namespace {ns}\n\nopen KPrelude\n\n"
    );
    let mut guarded = Vec::new();
    if let Some(p) = &i.defined {
        t.push_str(&format!(
            "/-- The measure is defined at every configuration. -/\n\
theorem Measure.defined (c : {top}) : (Measure.value c).isSome := {p}\n\n"
        ));
        guarded.push("Measure.defined");
    }
    let (hmu, mu) = if i.defined.is_some() {
        ("", "(Measure.defined c)".to_string())
    } else {
        (" (hμ : (Measure.value c).isSome)", "hμ".to_string())
    };
    let term = if i.measure_inv {
        format!("Measure.terminates c hI {mu}")
    } else {
        format!("Measure.terminates c {mu}")
    };
    let where_def = if i.defined.is_some() {
        ""
    } else {
        " where the measure is defined"
    };
    t.push_str(&format!(
        "/-- **Every run ends, in an acceptable ending:** from a configuration that satisfies `Invariant`{where_def},\n\
every run reaches a configuration that does not step, and it is {what}. -/\n\
theorem ends (c : {top}) (hI : Invariant c){hmu} :\n    KPrelude.Ends.Every Step c fun e => {res} :=\n  \
KPrelude.Ends.every_of_progress Invariant.preserved hI ({term}) fun e he ht => by\n    \
simpa only [show ¬ ∃ c', Step e c' from fun ⟨_, hs⟩ => ht _ hs, false_or, or_false] using\n      \
progress_step e he\n\n"
    ));
    guarded.push("ends");
    if let Some(s) = i.init {
        let (hmu0, mu0) = if i.defined.is_some() {
            (String::new(), "")
        } else {
            (
                format!(" (hμ : (Measure.value (init{})).isSome)", s.args),
                " hμ",
            )
        };
        t.push_str(&format!(
            "/-- **From the start, every run ends, in an acceptable ending:** every run from the initial\n\
configuration{where_def} reaches a configuration that does not step, and it is {what}. -/\n\
theorem ends_init{}{}{hmu0} :\n    KPrelude.Ends.Every Step (init{}) fun e => {res} :=\n  \
ends (init{}) (Invariant.init_holds{}{}){mu0}\n\n",
            s.params, s.hyps, s.args, s.args, s.args, s.hargs
        ));
        guarded.push("ends_init");
    }
    t.push_str(&format!(
        "#k2l_assert_axioms {}\n\nend {ns}\n",
        guarded.join(" ")
    ));
    t
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sig() -> InitSig {
        InitSig {
            params: " (pgm : SortPgm)".into(),
            hyps: String::new(),
            args: " pgm".into(),
            hargs: String::new(),
        }
    }

    /// With no outcome and a measure defined everywhere, nothing is assumed: from the start, every run ends in
    /// an ending.
    #[test]
    fn a_total_measure_and_no_outcome_assume_nothing() {
        let s = sig();
        let t = emit(&Inputs {
            ns: "N",
            top: "SortGeneratedTopCell",
            outcomes: &[],
            measure_inv: false,
            defined: Some("rfl".into()),
            init: Some(&s),
        });
        assert!(t.contains(
            "theorem ends (c : SortGeneratedTopCell) (hI : Invariant c) :\n    KPrelude.Ends.Every Step c fun e => Ending e :="
        ), "{t}");
        assert!(
            t.contains("(Measure.terminates c (Measure.defined c))"),
            "{t}"
        );
        assert!(t.contains(
            "theorem ends_init (pgm : SortPgm) :\n    KPrelude.Ends.Every Step (init pgm) fun e => Ending e :=\n  ends (init pgm) (Invariant.init_holds pgm)\n"
        ), "{t}");
        assert!(
            t.contains("#k2l_assert_axioms Measure.defined ends ends_init"),
            "{t}"
        );
    }

    /// The outcomes stay in the statement; a partial measure's definedness and the invariant the
    /// measure is under are hypotheses where they are needed.
    #[test]
    fn outcomes_and_a_partial_measure_are_stated() {
        let s = sig();
        let outs = vec!["Undefined".to_string(), "Progress.Refuted".to_string()];
        let t = emit(&Inputs {
            ns: "N",
            top: "T",
            outcomes: &outs,
            measure_inv: true,
            defined: None,
            init: Some(&s),
        });
        assert!(t.contains(
            "theorem ends (c : T) (hI : Invariant c) (hμ : (Measure.value c).isSome) :\n    KPrelude.Ends.Every Step c fun e => Ending e ∨ Undefined e ∨ Progress.Refuted e :="
        ), "{t}");
        assert!(t.contains("(Measure.terminates c hI hμ)"), "{t}");
        assert!(
            t.contains(
                "theorem ends_init (pgm : SortPgm) (hμ : (Measure.value (init pgm)).isSome) :"
            ),
            "{t}"
        );
        assert!(
            t.contains("ends (init pgm) (Invariant.init_holds pgm) hμ\n"),
            "{t}"
        );
        assert!(!t.contains("Measure.defined"), "{t}");
    }

    fn stated(name: &str, statement: &str) -> Stated {
        Stated {
            name: name.into(),
            statement: statement.into(),
            what: String::new(),
            unfold_first: vec![],
            case_first: vec![],
            simp_with: vec![],
            normalizers: vec![],
            nf: vec![],
            row: None,
            induct: vec![],
        }
    }

    /// A proved simplification about every call of the measure's function makes it defined
    /// everywhere; one with a hypothesis, about another function, or open does not.
    #[test]
    fn a_lemma_about_every_call_gives_definedness() {
        let f = "K.«m(_)_N_Int_K»";
        let good = stated(
            "Simp.s_1",
            " (Gen0 : SortK) :\n    (Option.bind (K.«m(_)_N_Int_K» Gen0) fun r => some (KPrelude.IntHook.ge r (0 : Int))) = some true",
        );
        let hyp = stated(
            "Simp.s_2",
            " (Gen0 : SortK) (h : P Gen0) :\n    (Option.bind (K.«m(_)_N_Int_K» Gen0) fun r => some true) = some true",
        );
        let other = stated(
            "Simp.s_3",
            " (Gen0 : SortK) :\n    (Option.bind (K.«g(_)_N_Int_K» Gen0) fun r => some true) = some true",
        );
        let none = BTreeSet::new();
        assert_eq!(
            defined_by_lemma(f, &[hyp.clone(), other.clone(), good.clone()], &none).as_deref(),
            Some(
                "by\n  simp only [Measure.value]\n  exact KPrelude.Measure.isSome_of_bind (Simp.s_1 _)"
            )
        );
        assert_eq!(defined_by_lemma(f, &[hyp, other], &none), None);
        let open: BTreeSet<String> = ["Simp.s_1".to_string()].into();
        assert_eq!(defined_by_lemma(f, &[good], &open), None);
    }
}
