//! The divergence obligations of the least fixed points (TERM-1).
//!
//! A group of functions defined as least fixed points (`partial_fixpoint`, `funcs.rs`) is
//! faithful to the partial reading of K's equations by construction: `none` where some model
//! has `⊥`. What it needs is evidence that it is not a function whose rewriting terminates, for
//! which a termination measure should have been given: the obligation `F.diverges.statement`,
//! that the group's pending calls go on forever (`KPrelude.Pending.Chain`). It is stated over the
//! group's pending-call function `F.pending` (`funcs::render_fixpoint`), not over the functions:
//! a divergent group and an undefined one can have the same least fixed point.
//!
//! `NS/Diverges.lean` holds the statements (specification); the proofs are in
//! `NS/DivergesHand.lean`, written once and never overwritten; `NSTest/Diverges.lean` checks each
//! proof against its statement under the axiom guard. A group whose proof is not in the hand file
//! (no `theorem F.diverges`), or that the open list names, is open.
//!
//! Each group also states that its pending-call function is sound for its functions
//! (`F.pending_sound.statement`, TERM-1c): a call waits only where it and the call it waits for
//! have no value, so a divergent call has no value. It holds by construction, and its proof is
//! derived: a generic tactic in `NS/DivergesSound.lean` (`k2l_pending_arm`); a proof the tactic
//! does not close is open (the open list, `open-from-log` of that module's build log), never
//! assumed.
//!
//! A group whose functions K declares total states that every call has a value
//! (`F.total.statement`, TERM-1h): K's `total` is the K author's claim, stated and never assumed.
//! Where every member is declared total and both `F.diverges` and `F.pending_sound` are proved,
//! its refutation is derived (`NS/DivergesTotal.lean`, `F.total.refuted`: the chain's first call
//! has no value) and checked by `#k2l_refuted`; otherwise it is open. A refuted `F.total` is a
//! finding about the K definition, not a failure of the library.

/// `NS/Diverges.lean`: each group's calls, pending-call function and divergence statement.
pub fn emit(ns: &str, groups: &[(String, String)]) -> String {
    let mut o = format!(
        "import {ns}.Functions\nimport KPrelude.Pending\n\n/-! Generated by k2lean; do not edit.\n\n\
The divergence obligations of the least fixed points (`partial_fixpoint`): for each group, the\n\
calls of its functions, the call that the evaluation of a call waits for (`pending`), and the\n\
statement that K's rewriting of the group does not terminate. Their proofs are in\n\
`{ns}/DivergesHand.lean`. -/\n\nset_option linter.unusedVariables false\n\nnamespace {ns}\n\nopen KPrelude\n\n"
    );
    for (_, text) in groups {
        o.push_str(text);
    }
    o.push_str(&format!("end {ns}\n"));
    o
}

/// `NS/DivergesHand.lean`, written once: where the divergence proofs go.
pub fn hand_template(ns: &str, names: &[&String]) -> String {
    let mut list = String::new();
    for n in names {
        list.push_str(&format!("- `{n}`\n"));
    }
    format!(
        "import {ns}.Diverges\nimport KPrelude.Tactic\n\n/-! The proofs that K's rewriting of the least fixed points does not terminate (TERM-1).\n\
Written once by k2lean and never overwritten: edit it. Each is `theorem F.diverges :\n\
F.diverges.statement`, an infinite chain of pending calls (`KPrelude.Pending.chain_of_fixed`,\n\
`chain_of_cycle`); `{ns}Test/Diverges.lean` checks it. A group with no proof here is open. The\n\
groups when this file was written:\n{list}-/\n\nnamespace {ns}\n\nopen KPrelude\n\nend {ns}\n"
    )
}

/// Whether the hand file proves `name` (a `theorem name` declaration).
pub fn proved_in(hand: &str, name: &str) -> bool {
    hand.lines().any(|l| {
        l.strip_prefix("theorem ")
            .and_then(|r| r.strip_prefix(name))
            .is_some_and(|r| r.starts_with([' ', ':']) || r.is_empty())
    })
}

/// `NS/DivergesSound.lean`: the derived proofs that the groups' pending-call functions are sound
/// (those the open list does not name).
pub fn emit_sound(ns: &str, proofs: &[&(String, String)]) -> String {
    let mut o = format!(
        "import {ns}.Diverges\nimport KPrelude.PendingTactic\n\n/-! Generated by k2lean; do not edit.\n\n\
Each group's pending-call function is sound for its functions (TERM-1c): a call waits only where it\n\
and the call it waits for have no value. Derived (`k2l_pending_arm`); a group whose proof the tactic\n\
does not close is open and absent here. -/\n\nnamespace {ns}\n\nopen KPrelude\n\n"
    );
    for (_, text) in proofs {
        o.push_str(text);
    }
    o.push_str(&format!("end {ns}\n"));
    o
}

/// `NS/DivergesTotal.lean`: the derived refutations of `F.total` (TERM-1h), for the groups
/// `refuted` whose members are all declared total and whose `F.diverges` and `F.pending_sound`
/// are proved: the first call of an infinite chain of pending calls has no value
/// (`KPrelude.Pending.Sound.undef_of_chain`).
pub fn emit_total(ns: &str, refuted: &[&String]) -> String {
    let mut o = format!(
        "import {ns}.DivergesHand\nimport {ns}.DivergesSound\n\n/-! Generated by k2lean; do not edit.\n\n\
K's `total` refuted (TERM-1h) for each group whose rewriting diverges: the first call of an infinite\n\
chain of pending calls has no value. A group absent here has `F.total` open. -/\n\nnamespace {ns}\n\nopen KPrelude\n\n"
    );
    for n in refuted {
        let g = n.strip_suffix(".total").unwrap_or(n);
        o.push_str(&format!(
            "theorem {g}.total.refuted : ¬ {g}.total.statement := by\n  intro h\n  \
obtain ⟨c, hc⟩ := ({g}.diverges : ∃ c, Pending.Chain {g}.pending c)\n  \
exact h c (Pending.Sound.undef_of_chain ({g}.pending_sound : Pending.Sound {g}.pending {g}.Call.undef) hc)\n\n"
        ));
    }
    o.push_str(&format!("end {ns}\n"));
    o
}

/// `NSTest/Diverges.lean`: each proved obligation, and each derived soundness theorem, checked
/// against its statement, on Lean's three axioms; each derived refutation of `F.total` by
/// `#k2l_refuted`.
pub fn emit_check(ns: &str, proved: &[&String], sound: &[&String], refuted: &[&String]) -> String {
    let mut o = format!(
        "import {ns}.DivergesHand\nimport {ns}.DivergesSound\nimport {ns}.DivergesTotal\nimport KPrelude.Tactic\n\n/-! Generated by k2lean; do not edit. Each divergence obligation with a proof in\n\
`{ns}/DivergesHand.lean`, and each soundness theorem of `{ns}/DivergesSound.lean`, is proved as\n\
stated, on Lean's three axioms; each refutation of `{ns}/DivergesTotal.lean` refutes its statement. -/\n\nnamespace {ns}\n\nopen KPrelude\n\n"
    );
    for n in proved.iter().chain(sound) {
        o.push_str(&format!("example : {n}.statement := {n}\n"));
    }
    o.push_str(&format!("\nend {ns}\n\n"));
    for n in proved.iter().chain(sound) {
        o.push_str(&format!("#k2l_assert_axioms {ns}.{n}\n"));
    }
    for n in refuted {
        o.push_str(&format!("#k2l_refuted {ns}.{n}\n"));
    }
    o
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_proof_is_found_by_its_declaration() {
        let hand = "theorem K.align.diverges : K.align.diverges.statement :=\n  chain_of_fixed _ _ h\ntheorem K.size.divergesX : True := trivial\n";
        assert!(proved_in(hand, "K.align.diverges"));
        assert!(!proved_in(hand, "K.size.diverges"));
        assert!(!proved_in(
            "-- theorem K.align.diverges",
            "K.align.diverges"
        ));
    }
}
