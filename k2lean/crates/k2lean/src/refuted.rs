//! Refuted obligations (REF-1): an open obligation shown false is marked in the open list and
//! refuted by a theorem beside its statement, which the axiom guard checks (`#k2l_refuted`).
//!
//! `open-obligations.txt` lists the obligations emitted as statements with no proof, one per line,
//! the name first (`«…»`-aware); an optional marker says the statement is false, and how its
//! refutation is supplied; `#` starts a comment:
//!
//! ```text
//! Eqn.foo_2                         # open: unproved
//! Eqn.«…_2» | refuted               # NS/Refuted.lean: a prelude refutation (`k2l_hook_refute`)
//! Eqn.bar_1 | refuted hand          # NS/RefutedHand.lean (written once, never overwritten)
//! ```
//!
//! A refuted obligation stays a statement (never assumed, never proved). The list declares the
//! status and the build checks it: `NSTest/Refuted.lean` runs `#k2l_refuted` for each marked entry,
//! so a missing, restated or `sorry` refutation fails the axiom guard that imports it.

use std::collections::{BTreeMap, BTreeSet};

/// How a refuted obligation's refutation is supplied.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Source {
    /// Generated in `NS/Refuted.lean`, by a refutation of the prelude (`k2l_hook_refute`).
    Prelude,
    /// Written in `NS/RefutedHand.lean` (by hand or by the optimization loop).
    Hand,
}

/// The open list: every name, and the refuted ones with their source.
#[derive(Default, Debug)]
pub struct OpenList {
    pub names: BTreeSet<String>,
    pub refuted: BTreeMap<String, Source>,
}

/// The name of an entry line (its first token, `«…»`-aware), or `None` for a blank or comment line.
pub fn name_of(line: &str) -> Option<String> {
    crate::invariants::case_token(line)
}

/// The marker of an entry line after its name `n`: `| refuted` or `| refuted hand`, before any
/// `#` comment (a name may hold `#` and `|`: `«#mapOffset(_,_)…»`, `«_|Set__…»`).
fn marker(line: &str, n: &str) -> Result<Option<Source>, String> {
    let rest = &line.trim()[n.len()..];
    let body = rest.split('#').next().unwrap_or("");
    let Some((_, m)) = body.split_once('|') else {
        return Ok(None);
    };
    match m.split_whitespace().collect::<Vec<_>>().as_slice() {
        ["refuted"] => Ok(Some(Source::Prelude)),
        ["refuted", "hand"] => Ok(Some(Source::Hand)),
        other => Err(format!("unknown marker `| {}`", other.join(" "))),
    }
}

pub fn parse(text: &str) -> Result<OpenList, String> {
    let mut o = OpenList::default();
    for l in text.lines() {
        let Some(n) = name_of(l) else { continue };
        if let Some(src) = marker(l, &n).map_err(|e| format!("{n}: {e}"))? {
            o.refuted.insert(n.clone(), src);
        }
        o.names.insert(n);
    }
    Ok(o)
}

/// `text` with the entries `new` added (as bare names): every existing line is kept as it is
/// (markers and comments), comment lines first, entries in name order.
pub fn add_names(text: &str, new: &BTreeSet<String>) -> String {
    let mut comments = Vec::new();
    let mut entries: BTreeMap<String, String> = BTreeMap::new();
    for l in text.lines() {
        match name_of(l) {
            Some(n) => {
                entries.insert(n, l.trim_end().to_string());
            }
            None if !l.trim().is_empty() => comments.push(l.trim_end().to_string()),
            None => {}
        }
    }
    for n in new {
        entries.entry(n.clone()).or_insert_with(|| n.clone());
    }
    let mut out = String::new();
    for l in comments.iter().chain(entries.values()) {
        out.push_str(l);
        out.push('\n');
    }
    out
}

/// `NS/Refuted.lean`: the prelude refutations of the entries marked `refuted`. A library with
/// parameters has none (refuting the statement for every implementation needs an instance:
/// `refuted hand`).
pub fn emit_refuted(ns: &str, names: &[&String]) -> String {
    let mut o = format!(
        "import {ns}.Equations\nimport KPrelude.Tactic\n\n/-! Generated by k2lean; do not edit.\n\n\
The refutations of the open obligations that `open-obligations.txt` marks `refuted`: each is a\n\
refutation of the prelude, in the shape the generator states the obligation (`k2l_hook_refute`). -/\n\n\
namespace {ns}\n\nopen KPrelude\n\n"
    );
    for n in names {
        o.push_str(&format!(
            "theorem {n}.refuted : ¬ {n}.statement := by\n  unfold {n}.statement\n  k2l_hook_refute\n\n"
        ));
    }
    o.push_str(&format!("end {ns}\n"));
    o
}

/// `NS/RefutedHand.lean`, written once: where the refutations marked `refuted hand` go.
pub fn hand_template(ns: &str, names: &[&String], params: bool) -> String {
    let form = if params {
        "`omit [Hooks] in theorem X.refuted : ¬ ∀ [Hooks], X.statement` (the obligation is the\nstatement for every implementation of the parameters, so its refutation picks one)"
    } else {
        "`theorem X.refuted : ¬ X.statement`"
    };
    let mut list = String::new();
    for n in names {
        list.push_str(&format!("- `{n}`\n"));
    }
    format!(
        "import {ns}.Equations\nimport KPrelude.Tactic\n\n/-! The refutations of the open obligations that `open-obligations.txt` marks `refuted hand`.\n\
Written once by k2lean and never overwritten: edit it. Each is {form}; `{ns}Test/Refuted.lean`\n\
checks it (`#k2l_refuted`). The entries marked when this file was written:\n{list}-/\n\nnamespace {ns}\n\nopen KPrelude\n\nend {ns}\n"
    )
}

/// `NSTest/Refuted.lean`: `#k2l_refuted` for each marked entry (imported by the axiom guard).
pub fn emit_check(ns: &str, list: &OpenList) -> String {
    let mut o = String::new();
    if list.refuted.values().any(|s| *s == Source::Prelude) {
        o.push_str(&format!("import {ns}.Refuted\n"));
    }
    if list.refuted.values().any(|s| *s == Source::Hand) {
        o.push_str(&format!("import {ns}.RefutedHand\n"));
    }
    o.push_str(
        "import KPrelude.Tactic\n\n/-! Generated by k2lean; do not edit. Each obligation marked refuted in\n\
`open-obligations.txt` has a refutation of the obligation itself (`#k2l_refuted`), on Lean's\n\
three axioms. -/\n\n",
    );
    for n in list.refuted.keys() {
        o.push_str(&format!("#k2l_refuted {ns}.{n}\n"));
    }
    o
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn markers_and_comments() {
        let o = parse(
            "# a comment\nEqn.a_1\nEqn.«b c_2» | refuted   # false at \"\"\nEqn.c_3 | refuted hand\n\n",
        )
        .unwrap();
        assert_eq!(o.names.len(), 3);
        assert_eq!(o.refuted.get("Eqn.«b c_2»"), Some(&Source::Prelude));
        assert_eq!(o.refuted.get("Eqn.c_3"), Some(&Source::Hand));
        assert!(!o.refuted.contains_key("Eqn.a_1"));
        assert!(parse("Eqn.a_1 | proved\n").is_err());
        let o =
            parse("Eqn.«_|Set__SET_Set_Set_Set_1»\nEqn.«#mapOffset(_,_)_2» | refuted\n").unwrap();
        assert!(!o.refuted.contains_key("Eqn.«_|Set__SET_Set_Set_Set_1»"));
        assert!(o.refuted.contains_key("Eqn.«#mapOffset(_,_)_2»"));
    }

    /// Adding names keeps every marker and comment.
    #[test]
    fn adding_names_keeps_the_markers() {
        let text = "# why\nEqn.z_9 | refuted   # reason\nEqn.b_1\n";
        let new: BTreeSet<String> = ["Eqn.a_1".to_string(), "Eqn.b_1".to_string()].into();
        assert_eq!(
            add_names(text, &new),
            "# why\nEqn.a_1\nEqn.b_1\nEqn.z_9 | refuted   # reason\n"
        );
    }
}
