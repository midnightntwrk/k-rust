//! `k2lean noninterference`: termination-insensitive noninterference as a scaffold
//! (`k2lean/docs/design.md`, section 3.7).
//!
//! Statement, for a program accepted by a security checker (`secure P`, a hand-module
//! predicate, typically a K checker's function at the program's translation) and two initial
//! stores equal on the low part (`lowEq E₁ E₂`, hand module): two runs of `Step` from
//! `init P E₁` and `init P E₂` that both end in final states (`<k>` empty) end in stores equal on
//! the low part.
//!
//! It is reduced, by `KPrelude.ProductInv.final` and `ProductInv.of_modes`, to a relation `Rel` on
//! pairs of configurations and three modes of it: `Sync` (both runs step together), `Left` and
//! `Right` (one run steps alone, the other waits: the secret branches that desynchronize the
//! runs). The obligations are the fields of `Obligations Rel Sync Left Right`: `init`, `final`,
//! `cover` (a related pair that is not final on both sides is in a mode where the stepping side
//! is not final), and one per rule and mode (`sync:r`, `left:r`, `right:r`), stated with
//! `Step.Rel`. The generated module proves the reduction, `Final`, and that a final
//! configuration has no step; the relation and its obligations are the person's.

use crate::confluence::{load, proj_def};
use std::collections::BTreeMap;
use std::fmt::Write as _;

fn fail(msg: &str) -> ! {
    eprintln!("noninterference: {msg}");
    std::process::exit(2)
}

fn field(mode: &str, lean: &str) -> String {
    let inner = lean
        .strip_prefix('«')
        .and_then(|x| x.strip_suffix('»'))
        .unwrap_or(lean);
    format!("«{mode}:{inner}»")
}

pub fn main(args: &[String]) {
    let mut opt: BTreeMap<String, String> = BTreeMap::new();
    let mut it = args.iter();
    while let Some(k) = it.next() {
        let v = it
            .next()
            .unwrap_or_else(|| fail(&format!("{k} needs a value")));
        opt.insert(k.trim_start_matches("--").to_string(), v.clone());
    }
    let get = |k: &str| {
        opt.get(k)
            .cloned()
            .unwrap_or_else(|| fail(&format!("--{k} is required")))
    };
    let lib = load(&get("kore"));
    let (name, ns) = (get("name"), get("ns"));
    if lib.ranked && lib.prios.len() > 1 {
        fail("definitions with several priority ranks are not supported");
    }
    let hand = opt
        .get("hand-module")
        .cloned()
        .unwrap_or(format!("{ns}.Hand"));
    let secure = opt.get("secure").cloned().unwrap_or("secure".into());
    let low = opt.get("low-eq").cloned().unwrap_or("lowEq".into());
    let store = get("store-cell");
    let kcell = opt.get("k-cell").cloned().unwrap_or("k".into());
    let pgm = get("program-sort");
    let store_sort = opt.get("store-sort").cloned().unwrap_or("SortMap".into());
    // the names the parameters bind (`(G : T)` → `G`), passed to `Obligations`
    let pnames: String = opt
        .get("params")
        .map(|p| {
            p.split('(')
                .filter_map(|g| g.split_once(':').map(|(n, _)| n.trim().to_string()))
                .flat_map(|n| n.split_whitespace().map(String::from).collect::<Vec<_>>())
                .map(|n| format!("{n} "))
                .collect()
        })
        .unwrap_or_default();
    let top = format!("{name}.{}", lib.top);
    let rs = &lib.rules;
    let mut o = String::new();
    writeln!(
        o,
        "import {hand}\nimport {name}.Init\nimport KPrelude.Tactic\n"
    )
    .unwrap();
    writeln!(
        o,
        "/-! Generated by `k2lean noninterference`; do not edit.\n\n\
Termination-insensitive noninterference for `{name}.Step`: two runs of a program accepted by\n\
`{secure}`, from stores related by `{low}`, that both end in final configurations, end in stores\n\
related by `{low}`. It holds for every relation `Rel` with modes `Sync`, `Left`, `Right` that\n\
satisfies `Obligations` ({} fields: `init`, `final`, `cover`, and `sync:r`, `left:r`, `right:r`\n\
for each of the {} rules). -/\n",
        3 * rs.len() + 3,
        rs.len()
    )
    .unwrap();
    writeln!(o, "set_option maxHeartbeats 0\nset_option linter.unusedVariables false\n\nnamespace {ns}\n\nopen KPrelude\n").unwrap();
    if let Some(p) = opt.get("params") {
        writeln!(o, "variable {p}\n").unwrap();
    }
    o.push_str(&proj_def(
        &lib,
        &name,
        "kOf",
        std::slice::from_ref(&kcell),
        Some("SortK"),
    ));
    o.push('\n');
    o.push_str(&proj_def(
        &lib,
        &name,
        "storeOf",
        std::slice::from_ref(&store),
        Some(&store_sort),
    ));
    o.push('\n');
    writeln!(
        o,
        "/-- A final configuration: `<{kcell}>` is empty. -/\ndef Final (c : {top}) : Prop := kOf c = {name}.SortK.dotk\n\n\
/-- A final configuration has no step: every rule matches an item on `<{kcell}>`. -/\n\
theorem final_no_step {{c c' : {top}}} (hf : Final c) (h : {name}.Step c c') : False := by\n  cases h <;> simp [Final, kOf] at hf\n"
    )
    .unwrap();
    writeln!(
        o,
        "/-- What a relation on pairs of runs owes, with its three modes. -/\nstructure Obligations (Rel Sync Left Right : {top} → {top} → Prop) : Prop where\n  \
init : ∀ P E₁ E₂, {secure} P → {low} E₁ E₂ → Rel ({name}.init P E₁) ({name}.init P E₂)\n  \
final : ∀ {{f₁ f₂}}, Rel f₁ f₂ → Final f₁ → Final f₂ → {low} (storeOf f₁) (storeOf f₂)\n  \
cover : ∀ {{c₁ c₂}}, Rel c₁ c₂ → ¬ (Final c₁ ∧ Final c₂) →\n    (Left c₁ c₂ ∧ ¬ Final c₁) ∨ (Right c₁ c₂ ∧ ¬ Final c₂) ∨ (Sync c₁ c₂ ∧ ¬ Final c₁ ∧ ¬ Final c₂)"
    )
    .unwrap();
    for r in rs {
        let l = &r.lean;
        writeln!(o, "  /-- Both runs step, the left one by `{}`. -/\n  {} : {name}.Step.Rel.{l} (fun c₁ c₁' => ∀ c₂ c₂', Sync c₁ c₂ → {name}.Step c₂ c₂' → Rel c₁' c₂')", crate::rules::display_name(r), field("sync", l)).unwrap();
        writeln!(
            o,
            "  {} : {name}.Step.Rel.{l} (fun c₁ c₁' => ∀ c₂, Left c₁ c₂ → Rel c₁' c₂)",
            field("left", l)
        )
        .unwrap();
        writeln!(
            o,
            "  {} : {name}.Step.Rel.{l} (fun c₂ c₂' => ∀ c₁, Right c₁ c₂ → Rel c₁ c₂')",
            field("right", l)
        )
        .unwrap();
    }
    let fields = |mode: &str| -> String {
        rs.iter()
            .map(|r| format!("O.{}", field(mode, &r.lean)))
            .collect::<Vec<_>>()
            .join(" ")
    };
    writeln!(
        o,
        "\nvariable {{Rel Sync Left Right : {top} → {top} → Prop}}\n\n\
theorem Obligations.product (O : Obligations {pnames}Rel Sync Left Right) : ProductInv {name}.Step Final Rel :=\n  ProductInv.of_modes\n    (fun hs h₁ h₂ => {name}.Step.rel_of {} h₁ _ _ hs h₂)\n    (fun hl h => {name}.Step.rel_of {} h _ hl)\n    (fun hr h => {name}.Step.rel_of {} h _ hr)\n    O.cover\n",
        fields("sync"),
        fields("left"),
        fields("right")
    )
    .unwrap();
    writeln!(
        o,
        "/-- Termination-insensitive noninterference. -/\n\
theorem noninterference (O : Obligations {pnames}Rel Sync Left Right) {{P : {name}.{pgm}}} {{E₁ E₂ : {name}.{store_sort}}}\n    (hP : {secure} P) (hE : {low} E₁ E₂) {{f₁ f₂ : {top}}}\n    (h₁ : Star {name}.Step ({name}.init P E₁) f₁) (hf₁ : Final f₁)\n    (h₂ : Star {name}.Step ({name}.init P E₂) f₂) (hf₂ : Final f₂) :\n    {low} (storeOf f₁) (storeOf f₂) :=\n  O.final (O.product.final (fun hf h => final_no_step hf h) h₁ hf₁ h₂ hf₂ (O.init _ _ _ hP hE)) hf₁ hf₂\n\n\
#k2l_assert_axioms final_no_step Obligations.product noninterference\n\nend {ns}"
    )
    .unwrap();
    let out = get("out");
    if let Some(d) = std::path::Path::new(&out).parent() {
        std::fs::create_dir_all(d).unwrap_or_else(|e| fail(&format!("{}: {e}", d.display())));
    }
    std::fs::write(&out, &o).unwrap_or_else(|e| fail(&format!("{out}: {e}")));
    let rep = format!(
        "# k2lean noninterference: the obligations of {name}\n\nrules = {}\nobligations = {}\nper_rule = {}\nglobal = 3\ngenerated = 0\n",
        rs.len(),
        3 * rs.len() + 3,
        3 * rs.len()
    );
    if let Some(p) = opt.get("report") {
        std::fs::write(p, rep).unwrap_or_else(|e| fail(&format!("{p}: {e}")));
    }
    eprintln!(
        "noninterference: {} rules, {} obligations",
        rs.len(),
        3 * rs.len() + 3
    );
}
