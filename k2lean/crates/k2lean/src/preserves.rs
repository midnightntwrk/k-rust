//! The per-rule preservation principle `Step.preserves_of` (`{ns}/Preserves.lean`).
//!
//! `Preserved Step P` says that every step from a configuration satisfying `P` leads to one
//! satisfying `P`. `Step` has one constructor per rule, whose arguments are the rule's variables
//! and side conditions and whose indices are the rule's left- and right-hand sides, so a step is
//! an instance of exactly one constructor: `Preserved Step P` holds exactly when, for every rule
//! `r`, `P lhs → P rhs` holds for every instance of `r`. That per-rule statement is
//! `Step.Case.r P`, and `Step.preserves_of` takes one hypothesis per rule, named by the rule,
//! and proves `Preserved Step P` by one `cases` on the step. The hypothesis of rule `r` is also
//! the goal that `k2l_preserve` leaves for `r` when it cannot close it, so a residual case can be
//! taken as a hypothesis of type `Step.Case.r P` without restating it.

use crate::rules::{Rule, ctor_args};
use std::collections::BTreeSet;

/// One `Step` constructor as `Preserves.lean` needs it.
pub struct Ctor {
    pub lean: String,
    pub doc: String,
    /// The rule's source position, when the KORE records it.
    pub loc: Option<String>,
    /// The binders and hypotheses, as `(x : T)` groups.
    pub binders: Vec<String>,
    pub args: Vec<String>,
    pub lhs: String,
    pub rhs: String,
}

/// The constructors of `Step`: the rule's relation, and for a stratified `Step` (`ranks`, the
/// priorities in order) the hypothesis that no rule of a higher rank applies.
pub fn ctors(rules: &[Rule], ranks: Option<&[i64]>) -> Vec<Ctor> {
    rules
        .iter()
        .map(|r| {
            let lhs = r.step.index.render_arg();
            let mut binders: Vec<String> = r
                .step
                .binders
                .iter()
                .map(|(b, t)| format!("({b} : {t})"))
                .collect();
            binders.extend(r.step.hyps.iter().map(|(h, p)| format!("({h} : {p})")));
            let mut args = ctor_args(&r.step);
            if let Some(prios) = ranks {
                let i = prios.iter().position(|p| *p == r.priority).unwrap();
                if i > 0 {
                    binders.push(format!("(hpri : ∀ j, j < {i} → ¬ App j {lhs})"));
                    args.push("hpri".into());
                }
            }
            Ctor {
                lean: r.lean.clone(),
                doc: crate::rules::doc(r),
                loc: r.loc.clone().or_else(|| {
                    r.source
                        .as_ref()
                        .map(|f| format!("{f} (no line in the KORE)"))
                }),
                binders,
                args,
                lhs,
                rhs: r.rhs.subst(&r.step.subst).render_arg(),
            }
        })
        .collect()
}

/// A name for the predicate and for the arguments of the `cases` arms that no rule (no hypothesis
/// of `preserves_of`) is named.
fn free(base: &str, taken: &BTreeSet<String>) -> String {
    let mut n = base.to_string();
    while taken.contains(&n) {
        n.push('\'');
    }
    n
}

pub fn emit(ctors: &[Ctor], top: &str, ns: &str) -> String {
    let taken: BTreeSet<String> = ctors.iter().map(|c| c.lean.clone()).collect();
    let p = free("P", &taken);
    let mut o = format!(
        "import {ns}.Rules\nimport KPrelude.Invariant\n\n/-! Generated by k2lean; do not edit.\n\n\
The per-rule preservation principle of `Step`. `Step.Case.r P` states that rule `r` keeps `P`:\n\
for every instance of the rule's variables that satisfies its side conditions, `P` of the\n\
left-hand side implies `P` of the right-hand side. `Step.preserves_of` proves `Preserved Step P`\n\
from one hypothesis per rule, named by the rule. When `k2l_preserve` cannot close the case of\n\
rule `r`, the goal it leaves is `Step.Case.r P` with the rule's variables and side conditions\n\
introduced, so the case can be taken as a hypothesis `(h : Step.Case.r P)` and closed by\n\
`exact h x₁ … xₙ`. -/\n\n\
set_option linter.unusedVariables false\n\nnamespace {ns}\n\nopen KPrelude\n\n"
    );
    for c in ctors {
        let body = if c.binders.is_empty() {
            format!("{p} {} → {p} {}", c.lhs, c.rhs)
        } else {
            format!(
                "∀ {},\n    {p} {} →\n    {p} {}",
                c.binders.join(" "),
                c.lhs,
                c.rhs
            )
        };
        o.push_str(&format!(
            "/-- Rule {} keeps `{p}`. -/\ndef Step.Case.{} ({p} : {top} → Prop) : Prop :=\n  {body}\n\n",
            c.doc, c.lean
        ));
    }
    o.push_str(&format!(
        "/-- `Preserved Step {p}` from one hypothesis per rule ({} rules), each named by its rule. -/\n\
theorem Step.preserves_of {{{p} : {top} → Prop}}\n",
        ctors.len()
    ));
    for c in ctors {
        o.push_str(&format!("    ({} : Step.Case.{} {p})\n", c.lean, c.lean));
    }
    let max_args = ctors.iter().map(|c| c.args.len()).max().unwrap_or(0);
    let mut arm_taken = taken.clone();
    arm_taken.insert(p.clone());
    let clash = |pre: &str| (1..=max_args).any(|i| arm_taken.contains(&format!("{pre}{i}")));
    let mut x = "x".to_string();
    while clash(&x) {
        x.push('x');
    }
    let (c0, c1, hc, h) = (
        free("c", &arm_taken),
        free("c'", &arm_taken),
        free("hc", &arm_taken),
        free("h", &arm_taken),
    );
    o.push_str(&format!(
        "    : Preserved Step {p} := by\n  intro {c0} {c1} {hc} {h}\n  cases {h} with\n"
    ));
    for c in ctors {
        let xs: Vec<String> = (1..=c.args.len()).map(|i| format!("{x}{i}")).collect();
        let xs = xs.join(" ");
        let sep = if xs.is_empty() { "" } else { " " };
        o.push_str(&format!(
            "  | {}{sep}{xs} => exact {}{sep}{xs} {hc}\n",
            c.lean, c.lean
        ));
    }
    emit_rel(&mut o, ctors, top, &taken, &x);
    o.push_str(&format!("\nend {ns}\n"));
    o
}

/// The per-rule principle for a property `Q c c'` of a step's source and target
/// (`Step.Rel.r Q`, `Step.rel_of`): what the scaffolds (`refine`, `confluence`,
/// `noninterference`) state their per-rule obligations with, since a relation between the two
/// sides of a step is not a preserved predicate.
fn emit_rel(o: &mut String, ctors: &[Ctor], top: &str, taken: &BTreeSet<String>, x: &str) {
    let q = free("Q", taken);
    o.push_str("/-! ## The per-rule principle for a relation between the two sides of a step -/\n\n");
    for c in ctors {
        let body = if c.binders.is_empty() {
            format!("{q} {} {}", c.lhs, c.rhs)
        } else {
            format!("∀ {},\n    {q} {}\n      {}", c.binders.join(" "), c.lhs, c.rhs)
        };
        o.push_str(&format!(
            "/-- Rule {} relates its left- and right-hand sides by `{q}`. -/\ndef Step.Rel.{} ({q} : {top} → {top} → Prop) : Prop :=\n  {body}\n\n",
            c.doc, c.lean
        ));
    }
    o.push_str(&format!(
        "/-- Every step relates its source and target by `{q}`, from one hypothesis per rule ({} rules). -/\n\
theorem Step.rel_of {{{q} : {top} → {top} → Prop}}\n",
        ctors.len()
    ));
    for c in ctors {
        o.push_str(&format!("    ({} : Step.Rel.{} {q})\n", c.lean, c.lean));
    }
    let mut t = taken.clone();
    t.insert(q.clone());
    let (c0, c1, h) = (free("c", &t), free("c'", &t), free("h", &t));
    o.push_str(&format!(
        "    {{{c0} {c1} : {top}}} ({h} : Step {c0} {c1}) : {q} {c0} {c1} := by\n  cases {h} with\n"
    ));
    for c in ctors {
        let xs: Vec<String> = (1..=c.args.len()).map(|i| format!("{x}{i}")).collect();
        let xs = xs.join(" ");
        let sep = if xs.is_empty() { "" } else { " " };
        o.push_str(&format!("  | {}{sep}{xs} => exact {}{sep}{xs}\n", c.lean, c.lean));
    }
}
