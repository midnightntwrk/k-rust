//! The generated step property (`gen --step-property NAME@CELL`, `{ns}/StepProp.lean`;
//! `docs/design.md` §3.12).
//!
//! A step property relates a cell's content before and after each step ("the fees never
//! decrease"). The author writes it in K, a `Bool` function of two contents of one cell, and this
//! module states, per rule `r`, that the rule's step relates its source and target by it:
//! `Step.Rel.r StepProp.holds`, where `StepProp.holds c c'` is `StepProp.rel (x c) (x c') = some
//! true` for the cell's projection `x`. That is the per-rule principle the measure's obligation is
//! an instance of (`Step.Rel.r (Lower μ)`, `measure.rs`), so the cases are proved by the measure's
//! stages (`k2l_step`, `KPrelude/StepProp.lean`) with the property's unfolding set (its projections
//! and the proved equations of every function it calls) and the author's proved lemmas about those
//! functions, or, for the cases listed in `open-step-cases.txt`, by the hand-written
//! `StepProp.hand.r` of `{ns}/StepPropHand.lean`. `StepProp.step` gathers the cases
//! (`Step.rel_of`).
//!
//! With `--step-property-trans`, the function's transitivity is stated as an obligation
//! (`StepProp.trans`, over the cell's contents; never assumed), and the fact then holds between a
//! configuration and every one reached from it in one or more steps (`StepProp.plus`,
//! `KPrelude.StepProp.plus_of_step`). It is not stated otherwise: a property that limits how much a
//! step may change a value is a fact of every step and is not transitive.

use crate::eqns::Stated;
use crate::invariants::{Ctx, Spec, closure, find_cell, resolve};
use crate::names;
use std::collections::BTreeSet;

/// The files to write.
pub struct Out {
    pub defs: String,
    pub theorems: String,
    pub open_list: String,
    /// The skeleton of the hand module, when it does not exist and some case is open.
    pub hand_skeleton: Option<String>,
}

/// The first line of the generated modules, by which a stale one is recognized.
const HEADER: &str = "/-! Generated by k2lean (`gen --step-property ";

/// Remove `path` if `gen --step-property` wrote it; a file of that name that `gen` did not write
/// is kept.
pub fn remove_generated(path: &std::path::Path) {
    if std::fs::read_to_string(path).is_ok_and(|t| t.contains(HEADER)) {
        let _ = std::fs::remove_file(path);
    }
}

/// `StepPropDefs.lean` and `StepProp.lean` for the step property `spec` (`NAME@CELL`), with the
/// cases of `open_in` by hand, and with `trans` its transitivity and the fact along runs.
pub fn emit(
    cx: &Ctx,
    spec: &Spec,
    stated: &[Stated],
    open_in: &BTreeSet<String>,
    hand_exists: bool,
    trans: bool,
) -> Result<Out, String> {
    let (m, ns, top) = (cx.m, cx.ns, cx.top);
    let flag = "--step-property";
    let sym = resolve(cx.def, &spec.name).map_err(|e| e.replace("--invariant", flag))?;
    let sig = cx.fns.get(&sym).ok_or_else(|| {
        format!(
            "{flag} {}: {} was not generated",
            spec.name,
            names::demangle(&sym)
        )
    })?;
    if sig.result != "SortBool" || sig.args.len() != 2 || sig.args[0] != sig.args[1] {
        return Err(format!(
            "{flag} {}: {} must take two arguments of one sort (the cell's content before and after a step) and return Bool",
            spec.name,
            names::demangle(&sym)
        ));
    }
    let arg = &sig.args[0];
    let cell = spec
        .cell
        .as_ref()
        .ok_or_else(|| format!("{flag} {}: name the cell it reads (NAME@CELL)", spec.name))?;
    let path = find_cell(m, top, cell)?;
    if !path.colls.is_empty() {
        return Err(format!(
            "{flag} {}@{cell}: <{cell}> is inside a cell collection; the elements before and after a step \
             are related by their keys, which the property states over the collection's cell (a function of \
             two contents of that cell)",
            spec.name
        ));
    }
    // the function takes the cell itself, or the one value the cell holds
    let content = path.cell_args.len() == 1 && path.cell_args[0] == *arg;
    if !content && path.cell_sort != *arg {
        return Err(format!(
            "{flag} {}@{cell}: {} takes a {arg}, but <{cell}> is a {} holding {:?}",
            spec.name,
            names::demangle(&sym),
            path.cell_sort,
            path.cell_args
        ));
    }

    // the projections from the configuration to the cell (the same as a measure's, in their own
    // namespace), the relation on the cell's contents and the property of a step's two sides
    let mut defs = String::new();
    let mut unfold: Vec<String> = Vec::new();
    let mut chain: Vec<String> = Vec::new();
    let mut proj = |name: String,
                    sort: &str,
                    child: &str,
                    lean: &str,
                    arity: usize,
                    index: usize,
                    doc: String| {
        let pats: Vec<&str> = (0..arity)
            .map(|i| if i == index { "x" } else { "_" })
            .collect();
        defs.push_str(&format!(
            "/-- {doc} -/\ndef {name} : {sort} → {child}\n  | {lean} {} => x\n\n",
            pats.join(" ")
        ));
        chain.push(name.clone());
        unfold.push(name);
    };
    for lv in &path.levels {
        proj(
            format!("StepProp.cell_{}", lv.name),
            &lv.sort,
            &lv.child,
            &lv.lean,
            lv.arity,
            lv.index,
            format!("The `<{}>` cell of a `{}`.", lv.name, lv.sort),
        );
    }
    if content {
        proj(
            format!("StepProp.content_{cell}"),
            &path.cell_sort,
            arg,
            &path.cell_lean,
            1,
            0,
            format!("What a `<{cell}>` cell holds."),
        );
    }
    // the cell of the configuration `v`, through the projections
    let read = |v: &str| {
        chain.iter().fold(v.to_string(), |acc, p| {
            if acc.contains(' ') {
                format!("{p} ({acc})")
            } else {
                format!("{p} {acc}")
            }
        })
    };
    let paren = |e: String| if e.contains(' ') { format!("({e})") } else { e };
    let call = format!("{} x y", sig.lean);
    let rel = if sig.partial {
        call
    } else {
        format!("some ({call})")
    };
    let pname = names::demangle(&sym);
    // `rel` is a proposition rather than `value x y = some true`, so that the closer reads it as a
    // fact to unfold where it is a hypothesis (transitivity), not as a known value of a call
    defs.push_str(&format!(
        "/-- The value of the step property `{pname}` at two contents of the `<{cell}>` cell. -/\n\
def StepProp.value (x y : {arg}) : Option Bool :=\n  {rel}\n\n\
/-- Two contents of the `<{cell}>` cell, before and after, satisfy `{pname}`. -/\n\
def StepProp.rel (x y : {arg}) : Prop :=\n  StepProp.value x y = some true\n\n\
/-- A step from `c` to `c'` satisfies `{pname}` at their `<{cell}>` cells. -/\n\
def StepProp.holds (c c' : {top}) : Prop :=\n  StepProp.rel {} {}\n\n",
        paren(read("c")),
        paren(read("c'"))
    ));
    for n in ["StepProp.value", "StepProp.rel", "StepProp.holds"] {
        unfold.insert(0, n.into());
    }

    // the proved equations of every function the property calls, and the author's proved lemmas
    // about them (a simplification rule whose statement applies one of them)
    let proved = |n: &String| cx.stated.contains(n) && !cx.open_eqns.contains(n);
    let mut called: Vec<String> = Vec::new();
    for g in closure(cx.def, cx.eqs, &sym) {
        let Some(gs) = cx.fns.get(&g) else { continue };
        if !gs.lean.starts_with("K.") {
            continue;
        }
        called.push(gs.lean.clone());
        let n = cx.eqs.get(&g).map_or(0, |es| es.len());
        for i in 0..n {
            let e = format!(
                "Eqn.{}",
                names::ident(&format!("{}_{}", names::demangle(&g), i + 1))
            );
            if proved(&e) {
                unfold.push(e);
            }
        }
    }
    let lemmas: Vec<String> = stated
        .iter()
        .filter(|s| {
            (s.name.starts_with("Simp.") || s.name.starts_with("Lemma.")) && proved(&s.name)
        })
        .filter(|s| called.iter().any(|f| s.statement.contains(f.as_str())))
        .map(|s| s.name.clone())
        .collect();
    let (us, ls) = (unfold.join(", "), lemmas.join(", "));

    // the cases, and the transitivity
    let open: BTreeSet<String> = cx
        .ctors
        .iter()
        .filter(|c| open_in.contains(&c.lean))
        .map(|c| c.lean.clone())
        .collect();
    let trans_stmt =
        format!("∀ x y z : {arg}, StepProp.rel x y → StepProp.rel y z → StepProp.rel x z");
    let trans_open = trans && open_in.contains("StepProp.trans");
    let flags = if trans {
        format!("{flag} {}@{cell} --step-property-trans", spec.name)
    } else {
        format!("{flag} {}@{cell}", spec.name)
    };
    let d = format!(
        "import {ns}.Equations\nimport {ns}.Preserves\nimport KPrelude.StepProp\n\n\
{HEADER}{}`); do not edit. The step property\n\
of a step's two sides; `StepProp.lean` states that every rule's step satisfies it. -/\n\n\
set_option linter.unusedVariables false\n\nnamespace {ns}\n\nopen KPrelude\n\n{defs}end {ns}\n",
        &flags[flag.len() + 1..]
    );
    let mut t = format!("import {ns}.StepPropDefs\n");
    if !open.is_empty() || trans_open {
        t.push_str(&format!("import {ns}.StepPropHand\n"));
    }
    let along = if trans {
        "\n\n`StepProp.trans` states that `StepProp.rel` is transitive, so the fact holds between a\n\
configuration and every one reached from it in one or more steps (`StepProp.plus`)."
    } else {
        ""
    };
    t.push_str(&format!(
        "\n{HEADER}{}`); do not edit.\n\n\
Every rule of `{ns}` satisfies the step property `{pname}` (`StepProp.holds`): at its `<{cell}>`\n\
cell, the source and the target of the step are related by it (`Step.Rel.r StepProp.holds`). Each\n\
case is proved by `k2l_step` with the property's unfolding set and the author's proved lemmas about\n\
the functions it calls (K simplification rules), or, for the cases listed in `open-step-cases.txt`,\n\
by the hand-written `StepProp.hand.r` of `StepPropHand.lean`.{along} -/\n\n\
set_option linter.unusedVariables false\n\nnamespace {ns}\n\nopen KPrelude\n\n\
/-- `k2l_step` with the property's unfolding set and the author's lemmas (declared before it: a\n\
quotation resolves its global names where it is written). -/\n\
local macro \"k2l_stepp\" : tactic => `(tactic| k2l_step [{us}] [{ls}])\n\n",
        &flags[flag.len() + 1..]
    ));
    if trans {
        if trans_open {
            t.push_str(&format!(
                "/-- `{pname}` is transitive: the hand proof. -/\ntheorem StepProp.trans : {trans_stmt} :=\n  StepProp.hand.trans\n\n"
            ));
        } else {
            t.push_str(&format!(
                "/-- `{pname}` is transitive. -/\ntheorem StepProp.trans : {trans_stmt} := by\n  k2l_stepp\n\n"
            ));
        }
    }
    t.push_str("namespace StepProp.case\n\n");
    let mut n_auto = 0;
    for c in cx.ctors {
        if open.contains(&c.lean) {
            t.push_str(&format!(
                "/-- Rule {} satisfies the step property: the hand proof. -/\ntheorem {} : Step.Rel.{} StepProp.holds := StepProp.hand.{}\n\n",
                c.doc, c.lean, c.lean, c.lean
            ));
        } else {
            n_auto += 1;
            t.push_str(&format!(
                "/-- Rule {} satisfies the step property. -/\ntheorem {} : Step.Rel.{} StepProp.holds := by k2l_stepp\n\n",
                c.doc, c.lean, c.lean
            ));
        }
    }
    t.push_str("end StepProp.case\n\n");
    t.push_str(&format!(
        "/-- Every step satisfies the step property ({} rules: {n_auto} by `k2l_step`, {} by hand). -/\n\
theorem StepProp.step {{c c' : {top}}} (h : Step c c') : StepProp.holds c c' :=\n  Step.rel_of\n",
        cx.ctors.len(),
        cx.ctors.len() - n_auto,
    ));
    for c in cx.ctors {
        t.push_str(&format!("    StepProp.case.{}\n", c.lean));
    }
    t.push_str("    h\n\n");
    if trans {
        t.push_str(&format!(
            "/-- Along every path of one or more steps, the first and the last configuration satisfy the\n\
step property. -/\n\
theorem StepProp.plus {{c c' : {top}}} (h : Relation.TransGen Step c c') : StepProp.holds c c' :=\n  \
KPrelude.StepProp.plus_of_step StepProp.step\n    \
(fun {{a b d}} h₁ h₂ => StepProp.trans {} {} {} h₁ h₂) h\n\n\
#k2l_assert_axioms StepProp.step StepProp.trans StepProp.plus\n\nend {ns}\n",
            paren(read("a")),
            paren(read("b")),
            paren(read("d"))
        ));
    } else {
        t.push_str(&format!("#k2l_assert_axioms StepProp.step\n\nend {ns}\n"));
    }

    // open-step-cases.txt and the hand module's skeleton
    let mut ol = format!(
        "# Cases of the step property `{ns}.StepProp.holds` that `k2l_step` does not close (`k2lean gen --step-property`).\n\
# `k2lean open-from-log {ns}/StepProp.lean BUILD.log open-step-cases.txt` adds the cases whose proof failed.\n\
# Each line: the case, its statement, the rule's source position. Prove each in {ns}/StepPropHand.lean as\n\
# `theorem StepProp.hand.r : Step.Rel.r StepProp.holds` (namespace `{ns}`; `Step.Rel.r`\n\
# is stated in {ns}/Preserves.lean, `StepProp.holds` in {ns}/StepPropDefs.lean). A case that is false\n\
# shows that the property does not hold of that rule.\n"
    );
    let mut skel = String::new();
    if trans_open {
        ol.push_str(&format!(
            "StepProp.trans | {} | the property's definition\n",
            trans_stmt
        ));
        skel.push_str(&format!(
            "-- The step property is transitive:\n-- theorem StepProp.hand.trans : {} := by\n--   …\n\n",
            trans_stmt
        ));
    }
    for c in cx.ctors {
        if open.contains(&c.lean) {
            ol.push_str(&format!(
                "{} | Step.Rel.{} StepProp.holds | {}\n",
                c.lean,
                c.lean,
                c.loc.clone().unwrap_or_else(|| "no position".into())
            ));
            skel.push_str(&format!(
                "-- Rule {}:\n-- theorem StepProp.hand.{} : Step.Rel.{} StepProp.holds := by\n--   …\n\n",
                c.doc, c.lean, c.lean
            ));
        }
    }
    let hand_skeleton = ((!open.is_empty() || trans_open) && !hand_exists).then(|| {
        format!(
            "import {ns}.StepPropDefs\n\n\
/-! Hand-written proofs of the cases of the step property listed in `open-step-cases.txt`.\n\n\
`k2lean gen` wrote this file once, because it did not exist, and never changes it. Prove each case\n\
below as the theorem it names (uncomment and complete it); `StepProp.lean` uses them by name. The\n\
generated proofs use `k2l_step [{us}] [{ls}]`. -/\n\n\
namespace {ns}\n\nopen KPrelude\n\n{skel}end {ns}\n"
        )
    });
    Ok(Out {
        defs: d,
        theorems: t,
        open_list: ol,
        hand_skeleton,
    })
}
