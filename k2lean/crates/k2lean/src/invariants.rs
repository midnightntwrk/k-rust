//! Kind 1 preserved invariants (`k2lean/docs/invariants.md`, part 2): `k2lean gen --invariant NAME[@CELL]`
//! and `k2lean gen --sidecar FILE` write `{ns}/InvariantDefs.lean` and `{ns}/Invariants.lean`, and
//! beside the library `invariant-unfold.txt`, the invariant's unfolding set (below) as data for
//! `k2lean claims --assume-invariant`.
//!
//! **The predicate.** An invariant is a K function `NAME` of the definition with result `Bool`.
//! With `@CELL` its argument is the content of the cell `<CELL>` (or the cell itself), otherwise
//! the whole configuration. Its part of the predicate is `NAME (content (cell c)) = true` (`= some
//! true` when the generated function is `Option`-valued): the configurations at which K's
//! function evaluates to `true`. A KRS sidecar declares element sorts of collection cells
//! (`env: Map<Id, Value>`); its part says that every binding (element) of the cell has the
//! declared sorts, where "a `KItem` `t` has sort `S`" is `∃ y, proj_KItem_S t = some y`: the
//! generated projection is the partial inverse of the injection `inj{S, KItem}`, so it is defined
//! exactly on the injections of values of sort `S`. Several parts are conjoined into `Invariant`.
//!
//! The cell is read through one projection per level of the configuration (`Invariant.cell_env`, then
//! `Invariant.content_env`): each reduces as soon as its argument is a constructor application, so on a
//! rule that matches the cell with a variable both sides of the rule's case read the same
//! variable, and `k2l_preserve` closes it by `exact`. A cell inside cell collections (SIMPLE's
//! `<holds>` in every `<thread>`; a cell in a collection of an element of another collection) is
//! lifted to "for every element" once per collection: the part is `EntriesOn` (`ElemsOn`) of an
//! element predicate over the outermost collection, and each element predicate is the next
//! collection's predicate of the collection its element holds, down to the K function on the cell.
//!
//! **Functions of a tree of cells.** A K function of a cell sort (the top cell, or `<T>`) whose one
//! equation matches a tree of cell constructors with variables at the leaves (`topOk(<generatedTop>
//! <k> _ </k> <env> E </env> _ </generatedTop>) => φ(E)`) matches every value of the sort: each
//! cell sort has exactly one constructor, so every value is that constructor applied to its
//! projections. The generated `Invariant.f_cells : ∀ x, f x = φ(content_env (cell_env x))`, proved
//! by cases on `x`, joins the unfolding set; the equation itself rewrites only a constructor term,
//! and a rule's case has variables for the cells it does not mention. When `φ` binds partial calls
//! (`A andBool B`), the proof cases on each call, and the unfolding set gets the split of the
//! bind chain (`BIND_SPLIT`) and not the function's own definition, which would unfold first and
//! stay stuck on a rule's cell variables.
//!
//! **Preservation.** `Step.preserves_of` (`{ns}/Preserves.lean`) proves `Preserved Step Invariant` from
//! one `Step.Case.r Invariant` per rule, and each case is a theorem `Invariant.case.r` proved by `k2l_preserve`
//! in its per-case mode. A case that the tactic does not close is listed in
//! `open-invariant-cases.txt` (by `k2lean open-from-log` from a failed build) and then taken from
//! the hand-written module `{ns}/InvariantsHand.lean`, as the theorem `Invariant.hand.r` of the same
//! statement. The generator writes that module only when it does not exist (a skeleton with the
//! statements in comments) and never changes it afterwards, so a missing hand proof fails the
//! build at `Invariant.case.r` with "unknown identifier 'Invariant.hand.r'", naming the rule.
//!
//! **Unfolding.** The tactic is given the parts, the projections, the K equations (`Eqn.*` of
//! `{ns}/Equations.lean`, the `owise` ones included, as rewrites conditional on their side
//! condition) of the non-recursive functions the invariant calls, and, for each
//! recursive function that is a list fold (`f(.List, P…) => true`, `f(ListItem(X) L, P…) =>
//! φ(X, P…) andBool f(L, P…)`, the parameters `P…` passed unchanged), the theorem that `f l p =
//! some true` exactly when every element satisfies `φ(·, p)` (`ListHook.all_iff_of_eqns`, from the
//! two equations, which `k2l_fold_eqn` proves from the definition). Lists are freely generated by
//! `.List` and `ListItem(X) L`, so for fixed parameters the two equations determine `f`; the
//! element-wise form is what the collection lemmas of `KPrelude.InvColl` read. A recursive
//! function that is structurally recursive on a constructor argument (`even(s(s(N))) =>
//! even(N)`), not mutually recursive, with proved equations, gets its equations: rewriting with
//! them replaces a call on a constructor term by calls on its strict subterms, so it terminates.
//!
//! **Map walks.** A recursive function the invariant calls with the equations `f(.Map, P…) =>
//! true` and `f((K |-> V) R, P…) => φ(K, V, P…) andBool f(R, P…)` (the map possibly the content
//! of a cell, `<threads>` and its cell map; `K`, `V` trees of cells with variables at the leaves)
//! lowers to `MapHook.chooseFirst`, whose recursive call is on the rest of the binding it picks,
//! so it is neither a fold nor structural. Its test of one binding, `Invariant.f_test k v p`, reads
//! the patterns' variables through projections (each cell sort has one constructor, so the
//! patterns match every binding up to the equality of a variable read twice), and
//! `Invariant.f_walk : f m p = some true ↔ WF m ∧ EntriesOn (test) m` is proved from the function's
//! instances (`F.eq_instances`) and its unit equation by `MapHook.all_iff_of_walk`: by induction on
//! the number of bindings, a `true` value is a binding that passes with a `true` rest, and a map
//! whose every binding passes has the value `true` at every binding, whichever comes first. Both
//! join the unfolding set, so the invariant reads as
//! `EntriesOn` facts, which the collection lemmas and `MapHook.wf_of_concat` and its kin read.
//!
//! **Maps built on an `Int` range.** A function of the definition (called by a rule, not
//! necessarily by the invariant) with the two equations `f(A, B, P…) => .Map requires A >Int B`
//! and `f(A, B, P…) => K(A) |-> V f(A +Int 1, B, P…) requires A <=Int B` (SIMPLE's `N ... M |->
//! K`) gets the `@[k2l_coll]` theorem `Invariant.range_f`: a result of `f` satisfies `EntriesOn
//! Q` for every `Q` that holds of `(K(a), V)` for all `a`. Above the bound the result is `.Map`,
//! within it the second equation adds `K(a) |-> V` to the result from `a + 1`, which has one key
//! fewer left, so by induction on `(b + 1 - a).toNat` every binding is some `(K(a), V)`
//! (`MapHook.entriesOn_of_range`, with the two proved equations as its hypotheses). The
//! collections closer applies it to the map a rule's right-hand side binds to a call of `f`.
//!
//! **Initial configurations.** `init` (`{ns}/Init.lean`) has one parameter per configuration
//! variable. A part whose cell holds a configuration variable in `init` holds there exactly when
//! the part's predicate holds of that variable, which becomes a hypothesis of `Invariant.init_holds`; a
//! part whose cell holds a closed term is proved by computation; any other part makes the init
//! theorem an obligation (`init` in `open-invariant-cases.txt`, `Invariant.hand.init`). The corollaries
//! `Invariant.star` and `Invariant.stepsN` say that every configuration reachable from `init` satisfies `Invariant`.

