/// A predicate over one collection element, rendered from the element's Lean name.
type Pred = Box<dyn Fn(&str) -> String>;

/// `--invariant NAME[@CELL]`.
#[derive(Clone, Debug)]
pub struct Spec {
    pub name: String,
    pub cell: Option<String>,
}

pub fn parse_spec(s: &str) -> Spec {
    match s.split_once('@') {
        Some((n, c)) => Spec {
            name: n.to_string(),
            cell: Some(c.trim_start_matches('<').trim_end_matches('>').to_string()),
        },
        None => Spec {
            name: s.to_string(),
            cell: None,
        },
    }
}

/// One declared cell type of a KRS sidecar (`k2lean/docs/design.md`, "The KRS sidecar"), keyed by KORE
/// names: the cell's symbol and the declared element sorts.
#[derive(Clone, Debug)]
pub struct Declared {
    /// The cell's KORE symbol (`Lbl'-LT-'env'-GT-'`).
    pub cell: String,
    /// The KRS declaration, for the documentation (`env: Map<Id, Value>`).
    pub krs: String,
    pub coll: Coll,
    /// `[key, value]` for a map, `[element]` for a list or a set: KORE sort names.
    pub sorts: Vec<String>,
}

/// Read a sidecar (format `k2lean-krs-sidecar`, version 1; `k2lean/docs/design.md`, "The KRS sidecar").
pub fn read_sidecar(path: &Path) -> Result<Vec<Declared>, String> {
    let text = std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
    let j: serde_json::Value =
        serde_json::from_str(&text).map_err(|e| format!("{}: {e}", path.display()))?;
    if j["format"].as_str() != Some("k2lean-krs-sidecar") || j["version"].as_u64() != Some(1) {
        return Err(format!(
            "{}: not a k2lean-krs-sidecar, version 1",
            path.display()
        ));
    }
    let mut out = Vec::new();
    for c in j["cells"]
        .as_array()
        .ok_or("sidecar: `cells` must be an array")?
    {
        let s = |k: &str| c[k].as_str().map(|x| x.to_string());
        let cell = s("cell").ok_or("sidecar: a cell without `cell`")?;
        let (coll, sorts) = match s("collection").as_deref() {
            Some("Map") => (
                Coll::Map,
                vec![
                    s("key").ok_or("sidecar: a Map without `key`")?,
                    s("value").ok_or("sidecar: a Map without `value`")?,
                ],
            ),
            Some("List") => (
                Coll::List,
                vec![s("element").ok_or("sidecar: a List without `element`")?],
            ),
            Some("Set") => (
                Coll::Set,
                vec![s("element").ok_or("sidecar: a Set without `element`")?],
            ),
            other => {
                return Err(format!(
                    "sidecar: cell {cell}: collection {other:?} is not Map, List or Set"
                ));
            }
        };
        out.push(Declared {
            krs: s("krs").unwrap_or_default(),
            cell,
            coll,
            sorts,
        });
    }
    Ok(out)
}

/// The function symbol an invariant names: its K label up to `(` (as `--extra-fns`).
pub fn resolve(def: &Def, name: &str) -> Result<String, String> {
    let hits: Vec<&String> = def
        .symbols
        .iter()
        .filter(|(sym, d)| {
            let l = names::demangle(sym);
            d.is_function() && (l == name || l.starts_with(&format!("{name}(")))
        })
        .map(|(s, _)| s)
        .collect();
    match hits.as_slice() {
        [s] => Ok((*s).clone()),
        [] => Err(format!(
            "--invariant {name}: no function of the definition is named {name}"
        )),
        _ => Err(format!(
            "--invariant {name}: several functions are named {name}: {hits:?}"
        )),
    }
}

/// One level of a cell path: the constructor `ctor` (of `sort`) and the argument `index` that holds
/// the next cell.
#[derive(Clone, Debug)]
struct Level {
    sort: String,
    lean: String,
    arity: usize,
    index: usize,
    child: String,
    /// The child cell's name (`env`), for the projection's name.
    name: String,
    sym: String,
}

/// The cell collection on a cell path (SIMPLE's `<thread>` cell map, inside `<threads>`): the
/// cell that holds it, and the collection's sort and element sorts.
#[derive(Clone, Debug)]
struct CollLevel {
    /// The holding cell (`<threads>`): its sort, constructor (Lean, full), arity, symbol, name, and
    /// the argument that is the collection.
    holder_sort: String,
    holder_lean: String,
    holder_arity: usize,
    holder_sym: String,
    holder_name: String,
    index: usize,
    /// The collection sort (`SortThreadCellMap`) and its kind.
    sort: String,
    kind: Coll,
    /// `[key, value]` for a cell map, `[element]` for a cell list or set: the element cell is the
    /// last one.
    elems: Vec<String>,
}

/// The path from the top cell to a cell.
#[derive(Clone, Debug)]
struct CellPath {
    /// From the top cell to the cell (or, with `colls`, to the cell holding the first collection).
    levels: Vec<Level>,
    /// The cell collections the cell is inside, outermost first, each with the path from its
    /// element cell (`<thread>`) to the cell holding the next collection, or to the cell itself
    /// for the last one.
    colls: Vec<(CollLevel, Vec<Level>)>,
    /// The cell's own constructor (Lean, full), its sort, its argument sorts.
    cell_sort: String,
    cell_lean: String,
    cell_args: Vec<String>,
    cell_sym: String,
}

/// `e`, parenthesized when it is an application.
fn paren(e: &str) -> String {
    if e.contains(' ') {
        format!("({e})")
    } else {
        e.to_string()
    }
}

fn cell_name(klabel: &str) -> Option<String> {
    let n = klabel.strip_prefix('<')?.strip_suffix('>')?;
    Some(
        n.chars()
            .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
            .collect(),
    )
}

/// The constructor of a cell sort (a sort with one own constructor whose K label is `<x>`).
fn cell_ctor<'a>(m: &'a Model, sort: &str) -> Option<&'a crate::model::CtorInfo> {
    let info = m.sorts.get(sort)?;
    let [c] = info.own.as_slice() else {
        return None;
    };
    let ci = m.ctors.get(c)?;
    cell_name(&ci.klabel).map(|_| ci)
}

fn find_cell(m: &Model, top: &str, cell: &str) -> Result<CellPath, String> {
    let want = format!("<{cell}>");
    let Some(target) = m.ctors.values().find(|c| c.klabel == want) else {
        return Err(format!("the configuration has no cell {want}"));
    };
    let target_sort = target.sort.clone();
    // depth-first from the top cell, through cell constructors only
    fn reach(m: &Model, sort: &str, target: &str, seen: &mut BTreeSet<String>) -> bool {
        if sort == target {
            return true;
        }
        if !seen.insert(sort.to_string()) {
            return false;
        }
        if let Some(ci) = cell_ctor(m, sort) {
            return ci.args.iter().any(|a| reach(m, a, target, seen));
        }
        if let Some(info) = m.sorts.get(sort)
            && matches!(info.kind, Kind::Coll(_))
        {
            return info.elems.iter().any(|e| reach(m, e, target, seen));
        }
        false
    }
    let mut levels = Vec::new();
    let mut colls: Vec<(CollLevel, Vec<Level>)> = Vec::new();
    let mut cur = top.to_string();
    while cur != target_sort {
        let ci = cell_ctor(m, &cur)
            .ok_or_else(|| format!("{cur} is not a cell sort on the way to {want}"))?;
        let mut next = None;
        for (j, a) in ci.args.iter().enumerate() {
            if reach(m, a, &target_sort, &mut BTreeSet::new()) {
                next = Some((j, a.clone()));
                break;
            }
        }
        let Some((j, a)) = next else {
            return Err(format!("{want} is not reachable from the top cell"));
        };
        if let Some(info) = m.sorts.get(&a)
            && let Kind::Coll(kind) = &info.kind
        {
            // the cell is inside a cell collection: the predicate is lifted to "for every
            // element"; the path goes on from the element cell
            let elem = info.elems.last().cloned().unwrap_or_default();
            if cell_ctor(m, &elem).is_none() {
                return Err(format!(
                    "the elements of the collection {a} on the way to {want} are {elem}, not cells"
                ));
            }
            colls.push((
                CollLevel {
                    holder_sort: cur.clone(),
                    holder_lean: format!("{}.{}", ci.sort, ci.lean),
                    holder_arity: ci.args.len(),
                    holder_sym: ci.sym.clone(),
                    holder_name: cell_name(&ci.klabel).unwrap(),
                    index: j,
                    sort: a.clone(),
                    kind: kind.clone(),
                    elems: info.elems.clone(),
                },
                Vec::new(),
            ));
            cur = elem;
            continue;
        }
        let child = cell_ctor(m, &a).ok_or_else(|| format!("{a} is not a cell sort"))?;
        let path = match colls.last_mut() {
            Some((_, inner)) => inner,
            None => &mut levels,
        };
        path.push(Level {
            sort: cur.clone(),
            lean: format!("{}.{}", ci.sort, ci.lean),
            arity: ci.args.len(),
            index: j,
            child: a.clone(),
            name: cell_name(&child.klabel).unwrap(),
            sym: ci.sym.clone(),
        });
        cur = a;
    }
    let ci =
        cell_ctor(m, &target_sort).ok_or_else(|| format!("{target_sort} is not a cell sort"))?;
    Ok(CellPath {
        levels,
        colls,
        cell_sort: target_sort,
        cell_lean: format!("{}.{}", ci.sort, ci.lean),
        cell_args: ci.args.clone(),
        cell_sym: ci.sym.clone(),
    })
}

/// A list fold recognized among the functions an invariant calls.
struct Fold {
    lean: String,
    base: String,
    list: String,
    elem: String,
    x: String,
    phi: String,
    swapped: bool,
    /// The argument position of the list, and the Lean name and sort of every other argument (a
    /// parameter the fold passes unchanged to its recursive call), in argument order.
    pos: usize,
    params: Vec<(String, String)>,
}

impl Fold {
    /// `f a₀ … aₙ` with `list` at the list's position and the parameters elsewhere.
    fn call(&self, list: &str) -> String {
        let mut args: Vec<String> = self.params.iter().map(|(n, _)| n.clone()).collect();
        args.insert(self.pos, paren(list));
        format!("{} {}", self.lean, args.join(" "))
    }

    /// ` (p₀ : S₀) …`: the parameters as binders.
    fn binders(&self) -> String {
        self.params
            .iter()
            .map(|(n, t)| format!(" ({n} : {t})"))
            .collect()
    }

    /// ` p₀ …`: the parameters as arguments.
    fn args(&self) -> String {
        self.params.iter().map(|(n, _)| format!(" {n}")).collect()
    }
}

fn hook<'a>(m: &'a Model, f: &str) -> Option<&'a str> {
    m.hooks.get(f).map(|s| s.as_str())
}

/// Whether `p` mentions the function `f` or the variable `v`.
fn mentions(p: &P, f: &str, v: &str) -> bool {
    match p {
        P::Var(n, _) => n == v,
        P::App(g, _, a) => g == f || a.iter().any(|q| mentions(q, f, v)),
        _ => false,
    }
}

/// `f(.List, P…) => true` and `f(ListItem(X) L, P…) => φ(X, P…) andBool f(L, P…)` (or
/// `f(L, P…) andBool φ(X, P…)`), with the list at any one argument position and the other
/// arguments variables that the recursive call passes unchanged; no requires, `φ` total and not
/// mentioning `f` or `L`. Lists are freely generated by `.List` and `ListItem(X) L`, so for fixed
/// parameters the two equations determine `f` on every list.
fn fold_of(m: &Model, fns: &Fns, eqs: &BTreeMap<String, Vec<Equation>>, f: &str) -> Option<Fold> {
    let sig = fns.get(f)?;
    let es = eqs.get(f)?;
    if es.len() != 2
        || sig.args.is_empty()
        || sig.result != "SortBool"
        || es.iter().any(|e| e.owise || !e.requires.is_empty())
    {
        return None;
    }
    let is_unit =
        |p: &P| matches!(p, P::App(u, _, a) if a.is_empty() && hook(m, u) == Some("LIST.unit"));
    (0..sig.args.len()).find_map(|pos| {
        let list = sig.args[pos].clone();
        if m.sorts.get(&list)?.kind != Kind::Coll(Coll::List) {
            return None;
        }
        let unit = es.iter().find(|e| is_unit(&e.args[pos]))?;
        if !matches!(&unit.rhs, P::Dv(_, v) if v == "true") {
            return None;
        }
        let cons = es.iter().find(|e| !is_unit(&e.args[pos]))?;
        let P::App(c, _, ca) = &cons.args[pos] else {
            return None;
        };
        if hook(m, c) != Some("LIST.concat") || ca.len() != 2 {
            return None;
        }
        let P::App(el, _, ea) = &ca[0] else {
            return None;
        };
        let (P::Var(xv, _), P::Var(lv, _)) = (ea.first()?, &ca[1]) else {
            return None;
        };
        if hook(m, el) != Some("LIST.element") || ea.len() != 1 || xv == lv {
            return None;
        }
        // the parameters: distinct variables in both equations, other than `X` and `L`
        let mut pvars: Vec<(usize, String)> = Vec::new();
        for j in (0..sig.args.len()).filter(|&j| j != pos) {
            let (P::Var(u, _), P::Var(v, _)) = (&unit.args[j], &cons.args[j]) else {
                return None;
            };
            let _ = u;
            if v == xv || v == lv || pvars.iter().any(|(_, w)| w == v) {
                return None;
            }
            pvars.push((j, v.clone()));
        }
        let P::App(and, _, aa) = &cons.rhs else {
            return None;
        };
        if hook(m, and) != Some("BOOL.and") || aa.len() != 2 {
            return None;
        }
        // the recursive call `f(L, P…)`: the list's tail at the list's position, each parameter
        // at its own
        let is_rec = |p: &P| {
            matches!(p, P::App(g, _, a) if g == f && a.len() == sig.args.len()
                && matches!(&a[pos], P::Var(v, _) if v == lv)
                && pvars.iter().all(|(j, w)| matches!(&a[*j], P::Var(v, _) if v == w)))
        };
        let (phi, swapped) = if is_rec(&aa[1]) {
            (&aa[0], false)
        } else if is_rec(&aa[0]) {
            (&aa[1], true)
        } else {
            return None;
        };
        if mentions(phi, f, lv) {
            return None;
        }
        let elem = m.elems(&list).first()?.clone();
        let mut lw = Lower::new(m, fns, &["l"]);
        let x = lw.param("x", &elem);
        lw.vars.insert(xv.clone(), x.clone());
        let mut params = Vec::new();
        for (j, v) in &pvars {
            let n = lw.param(&format!("p{j}"), &sig.args[*j]);
            lw.vars.insert(v.clone(), n.clone());
            params.push((n, sig.args[*j].clone()));
        }
        let e = lw.expr(phi, "SortBool").ok()?;
        if !lw.steps.is_empty() {
            return None;
        }
        let base = names::demangle(f)
            .split('(')
            .next()
            .unwrap_or("fold")
            .chars()
            .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
            .collect();
        Some(Fold {
            lean: sig.lean.clone(),
            base,
            list,
            elem,
            x,
            phi: e.render(),
            swapped,
            pos,
            params,
        })
    })
}

/// A walk over a map by a free-key pattern, recognized among the functions an invariant calls.
struct Walk {
    lean: String,
    base: String,
    /// the map's argument position, and the Lean constructor of the cell that holds it there
    /// (`<threads>` and its cell map), when the argument is that cell
    pos: usize,
    wrap: Option<String>,
    /// the sort of that cell
    cell: Option<String>,
    /// the sorts of the map, its keys and its values
    map: String,
    key: String,
    val: String,
    /// every other argument, a parameter the recursive call passes unchanged: (Lean name, sort)
    params: Vec<(String, String)>,
    /// the test of one binding `k |-> v`, a proposition over `k`, `v` and the parameters
    test: String,
    unit_eqn: String,
    /// the projections the test reads
    reads: Vec<String>,
}

impl Walk {
    /// `f a₀ … aₙ` with `map` (in its cell) at the map's position and the parameters elsewhere.
    fn call(&self, map: &str) -> String {
        let mut args: Vec<String> = self.params.iter().map(|(n, _)| n.clone()).collect();
        let arg = match &self.wrap {
            Some(c) => format!("({c} {map})"),
            None => paren(map),
        };
        args.insert(self.pos, arg);
        format!("{} {}", self.lean, args.join(" "))
    }

    /// `f a₀ … aₙ` with the term `arg` itself at the map's position.
    fn call_at(&self, arg: &str) -> String {
        let mut args: Vec<String> = self.params.iter().map(|(n, _)| n.clone()).collect();
        args.insert(self.pos, arg.to_string());
        format!("{} {}", self.lean, args.join(" "))
    }

    fn binders(&self) -> String {
        self.params
            .iter()
            .map(|(n, t)| format!(" ({n} : {t})"))
            .collect()
    }

    fn args(&self) -> String {
        self.params.iter().map(|(n, _)| format!(" {n}")).collect()
    }
}

/// `f(.Map, P…) => true` and `f((K |-> V) R, P…) => φ(K, V, P…) andBool f(R, P…)` (in that
/// order, which the generated proof of the element-wise form is checked on): the map at one argument, or the content of the cell at that argument
/// (`<threads>` and its cell map), the other arguments variables that the recursive call passes
/// unchanged, no requires, the unit equation proved; `K` and `V` variables or trees of cells
/// with variables at the leaves, where a variable read twice (a cell map's key and the element's
/// own id) means that both reads are equal; `φ` mentioning neither `f` nor `R`. Through its
/// instances (`F.eq_instances`), such a function is `true` exactly on the well-formed maps whose
/// every binding passes the test (`MapHook.all_iff_of_walk`): a `true` value at a nonempty map is
/// the value at a binding whose test holds and whose rest is `true`, and a map whose every binding
/// passes and has a `true` rest has the value `true` at every binding. The test reads the
/// binding's cells through projections, so it reduces on a rule's rebuilt element whose cells are
/// variables, where a match on the patterns would not.
fn walk_of(
    cx: &Ctx,
    f: &str,
    projections: &mut BTreeMap<String, String>,
    proj_names: &mut Vec<String>,
) -> Option<Walk> {
    let m = cx.m;
    let sig = cx.fns.get(f)?;
    let es = cx.eqs.get(f)?;
    if es.len() != 2
        || !sig.partial
        || sig.result != "SortBool"
        || es.iter().any(|e| e.owise || !e.requires.is_empty())
    {
        return None;
    }
    let is_map = |s: &str| {
        m.sorts
            .get(s)
            .is_some_and(|i| i.kind == Kind::Coll(Coll::Map))
    };
    let (pos, wrap_sym, map) = (0..sig.args.len()).find_map(|j| {
        let a = &sig.args[j];
        if is_map(a) {
            return Some((j, None, a.clone()));
        }
        let c = cell_ctor(m, a)?;
        match c.args.as_slice() {
            [inner] if is_map(inner) => Some((j, Some(c.sym.clone()), inner.clone())),
            _ => None,
        }
    })?;
    let unwrap = |p: &P| -> Option<P> {
        match (&wrap_sym, p) {
            (None, _) => Some(p.clone()),
            (Some(w), P::App(s, _, a)) if s == w && a.len() == 1 => Some(a[0].clone()),
            _ => None,
        }
    };
    let is_unit =
        |p: &P| matches!(p, P::App(u, _, a) if a.is_empty() && hook(m, u) == Some("MAP.unit"));
    let i_unit = es
        .iter()
        .position(|e| unwrap(&e.args[pos]).is_some_and(|p| is_unit(&p)))?;
    let (unit, step) = (&es[i_unit], &es[1 - i_unit]);
    if !matches!(&unit.rhs, P::Dv(_, t) if t == "true")
        || (0..sig.args.len()).any(|j| j != pos && !matches!(&unit.args[j], P::Var(..)))
    {
        return None;
    }
    // the free-key pattern `(K |-> V) R`
    let P::App(c, _, ca) = unwrap(&step.args[pos])? else {
        return None;
    };
    if hook(m, &c) != Some("MAP.concat") || ca.len() != 2 {
        return None;
    }
    // `(K |-> V) R`, the binding first: the shape the generated proof is checked on
    let (el, rest) = match (&ca[0], &ca[1]) {
        (P::App(e, _, ea), P::Var(r, _)) if hook(m, e) == Some("MAP.element") => (ea, r),
        _ => return None,
    };
    let [kp, vp] = el.as_slice() else {
        return None;
    };
    // the parameters: distinct variables, not read by the pattern
    let mut in_pat = Vec::new();
    free_vars(kp, &mut in_pat);
    free_vars(vp, &mut in_pat);
    let mut pvars: Vec<(usize, String)> = Vec::new();
    for j in (0..sig.args.len()).filter(|&j| j != pos) {
        let P::Var(v, _) = &step.args[j] else {
            return None;
        };
        if v == rest || in_pat.contains(v) || pvars.iter().any(|(_, w)| w == v) {
            return None;
        }
        pvars.push((j, v.clone()));
    }
    let P::App(and, _, aa) = &step.rhs else {
        return None;
    };
    if hook(m, and) != Some("BOOL.and") || aa.len() != 2 {
        return None;
    }
    let is_rec = |p: &P| {
        matches!(p, P::App(g, _, a) if g == f && a.len() == sig.args.len()
            && unwrap(&a[pos]).is_some_and(|x| matches!(x, P::Var(v, _) if v == *rest))
            && pvars.iter().all(|(j, w)| matches!(&a[*j], P::Var(v, _) if v == w)))
    };
    // `φ andBool f(R, P…)`, the test first: the shape the generated proof is checked on
    if !is_rec(&aa[1]) {
        return None;
    }
    let phi = &aa[0];
    if mentions(phi, f, rest) {
        return None;
    }
    // every binding matches a pattern that is a tree of cells (each sort's only constructor)
    // with variables at the leaves, up to the equalities of a variable read twice
    fn cells_only(m: &Model, p: &P) -> bool {
        match p {
            P::Var(..) => true,
            P::App(s, _, args) => m.ctors.get(s).is_some_and(|ci| {
                cell_ctor(m, &ci.sort).is_some_and(|c| c.sym == *s)
                    && args.len() == ci.args.len()
                    && args.iter().all(|a| cells_only(m, a))
            }),
            _ => false,
        }
    }
    if !cells_only(m, kp) || !cells_only(m, vp) {
        return None;
    }
    // the variables the test reads: those of `φ`, and those the patterns read twice
    let mut need = Vec::new();
    free_vars(phi, &mut need);
    fn count(p: &P, out: &mut BTreeMap<String, usize>) {
        match p {
            P::Var(v, _) => *out.entry(v.clone()).or_default() += 1,
            P::App(_, _, a) => a.iter().for_each(|q| count(q, out)),
            _ => {}
        }
    }
    let mut seen = BTreeMap::new();
    count(kp, &mut seen);
    count(vp, &mut seen);
    need.extend(seen.into_iter().filter(|(_, n)| *n > 1).map(|(v, _)| v));
    // the reads of those variables off `k` and `v`, through one projection per cell
    #[allow(clippy::too_many_arguments)]
    fn reads(
        m: &Model,
        p: &P,
        at: String,
        need: &[String],
        out: &mut Vec<(String, String)>,
        projections: &mut BTreeMap<String, String>,
        proj_names: &mut Vec<String>,
    ) -> Option<()> {
        match p {
            P::Var(v, _) => {
                if need.contains(v) {
                    out.push((v.clone(), at));
                }
                Some(())
            }
            P::App(s, _, args) => {
                let ci = m.ctors.get(s)?;
                if cell_ctor(m, &ci.sort)?.sym != *s || args.len() != ci.args.len() {
                    return None;
                }
                for (i, a) in args.iter().enumerate() {
                    let mut vs = Vec::new();
                    free_vars(a, &mut vs);
                    if !vs.iter().any(|v| need.contains(v)) {
                        continue;
                    }
                    let n = proj_arg(m, s, i, projections, proj_names)?;
                    reads(
                        m,
                        a,
                        format!("({n} {at})"),
                        need,
                        out,
                        projections,
                        proj_names,
                    )?;
                }
                Some(())
            }
            _ => None,
        }
    }
    let (mut projs, mut names_new) = (projections.clone(), proj_names.clone());
    let mut rd: Vec<(String, String)> = Vec::new();
    reads(
        m,
        kp,
        "k".into(),
        &need,
        &mut rd,
        &mut projs,
        &mut names_new,
    )?;
    reads(
        m,
        vp,
        "v".into(),
        &need,
        &mut rd,
        &mut projs,
        &mut names_new,
    )?;
    let eq_name = |i: usize| {
        format!(
            "Eqn.{}",
            names::ident(&format!("{}_{}", names::demangle(f), i + 1))
        )
    };
    let unit_eqn = eq_name(i_unit);
    if !cx.stated.contains(&unit_eqn) || cx.open_eqns.contains(&unit_eqn) {
        return None;
    }
    let mut lw = Lower::new(
        m,
        cx.fns,
        &["k", "v", "m", "q", "h", "hu", "hw", "hb", "hk", "hr"],
    );
    let mut params = Vec::new();
    for (j, v) in &pvars {
        let n = lw.param(&crate::lower::sanitize(v), &sig.args[*j]);
        lw.vars.insert(v.clone(), n.clone());
        params.push((n, sig.args[*j].clone()));
    }
    // a variable read twice: the reads are equal
    let mut conj = Vec::new();
    for (i, (v, r)) in rd.iter().enumerate() {
        match rd[..i].iter().find(|(w, _)| w == v) {
            Some((_, first)) => conj.push(format!("{r} = {first}")),
            None => {
                lw.vars.insert(v.clone(), r.clone());
            }
        }
    }
    let e = lw.expr(phi, "SortBool").ok()?;
    let steps = std::mem::take(&mut lw.steps);
    conj.push(match steps.as_slice() {
        [] => format!("{} = true", e.render()),
        [crate::lower::Step::Bind { expr, var, .. }] if e.render() == *var => {
            format!("{} = some true", expr.render_arg())
        }
        _ => format!("{} = some true", option_expr(&steps, &e)?),
    });
    let elems = m.elems(&map);
    let (key, val) = (elems.first()?.clone(), elems.get(1)?.clone());
    let added: Vec<String> = names_new
        .iter()
        .filter(|n| !proj_names.contains(n))
        .cloned()
        .collect();
    let used: Vec<String> = names_new
        .iter()
        .filter(|n| rd.iter().any(|(_, r)| r.contains(&format!("({n} "))))
        .cloned()
        .collect();
    *projections = projs;
    proj_names.extend(added);
    let (wrap, cell) = match &wrap_sym {
        Some(s) => {
            let ci = m.ctors.get(s)?;
            (
                Some(format!("{}.{}", ci.sort, ci.lean)),
                Some(ci.sort.clone()),
            )
        }
        None => (None, None),
    };
    let base = names::demangle(f)
        .split('(')
        .next()
        .unwrap_or("walk")
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect();
    Some(Walk {
        lean: sig.lean.clone(),
        base,
        pos,
        wrap,
        cell,
        map,
        key,
        val,
        params,
        test: conj.join(" ∧ "),
        unit_eqn,
        reads: used,
    })
}

/// A map built by recursion on an `Int` range, recognized among the functions of the definition.
struct Range {
    lean: String,
    /// `Eqn.…` of the equation above the bound and of the one within it
    above: String,
    within: String,
    /// the theorem's implicit binders after `a` and `b`: the other arguments' variables
    binders: Vec<(String, String)>,
    /// the arguments after the two bounds, the key (of `a`) and the value, rendered
    rest: Vec<String>,
    key: String,
    val: String,
    map: String,
    entry: String,
}

/// The condition `h(X, Y) = true` of a requires clause, with `h` a hook: `(h, X, Y)`.
fn hook_test<'a>(m: &'a Model, p: &'a P) -> Option<(&'a str, &'a P, &'a P)> {
    let P::Equals(_, _, l, r) = p else {
        return None;
    };
    let (P::App(h, _, a), P::Dv(_, t)) = (&**l, &**r) else {
        return None;
    };
    if t != "true" || a.len() != 2 {
        return None;
    }
    Some((hook(m, h)?, &a[0], &a[1]))
}

/// `f(A, B, P…) => .Map requires A >Int B` and `f(A, B, P…) => K(A) |-> V f(A +Int 1, B, P…)
/// requires A <=Int B` (SIMPLE's `N ... M |-> K`), the recursive call passing the other
/// arguments unchanged, `V` mentioning neither `A` nor `f`, `K(A)` no variable but `A`, both
/// equations proved. Their instances for `a` from a start up to `b + 1` determine the result,
/// which binds `V` at every key `K(a)` (`MapHook.entriesOn_of_range`).
fn range_of(
    m: &Model,
    fns: &Fns,
    eqs: &BTreeMap<String, Vec<Equation>>,
    proved: &dyn Fn(&str) -> bool,
    f: &str,
) -> Option<Range> {
    let sig = fns.get(f)?;
    let es = eqs.get(f)?;
    if es.len() != 2
        || !sig.partial
        || sig.args.len() < 2
        || sig.args[0] != "SortInt"
        || sig.args[1] != "SortInt"
        || m.sorts.get(&sig.result)?.kind != Kind::Coll(Coll::Map)
        || es.iter().any(|e| e.owise || e.requires.len() != 1)
    {
        return None;
    }
    let bounds = |e: &Equation, h: &str| -> Option<(String, String)> {
        let (P::Var(a, _), P::Var(b, _)) = (&e.args[0], &e.args[1]) else {
            return None;
        };
        let (t, x, y) = hook_test(m, &e.requires[0])?;
        let ok = t == h
            && matches!(x, P::Var(v, _) if v == a)
            && matches!(y, P::Var(v, _) if v == b)
            && a != b;
        ok.then(|| (a.clone(), b.clone()))
    };
    let is_unit =
        |p: &P| matches!(p, P::App(u, _, a) if a.is_empty() && hook(m, u) == Some("MAP.unit"));
    let i_above = es.iter().position(|e| is_unit(&e.rhs))?;
    let (above, within) = (&es[i_above], &es[1 - i_above]);
    bounds(above, "INT.gt")?;
    // the other arguments of the equation above the bound must be variables, so that it applies
    // to the other equation's arguments
    if above.args[2..].iter().any(|p| !matches!(p, P::Var(..))) {
        return None;
    }
    let (a, b) = bounds(within, "INT.le")?;
    let P::App(c, _, ca) = &within.rhs else {
        return None;
    };
    if hook(m, c) != Some("MAP.concat") || ca.len() != 2 {
        return None;
    }
    let (P::App(el, _, ea), P::App(g, _, ra)) = (&ca[0], &ca[1]) else {
        return None;
    };
    if hook(m, el) != Some("MAP.element") || ea.len() != 2 || g != f || ra.len() != sig.args.len() {
        return None;
    }
    let succ = matches!(&ra[0], P::App(add, _, xa) if hook(m, add) == Some("INT.add")
        && matches!(xa.as_slice(), [P::Var(v, _), P::Dv(_, one)] if v == &a && one == "1"));
    if !succ || !matches!(&ra[1], P::Var(v, _) if v == &b) {
        return None;
    }
    // the other arguments: a pattern, or a pattern named by an alias (`P #as X`, which the
    // recursive call may pass as `X`); the recursive call passes each unchanged
    let mut pats: Vec<(&P, Option<&String>)> = Vec::new();
    for (j, p) in within.args.iter().enumerate().skip(2) {
        let (pat, alias) = match p {
            P::And(_, xs) if xs.len() == 2 => match (&xs[0], &xs[1]) {
                (q, P::Var(x, _)) | (P::Var(x, _), q) => (q, Some(x)),
                _ => return None,
            },
            _ => (p, None),
        };
        let same = &ra[j] == p || matches!((&ra[j], alias), (P::Var(v, _), Some(x)) if v == x);
        if !same {
            return None;
        }
        pats.push((pat, alias));
    }
    let aliases: Vec<&String> = pats.iter().filter_map(|(_, x)| *x).collect();
    let (key, val) = (&ea[0], &ea[1]);
    let mut kv = Vec::new();
    free_vars(key, &mut kv);
    if mentions(val, f, &a) || mentions(key, f, "") || kv.iter().any(|v| v != &a) {
        return None;
    }
    let eq_name = |i: usize| {
        format!(
            "Eqn.{}",
            names::ident(&format!("{}_{}", names::demangle(f), i + 1))
        )
    };
    let (n_above, n_within) = (eq_name(i_above), eq_name(1 - i_above));
    if !proved(&n_above) || !proved(&n_within) {
        return None;
    }
    let elems = m.elems(&sig.result);
    let (ks, vs) = (elems.first()?.clone(), elems.get(1)?.clone());
    let mut lw = Lower::new(m, fns, &["a", "b", "Q", "r", "h", "hq", "ha"]);
    lw.vars.insert(a.clone(), "a".into());
    lw.vars.insert(b.clone(), "b".into());
    let mut vars = Vec::new();
    for p in pats.iter().map(|(p, _)| *p).chain([val]) {
        free_vars(p, &mut vars);
    }
    let mut binders = Vec::new();
    for v in vars
        .iter()
        .filter(|v| **v != a && **v != b && !aliases.contains(v))
    {
        let sort = pats
            .iter()
            .map(|(p, _)| *p)
            .chain([val])
            .find_map(|p| var_sort(p, v))?;
        let n = lw.param(&crate::lower::sanitize(v), &sort);
        lw.vars.insert(v.clone(), n.clone());
        binders.push((n, sort));
    }
    let mut rest = Vec::new();
    for (j, (p, alias)) in pats.iter().enumerate() {
        let e = lw.expr(p, &sig.args[j + 2]).ok()?.render_arg();
        if let Some(x) = alias {
            lw.vars.insert((*x).clone(), e.clone());
        }
        rest.push(e);
    }
    let key = lw.expr(key, &ks).ok()?.render();
    let val = lw.expr(val, &vs).ok()?.render_arg();
    if !lw.steps.is_empty() {
        return None;
    }
    Some(Range {
        lean: sig.lean.clone(),
        above: n_above,
        within: n_within,
        binders,
        rest,
        key,
        val,
        map: sig.result.clone(),
        entry: format!("{ks} × {vs}"),
    })
}

/// The sort of the variable `v` in `p`.
fn var_sort(p: &P, v: &str) -> Option<String> {
    match p {
        P::Var(n, s) if n == v => crate::model::sort_name(s),
        P::App(_, _, a) => a.iter().find_map(|q| var_sort(q, v)),
        _ => None,
    }
}

/// Whether the K equations of the recursive function `f` can join the unfolding set as rewrite
/// rules: `f` is not mutually recursive with another function, and for some argument position
/// `j`, every non-`owise` equation that calls `f` (in its right-hand side or requires) has a
/// constructor pattern at `j` and passes, at `j` of each recursive call, a variable bound inside
/// that pattern. Rewriting with such equations replaces a call on a constructor term by calls
/// on strict subterms of it, so it terminates, and each equation is a proved theorem of the
/// library (`Eqn.*`), so it is sound.
fn structural(def: &Def, m: &Model, eqs: &BTreeMap<String, Vec<Equation>>, f: &str) -> bool {
    let Some(es) = eqs.get(f) else { return false };
    // no mutual recursion: no function `f` calls calls `f` back
    let mut callees = BTreeSet::new();
    for e in es {
        for p in e
            .args
            .iter()
            .chain(&e.requires)
            .chain(std::iter::once(&e.rhs))
        {
            crate::funcs::applied(p, def, &mut callees);
        }
    }
    if callees
        .iter()
        .any(|c| c != f && closure(def, eqs, c).contains(f))
    {
        return false;
    }
    fn calls<'a>(p: &'a P, f: &str, out: &mut Vec<&'a [P]>) {
        match p {
            P::App(g, _, a) => {
                if g == f {
                    out.push(a);
                }
                a.iter().for_each(|q| calls(q, f, out));
            }
            P::And(_, ps) | P::Or(_, ps) => ps.iter().for_each(|q| calls(q, f, out)),
            P::Not(_, a) => calls(a, f, out),
            P::Equals(_, _, a, b) | P::In(_, _, a, b) | P::Implies(_, a, b) => {
                calls(a, f, out);
                calls(b, f, out);
            }
            _ => {}
        }
    }
    fn vars_in(p: &P, out: &mut BTreeSet<String>) {
        match p {
            P::Var(v, _) => {
                out.insert(v.clone());
            }
            P::App(_, _, a) => a.iter().for_each(|q| vars_in(q, out)),
            _ => {}
        }
    }
    // a constructor application, possibly under injections
    let ctor = |p: &P| -> bool {
        let mut p = p;
        while let P::App(g, _, a) = p {
            if g == "inj" && a.len() == 1 {
                p = &a[0];
                continue;
            }
            return m.ctors.contains_key(g) && !m.anywhere.contains(g);
        }
        false
    };
    let arity = es.first().map_or(0, |e| e.args.len());
    (0..arity).any(|j| {
        es.iter().filter(|e| !e.owise).all(|e| {
            let mut rec = Vec::new();
            for p in e.requires.iter().chain(std::iter::once(&e.rhs)) {
                calls(p, f, &mut rec);
            }
            if rec.is_empty() {
                return true;
            }
            if !ctor(&e.args[j]) {
                return false;
            }
            let mut inside = BTreeSet::new();
            vars_in(&e.args[j], &mut inside);
            rec.iter()
                .all(|a| matches!(a.get(j), Some(P::Var(v, _)) if inside.contains(v)))
        })
    })
}

/// A function of one argument whose only equation (no `owise`, no requires) matches a tree of
/// cell constructors with variables at its leaves (`topOk(<generatedTop> <k> _ </k> <env> E </env>
/// _ </generatedTop>)`, `f(<T> <store> S </store> ... </T>)`): its value at any `x` of the cell
/// sort, read through one projection per level.
struct CellTree {
    /// `Invariant.f_cells`
    name: String,
    /// The theorem: `∀ x, f x = rhs[v ↦ the projection of x at v's position]`.
    theorem: String,
    /// The KORE variables of the pattern and their positions (constructor symbol, argument)
    /// below the root, and the right-hand side, for `init`.
    vars: Vec<(String, Vec<(String, usize)>)>,
    rhs: P,
    /// Whether the right-hand side binds partial calls (`Option.bind`), which
    /// `KPrelude.bind_bool_eq_some_true` splits.
    binds: bool,
}

/// What splits a chain of `Option.bind`s over partial `Bool` calls equated to `some true`
/// (`f_cells` of a function whose right-hand side is `A andBool B`): the split of one link, the
/// connectives at constants, and the propositional clean-up of the branches that fail.
const BIND_SPLIT: &[&str] = &[
    "KPrelude.bind_bool_eq_some_true",
    "KPrelude.BoolHook.and",
    "KPrelude.BoolHook.or",
    "KPrelude.BoolHook.not",
    "Option.some.injEq",
    "Bool.false_eq_true",
    "and_false",
    "false_and",
    "or_false",
    "false_or",
];

/// The variables of a pattern, in order (for the right-hand side of an equation).
fn free_vars(p: &P, out: &mut Vec<String>) {
    match p {
        P::Var(v, _) => {
            if !out.contains(v) {
                out.push(v.clone());
            }
        }
        P::App(_, _, a) => a.iter().for_each(|q| free_vars(q, out)),
        P::And(_, ps) | P::Or(_, ps) => ps.iter().for_each(|q| free_vars(q, out)),
        P::Not(_, a) => free_vars(a, out),
        P::Equals(_, _, a, b) | P::In(_, _, a, b) | P::Implies(_, a, b) => {
            free_vars(a, out);
            free_vars(b, out);
        }
        _ => {}
    }
}

/// Render a term whose lowering pushed `Bind` steps as an `Option` expression.
fn option_expr(steps: &[crate::lower::Step], value: &crate::lower::L) -> Option<String> {
    let mut e = format!("some {}", value.render_arg());
    for s in steps.iter().rev() {
        match s {
            crate::lower::Step::Bind { expr, var, .. } => {
                e = format!("(Option.bind {} fun {var} => {e})", expr.render_arg())
            }
            _ => return None,
        }
    }
    Some(e)
}

/// The name of the projection of argument `i` of the cell constructor `sym` (`proj_arg`).
fn proj_name(m: &Model, sym: &str, i: usize) -> Option<String> {
    let ci = m.ctors.get(sym)?;
    let a = ci.args.get(i)?;
    match cell_ctor(m, a) {
        Some(child) => Some(format!("Invariant.cell_{}", cell_name(&child.klabel)?)),
        None if ci.args.len() == 1 => Some(format!("Invariant.content_{}", cell_name(&ci.klabel)?)),
        None => None,
    }
}

/// The projection of argument `i` of the cell constructor `sym` (`Invariant.cell_x` for a
/// subcell, `Invariant.content_x` for the content of a leaf cell), defined once; returns its name.
fn proj_arg(
    m: &Model,
    sym: &str,
    i: usize,
    projections: &mut BTreeMap<String, String>,
    proj_names: &mut Vec<String>,
) -> Option<String> {
    let ci = m.ctors.get(sym)?;
    let a = ci.args.get(i)?;
    if let Some(child) = cell_ctor(m, a) {
        return Some(proj_level(
            &Level {
                sort: ci.sort.clone(),
                lean: format!("{}.{}", ci.sort, ci.lean),
                arity: ci.args.len(),
                index: i,
                child: a.clone(),
                name: cell_name(&child.klabel)?,
                sym: sym.to_string(),
            },
            projections,
            proj_names,
        ));
    }
    if ci.args.len() != 1 {
        return None;
    }
    let cname = cell_name(&ci.klabel)?;
    let name = format!("Invariant.content_{cname}");
    projections.entry(name.clone()).or_insert_with(|| {
        proj_names.push(name.clone());
        format!(
            "/-- The content of a `<{cname}>` cell. -/\ndef {name} : {} → {}\n  | {}.{} x => x\n",
            ci.sort, a, ci.sort, ci.lean
        )
    });
    Some(name)
}

#[allow(clippy::too_many_arguments)]
fn cell_tree(
    cx: &Ctx,
    sym: &str,
    base: &str,
    arg: &str,
    stated_eqn: Option<&str>,
    projections: &mut BTreeMap<String, String>,
    proj_names: &mut Vec<String>,
) -> Option<CellTree> {
    let m = cx.m;
    let es = cx.eqs.get(sym)?;
    let [e] = es.as_slice() else { return None };
    if e.owise || !e.requires.is_empty() || e.args.len() != 1 {
        return None;
    }
    // the tree: cell constructors (each the only constructor of its sort) down to variables
    fn walk(
        m: &Model,
        p: &P,
        path: &mut Vec<(String, usize)>,
        vars: &mut Vec<(String, Vec<(String, usize)>)>,
        pat: &mut String,
    ) -> Option<()> {
        match p {
            P::Var(v, _) => {
                if vars.iter().any(|(w, _)| w == v) {
                    return None;
                }
                vars.push((v.clone(), path.clone()));
                pat.push('_');
                Some(())
            }
            P::App(s, _, args) => {
                let ci = m.ctors.get(s)?;
                let own = cell_ctor(m, &ci.sort)?;
                if own.sym != *s || args.len() != ci.args.len() {
                    return None;
                }
                pat.push('⟨');
                for (i, a) in args.iter().enumerate() {
                    if i > 0 {
                        pat.push_str(", ");
                    }
                    path.push((s.clone(), i));
                    walk(m, a, path, vars, pat)?;
                    path.pop();
                }
                pat.push('⟩');
                Some(())
            }
            _ => None,
        }
    }
    if !matches!(&e.args[0], P::App(..)) {
        return None;
    }
    let mut vars = Vec::new();
    let mut pat = String::new();
    walk(m, &e.args[0], &mut vec![], &mut vars, &mut pat)?;
    let sig = cx.fns.get(sym)?;
    let mut used = Vec::new();
    free_vars(&e.rhs, &mut used);
    let mut lw = Lower::new(m, cx.fns, &["x"]);
    for (v, path) in &vars {
        if !used.contains(v) {
            continue;
        }
        let mut r = "x".to_string();
        for (s, i) in path {
            let n = proj_arg(m, s, *i, projections, proj_names)?;
            r = format!("({n} {r})");
        }
        lw.vars.insert(v.clone(), r);
    }
    let rhs = lw.expr(&e.rhs, &sig.result).ok()?;
    let steps = std::mem::take(&mut lw.steps);
    let call = format!("{} x", sig.lean);
    let concl = match (sig.partial, steps.is_empty()) {
        (false, true) => format!("{call} = {}", rhs.render()),
        (true, true) => format!("{call} = some {}", rhs.render_arg()),
        (true, false) => format!("{call} = {}", option_expr(&steps, &rhs)?),
        (false, false) => format!("some ({call}) = {}", option_expr(&steps, &rhs)?),
    };
    let name = format!("Invariant.{base}_cells");
    let by_eqn = stated_eqn
        .map(|n| format!(" | exact ({n} ..)"))
        .unwrap_or_default();
    // With partial calls on the right-hand side, the function's match on each call's result and
    // the right-hand side's `Option.bind` on it agree once that result is a constructor: the
    // last alternative names the pattern's variables, unfolds the function and the projections,
    // and cases on each call in order (a later call may use an earlier one's value). One call
    // whose value is the result (`A.bind fun r => some r`) is `A` by `Option.bind_fun_some`,
    // which every unfolding set has, so it needs neither this nor `BIND_SPLIT`.
    let binds = match steps.as_slice() {
        [] => false,
        [crate::lower::Step::Bind { var, .. }] => rhs.render() != *var,
        _ => true,
    };
    let mut chain = String::new();
    if binds {
        let mut names_of: BTreeMap<&str, String> = BTreeMap::new();
        for (v, _) in &vars {
            if used.contains(v) {
                names_of.insert(v, format!("y{}", names_of.len()));
            }
        }
        let reserved: Vec<&str> = std::iter::once("x")
            .chain(names_of.values().map(String::as_str))
            .collect();
        let mut lw = Lower::new(m, cx.fns, &reserved);
        for (v, n) in &names_of {
            lw.vars.insert(v.to_string(), n.clone());
        }
        lw.expr(&e.rhs, &sig.result).ok()?;
        let mut cases = String::new();
        for s in &lw.steps {
            let crate::lower::Step::Bind { expr, var, .. } = s else {
                return None;
            };
            cases.push_str(&format!(
                "; (rcases {} with _ | {var}) <;> (try rfl)",
                expr.render_arg()
            ));
        }
        let mut it = vars.iter();
        pat = pat
            .split('_')
            .enumerate()
            .map(|(i, piece)| match i {
                0 => piece.to_string(),
                _ => {
                    let (v, _) = it.next().expect("one `_` per pattern variable");
                    let n = names_of.get(v.as_str()).map_or("_", String::as_str);
                    format!("{n}{piece}")
                }
            })
            .collect();
        let mut unfolds = vec![sig.lean.clone(), format!("{}.rule1", sig.lean)];
        for (v, path) in &vars {
            if names_of.contains_key(v.as_str()) {
                for (s, i) in path {
                    let n = proj_arg(m, s, *i, projections, proj_names)?;
                    if !unfolds.contains(&n) {
                        unfolds.push(n);
                    }
                }
            }
        }
        chain = format!(" | (simp only [{}]{cases})", unfolds.join(", "));
    }
    let split = if cx.arity { "k2l_cases" } else { "rcases" };
    let theorem = format!(
        "/-- `{}` at any `{arg}`: its one equation matches every value of the cell sort, whose\n\
cells each have one constructor, so its value is the right-hand side at the projections. -/\n\
theorem {name} (x : {arg}) :\n    {concl} := by\n  {split} x with {pat}\n  first{by_eqn} | rfl | (simp only [{}, {}.rule1]; done){chain}\n",
        names::demangle(sym),
        sig.lean,
        sig.lean
    );
    Some(CellTree {
        name,
        theorem,
        vars,
        rhs: e.rhs.clone(),
        binds,
    })
}

/// The functions an invariant function calls, transitively (itself included).
fn closure(def: &Def, eqs: &BTreeMap<String, Vec<Equation>>, f: &str) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    let mut todo = vec![f.to_string()];
    while let Some(g) = todo.pop() {
        if !out.insert(g.clone()) {
            continue;
        }
        let mut called = BTreeSet::new();
        for e in eqs.get(&g).into_iter().flatten() {
            for p in e
                .args
                .iter()
                .chain(&e.requires)
                .chain(std::iter::once(&e.rhs))
            {
                crate::funcs::applied(p, def, &mut called);
            }
        }
        todo.extend(called.into_iter().filter(|c| !out.contains(c)));
    }
    out
}

/// What the generator knows of the library, for `emit`.
pub struct Ctx<'a> {
    pub def: &'a Def,
    pub m: &'a Model,
    pub fns: &'a Fns,
    pub eqs: &'a BTreeMap<String, Vec<Equation>>,
    /// Names of the stated equation theorems (`Eqn.…`) and the open ones.
    pub stated: &'a BTreeSet<String>,
    pub open_eqns: &'a BTreeSet<String>,
    pub recursive: &'a BTreeSet<String>,
    pub ctors: &'a [Ctor],
    pub top: &'a str,
    pub ns: &'a str,
    /// The initial configuration, with the Lean parameters of `init` (name, sort, `$X`).
    pub init: Option<(&'a InitTerm, crate::init::InitParams)>,
    /// The library is in the arity-indexed universe (`terms_arity.rs`): a case split on a term
    /// is `k2l_cases`, which refutes the family's constructors that no value of the sort has.
    pub arity: bool,
}

/// The files to write.
pub struct Out {
    pub defs: String,
    pub theorems: String,
    pub open_list: String,
    /// `invariant-unfold.txt`: the unfolding set of `k2l_inv`, one Lean name per line, for
    /// `claims --assume-invariant` (which unfolds the invariant where no rule applies).
    pub unfold_list: String,
    /// The skeleton of the hand module, when it does not exist and some case is open.
    pub hand_skeleton: Option<String>,
    pub notes: Vec<String>,
}

/// The path from the elements of each collection of a lifted part to the next collection, or,
/// for the last, to the content: the collection's kind and (constructor symbol, argument)s.
type ElemPath = Vec<(Coll, Vec<(String, usize)>)>;

struct Part {
    /// `Invariant.envOk`
    name: String,
    doc: String,
    /// The predicate of the cell content, as a function of a Lean variable.
    pred: Box<dyn Fn(&str) -> String>,
    /// The content read off a configuration `c`.
    read: String,
    /// The KORE path to the content in `init`: (constructor symbol, argument index)…
    kore_path: Vec<(String, usize)>,
    /// For a part lifted over a cell collection: `kore_path` leads to the collection, and this is
    /// the collection's kind and the path from an element cell to the content.
    elem_path: Option<ElemPath>,
    /// For a K function whose one equation matches a tree of cells: the theorem that reads it
    /// through projections (`kore_path` leads to the function's argument).
    cells: Option<CellTree>,
    /// `K.f` and whether it is `Option`-valued, for a K function part.
    func: Option<(String, bool)>,
}

/// A cell predicate lifted over a cell collection: the element predicate's binder and the read of
/// the cell from it.
struct Lifted {
    kind: Coll,
    /// `p` (a binding of a cell map) or `x` (an element of a cell list or set), and its type.
    binder: String,
    ty: String,
    /// The cell (or its content) read off the binder.
    read: String,
    /// The element cell's name (`thread`), for the documentation.
    elem_cell: String,
    /// The enclosing collections, outermost first, for a cell inside nested cell collections:
    /// each with the read of the next collection off its binder.
    outer: Vec<Lifted>,
}

/// The projection of one level of a cell path, defined once; returns its name.
fn proj_level(
    lv: &Level,
    projections: &mut BTreeMap<String, String>,
    proj_names: &mut Vec<String>,
) -> String {
    let name = format!("Invariant.cell_{}", lv.name);
    let pats: Vec<String> = (0..lv.arity)
        .map(|i| {
            if i == lv.index {
                "x".into()
            } else {
                "_".into()
            }
        })
        .collect();
    projections.entry(name.clone()).or_insert_with(|| {
        proj_names.push(name.clone());
        format!(
            "/-- The `<{}>` cell of a `{}`. -/\ndef {name} : {} → {}\n  | {} {} => x\n",
            lv.name,
            lv.sort,
            lv.sort,
            lv.child,
            lv.lean,
            pats.join(" ")
        )
    });
    name
}

/// The elements of a collection term of `init` (`.Map`, `K |-> V`, `M₁ M₂` and their list and set
/// analogues): the element cells, or `None` when the term is not built from these.
fn coll_elements<'a>(m: &Model, kind: &Coll, t: &'a P) -> Option<Vec<&'a P>> {
    let (unit, element, concat) = match kind {
        Coll::Map => ("MAP.unit", "MAP.element", "MAP.concat"),
        Coll::Set => ("SET.unit", "SET.element", "SET.concat"),
        Coll::List => ("LIST.unit", "LIST.element", "LIST.concat"),
    };
    let P::App(f, _, args) = t else { return None };
    match hook(m, f) {
        Some(h) if h == unit => Some(vec![]),
        Some(h) if h == element => args.last().map(|v| vec![v]),
        Some(h) if h == concat && args.len() == 2 => {
            let mut a = coll_elements(m, kind, &args[0])?;
            a.extend(coll_elements(m, kind, &args[1])?);
            Some(a)
        }
        _ => None,
    }
}

/// The name of a case in `open-invariant-cases.txt` (the first token; `«…»` may hold spaces).
pub fn case_token(line: &str) -> Option<String> {
    let l = line.trim();
    if l.is_empty() || l.starts_with('#') {
        return None;
    }
    let mut out = String::new();
    let mut quoted = false;
    for ch in l.chars() {
        match ch {
            '«' => quoted = true,
            '»' => quoted = false,
            c if c.is_whitespace() && !quoted => break,
            _ => {}
        }
        out.push(ch);
    }
    Some(out)
}

/// The case names of `open-invariant-cases.txt`, as Lean writes them (`«incr»` is `incr`).
pub fn read_open(path: &Path) -> BTreeSet<String> {
    std::fs::read_to_string(path)
        .unwrap_or_default()
        .lines()
        .filter_map(case_token)
        .map(
            |t| match t.strip_prefix('«').and_then(|x| x.strip_suffix('»')) {
                Some(inner) if names::ident(inner) == inner => inner.to_string(),
                _ => t,
            },
        )
        .collect()
}

pub fn emit(
    cx: &Ctx,
    specs: &[Spec],
    declared: &[Declared],
    open_in: &BTreeSet<String>,
    hand_exists: bool,
) -> Result<Out, String> {
    let (m, ns, top) = (cx.m, cx.ns, cx.top);
    let mut notes = Vec::new();
    let mut projections: BTreeMap<String, String> = BTreeMap::new(); // name → definition
    let mut proj_names: Vec<String> = Vec::new();
    let mut aux: Vec<String> = Vec::new(); // auxiliary definitions (entry predicates)
    let mut unfold: Vec<String> = Vec::new(); // the k2l_preserve simp list
    let mut parts: Vec<Part> = Vec::new();
    let mut folds: Vec<Fold> = Vec::new();
    let mut walks: Vec<Walk> = Vec::new();

    // the projection chain of a cell path; returns the read expression for `c` (for a cell inside
    // a cell collection: the collection, and the read of the cell off an element)
    let chain = |path: &CellPath,
                 content: bool,
                 projections: &mut BTreeMap<String, String>,
                 proj_names: &mut Vec<String>|
     -> (String, String, Option<Lifted>) {
        let mut read = "c".to_string();
        for lv in &path.levels {
            let name = proj_level(lv, projections, proj_names);
            read = format!("{name} {}", paren(&read));
        }
        let mut lifted = None;
        // the collection in its holding cell, read through one projection
        let holder = |cl: &CollLevel,
                      projections: &mut BTreeMap<String, String>,
                      proj_names: &mut Vec<String>| {
            let name = format!("Invariant.content_{}", cl.holder_name);
            let pats: Vec<String> = (0..cl.holder_arity)
                .map(|i| {
                    if i == cl.index {
                        "x".into()
                    } else {
                        "_".into()
                    }
                })
                .collect();
            projections.entry(name.clone()).or_insert_with(|| {
                proj_names.push(name.clone());
                format!(
                    "/-- The cell collection in a `<{}>` cell. -/\ndef {name} : {} → {}\n  | {} {} => x\n",
                    cl.holder_name, cl.holder_sort, cl.sort, cl.holder_lean, pats.join(" ")
                )
            });
            name
        };
        if let Some((cl0, _)) = path.colls.first() {
            let name = holder(cl0, projections, proj_names);
            read = format!("{name} {}", paren(&read));
            let mut outer = Vec::new();
            for (k, (cl, inner)) in path.colls.iter().enumerate() {
                let (binder, ty, elem) = match cl.kind {
                    Coll::Map => ("p", format!("{} × {}", cl.elems[0], cl.elems[1]), "p.2"),
                    _ => ("x", cl.elems[0].clone(), "x"),
                };
                let mut r = elem.to_string();
                for lv in inner {
                    let name = proj_level(lv, projections, proj_names);
                    r = format!("{name} {}", paren(&r));
                }
                let elem_cell = cell_ctor(m, cl.elems.last().unwrap())
                    .and_then(|c| cell_name(&c.klabel))
                    .unwrap_or_default();
                let lv = Lifted {
                    kind: cl.kind.clone(),
                    binder: binder.into(),
                    ty,
                    read: r,
                    elem_cell,
                    outer: Vec::new(),
                };
                match path.colls.get(k + 1) {
                    // an outer collection: its element predicate is the next collection's
                    // predicate of the next collection in the element
                    Some((next, _)) => {
                        let name = holder(next, projections, proj_names);
                        outer.push(Lifted {
                            read: format!("{name} {}", paren(&lv.read)),
                            ..lv
                        });
                    }
                    None => {
                        lifted = Some(Lifted {
                            outer: std::mem::take(&mut outer),
                            ..lv
                        })
                    }
                }
            }
        }
        let lift = |e: String, lifted: &mut Option<Lifted>| -> String {
            match lifted {
                Some(l) => {
                    l.read = e;
                    read.clone()
                }
                None => e,
            }
        };
        let base = match &lifted {
            Some(l) => l.read.clone(),
            None => read.clone(),
        };
        if content {
            let cname = cell_name(&m.ctors[&path.cell_sym].klabel).unwrap();
            let name = format!("Invariant.content_{cname}");
            projections.entry(name.clone()).or_insert_with(|| {
                proj_names.push(name.clone());
                format!(
                    "/-- The content of a `<{cname}>` cell. -/\ndef {name} : {} → {}\n  | {} x => x\n",
                    path.cell_sort, path.cell_args[0], path.cell_lean
                )
            });
            let e = format!("{name} {}", paren(&base));
            let r = lift(e, &mut lifted);
            (r, path.cell_args[0].clone(), lifted)
        } else {
            let r = lift(base, &mut lifted);
            (r, path.cell_sort.clone(), lifted)
        }
    };

    // K functions
    for s in specs {
        let sym = resolve(cx.def, &s.name)?;
        let sig = cx.fns.get(&sym).ok_or_else(|| {
            format!(
                "--invariant {}: {} was not generated",
                s.name,
                names::demangle(&sym)
            )
        })?;
        if sig.result != "SortBool" || sig.args.len() != 1 {
            return Err(format!(
                "--invariant {}: {} must take one argument and return Bool",
                s.name,
                names::demangle(&sym)
            ));
        }
        let arg = sig.args[0].clone();
        let mut elem_def: Option<(Lifted, ElemPath)> = None;
        let (read, kore_path, what) = match &s.cell {
            Some(cell) => {
                let path = find_cell(m, top, cell)?;
                let content = path.cell_args.len() == 1 && path.cell_args[0] == arg;
                if !content && path.cell_sort != arg {
                    return Err(format!(
                        "--invariant {}@{cell}: {} takes a {}, but <{cell}> holds a {} (cell sort {})",
                        s.name,
                        names::demangle(&sym),
                        arg,
                        path.cell_args.first().cloned().unwrap_or_default(),
                        path.cell_sort
                    ));
                }
                let (read, _, lifted) = chain(&path, content, &mut projections, &mut proj_names);
                let mut kp: Vec<(String, usize)> = path
                    .levels
                    .iter()
                    .map(|l| (l.sym.clone(), l.index))
                    .collect();
                match (lifted, path.colls.first()) {
                    (Some(l), Some((cl, _))) => {
                        kp.push((cl.holder_sym.clone(), cl.index));
                        // from each collection's element to the next collection, and from the
                        // last one's to the content
                        let mut ep: ElemPath = Vec::new();
                        for (k, (cl, inner)) in path.colls.iter().enumerate() {
                            let mut seg: Vec<(String, usize)> =
                                inner.iter().map(|l| (l.sym.clone(), l.index)).collect();
                            match path.colls.get(k + 1) {
                                Some((next, _)) => seg.push((next.holder_sym.clone(), next.index)),
                                None if content => seg.push((path.cell_sym.clone(), 0)),
                                None => {}
                            }
                            ep.push((cl.kind.clone(), seg));
                        }
                        let what = l
                            .outer
                            .iter()
                            .chain(std::iter::once(&l))
                            .rev()
                            .map(|o| format!("every `<{}>`", o.elem_cell))
                            .collect::<Vec<_>>()
                            .join(" of ");
                        let what = format!(
                            "the `<{cell}>` cell of {what} in the cell collection{}",
                            if l.outer.is_empty() { "" } else { "s" }
                        );
                        elem_def = Some((l, ep));
                        (read, kp, what)
                    }
                    _ => {
                        if content {
                            kp.push((path.cell_sym.clone(), 0));
                        }
                        (read, kp, format!("the `<{cell}>` cell"))
                    }
                }
            }
            None => {
                if arg != top {
                    return Err(format!(
                        "--invariant {}: {} takes a {}, not the top cell {top}; name a cell with @CELL",
                        s.name,
                        names::demangle(&sym),
                        arg
                    ));
                }
                ("c".to_string(), vec![], "the configuration".to_string())
            }
        };
        let lean = sig.lean.clone();
        let rhs = if sig.partial { "some true" } else { "true" };
        let pname = format!("Invariant.{}", names::ident(&s.name));
        // a function whose one equation matches a tree of cells: the theorem that reads it
        // through projections joins the unfolding set, so it applies to a rule's configuration,
        // whose cells are variables, and not only to a constructor term
        let eqn1 = format!(
            "Eqn.{}",
            names::ident(&format!("{}_1", names::demangle(&sym)))
        );
        let stated_eqn =
            (cx.stated.contains(&eqn1) && !cx.open_eqns.contains(&eqn1)).then_some(eqn1.as_str());
        let cells = if cx.recursive.contains(&lean) {
            None
        } else {
            cell_tree(
                cx,
                &sym,
                &names::ident(&s.name),
                &arg,
                stated_eqn,
                &mut projections,
                &mut proj_names,
            )
        };
        if let Some(ct) = &cells {
            unfold.push(ct.name.clone());
            if ct.binds {
                // the bind chain of partial `Bool` calls, split one call at a time, and the
                // `Bool` connectives at the values it substitutes
                for n in BIND_SPLIT {
                    if !unfold.iter().any(|u| u == n) {
                        unfold.push(n.to_string());
                    }
                }
            }
        }
        let has_cells = cells.is_some();
        match elem_def {
            // "for every element": the K function on the element's cell is an element predicate,
            // and the part is the collection predicate of the prelude (`EntriesOn`, `ElemsOn`), so
            // the collection lemmas (`KPrelude.InvColl`) apply to it
            Some((l, ep)) => {
                let coll_pred = |k: &Coll| match k {
                    Coll::Map => "KPrelude.MapHook.EntriesOn",
                    Coll::List => "KPrelude.ListHook.ElemsOn",
                    Coll::Set => "KPrelude.SetHook.ElemsOn",
                };
                let mut ename = format!("{pname}_elem");
                aux.push(format!(
                    "/-- The K function `{}` is `true` of the `<{}>` cell of one `<{}>`. -/\ndef {ename} ({} : {}) : Prop :=\n  {lean} {} = {rhs}\n",
                    names::demangle(&sym),
                    s.cell.as_deref().unwrap_or_default(),
                    l.elem_cell,
                    l.binder,
                    l.ty,
                    paren(&l.read)
                ));
                unfold.push(ename.clone());
                // nested collections: the predicate of an element of an outer collection is the
                // inner collection's predicate of the inner collection it holds
                let mut kind = l.kind.clone();
                let mut inner_cell = l.elem_cell.clone();
                for o in l.outer.iter().rev() {
                    let oname = format!("{pname}_in_{}", o.elem_cell);
                    aux.push(format!(
                        "/-- `{ename}` of every `<{inner_cell}>` of one `<{}>`. -/\ndef {oname} ({} : {}) : Prop :=\n  {} {ename} {}\n",
                        o.elem_cell,
                        o.binder,
                        o.ty,
                        coll_pred(&kind),
                        paren(&o.read)
                    ));
                    unfold.push(oname.clone());
                    ename = oname;
                    kind = o.kind.clone();
                    inner_cell = o.elem_cell.clone();
                }
                let coll_pred = coll_pred(&kind);
                parts.push(Part {
                    name: pname,
                    doc: format!(
                        "The K function `{}` is `true` of {what}.",
                        names::demangle(&sym)
                    ),
                    pred: Box::new(move |x| format!("{coll_pred} {ename} {x}")),
                    read,
                    kore_path,
                    elem_path: Some(ep),
                    cells,
                    func: Some((lean.clone(), sig.partial)),
                });
            }
            None => parts.push(Part {
                name: pname,
                doc: format!(
                    "The K function `{}` is `true` of {what}.",
                    names::demangle(&sym)
                ),
                pred: Box::new({
                    let lean = lean.clone();
                    move |x| format!("{lean} {x} = {rhs}")
                }),
                read,
                kore_path,
                elem_path: None,
                cells,
                func: Some((lean.clone(), sig.partial)),
            }),
        }
        // what the tactic unfolds: the K equations of the non-recursive functions it calls, and
        // the element-wise form of the list folds
        for g in closure(cx.def, cx.eqs, &sym) {
            let Some(gs) = cx.fns.get(&g) else { continue };
            if !gs.lean.starts_with("K.") {
                continue;
            }
            let es = &cx.eqs[&g];
            let eq_name = |i: usize| {
                format!(
                    "Eqn.{}",
                    names::ident(&format!("{}_{}", names::demangle(&g), i + 1))
                )
            };
            let proved = |n: &String| cx.stated.contains(n) && !cx.open_eqns.contains(n);
            let eq_names: Vec<String> = (0..es.len())
                .filter(|&i| !es[i].owise)
                .map(eq_name)
                .collect();
            let all_proved = !eq_names.is_empty() && eq_names.iter().all(proved);
            if cx.recursive.contains(&gs.lean) {
                if let Some(w) = walk_of(cx, &g, &mut projections, &mut proj_names) {
                    // a map walked by a free-key pattern: its element-wise form, from its
                    // instances and its unit equation
                    if !walks.iter().any(|x| x.lean == w.lean) {
                        walks.push(w);
                    }
                } else if let Some(f) = fold_of(m, cx.fns, cx.eqs, &g) {
                    if !folds.iter().any(|x| x.lean == f.lean) {
                        folds.push(f);
                    }
                } else if all_proved && structural(cx.def, m, cx.eqs, &g) {
                    // structural recursion: its equations rewrite a call on a constructor term
                    // into calls on its subterms
                    for n in eq_names {
                        if !unfold.contains(&n) {
                            unfold.push(n);
                        }
                    }
                } else {
                    notes.push(format!(
                        "invariant {}: the recursive function {} is neither a map walk, a list fold nor structurally recursive with proved equations; its cases may need hand proofs",
                        s.name,
                        names::demangle(&g)
                    ));
                }
                continue;
            }
            // an `owise` equation is a conditional rewrite whose side condition says that no
            // other equation's patterns match (`howise : ∀ …, x = pat → False`); simp uses it
            // where it can discharge that condition, which it does when the argument is built
            // from constructors other than the patterns' (and after a case split on a variable
            // under an injection), so it joins the unfolding set when it is proved
            let owise_names: Vec<String> = (0..es.len())
                .filter(|&i| es[i].owise)
                .map(eq_name)
                .filter(proved)
                .collect();
            if all_proved {
                unfold.extend(eq_names);
                unfold.extend(owise_names);
            } else if has_cells && g == sym {
                // `f_cells` states the function at every value of its sort; its definition
                // would unfold first and leave a match stuck on a rule's cell variables
            } else {
                unfold.push(gs.lean.clone());
                unfold.extend((1..=es.len()).map(|k| format!("{}.rule{k}", gs.lean)));
            }
        }
    }

    // KRS declared cell types
    for d in declared {
        let ci = m
            .ctors
            .get(&d.cell)
            .ok_or_else(|| format!("sidecar: no cell symbol {} in the definition", d.cell))?;
        let cname =
            cell_name(&ci.klabel).ok_or_else(|| format!("sidecar: {} is not a cell", d.cell))?;
        let path = find_cell(m, top, &cname)?;
        if !path.colls.is_empty() {
            return Err(format!(
                "sidecar: <{cname}> is inside a cell collection; declared types there are not supported"
            ));
        }
        let [content_sort] = path.cell_args.as_slice() else {
            return Err(format!(
                "sidecar: <{cname}> has subcells; declared types are for collection cells"
            ));
        };
        let info = m
            .sorts
            .get(content_sort)
            .ok_or_else(|| format!("sidecar: unknown sort {content_sort}"))?;
        if info.kind != Kind::Coll(d.coll.clone()) {
            return Err(format!(
                "sidecar: <{cname}> holds a {content_sort}, not a {:?}",
                d.coll
            ));
        }
        let elems = info.elems.clone();
        let injs: BTreeSet<(String, String)> = crate::terms::inj_pairs(m).into_iter().collect();
        // "e has sort s": the projection out of the element sort is defined
        let has = |e: &str, s: &str, v: &str| -> Result<Option<String>, String> {
            if e == s {
                return Ok(None);
            }
            if !m.sorts.contains_key(s) {
                return Err(format!("sidecar: <{cname}>: unknown sort {s}"));
            }
            if !injs.contains(&(s.to_string(), e.to_string())) {
                return Err(format!("sidecar: <{cname}>: {s} is not a subsort of {e}"));
            }
            Ok(Some(format!(
                "(∃ y, proj_{}_{} {v} = some y)",
                names::short_sort(e),
                names::short_sort(s)
            )))
        };
        let (read, _, _) = chain(&path, true, &mut projections, &mut proj_names);
        let pname = format!("Invariant.declared_{cname}");
        let ename = format!(
            "Invariant.{}_{cname}",
            if d.coll == Coll::Map { "entry" } else { "elem" }
        );
        let (body, pred): (String, Pred) = match d.coll {
            Coll::Map => {
                let k = has(&elems[0], &d.sorts[0], "p.1")?;
                let v = has(&elems[1], &d.sorts[1], "p.2")?;
                let conj: Vec<String> = [k, v].into_iter().flatten().collect();
                let body = if conj.is_empty() {
                    "True".to_string()
                } else {
                    conj.join(" ∧ ")
                };
                let e2 = ename.clone();
                (
                    format!(
                        "def {ename} (p : {} × {}) : Prop :=\n  {body}\n",
                        elems[0], elems[1]
                    ),
                    Box::new(move |x| format!("KPrelude.MapHook.EntriesOn {e2} {x}")),
                )
            }
            Coll::List | Coll::Set => {
                let e = has(&elems[0], &d.sorts[0], "x")?.unwrap_or_else(|| "True".into());
                let hk = if d.coll == Coll::List {
                    "ListHook"
                } else {
                    "SetHook"
                };
                let e2 = ename.clone();
                (
                    format!("def {ename} (x : {}) : Prop :=\n  {e}\n", elems[0]),
                    Box::new(move |x| format!("KPrelude.{hk}.ElemsOn {e2} {x}")),
                )
            }
        };
        aux.push(format!(
            "/-- The declared element sorts of `<{cname}>` (KRS: `{}`). -/\n{body}",
            d.krs
        ));
        unfold.push(ename.clone());
        parts.push(Part {
            name: pname,
            doc: format!("`<{cname}>` holds its KRS declared type `{}`.", d.krs),
            pred,
            read,
            kore_path: path
                .levels
                .iter()
                .map(|l| (l.sym.clone(), l.index))
                .chain(std::iter::once((path.cell_sym.clone(), 0)))
                .collect(),
            elem_path: None,
            cells: None,
            func: None,
        });
    }
    if parts.is_empty() {
        return Err("no invariant".into());
    }
    {
        let mut seen = BTreeSet::new();
        for p in &parts {
            if !seen.insert(p.name.clone()) {
                return Err(format!("two invariants are named {}", p.name));
            }
        }
    }

    // the unfolding set: parts, projections, auxiliary predicates, equations, folds
    let mut simp: Vec<String> = parts.iter().map(|p| p.name.clone()).collect();
    simp.extend(proj_names.iter().cloned());
    for u in unfold {
        if !simp.contains(&u) {
            simp.push(u);
        }
    }
    for f in &folds {
        simp.push(format!("Invariant.{}_iff", f.base));
    }
    for w in &walks {
        simp.push(format!("Invariant.{}_walk", w.base));
        simp.push(format!("Invariant.{}_test", w.base));
        if w.cell.is_some() {
            simp.push(format!("Invariant.{}_walk_cell", w.base));
            simp.push(format!("Invariant.{}_map", w.base));
        }
    }
    simp.push("Option.bind_fun_some".into());

    // maps built by recursion on an `Int` range, wherever a rule calls them: a `@[k2l_coll]`
    // lemma for each (below), proved from the function's two equations
    let proved = |n: &str| cx.stated.contains(n) && !cx.open_eqns.contains(n);
    let ranges: Vec<(&String, Range)> = cx
        .eqs
        .keys()
        .filter_map(|g| range_of(m, cx.fns, cx.eqs, &proved, g).map(|r| (g, r)))
        .collect();

    // ---------------------------------------------------------------- InvariantDefs.lean
    let mut d = String::new();
    d.push_str(&format!(
        "/-! Generated by k2lean (`gen --invariant`, `--sidecar`); do not edit.\n\n\
The kind 1 invariant `Invariant` of `{ns}` and what its proofs unfold. `Invariants.lean` proves that\n\
every rule preserves it; this module is separate so that the hand-written `InvariantsHand.lean`\n\
can state the cases the generic tactic does not close. -/\n\n\
set_option linter.unusedVariables false\n\nnamespace {ns}\n\nopen KPrelude\n\n"
    ));
    for name in &proj_names {
        d.push_str(&projections[name]);
        d.push('\n');
    }
    for a in &aux {
        d.push_str(a);
        d.push('\n');
    }
    for p in &parts {
        d.push_str(&format!(
            "/-- {} -/\ndef {} (c : {top}) : Prop :=\n  {}\n\n",
            p.doc,
            p.name,
            (p.pred)(&paren(&p.read))
        ));
    }
    let conj: Vec<String> = parts.iter().map(|p| format!("{} c", p.name)).collect();
    d.push_str(&format!(
        "/-- The invariant: {}. -/\ndef Invariant (c : {top}) : Prop :=\n  {}\n\n",
        parts
            .iter()
            .map(|p| format!("`{}`", p.name))
            .collect::<Vec<_>>()
            .join(", "),
        conj.join(" ∧ ")
    ));
    for f in &folds {
        let (b, l, x) = (&f.base, &f.lean, &f.x);
        let step = if f.swapped {
            format!("KPrelude.BoolHook.and r ({})", f.phi)
        } else {
            format!("KPrelude.BoolHook.and ({}) r", f.phi)
        };
        let lemma = if f.swapped {
            "all_iff_of_eqns'"
        } else {
            "all_iff_of_eqns"
        };
        let (ps, pa) = (f.binders(), f.args());
        let unit = if f.params.is_empty() {
            format!("Invariant.{b}_unit")
        } else {
            format!("(Invariant.{b}_unit{pa})")
        };
        let at = |e: &str| f.call(e);
        // with parameters, the fold is a function of the list for the fixed parameters
        let fun = if f.params.is_empty() {
            String::new()
        } else {
            format!(" (f := fun l => {})", at("l"))
        };
        d.push_str(&format!(
            "/-- The list fold `{l}`, its `.List` equation. -/\n\
theorem Invariant.{b}_unit{ps} : {} = some true := by\n  k2l_fold_eqn {l}\n\n\
/-- The list fold `{l}`, its `ListItem(X) L` equation. -/\n\
theorem Invariant.{b}_cons (l : {}) ({x} : {}){ps} :\n    {} = ({}).bind fun r => some ({step}) := by\n  k2l_fold_eqn {l}\n\n\
/-- `{l}` is `true` of a list exactly when every element satisfies its test. -/\n\
theorem Invariant.{b}_iff (l : {}){ps} :\n    {} = some true ↔ KPrelude.ListHook.ElemsOn (fun {x} => {} = true) l :=\n  KPrelude.ListHook.{lemma}{fun} {unit} (fun _ _ => Invariant.{b}_cons _ _{pa}) l\n\n",
            at("KPrelude.ListHook.unit"),
            f.list,
            f.elem,
            at(&format!("KPrelude.ListHook.concat (KPrelude.ListHook.element {x}) l")),
            at("l"),
            f.list,
            at("l"),
            f.phi
        ));
    }
    for w in &walks {
        let (b, l) = (&w.base, &w.lean);
        let (ps, pa) = (w.binders(), w.args());
        let mut unfold = vec![format!("Invariant.{b}_test")];
        unfold.extend(w.reads.iter().cloned());
        unfold.push("KPrelude.BoolHook.and".into());
        let unfold = unfold.join(", ");
        let insts = format!("{l}.instances, {l}.inst1, {l}.inst2");
        d.push_str(&format!(
            "set_option linter.unusedVariables false in\n\
/-- The map walk `{l}`: its test of one binding `k |-> v`. -/\n\
def Invariant.{b}_test (k : {}) (v : {}){ps} : Prop :=\n  {}\n\n\
/-- The map walk `{l}` is `true` of a map exactly when the map is well formed and every binding\n\
passes the test (`MapHook.all_iff_of_walk`, from its instances and its unit equation). -/\n\
theorem Invariant.{b}_walk (m : {}){ps} :\n    {} = some true ↔\n      KPrelude.MapHook.WF m ∧ KPrelude.MapHook.EntriesOn (fun q => Invariant.{b}_test q.1 q.2{pa}) m := by\n  \
refine KPrelude.MapHook.all_iff_of_walk (f := fun m => {}) (ψ := fun k v => Invariant.{b}_test k v{pa})\n    \
(by rw [{}]) ?_ ?_ m\n  \
· intro m hu h\n    \
rw [{l}.eq_instances] at h\n    \
simp only [{insts}, hu, ite_false, List.nil_append, KPrelude.firstNonempty_singleton] at h\n    \
split at h\n    \
· rename_i hw\n      \
obtain ⟨k, v, hk, hb⟩ := KPrelude.MapHook.mem_of_head?_chooseAll (Option.join_eq_some_iff.1 h)\n      \
refine ⟨(KPrelude.MapHook.wfb_iff _).1 hw, k, v, hk, ?_⟩\n      \
repeat' (split at hb)\n      \
all_goals simp_all [{unfold}]\n    \
· simp at h\n  \
· intro m hu hw h\n    \
rw [{l}.eq_instances]\n    \
simp only [{insts}, hu, ite_false, List.nil_append, KPrelude.firstNonempty_singleton,\n      \
(KPrelude.MapHook.wfb_iff m).2 hw, ite_true]\n    \
rw [KPrelude.MapHook.head?_chooseAll_of_forall (b := some true) (KPrelude.MapHook.toList_ne_nil_of_ne_unit hu)]\n    \
· rfl\n    \
· intro k v hk\n      \
obtain ⟨hψ, hr⟩ := h k v hk\n      \
repeat' split\n      \
all_goals simp_all [{unfold}]\n\n",
            w.key,
            w.val,
            w.test,
            w.map,
            w.call("m"),
            w.call("m"),
            w.unit_eqn,
        ));
        // a walk of a cell's map: the same at any cell, through the cell's map, so that it reads
        // a cell that a rule leaves as a variable (a rule that does not touch the cell map)
        if let (Some(cell), Some(wrap)) = (&w.cell, &w.wrap) {
            d.push_str(&format!(
                "/-- The map of the cell that the walk `{l}` walks. -/\n\
def Invariant.{b}_map : {cell} → {}\n  | {wrap} x => x\n\n\
/-- `Invariant.{b}_walk` at any cell, through its map: it rewrites a rule's cell variable too. -/\n\
theorem Invariant.{b}_walk_cell (w : {cell}){ps} :\n    {} = some true ↔\n      KPrelude.MapHook.WF (Invariant.{b}_map w) ∧ KPrelude.MapHook.EntriesOn (fun q => Invariant.{b}_test q.1 q.2{pa}) (Invariant.{b}_map w) := by\n  \
cases w\n  exact Invariant.{b}_walk _{pa}\n\n",
                w.map,
                w.call_at("w"),
            ));
        }
    }
    // the lemmas of the maps built on an `Int` range, which the collections closer applies to
    // the map a rule binds
    for (g, r) in &ranges {
        let call = |a: &str| {
            let mut s = format!("{} {a} b", r.lean);
            for x in &r.rest {
                s.push(' ');
                s.push_str(x);
            }
            s
        };
        let binders: String = r
            .binders
            .iter()
            .map(|(n, t)| format!(" {{{n} : {t}}}"))
            .collect();
        d.push_str(&format!(
            "/-- `{}` (a map built by recursion on an `Int` range) binds `{}` at each of its keys, from its two\n\
equations. -/\n\
@[k2l_coll] theorem Invariant.{} {{Q : {} → Prop}} {{a b : SortInt}}{binders} {{r : {}}}\n    \
(h : {} = some r) (hq : ∀ a, Q ({}, {})) : KPrelude.MapHook.EntriesOn Q r :=\n  \
KPrelude.MapHook.entriesOn_of_range (f := fun a => {}) (key := fun a => {})\n    \
(fun a ha => by rw [{}]; exact ha)\n    \
(fun a ha => by rw [{}]; (try simp only [Option.bind_fun_some]); exact ha) hq h\n\n",
            names::demangle(g),
            r.val,
            names::ident(&format!("range_{}", names::demangle(g))),
            r.entry,
            r.map,
            call("a"),
            r.key,
            r.val,
            call("a"),
            r.key,
            r.above,
            r.within,
        ));
    }
    let cell_trees: Vec<&CellTree> = parts.iter().filter_map(|p| p.cells.as_ref()).collect();
    for ct in &cell_trees {
        d.push_str(&ct.theorem);
        d.push('\n');
    }
    d.push_str(&format!("end {ns}\n"));
    // `Equations` exactly when something names an equation: these definitions (a lemma proved from
    // a function's equations) or the unfolding set, which `Invariants.lean` uses (with this file's
    // imports); read off what is emitted, so no shape can name one without the import
    let names_eqn = d.contains("Eqn.") || simp.iter().any(|n| n.starts_with("Eqn."));
    let d = format!(
        "import {ns}.Preserves\n{}import KPrelude.InvTactic\nimport KPrelude.InvColl\nimport KPrelude.InvFold\n\n{d}",
        if names_eqn {
            format!("import {ns}.Equations\n")
        } else {
            String::new()
        }
    );

    // ---------------------------------------------------------------- the cases
    let rule_names: BTreeSet<String> = cx.ctors.iter().map(|c| c.lean.clone()).collect();
    let mut open: BTreeSet<String> = BTreeSet::new();
    for o in open_in {
        let o = o.strip_prefix("Invariant.case.").unwrap_or(o);
        if rule_names.contains(o) {
            open.insert(o.to_string());
        } else if o == "init" || o == "Invariant.init_holds" || o == "init_holds" {
            open.insert("init".into());
        } else {
            notes.push(format!(
                "open-invariant-cases: {o} is not a rule of the definition (ignored)"
            ));
        }
    }

    // init: the parts' contents in the initial configuration
    let mut init_hyps: Vec<(String, String)> = Vec::new(); // (name, type)
    let mut init_terms: Vec<String> = Vec::new();
    let mut init_ok = cx.init.is_some();
    if let Some((it, params)) = &cx.init {
        let by_var: BTreeMap<&str, &str> = it
            .vars
            .iter()
            .zip(params)
            .map(|(v, (n, _, _))| (v.kore_var.as_str(), n.as_str()))
            .collect();
        for p in &parts {
            let mut t = &it.term;
            let mut found = true;
            for (sym, i) in &p.kore_path {
                match t {
                    P::App(f, _, args) if f == sym && *i < args.len() => t = &args[*i],
                    _ => {
                        found = false;
                        break;
                    }
                }
            }
            fn closed(p: &P) -> bool {
                match p {
                    P::Var(..) | P::SetVar(..) => false,
                    P::App(_, _, a) => a.iter().all(closed),
                    _ => true,
                }
            }
            fn follow<'a>(mut t: &'a P, path: &[(String, usize)]) -> Option<&'a P> {
                for (sym, i) in path {
                    match t {
                        P::App(f, _, args) if f == sym && *i < args.len() => t = &args[*i],
                        _ => return None,
                    }
                }
                Some(t)
            }
            // a part lifted over a cell collection: the collection in init is a literal of
            // element cells (one `<thread>` holding `$PGM`); the part holds by computation when
            // the cell it reads is closed in every element
            if let (true, Some(ep)) = (found, &p.elem_path) {
                // every element of every collection on the path is a literal, down to the cell
                fn closed_in(
                    m: &Model,
                    t: &P,
                    ep: &[(Coll, Vec<(String, usize)>)],
                ) -> Option<bool> {
                    let [(kind, seg), rest @ ..] = ep else {
                        return Some(closed(t));
                    };
                    let mut all = true;
                    for e in coll_elements(m, kind, t)? {
                        let Some(u) = follow(e, seg) else {
                            return Some(false);
                        };
                        all &= closed_in(m, u, rest)?;
                    }
                    Some(all)
                }
                let closed_all = closed_in(m, t, ep);
                match closed_all {
                    Some(true) => init_terms.push(format!(
                        "(by simp only [Invariant, {}, init]; first | rfl | decide | (k2l_coll_close [{}]) | (simp [{}]; done))",
                        simp.join(", "),
                        simp.join(", "),
                        simp.join(", ")
                    )),
                    _ => {
                        notes.push(format!(
                            "{}: in init, its cell collection is not a literal whose elements hold a closed term in the cell; the init theorem is an obligation",
                            p.name
                        ));
                        open.insert("init".into());
                    }
                }
                continue;
            }
            // a function whose one equation matches a tree of cells: at init, its value is the
            // right-hand side at the subterms of init that the pattern's variables match, which
            // are configuration variables (the hypothesis is about them) or closed terms
            if let (true, Some(ct), Some((flean, fpartial))) = (found, &p.cells, &p.func) {
                let args: String = params.iter().map(|(n, _, _)| format!(" {n}")).collect();
                let mut used = Vec::new();
                free_vars(&ct.rhs, &mut used);
                let mut lw = Lower::new(m, cx.fns, &[]);
                let (mut ok, mut param, mut all_closed) = (true, false, true);
                for (v, path) in &ct.vars {
                    if !used.contains(v) {
                        continue;
                    }
                    match follow(t, path) {
                        Some(P::Var(cv, _)) if by_var.contains_key(cv.as_str()) => {
                            lw.vars.insert(v.clone(), by_var[cv.as_str()].to_string());
                            param = true;
                        }
                        Some(u) => {
                            all_closed &= closed(u);
                            // read it off init
                            let mut r = format!("(init{args})");
                            for (sym, i) in p.kore_path.iter().chain(path) {
                                match proj_name(m, sym, *i) {
                                    Some(n) => r = format!("({n} {r})"),
                                    None => ok = false,
                                }
                            }
                            lw.vars.insert(v.clone(), r);
                        }
                        None => ok = false,
                    }
                }
                let hyp = ok.then(|| {
                    let sig = cx.fns.values().find(|f| f.lean == *flean)?;
                    let e = lw.expr(&ct.rhs, &sig.result).ok()?;
                    let steps = std::mem::take(&mut lw.steps);
                    let rhs_true = if *fpartial { "some true" } else { "true" };
                    // `x.bind some` is `x`
                    let shown = match (steps.as_slice(), &e) {
                        ([], _) if *fpartial => format!("some {}", e.render_arg()),
                        ([], _) => e.render(),
                        ([crate::lower::Step::Bind { expr, var, .. }], crate::lower::L::Var(r))
                            if var == r && *fpartial =>
                        {
                            expr.render()
                        }
                        _ if *fpartial => option_expr(&steps, &e)?,
                        _ => return None,
                    };
                    Some(format!("{shown} = {rhs_true}"))
                });
                match hyp.flatten() {
                    Some(_) if !param && all_closed => init_terms.push(format!(
                        "(by simp only [Invariant, {}, init]; first | rfl | decide | (k2l_coll_close [{}]) | (simp [{}]; done))",
                        simp.join(", "),
                        simp.join(", "),
                        simp.join(", ")
                    )),
                    Some(ty) => {
                        let h = format!("h_{}", names::ident(&p.name.replace("Invariant.", "")));
                        init_terms.push(format!(
                            "(by show {} (init{args}); unfold {}; rw [{}]; (try simp only [Option.bind_fun_some]); exact {h})",
                            p.name, p.name, ct.name
                        ));
                        init_hyps.push((h, ty));
                    }
                    None => {
                        notes.push(format!(
                            "{}: in init, its pattern's variables are not where the configuration declaration puts them; the init theorem is an obligation",
                            p.name
                        ));
                        open.insert("init".into());
                    }
                }
                continue;
            }
            match t {
                _ if !found => {
                    notes.push(format!("{}: its cell is not where the configuration declaration puts it in init", p.name));
                    open.insert("init".into());
                }
                P::Var(v, _) if by_var.contains_key(v.as_str()) => {
                    let x = by_var[v.as_str()];
                    let h = format!("h_{x}");
                    let h = if init_hyps.iter().any(|(n, _)| *n == h) { format!("{h}_{}", init_hyps.len()) } else { h };
                    init_hyps.push((h.clone(), (p.pred)(x)));
                    init_terms.push(h);
                }
                t if closed(t) => init_terms.push(format!(
                    "(by simp only [Invariant, {}, init]; first | rfl | decide | (k2l_coll_close [{}]) | (simp [{}]; done))",
                    simp.join(", "),
                    simp.join(", "),
                    simp.join(", ")
                )),
                _ => {
                    notes.push(format!("{}: its cell holds a term with configuration variables in init; the init theorem is an obligation", p.name));
                    open.insert("init".into());
                }
            }
        }
    } else {
        notes.push("no initial configuration (Init.lean): no init theorem or corollaries".into());
        init_ok = false;
    }

    let any_open = !open.is_empty();
    let mut t = String::new();
    t.push_str(&format!("import {ns}.InvariantDefs\n"));
    if init_ok {
        t.push_str(&format!("import {ns}.Init\n"));
    }
    if any_open {
        t.push_str(&format!("import {ns}.InvariantsHand\n"));
    }
    t.push_str("import KPrelude.InvSteps\nimport KPrelude.Tactic\n\n");
    t.push_str(&format!(
        "/-! Generated by k2lean (`gen --invariant`, `--sidecar`); do not edit.\n\n\
`Preserved Step Invariant` (`Invariant.preserved`): every rule of `{ns}` keeps the invariant `Invariant`\n\
(`InvariantDefs.lean`), whatever the program. It is proved by `Step.preserves_of` from one\n\
theorem `Invariant.case.r : Step.Case.r Invariant` per rule `r`, each by `k2l_preserve` in its per-case mode,\n\
or, for the cases listed in `open-invariant-cases.txt`, by the hand-written `Invariant.hand.r` of\n\
`InvariantsHand.lean`. `Invariant.init_holds` is `Invariant` at the initial configuration under hypotheses\n\
on the configuration variables, and `Invariant.star`, `Invariant.stepsN` extend it to every configuration\n\
reachable from `init`. -/\n\n\
set_option linter.unusedVariables false\n\nnamespace {ns}\n\nopen KPrelude\n\n\
/-- `k2l_preserve` with the unfolding set of `Invariant`. -/\n\
local macro \"k2l_inv\" : tactic => `(tactic| k2l_preserve [{}])\n\nnamespace Invariant.case\n\n",
        simp.join(", ")
    ));
    let mut n_auto = 0;
    for c in cx.ctors {
        if open.contains(&c.lean) {
            t.push_str(&format!("/-- Rule {} keeps `Invariant`: the hand proof. -/\ntheorem {} : Step.Case.{} Invariant := Invariant.hand.{}\n\n", c.doc, c.lean, c.lean, c.lean));
        } else {
            n_auto += 1;
            t.push_str(&format!("/-- Rule {} keeps `Invariant`. -/\ntheorem {} : Step.Case.{} Invariant := by k2l_inv\n\n", c.doc, c.lean, c.lean));
        }
    }
    t.push_str("end Invariant.case\n\n");
    t.push_str(&format!(
        "/-- Every rule keeps `Invariant` ({} rules: {n_auto} by `k2l_preserve`, {} by hand). -/\ntheorem Invariant.preserved : Preserved Step Invariant :=\n  Step.preserves_of\n",
        cx.ctors.len(),
        cx.ctors.len() - n_auto
    ));
    for c in cx.ctors {
        t.push_str(&format!("    Invariant.case.{}\n", c.lean));
    }
    t.push('\n');
    let mut guarded = vec!["Invariant.preserved".to_string()];
    if init_ok {
        let (_, params) = cx.init.as_ref().unwrap();
        let ps: String = params
            .iter()
            .map(|(n, s, _)| format!(" ({n} : {s})"))
            .collect();
        let psi: String = params
            .iter()
            .map(|(n, s, _)| format!(" {{{n} : {s}}}"))
            .collect();
        let args: String = params.iter().map(|(n, _, _)| format!(" {n}")).collect();
        let hs: String = init_hyps
            .iter()
            .map(|(h, ty)| format!(" ({h} : {ty})"))
            .collect();
        let hargs: String = init_hyps.iter().map(|(h, _)| format!(" {h}")).collect();
        let vars_doc: Vec<String> = params
            .iter()
            .map(|(n, _, v)| format!("`{n}` for `{v}`"))
            .collect();
        let body = if open.contains("init") {
            format!("Invariant.hand.init{args}{hargs}")
        } else if init_terms.len() == 1 {
            init_terms[0].clone()
        } else {
            format!("⟨{}⟩", init_terms.join(", "))
        };
        // a proof by computation names the whole unfolding set, of which one part uses a few
        let lint = if init_terms.iter().any(|x| x.starts_with("(by simp only"))
            && !open.contains("init")
        {
            "set_option linter.unusedSimpArgs false in\n"
        } else {
            ""
        };
        t.push_str(&format!(
            "{lint}/-- The initial configuration ({}) satisfies `Invariant`{}. -/\n\
theorem Invariant.init_holds{ps}{hs} :\n    Invariant (init{args}) :=\n  {body}\n\n\
/-- Every configuration reachable from an initial one satisfies `Invariant`. -/\n\
theorem Invariant.star{psi}{hs} {{c : {top}}} (h : Star Step (init{args}) c) : Invariant c :=\n  Invariant.preserved.star h (Invariant.init_holds{args}{hargs})\n\n\
/-- Every configuration reached in `n` steps from an initial one satisfies `Invariant`. -/\n\
theorem Invariant.stepsN{psi}{hs} {{n : Nat}} {{c : {top}}} (h : StepsN Step n (init{args}) c) : Invariant c :=\n  Invariant.preserved.stepsN h (Invariant.init_holds{args}{hargs})\n\n",
            vars_doc.join(", "),
            if init_hyps.is_empty() { String::new() } else { " when the configuration variables satisfy their cells' parts".to_string() }
        ));
        guarded.extend([
            "Invariant.init_holds".to_string(),
            "Invariant.star".into(),
            "Invariant.stepsN".into(),
        ]);
    }
    t.push_str(&format!(
        "#k2l_assert_axioms {}\n\nend {ns}\n",
        guarded.join(" ")
    ));

    // ---------------------------------------------------------------- open-invariant-cases.txt
    let mut ol = format!(
        "# Cases of the invariant `{ns}.Invariant` that `k2l_preserve` does not close (`k2lean gen --invariant`, `--sidecar`).\n\
# `k2lean open-from-log {ns}/Invariants.lean BUILD.log open-invariant-cases.txt` adds the cases whose proof failed.\n\
# Each line: the case, its statement, the rule's source position. Prove each in {ns}/InvariantsHand.lean as\n\
# `theorem Invariant.hand.r : Step.Case.r Invariant` (namespace `{ns}`; `Step.Case.r` is stated in {ns}/Preserves.lean).\n"
    );
    let mut skel = String::new();
    for c in cx.ctors {
        if open.contains(&c.lean) {
            ol.push_str(&format!(
                "{} | Step.Case.{} Invariant | {}\n",
                c.lean,
                c.lean,
                c.loc.clone().unwrap_or_else(|| "no position".into())
            ));
            skel.push_str(&format!("-- Rule {}:\n-- theorem Invariant.hand.{} : Step.Case.{} Invariant := by\n--   intro …\n\n", c.doc, c.lean, c.lean));
        }
    }
    if open.contains("init") {
        let (_, params) = cx.init.as_ref().expect("init");
        let ps: String = params
            .iter()
            .map(|(n, s, _)| format!(" ({n} : {s})"))
            .collect();
        let hs: String = init_hyps
            .iter()
            .map(|(h, ty)| format!(" ({h} : {ty})"))
            .collect();
        let args: String = params.iter().map(|(n, _, _)| format!(" {n}")).collect();
        ol.push_str(&format!(
            "init | ∀{ps}{hs}, Invariant (init{args}) | the configuration declaration\n"
        ));
        skel.push_str(&format!(
            "-- theorem Invariant.hand.init{ps}{hs} : Invariant (init{args}) := by\n--   …\n\n"
        ));
    }
    let hand_skeleton = (any_open && !hand_exists).then(|| {
        format!(
            "import {ns}.InvariantDefs\n\n/-! Hand-written proofs of the cases of `Invariant` listed in `open-invariant-cases.txt`.\n\n\
`k2lean gen` wrote this file once, because it did not exist, and never changes it. Prove each case\n\
below as the theorem it names (uncomment and complete it); `Invariants.lean` uses them by name. The\n\
generated proofs use `k2l_preserve [{}]`. -/\n\n\
namespace {ns}\n\nopen KPrelude\n\n{skel}end {ns}\n",
            simp.join(", ")
        )
    });
    let unfold_list = format!(
        "# The unfolding set of the invariant `{ns}.Invariant` (`k2lean gen --invariant`, `--sidecar`): the lemmas\n\
# of `k2l_inv` in {ns}/Invariants.lean, one per line. `k2lean claims --assume-invariant` reads it.\n{}\n",
        simp.join("\n")
    );
    Ok(Out {
        defs: d,
        theorems: t,
        open_list: ol,
        unfold_list,
        hand_skeleton,
        notes,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn case_tokens_keep_quoted_spaces() {
        assert_eq!(
            case_token("«X + Y» | Step.Case.«X + Y» Invariant | a.k:1:1").as_deref(),
            Some("«X + Y»")
        );
        assert_eq!(
            case_token("  «KRS-IMP.assign»").as_deref(),
            Some("«KRS-IMP.assign»")
        );
        assert_eq!(case_token("init | …").as_deref(), Some("init"));
        assert_eq!(case_token("# a comment"), None);
        assert_eq!(case_token("   "), None);
    }

    #[test]
    fn specs_name_a_cell() {
        let s = parse_spec("envOk@env");
        assert_eq!((s.name.as_str(), s.cell.as_deref()), ("envOk", Some("env")));
        let s = parse_spec("ok@<k>");
        assert_eq!(s.cell.as_deref(), Some("k"));
        assert!(parse_spec("topOk").cell.is_none());
    }
}
