//! `k2lean diff OLD NEW [--hand PATH]... [--toml FILE]`: the rules added, removed and changed
//! between two generations of a library, keyed by the stable rule names (`rulename.rs`), and the
//! hand-written proofs that refer to them.
//!
//! **What is compared.** Each generation is a generated library directory; its
//! `{ns}/Preserves.lean` states one `Step.Case.r P` per rule `r`: `∀ vars hyps, P lhs → P rhs`.
//! That statement is exactly what a hand-written case of rule `r` must prove (kind 1's
//! `Invariant.hand.r`, kind 2's `NS.hand.r`), so two generations agree on rule `r` for every hand
//! proof exactly when the two statements are equal. They are compared after renaming the bound
//! variables in order of their binders (`∀ (X : SortInt) …` and `∀ (Y : SortInt) …` are the same
//! statement), and without the source position, which is a doc comment. A rule present in both
//! generations is *changed* when its statement differs; the report says which parts differ: the
//! variables (their number or sorts), the side conditions, the left-hand side, the right-hand
//! side, the configuration sort.
//!
//! **Renames.** A rule's name is its K label or the focus of its left-hand side (with variable
//! sorts, then a content digest, on a collision). A name present in only one generation is paired
//! with one present only in the other when their statements are equal (a renamed label, a focus
//! edit that renames a variable, a new collision that adds sorts or a digest), and otherwise
//! *suggested* as a rename when exactly one name on each side qualifies, by the first of: the same
//! focus once sorts, digest and overload suffix are removed (a digest changes with any edit of
//! its rule); the same left-hand side (a relabelled rule whose other parts changed); the same
//! right-hand side and side conditions with the same head of the focus (a focus edit such as
//! `stop(s(s(N)))` to `stop(s(N))`). The rest are *added* or *removed*.
//!
//! **Context.** In a stratified `Step` (several priorities) a case of rank `i` has the hypothesis
//! `hpri : ∀ j, j < i → ¬ App j lhs`, whose meaning depends on the rules of the higher ranks:
//! when one of those is added, removed or changed, the case is reported as *context changed*
//! although its text is equal. A rule's statement also mentions generated functions, whose
//! equations this comparison does not read.
//!
//! **Hand-written references.** `--hand PATH` (a file, or a directory searched for `.lean` and
//! `.txt` files outside `.lake/`) is scanned for `Step.Case.r`, `Step.r`, `App.r` and `case r` tactic
//! tags (only the names of rules of OLD or NEW count); a file whose
//! header says it is generated by k2lean is skipped (it is regenerated, not revisited). Kind 1's
//! `open-invariant-cases.txt` lists its open cases as `Step.Case.r Invariant`, so it is read the
//! same way. Each reference to a rule that changed, was renamed or was removed is a case to
//! revisit.
//!
//! Exit status: 0 when no rule was added, removed, changed or renamed; 1 otherwise; 2 on a usage
//! or input error.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// One rule's case, as `Preserves.lean` states it.
#[derive(Clone, Debug)]
pub struct Case {
    /// The rule's name as Lean writes it (`«X + Y»`, `start`).
    pub name: String,
    pub loc: Option<String>,
    /// The configuration sort (`SortGeneratedTopCell`).
    pub top: String,
    /// `(name, type)` of the rule's variables and of its side conditions, in binder order.
    pub vars: Vec<(String, String)>,
    pub hyps: Vec<(String, String)>,
    pub lhs: String,
    pub rhs: String,
    /// The priority rank (0 for the first, or for an unstratified `Step`).
    pub rank: usize,
    norm: Norm,
}

#[derive(Clone, Debug, PartialEq, Eq)]
struct Norm {
    top: String,
    vars: Vec<String>,
    hyps: Vec<String>,
    lhs: String,
    rhs: String,
}

/// A generation: the namespace and the cases in file order.
pub struct Generation {
    pub ns: String,
    pub path: PathBuf,
    pub cases: Vec<Case>,
}

/// Lean tokens, as far as the comparison needs them: identifiers (with `.` and `«…»` segments),
/// numbers, string literals, and every other character on its own.
pub fn tokens(s: &str) -> Vec<String> {
    let cs: Vec<char> = s.chars().collect();
    let mut out = Vec::new();
    let mut i = 0;
    let ident_char = |c: char| {
        c.is_alphanumeric()
            || c == '_'
            || c == '\''
            || c == '!'
            || c == '?'
            || ('₀'..='₉').contains(&c)
    };
    while i < cs.len() {
        let c = cs[i];
        if c.is_whitespace() {
            i += 1;
        } else if c == '"' {
            let mut j = i + 1;
            while j < cs.len() && cs[j] != '"' {
                if cs[j] == '\\' {
                    j += 1;
                }
                j += 1;
            }
            out.push(cs[i..(j + 1).min(cs.len())].iter().collect());
            i = j + 1;
        } else if c == '«' || c.is_alphabetic() || c == '_' {
            let mut j = i;
            loop {
                if j < cs.len() && cs[j] == '«' {
                    while j < cs.len() && cs[j] != '»' {
                        j += 1;
                    }
                    j += 1;
                } else {
                    while j < cs.len() && ident_char(cs[j]) {
                        j += 1;
                    }
                }
                // a `.` continues the name when a segment follows
                if j + 1 < cs.len()
                    && cs[j] == '.'
                    && (cs[j + 1] == '«' || cs[j + 1].is_alphabetic() || cs[j + 1] == '_')
                {
                    j += 1;
                    continue;
                }
                break;
            }
            out.push(cs[i..j.min(cs.len())].iter().collect());
            i = j;
        } else if c.is_ascii_digit() {
            let mut j = i;
            while j < cs.len() && cs[j].is_ascii_digit() {
                j += 1;
            }
            out.push(cs[i..j].iter().collect());
            i = j;
        } else {
            out.push(c.to_string());
            i += 1;
        }
    }
    out
}

/// The name token at the start of `s` (`«…»` may hold spaces).
fn name_token(s: &str) -> String {
    crate::invariants::case_token(s).unwrap_or_default()
}

/// Split `toks` at the first `sep` outside parentheses.
fn split_top<'a>(toks: &'a [String], sep: &str) -> Option<(&'a [String], &'a [String])> {
    let mut d = 0i32;
    for (i, t) in toks.iter().enumerate() {
        match t.as_str() {
            "(" | "[" | "{" | "⟨" => d += 1,
            ")" | "]" | "}" | "⟩" => d -= 1,
            x if x == sep && d == 0 => return Some((&toks[..i], &toks[i + 1..])),
            _ => {}
        }
    }
    None
}

fn join(toks: &[String]) -> String {
    toks.join(" ")
}

/// Tokens written back for a reader: no space inside parentheses or before a comma.
fn render(toks: &[String]) -> String {
    let mut o = String::new();
    for (i, t) in toks.iter().enumerate() {
        let prev = if i > 0 { toks[i - 1].as_str() } else { "(" };
        if !matches!(prev, "(" | "[" | "⟨") && !matches!(t.as_str(), ")" | "]" | "⟩" | ",") {
            o.push(' ');
        }
        o.push_str(t);
    }
    o
}

/// The first part of a rule name that is not a variable (K variables are capitalized): the
/// head of its focus (`stop` of `stop(s(N))`, `*` of `X * Y`), or the label.
fn focus_head(n: &str) -> String {
    base_name(n)
        .split(|c: char| c.is_whitespace() || c == '(' || c == ')' || c == ',')
        .find(|w| !w.is_empty() && !w.starts_with(|c: char| c.is_uppercase() || c == '_'))
        .unwrap_or("")
        .to_string()
}

/// Parse the body of `def Step.Case.r (P : T → Prop) : Prop := BODY`.
fn parse_body(
    name: &str,
    loc: Option<String>,
    top: &str,
    p: &str,
    body: &str,
) -> Result<Case, String> {
    let toks = tokens(body);
    let mut i = 0;
    let mut binders: Vec<(String, Vec<String>)> = Vec::new();
    if toks.first().map(|t| t.as_str()) == Some("∀") {
        i = 1;
        while toks.get(i).map(|t| t.as_str()) == Some("(") {
            let b = toks.get(i + 1).ok_or("binder name")?.clone();
            if toks.get(i + 2).map(|t| t.as_str()) != Some(":") {
                return Err(format!("{name}: a binder without a type"));
            }
            let mut d = 1;
            let mut j = i + 3;
            while j < toks.len() {
                match toks[j].as_str() {
                    "(" => d += 1,
                    ")" => {
                        d -= 1;
                        if d == 0 {
                            break;
                        }
                    }
                    _ => {}
                }
                j += 1;
            }
            binders.push((b, toks[i + 3..j].to_vec()));
            i = j + 1;
        }
        if toks.get(i).map(|t| t.as_str()) != Some(",") {
            return Err(format!("{name}: no `,` after the binders"));
        }
        i += 1;
    }
    let rest = &toks[i..];
    let (l, r) = split_top(rest, "→").ok_or_else(|| format!("{name}: no `→`"))?;
    let strip = |side: &[String]| -> Result<Vec<String>, String> {
        match side.split_first() {
            Some((h, t)) if h == p => Ok(t.to_vec()),
            _ => Err(format!("{name}: a side that is not `{p} …`")),
        }
    };
    let (lhs, rhs) = (strip(l)?, strip(r)?);
    // variables have a sort (one identifier); side conditions are propositions
    let is_var = |t: &[String]| {
        t.len() == 1
            && t[0]
                .chars()
                .next()
                .is_some_and(|c| c.is_alphabetic() || c == '«')
    };
    let mut rename: BTreeMap<String, String> = BTreeMap::new();
    rename.insert(p.to_string(), "P".into());
    for (k, (b, _)) in binders.iter().enumerate() {
        rename.insert(b.clone(), format!("x{}", k + 1));
    }
    let rn = |ts: &[String]| -> String {
        join(
            &ts.iter()
                .map(|t| rename.get(t).cloned().unwrap_or_else(|| t.clone()))
                .collect::<Vec<_>>(),
        )
    };
    let mut vars = Vec::new();
    let mut hyps = Vec::new();
    let mut nvars = Vec::new();
    let mut nhyps = Vec::new();
    let mut rank = 0;
    for (b, t) in &binders {
        if is_var(t) {
            vars.push((b.clone(), render(t)));
            nvars.push(rn(t));
        } else {
            if b == "hpri" {
                // `∀ j, j < i → ¬ App j lhs`
                if let Some(k) = t.iter().position(|x| x == "<") {
                    rank = t.get(k + 1).and_then(|n| n.parse().ok()).unwrap_or(0);
                }
            }
            hyps.push((b.clone(), render(t)));
            nhyps.push(format!("{} : {}", rename[b], rn(t)));
        }
    }
    let norm = Norm {
        top: top.to_string(),
        vars: nvars,
        hyps: nhyps,
        lhs: rn(&lhs),
        rhs: rn(&rhs),
    };
    Ok(Case {
        name: name.to_string(),
        loc,
        top: top.to_string(),
        vars,
        hyps,
        lhs: render(&lhs),
        rhs: render(&rhs),
        rank,
        norm,
    })
}

/// Parse a `Preserves.lean`.
pub fn parse_preserves(text: &str) -> Result<(String, Vec<Case>), String> {
    let lines: Vec<&str> = text.lines().collect();
    let ns = lines
        .iter()
        .find_map(|l| l.strip_prefix("namespace "))
        .ok_or("no `namespace`")?
        .trim()
        .to_string();
    let mut cases = Vec::new();
    let mut i = 0;
    while i < lines.len() {
        let Some(rest) = lines[i].strip_prefix("def Step.Case.") else {
            i += 1;
            continue;
        };
        let name = name_token(rest);
        // `(P : Top → Prop) : Prop :=`
        let after = rest[name.len()..].trim_start();
        let ht = tokens(after);
        if ht.len() < 6 || ht[0] != "(" || ht[2] != ":" {
            return Err(format!("{name}: unexpected header `{}`", lines[i]));
        }
        let p = ht[1].clone();
        let top = ht[3].clone();
        let loc = if i > 0 {
            let d = lines[i - 1];
            // `/-- Rule `NAME` (LOC) keeps `P`. -/`
            d.find("` (").and_then(|a| {
                d[a + 3..]
                    .find(") keeps")
                    .map(|b| d[a + 3..a + 3 + b].to_string())
            })
        } else {
            None
        };
        let mut body = String::new();
        let mut j = i + 1;
        while j < lines.len() && !lines[j].trim().is_empty() {
            body.push_str(lines[j]);
            body.push('\n');
            j += 1;
        }
        cases.push(parse_body(&name, loc, &top, &p, &body)?);
        i = j;
    }
    Ok((ns, cases))
}

/// Load a generation from a library directory (or a `Preserves.lean` file).
pub fn load(path: &Path) -> Result<Generation, String> {
    let file = if path.is_file() {
        path.to_path_buf()
    } else {
        let mut found = Vec::new();
        for e in std::fs::read_dir(path).map_err(|e| format!("{}: {e}", path.display()))? {
            let d = e.map_err(|e| e.to_string())?.path();
            if d.is_dir() && d.join("Preserves.lean").is_file() && !d.ends_with(".lake") {
                found.push(d.join("Preserves.lean"));
            }
        }
        match found.len() {
            1 => found.pop().unwrap(),
            0 => {
                return Err(format!(
                    "{}: no NS/Preserves.lean (a library generated by `k2lean gen`)",
                    path.display()
                ));
            }
            _ => {
                return Err(format!(
                    "{}: several NS/Preserves.lean: {found:?}",
                    path.display()
                ));
            }
        }
    };
    let text = std::fs::read_to_string(&file).map_err(|e| format!("{}: {e}", file.display()))?;
    let (ns, cases) = parse_preserves(&text).map_err(|e| format!("{}: {e}", file.display()))?;
    Ok(Generation {
        ns,
        path: path.to_path_buf(),
        cases,
    })
}

/// The focus of a rule name without the disambiguation that a collision adds: variable sorts,
/// the content digest, the overload suffix.
pub fn base_name(n: &str) -> String {
    let s = n.trim_start_matches('«').trim_end_matches('»');
    let s = match s.rfind(" #") {
        Some(k) if s.len() - k == 8 && s[k + 2..].chars().all(|c| c.is_ascii_hexdigit()) => &s[..k],
        _ => s,
    };
    let s = match s.rfind("_ov") {
        Some(k) if !s[k + 3..].is_empty() && s[k + 3..].chars().all(|c| c.is_ascii_digit()) => {
            &s[..k]
        }
        _ => s,
    };
    // `X:Int` → `X`: a `:` followed by a sort name
    let cs: Vec<char> = s.chars().collect();
    let mut out = String::new();
    let mut i = 0;
    while i < cs.len() {
        if cs[i] == ':'
            && i + 1 < cs.len()
            && cs[i + 1].is_ascii_uppercase()
            && i > 0
            && (cs[i - 1].is_alphanumeric() || cs[i - 1] == '_')
        {
            i += 1;
            while i < cs.len()
                && (cs[i].is_alphanumeric()
                    || cs[i] == '_'
                    || cs[i] == '{'
                    || cs[i] == '}'
                    || cs[i] == ',')
            {
                i += 1;
            }
        } else {
            out.push(cs[i]);
            i += 1;
        }
    }
    out
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Status {
    Unchanged {
        moved: bool,
    },
    Changed {
        parts: Vec<&'static str>,
    },
    /// A name only in NEW whose statement equals that of a name only in OLD.
    Renamed {
        from: String,
        moved: bool,
    },
    /// A name only in NEW suggested as the new name of one only in OLD.
    RenamedChanged {
        from: String,
        why: String,
        parts: Vec<&'static str>,
    },
    Added,
    Removed,
    /// Equal text, but `hpri` reads `App` of a higher rank that changed.
    Context,
}

pub struct Entry {
    /// The NEW name (the OLD one for a removed rule).
    pub name: String,
    pub old_loc: Option<String>,
    pub new_loc: Option<String>,
    pub status: Status,
}

fn parts(a: &Case, b: &Case) -> Vec<&'static str> {
    let mut p = Vec::new();
    if a.norm.top != b.norm.top {
        p.push("configuration sort");
    }
    if a.norm.vars != b.norm.vars {
        p.push("variables");
    }
    if a.norm.hyps != b.norm.hyps {
        p.push("side conditions");
    }
    if a.norm.lhs != b.norm.lhs {
        p.push("left-hand side");
    }
    if a.norm.rhs != b.norm.rhs {
        p.push("right-hand side");
    }
    p
}

/// Compare two generations.
pub fn compare(old: &Generation, new: &Generation) -> Vec<Entry> {
    let om: BTreeMap<&str, &Case> = old.cases.iter().map(|c| (c.name.as_str(), c)).collect();
    let nm: BTreeMap<&str, &Case> = new.cases.iter().map(|c| (c.name.as_str(), c)).collect();
    let mut out = Vec::new();
    for c in &new.cases {
        if let Some(o) = om.get(c.name.as_str()) {
            let p = parts(o, c);
            let status = if p.is_empty() {
                Status::Unchanged {
                    moved: o.loc != c.loc,
                }
            } else {
                Status::Changed { parts: p }
            };
            out.push(Entry {
                name: c.name.clone(),
                old_loc: o.loc.clone(),
                new_loc: c.loc.clone(),
                status,
            });
        }
    }
    let mut removed: Vec<&Case> = old
        .cases
        .iter()
        .filter(|c| !nm.contains_key(c.name.as_str()))
        .collect();
    let mut added: Vec<&Case> = new
        .cases
        .iter()
        .filter(|c| !om.contains_key(c.name.as_str()))
        .collect();
    // equal statements: renames
    let mut i = 0;
    while i < removed.len() {
        let r = removed[i];
        let cands: Vec<usize> = (0..added.len())
            .filter(|&k| added[k].norm == r.norm)
            .collect();
        let pick = cands
            .iter()
            .copied()
            .find(|&k| base_name(&added[k].name) == base_name(&r.name))
            .or(cands.first().copied());
        if let Some(k) = pick {
            let a = added.remove(k);
            out.push(Entry {
                name: a.name.clone(),
                old_loc: r.loc.clone(),
                new_loc: a.loc.clone(),
                status: Status::Renamed {
                    from: r.name.clone(),
                    moved: r.loc != a.loc,
                },
            });
            removed.remove(i);
        } else {
            i += 1;
        }
    }
    // suggested renames: the same focus; else the same left-hand side; else the same right-hand
    // side and side conditions; each only when one rule of the other generation qualifies
    let mut taken_r = BTreeSet::new();
    let mut taken_a = BTreeSet::new();
    let mut pairs: Vec<(usize, usize, String)> = Vec::new();
    type Crit = (&'static str, fn(&Case, &Case) -> bool);
    let crits: [Crit; 3] = [
        ("same focus", |r, a| {
            base_name(&r.name) == base_name(&a.name)
        }),
        ("same left-hand side", |r, a| {
            r.norm.lhs == a.norm.lhs && r.norm.vars == a.norm.vars
        }),
        (
            "same right-hand side, side conditions and focus head",
            |r, a| {
                r.norm.rhs == a.norm.rhs
                    && r.norm.hyps == a.norm.hyps
                    && focus_head(&r.name) == focus_head(&a.name)
            },
        ),
    ];
    for (why, crit) in crits {
        for i in 0..removed.len() {
            if taken_r.contains(&i) {
                continue;
            }
            let cands: Vec<usize> = (0..added.len())
                .filter(|&k| !taken_a.contains(&k) && crit(removed[i], added[k]))
                .collect();
            let back = (0..removed.len())
                .filter(|&j| {
                    !taken_r.contains(&j)
                        && cands.first().is_some_and(|&k| crit(removed[j], added[k]))
                })
                .count();
            if cands.len() == 1 && back == 1 {
                taken_r.insert(i);
                taken_a.insert(cands[0]);
                pairs.push((i, cands[0], why.to_string()));
            }
        }
    }
    for (i, k, why) in &pairs {
        let (r, a) = (removed[*i], added[*k]);
        out.push(Entry {
            name: a.name.clone(),
            old_loc: r.loc.clone(),
            new_loc: a.loc.clone(),
            status: Status::RenamedChanged {
                from: r.name.clone(),
                why: why.clone(),
                parts: parts(r, a),
            },
        });
    }
    for (k, a) in added.iter().enumerate() {
        if !taken_a.contains(&k) {
            out.push(Entry {
                name: a.name.clone(),
                old_loc: None,
                new_loc: a.loc.clone(),
                status: Status::Added,
            });
        }
    }
    for (i, r) in removed.iter().enumerate() {
        if !taken_r.contains(&i) {
            out.push(Entry {
                name: r.name.clone(),
                old_loc: r.loc.clone(),
                new_loc: None,
                status: Status::Removed,
            });
        }
    }
    // a stratified `Step`: a change at rank k changes the meaning of `hpri` at every rank above k
    let rank_of = |n: &str, side: &BTreeMap<&str, &Case>| side.get(n).map(|c| c.rank);
    let mut changed_ranks: Vec<usize> = Vec::new();
    for e in &out {
        match &e.status {
            Status::Changed { .. } | Status::Added | Status::RenamedChanged { .. } => {
                changed_ranks.extend(rank_of(&e.name, &nm))
            }
            Status::Removed => changed_ranks.extend(rank_of(&e.name, &om)),
            _ => {}
        }
    }
    if let Some(&lo) = changed_ranks.iter().min() {
        for e in &mut out {
            if let Status::Unchanged { .. } = e.status
                && nm.get(e.name.as_str()).is_some_and(|c| c.rank > lo)
            {
                e.status = Status::Context;
            }
        }
    }
    out
}

/// A reference to a rule in a hand-written file.
#[derive(Clone, Debug)]
pub struct HandRef {
    pub rule: String,
    pub file: PathBuf,
    pub line: usize,
    /// `case` (`Step.Case.r`), `step` (`Step.r`, a constructor), `app` (`App.r`), `case tag`
    /// (`case r =>`).
    pub kind: &'static str,
}

fn generated_header(text: &str) -> bool {
    text.lines()
        .take(12)
        .any(|l| l.contains("Generated by k2lean") || l.contains("Generated by `k2lean"))
}

fn hand_files(p: &Path, out: &mut Vec<PathBuf>) {
    if p.is_file() {
        out.push(p.to_path_buf());
    } else if p.is_dir() {
        let mut es: Vec<PathBuf> = std::fs::read_dir(p)
            .into_iter()
            .flatten()
            .flatten()
            .map(|e| e.path())
            .collect();
        es.sort();
        for e in es {
            let n = e
                .file_name()
                .map(|n| n.to_string_lossy().to_string())
                .unwrap_or_default();
            if n == ".lake" || n.starts_with('.') {
                continue;
            }
            if e.is_dir() {
                hand_files(&e, out);
            } else if n.ends_with(".lean") || n.ends_with(".txt") {
                out.push(e);
            }
        }
    }
}

/// The references to the rules `known` in the hand-written files under `paths`.
pub fn hand_refs(paths: &[PathBuf], known: &BTreeSet<String>) -> (Vec<HandRef>, usize) {
    let mut files = Vec::new();
    for p in paths {
        hand_files(p, &mut files);
    }
    let mut out = Vec::new();
    let mut scanned = 0;
    for f in files {
        let Ok(text) = std::fs::read_to_string(&f) else {
            continue;
        };
        if generated_header(&text) {
            continue;
        }
        scanned += 1;
        for (ln, line) in text.lines().enumerate() {
            // a `case r …` tactic tag: a goal of rule `r` after `cases` on a step (`k2l_preserve`'s
            // residual goals are tagged so)
            let tl = line.trim_start().trim_start_matches(['·', '.', ' ']);
            if let Some(rest) = tl.strip_prefix("case ") {
                let n = name_token(rest);
                if known.contains(&n) {
                    out.push(HandRef {
                        rule: n,
                        file: f.clone(),
                        line: ln + 1,
                        kind: "case tag",
                    });
                }
            }
            for (kw, kind) in [("Step.Case.", "case"), ("Step.", "step"), ("App.", "app")] {
                let mut from = 0;
                while let Some(k) = line[from..].find(kw) {
                    let at = from + k;
                    from = at + kw.len();
                    let before = line[..at].chars().last();
                    if before.is_some_and(|c| c.is_alphanumeric() || c == '_') {
                        continue;
                    }
                    let rest = &line[at + kw.len()..];
                    if kind == "step" && rest.starts_with("Case.") {
                        continue;
                    }
                    let n: String = if rest.starts_with('«') {
                        match rest.find('»') {
                            Some(e) => rest[..e + '»'.len_utf8()].to_string(),
                            None => continue,
                        }
                    } else {
                        rest.chars()
                            .take_while(|c| {
                                c.is_alphanumeric()
                                    || *c == '_'
                                    || *c == '\''
                                    || *c == '.'
                                    || *c == '-'
                            })
                            .collect::<String>()
                            .trim_end_matches('.')
                            .to_string()
                    };
                    if known.contains(&n) {
                        out.push(HandRef {
                            rule: n,
                            file: f.clone(),
                            line: ln + 1,
                            kind,
                        });
                    }
                }
            }
        }
    }
    (out, scanned)
}

fn status_word(s: &Status) -> &'static str {
    match s {
        Status::Unchanged { .. } => "unchanged",
        Status::Changed { .. } => "changed",
        Status::Renamed { .. } => "renamed",
        Status::RenamedChanged { .. } => "renamed-changed",
        Status::Added => "added",
        Status::Removed => "removed",
        Status::Context => "context-changed",
    }
}

fn toml_str(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

fn differ(ps: &[&str]) -> String {
    format!(
        "{} {}",
        ps.join(", "),
        if ps.len() == 1 { "differs" } else { "differ" }
    )
}

fn loc(l: &Option<String>) -> &str {
    l.as_deref().unwrap_or("?")
}

/// The report: text for a reader, and TOML.
pub fn report(
    old: &Generation,
    new: &Generation,
    es: &[Entry],
    refs: &[HandRef],
    scanned: usize,
    hand_given: bool,
) -> (String, String, bool) {
    let count = |w: &str| es.iter().filter(|e| status_word(&e.status) == w).count();
    let moved = es
        .iter()
        .filter(|e| matches!(e.status, Status::Unchanged { moved: true }))
        .count();
    let (ch, ad, rm, rn, rc, cx, un) = (
        count("changed"),
        count("added"),
        count("removed"),
        count("renamed"),
        count("renamed-changed"),
        count("context-changed"),
        count("unchanged"),
    );
    let differs = ch + ad + rm + rn + rc + cx > 0;
    let mut t = String::new();
    writeln!(
        t,
        "k2lean diff: {} ({}) -> {} ({}): {} -> {} rules",
        old.ns,
        old.path.display(),
        new.ns,
        new.path.display(),
        old.cases.len(),
        new.cases.len()
    )
    .unwrap();
    writeln!(t, "changed {ch}, added {ad}, removed {rm}, renamed {rn} (same statement), renamed and changed {rc} (suggested), context changed {cx}; unchanged {un} ({moved} moved)").unwrap();
    let oc: BTreeMap<&str, &Case> = old.cases.iter().map(|c| (c.name.as_str(), c)).collect();
    let nc: BTreeMap<&str, &Case> = new.cases.iter().map(|c| (c.name.as_str(), c)).collect();
    let show_parts = |t: &mut String, a: &Case, b: &Case, ps: &[&str]| {
        for p in ps {
            let (x, y) = match *p {
                "variables" => (
                    a.vars
                        .iter()
                        .map(|(n, s)| format!("{n} : {s}"))
                        .collect::<Vec<_>>()
                        .join(", "),
                    b.vars
                        .iter()
                        .map(|(n, s)| format!("{n} : {s}"))
                        .collect::<Vec<_>>()
                        .join(", "),
                ),
                "side conditions" => (
                    a.hyps
                        .iter()
                        .map(|(n, s)| format!("{n} : {s}"))
                        .collect::<Vec<_>>()
                        .join(", "),
                    b.hyps
                        .iter()
                        .map(|(n, s)| format!("{n} : {s}"))
                        .collect::<Vec<_>>()
                        .join(", "),
                ),
                "left-hand side" => (a.lhs.clone(), b.lhs.clone()),
                "right-hand side" => (a.rhs.clone(), b.rhs.clone()),
                _ => (a.top.clone(), b.top.clone()),
            };
            writeln!(t, "      {p}:\n        - {x}\n        + {y}").unwrap();
        }
    };
    let section = |t: &mut String, title: &str, w: &str| {
        let xs: Vec<&Entry> = es.iter().filter(|e| status_word(&e.status) == w).collect();
        if xs.is_empty() {
            return;
        }
        writeln!(t, "\n{title}:").unwrap();
        for e in xs {
            match &e.status {
                Status::Changed { parts } => {
                    writeln!(
                        t,
                        "  {}  {} -> {}: {}",
                        e.name,
                        loc(&e.old_loc),
                        loc(&e.new_loc),
                        differ(parts)
                    )
                    .unwrap();
                    show_parts(t, oc[e.name.as_str()], nc[e.name.as_str()], parts);
                }
                Status::Renamed { from, .. } => writeln!(
                    t,
                    "  {from} -> {}  {} -> {}",
                    e.name,
                    loc(&e.old_loc),
                    loc(&e.new_loc)
                )
                .unwrap(),
                Status::RenamedChanged { from, why, parts } => {
                    writeln!(
                        t,
                        "  {from} -> {}?  {} -> {}: {why}; {}",
                        e.name,
                        loc(&e.old_loc),
                        loc(&e.new_loc),
                        differ(parts)
                    )
                    .unwrap();
                    show_parts(t, oc[from.as_str()], nc[e.name.as_str()], parts);
                }
                Status::Added => writeln!(t, "  {}  {}", e.name, loc(&e.new_loc)).unwrap(),
                Status::Removed => writeln!(t, "  {}  {}", e.name, loc(&e.old_loc)).unwrap(),
                Status::Context => writeln!(
                    t,
                    "  {}  {}: `hpri` reads `App` of a higher-priority rank that changed",
                    e.name,
                    loc(&e.new_loc)
                )
                .unwrap(),
                Status::Unchanged { .. } => {}
            }
        }
    };
    section(&mut t, "changed", "changed");
    section(&mut t, "renamed (same statement)", "renamed");
    section(
        &mut t,
        "renamed and changed (suggested by the content)",
        "renamed-changed",
    );
    section(&mut t, "added", "added");
    section(&mut t, "removed", "removed");
    section(&mut t, "context changed", "context-changed");
    // the hand-written references, by what happened to their rule
    let by_old: BTreeMap<&str, &Entry> = es
        .iter()
        .filter_map(|e| match &e.status {
            Status::Renamed { from, .. } | Status::RenamedChanged { from, .. } => {
                Some((from.as_str(), e))
            }
            Status::Removed => Some((e.name.as_str(), e)),
            _ => None,
        })
        .collect();
    let by_new: BTreeMap<&str, &Entry> = es
        .iter()
        .filter(|e| !matches!(e.status, Status::Removed))
        .map(|e| (e.name.as_str(), e))
        .collect();
    let mut revisit: BTreeMap<String, (String, Vec<&HandRef>)> = BTreeMap::new();
    let mut fine = BTreeSet::new();
    for r in refs {
        let what = if let Some(e) = by_old.get(r.rule.as_str()) {
            Some(match &e.status {
                Status::Renamed { .. } => format!(
                    "renamed to {} (same statement): rename the reference",
                    e.name
                ),
                Status::RenamedChanged { parts, .. } => format!(
                    "probably renamed to {} and changed ({})",
                    e.name,
                    differ(parts)
                ),
                _ => "removed".to_string(),
            })
        } else if let Some(e) = by_new.get(r.rule.as_str()) {
            match &e.status {
                Status::Changed { parts } => Some(format!("changed ({})", differ(parts))),
                Status::Context => {
                    Some("context changed (a higher-priority rule changed)".to_string())
                }
                _ => None,
            }
        } else {
            None
        };
        match what {
            Some(w) => revisit
                .entry(r.rule.clone())
                .or_insert_with(|| (w, Vec::new()))
                .1
                .push(r),
            None => {
                fine.insert(r.rule.clone());
            }
        }
    }
    if hand_given {
        writeln!(t, "\nhand-written references (files read: {scanned}):").unwrap();
        if revisit.is_empty() {
            writeln!(t, "  nothing to revisit").unwrap();
        } else {
            writeln!(t, "  revisit {} rule(s):", revisit.len()).unwrap();
            for (rule, (why, rs)) in &revisit {
                writeln!(t, "  {rule}: {why}").unwrap();
                for r in rs {
                    writeln!(t, "      {}:{} ({})", r.file.display(), r.line, r.kind).unwrap();
                }
            }
        }
        if !fine.is_empty() {
            writeln!(
                t,
                "  unaffected: {}",
                fine.iter().cloned().collect::<Vec<_>>().join(", ")
            )
            .unwrap();
        }
        let new_rules: Vec<&str> = es
            .iter()
            .filter(|e| matches!(e.status, Status::Added | Status::RenamedChanged { .. }))
            .map(|e| e.name.as_str())
            .collect();
        if !new_rules.is_empty() {
            writeln!(t, "  new rule cases ({}): `k2l_preserve` attempts them; one it does not close needs a hand case", new_rules.join(", ")).unwrap();
        }
    }
    let mut m = String::new();
    writeln!(
        m,
        "[summary]\nold = {}\nnew = {}\nold_rules = {}\nnew_rules = {}",
        toml_str(&old.path.display().to_string()),
        toml_str(&new.path.display().to_string()),
        old.cases.len(),
        new.cases.len()
    )
    .unwrap();
    writeln!(m, "changed = {ch}\nadded = {ad}\nremoved = {rm}\nrenamed = {rn}\nrenamed_changed = {rc}\ncontext_changed = {cx}\nunchanged = {un}\nmoved = {moved}").unwrap();
    for e in es
        .iter()
        .filter(|e| !matches!(e.status, Status::Unchanged { .. }))
    {
        writeln!(
            m,
            "\n[[rule]]\nname = {}\nstatus = {}",
            toml_str(&e.name),
            toml_str(status_word(&e.status))
        )
        .unwrap();
        if let Some(l) = &e.old_loc {
            writeln!(m, "old_loc = {}", toml_str(l)).unwrap();
        }
        if let Some(l) = &e.new_loc {
            writeln!(m, "new_loc = {}", toml_str(l)).unwrap();
        }
        match &e.status {
            Status::Changed { parts } => writeln!(
                m,
                "differs = [{}]",
                parts
                    .iter()
                    .map(|p| toml_str(p))
                    .collect::<Vec<_>>()
                    .join(", ")
            )
            .unwrap(),
            Status::Renamed { from, .. } => writeln!(m, "from = {}", toml_str(from)).unwrap(),
            Status::RenamedChanged { from, why, parts } => writeln!(
                m,
                "from = {}\nwhy = {}\ndiffers = [{}]",
                toml_str(from),
                toml_str(why),
                parts
                    .iter()
                    .map(|p| toml_str(p))
                    .collect::<Vec<_>>()
                    .join(", ")
            )
            .unwrap(),
            _ => {}
        }
    }
    for (rule, (why, rs)) in &revisit {
        for r in rs {
            writeln!(
                m,
                "\n[[revisit]]\nrule = {}\nwhy = {}\nfile = {}\nline = {}\nkind = {}",
                toml_str(rule),
                toml_str(why),
                toml_str(&r.file.display().to_string()),
                r.line,
                toml_str(r.kind)
            )
            .unwrap();
        }
    }
    (t, m, differs)
}

pub fn main(args: &[String]) {
    let usage = "usage: k2lean diff OLD NEW [--hand PATH]... [--toml FILE]\n  OLD, NEW: libraries generated by `k2lean gen` (directories holding NS/Preserves.lean)";
    let mut pos = Vec::new();
    let mut hand = Vec::new();
    let mut toml_out = None;
    let mut it = args.iter();
    while let Some(a) = it.next() {
        match a.as_str() {
            "--hand" => hand.push(PathBuf::from(it.next().unwrap_or_else(|| fail(usage)))),
            "--toml" => toml_out = Some(PathBuf::from(it.next().unwrap_or_else(|| fail(usage)))),
            x if x.starts_with("--") => fail(usage),
            x => pos.push(PathBuf::from(x)),
        }
    }
    let [o, n] = pos.as_slice() else { fail(usage) };
    let old = load(o).unwrap_or_else(|e| fail(&e));
    let new = load(n).unwrap_or_else(|e| fail(&e));
    let es = compare(&old, &new);
    let known: BTreeSet<String> = old
        .cases
        .iter()
        .chain(&new.cases)
        .map(|c| c.name.clone())
        .collect();
    let (refs, scanned) = hand_refs(&hand, &known);
    let (text, toml, differs) = report(&old, &new, &es, &refs, scanned, !hand.is_empty());
    print!("{text}");
    if let Some(p) = toml_out {
        std::fs::write(&p, toml).unwrap_or_else(|e| fail(&format!("{}: {e}", p.display())));
    }
    std::process::exit(if differs { 1 } else { 0 });
}

fn fail(msg: &str) -> ! {
    eprintln!("{msg}");
    std::process::exit(2)
}

