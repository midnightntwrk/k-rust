//! Refutations of a refinement by two runs (`refine --witnesses DIR`, `k2lean/docs/design.md`,
//! section 3.5): `Witnesses.lean`.
//!
//! What refutes a refinement along `tr` is a configuration `c` of `A` from which the runs that end
//! do not end in translations of each other: a run of `A` from `c` to a terminal configuration
//! whose translation no run of `B` from `tr c` ends in, or a run of `B` from `tr c` to a terminal
//! configuration that is no translation of where a run of `A` from `c` ends
//! (`KPrelude.TwoRuns.EndsMatch`, what `run_terminal` and `run_terminal_back` say at `c`). A
//! program on which the two definitions disagree, or a configuration that no program need reach:
//! the theorem is stated at every configuration of `A`, so two runs from one that end apart refute
//! it, which says that a legality is missing (`--assume-invariant`). Each witness `NAME` in `DIR`
//! is `NAME.kore`, a configuration of `A`, and the program `NAME.EXT` for the text: an initial
//! configuration (krust's `krun --depth 0`) is read as `init` at values of the configuration
//! variables (`init::witnesses`), any other as the configuration itself (written by the author or
//! an agent, e.g. from krust's `krun --depth N` of a nearby run). Under a legality a witness owes
//! it at its start, shown of an initial configuration only (`init_holds`). Generated: the values,
//! `witness.NAME.start`, `witness.NAME.disagrees`
//! (the run and the other side's reachable configurations found in the elaborator and checked by
//! the kernel, `k2l_ends_apart`, `KPrelude.TwoDefs`) and `Open.refuted`, from the terminal
//! corollaries under the open parts.

use super::fail;
use crate::ir::{self, P};
use crate::model::Model;
use std::collections::BTreeMap;
use std::fmt::Write as _;

/// What `Witnesses.lean` is written from.
pub(super) struct Ctx<'a> {
    pub dir: &'a str,
    /// `A`'s compiled KORE, whose initial configuration the witnesses are
    pub kore_a: &'a str,
    pub na: &'a str,
    pub nb: &'a str,
    pub ns: &'a str,
    /// the top cell's type at `A`, and the translation of the top sort
    pub ta: &'a str,
    /// the top sort, a non-initial witness's
    pub top: &'a str,
    pub tr: &'a str,
    /// whether each library is the ranked one, whose `successors` takes no rules
    pub ranked: (bool, bool),
    /// the legality (`--assume-invariant`), `A`'s generated invariant: a witness owes it at its
    /// start (`init_holds`)
    pub inv: Option<&'a str>,
}

struct Witness {
    name: String,
    program: Option<String>,
    start: Start,
}

/// A witness's start: an initial configuration, as the values of the configuration variables in
/// `init`'s order, or any configuration of `A`.
enum Start {
    Init(Vec<P>),
    Config(P),
}

/// `Witnesses.lean`, and the witnesses' names.
pub(super) fn emit(cx: &Ctx) -> (String, Vec<String>) {
    let text =
        std::fs::read_to_string(cx.kore_a).unwrap_or_else(|e| fail(&format!("{}: {e}", cx.kore_a)));
    let def = ir::load(&text).unwrap_or_else(|e| fail(&format!("{}: {e:?}", cx.kore_a)));
    let m = Model::build(&def).unwrap_or_else(|e| fail(&e));
    let it = crate::init::of(&def)
        .unwrap_or_else(|| fail("--witnesses: no initial configuration (topCellInitializer)"));
    let ws = read(cx.dir, &it, &def);
    let conv = crate::convert::Conv::new(&m, &def);
    let (na, nb, ns, ta) = (cx.na, cx.nb, cx.ns, cx.ta);
    // the functions that list exactly the steps (`successors_iff`)
    let succ = |n: &str, ranked: bool| {
        if ranked {
            format!("{n}.successors")
        } else {
            format!("KPrelude.successors {n}.rules")
        }
    };
    let (sa, sb) = (succ(na, cx.ranked.0), succ(nb, cx.ranked.1));
    let mut o = String::new();
    writeln!(
        o,
        "import {ns}.Refine\nimport {na}.Adequacy\nimport {na}.Init\nimport {nb}.Adequacy\nimport KPrelude.TwoDefs\n\n\
/-! Generated by `k2lean refine`; do not edit.\n\n\
Refutations by two runs (`--witnesses`). Each witness is a configuration of `{na}`\n\
(`witness.NAME.start`): the initial configuration of a program, or one that no program need\n\
reach, from which the runs that end, and those of `{nb}` from its translation, do not end in\n\
translations of each other (`witness.NAME.disagrees`): a run of one side to a terminal\n\
configuration, and the configurations the other side reaches, none of them terminal and matching\n\
it, found by a search in the elaborator and checked by the kernel (`k2l_ends_apart`). So the two\n\
definitions disagree there: the terminal corollaries fail at the witness, and the open parts are\n\
not all true (`Open.refuted`). At a configuration no program reaches, that says a legality is\n\
missing (`--assume-invariant`). -/\n\n\
set_option maxHeartbeats 0\nset_option maxRecDepth 100000\n\n\
namespace {ns}\n\nopen KPrelude KPrelude.TwoRuns\n"
    )
    .unwrap();
    let mut guard = vec![];
    for w in &ws {
        let wn = format!("witness.{}", crate::names::ident(&w.name));
        let program = match &w.program {
            Some(p) if p.lines().count() <= 12 && !p.contains("-/") => {
                format!(":\n```\n{p}\n```")
            }
            _ => String::new(),
        };
        writeln!(o, "/-! ## The witness `{}`{program} -/\n", w.name).unwrap();
        let vals = match &w.start {
            Start::Init(vals) => vals,
            Start::Config(p) => {
                if cx.inv.is_some() {
                    fail(&format!(
                        "--witnesses: `{}` is not an initial configuration: under a legality a witness owes it at its start, which is shown of an initial configuration only (`init_holds`)",
                        w.name
                    ));
                }
                let val = conv
                    .value(p, cx.top)
                    .unwrap_or_else(|e| fail(&format!("--witnesses: {}: {e}", w.name)))
                    .render();
                writeln!(
                    o,
                    "/-- The start: a configuration of `{na}`, which no program need reach. -/\ndef {wn}.start : {ta} :=\n  open {na} in {val}\n"
                )
                .unwrap();
                write_disagrees(&mut o, &wn, cx, &sa, &sb);
                guard.push(format!("{wn}.disagrees"));
                continue;
            }
        };
        let mut args = String::new();
        for (v, p) in it.vars.iter().zip(vals) {
            let val = conv
                .value(p, &v.sort)
                .unwrap_or_else(|e| fail(&format!("--witnesses: {}: {}: {e}", w.name, v.name)))
                .render();
            let n = crate::init::param_name(&v.name);
            writeln!(
                o,
                "/-- `{}`. -/\ndef {wn}.{n} : {na}.{} :=\n  open {na} in {val}\n",
                v.name, v.sort
            )
            .unwrap();
            write!(args, " {wn}.{n}").unwrap();
        }
        writeln!(
            o,
            "/-- The start: `{na}`'s initial configuration at these values. -/\ndef {wn}.start : {ta} :=\n  {na}.init{args}\n"
        )
        .unwrap();
        write_disagrees(&mut o, &wn, cx, &sa, &sb);
        guard.push(format!("{wn}.disagrees"));
        if let Some(i) = cx.inv {
            writeln!(
                o,
                "/-- The start satisfies the legality: it is an initial configuration (`{i}.init_holds`). -/\n\
theorem {wn}.legal : {i} {wn}.start := by\n  unfold {wn}.start\n  apply {i}.init_holds <;>\n    first | decide | fail \"a hypothesis of {i}.init_holds at `{wn}.start` is not decided\"\n"
            )
            .unwrap();
            guard.push(format!("{wn}.legal"));
        }
    }
    let w0 = format!("witness.{}", crate::names::ident(&ws[0].name));
    let hi = if cx.inv.is_some() {
        format!(" {w0}.legal")
    } else {
        String::new()
    };
    writeln!(
        o,
        "/-- The open parts are not all true: under them the terminal corollaries hold, which the runs of\n`{}` refute. -/\n\
theorem Open.refuted : ¬ Open := fun O =>\n  {w0}.disagrees ⟨fun h ht => run_terminal O{hi} h ht, fun h ht => run_terminal_back O{hi} h ht⟩\n\n\
#k2l_assert_axioms {} Open.refuted\n\nend {ns}",
        ws[0].name,
        guard.join(" ")
    )
    .unwrap();
    (o, ws.iter().map(|w| w.name.clone()).collect())
}

/// `witness.NAME.disagrees`: the runs that end from the start and from its translation do not end
/// in translations of each other.
fn write_disagrees(o: &mut String, wn: &str, cx: &Ctx, sa: &str, sb: &str) {
    let (na, nb, tr) = (cx.na, cx.nb, cx.tr);
    writeln!(
        o,
        "/-- The runs that end from the start and from its translation do not end in translations of each\nother. -/\n\
theorem {wn}.disagrees : ¬ EndsMatch {na}.Step {nb}.Step {tr} {wn}.start := by\n  \
k2l_ends_apart {sa}, {na}.successors_iff,\n    {sb}, {nb}.successors_iff\n"
    )
    .unwrap();
}

/// The witnesses of `DIR`: per name, its configuration (an initial one read as `init` at values of
/// the configuration variables) and its program's text.
fn read(dir: &str, it: &crate::init::InitTerm, def: &ir::Def) -> Vec<Witness> {
    let entries = std::fs::read_dir(dir).unwrap_or_else(|e| fail(&format!("{dir}: {e}")));
    let mut stems: BTreeMap<String, Option<std::path::PathBuf>> = BTreeMap::new();
    for e in entries {
        let path = e.unwrap_or_else(|e| fail(&format!("{dir}: {e}"))).path();
        let Some(f) = path.file_name().and_then(|s| s.to_str()) else {
            continue;
        };
        let Some((stem, ext)) = f.split_once('.') else {
            continue;
        };
        let slot = stems.entry(stem.to_string()).or_default();
        if !["kore", "vars"].contains(&ext) {
            *slot = Some(path.clone());
        }
    }
    let rd = |p: &std::path::Path| {
        std::fs::read_to_string(p).unwrap_or_else(|e| fail(&format!("{}: {e}", p.display())))
    };
    let mut out = vec![];
    for (name, program) in stems {
        let f = std::path::Path::new(dir).join(format!("{name}.kore"));
        if !f.exists() {
            fail(&format!(
                "--witnesses {dir}: `{name}` has no `{name}.kore` (a configuration of the first definition: an initial one is krust's `krun --depth 0`)"
            ));
        }
        let pat = k_rust_kore::kore::parser::parse_pattern(rd(&f).trim())
            .unwrap_or_else(|e| fail(&format!("{}: {e:?}", f.display())));
        let p = ir::pat(&pat);
        let start = match crate::init::witnesses(it, &p, def) {
            Some(vals) => Start::Init(vals),
            None => Start::Config(p),
        };
        out.push(Witness {
            name,
            program: program.map(|p| rd(&p).trim_end().to_string()),
            start,
        });
    }
    if out.is_empty() {
        fail(&format!(
            "--witnesses {dir}: no witness (`NAME.kore`, a configuration of the first definition, beside its program `NAME.EXT` when it is an initial one)"
        ));
    }
    out
}
