//! Refutations of noninterference by two runs (`noninterference --witnesses DIR`,
//! `k2lean/docs/design.md`, section 3.7): `Witnesses.lean`.
//!
//! What refutes the theorem is a labelling, a program the checker accepts at it, and two initial
//! configurations that satisfy the statement's premises (one value of each public input, the
//! related inputs related), from which one run each ends, with the same disclosed values, and the
//! observations differ: a flow the checker misses. Each witness `NAME` in `DIR` is
//! `NAME.1.kore` and `NAME.2.kore` (the two initial configurations, krust's `krun --depth 0`),
//! `NAME.lab` (the labelling: `KEY |-> LEVEL` pairs, K's map syntax, the keys tokens of the
//! labelled sort and the levels the checker's constants) and the program `NAME.EXT` for the text.
//! The configurations are read as `init` at values of the configuration variables
//! (`init::witnesses`). Generated: the labelling and the values; `witness.NAME.secure`, the
//! checker's verdict computed by its inversion lemmas (its functions recurse well-founded, which
//! the kernel does not unfold); `witness.NAME.related` for a related store, both stores `Good`
//! (their walk) and equal once the keys at which they differ are removed, none of those low
//! (`MapHook.AgreeOn.of_removeKeys`); `witness.NAME.leaks`, the two runs found in the elaborator
//! and checked by the kernel (`k2l_two_starts`, `KPrelude.TwoStarts`); and `Open.refuted`, from
//! the theorem under the open cases.

use super::{InputKind, Statement, fail};
use crate::ir::{P, S};
use crate::soundness::Lib;
use std::collections::BTreeMap;
use std::fmt::Write as _;

/// What `Witnesses.lean` is written from.
pub(super) struct Ctx<'a> {
    pub dir: &'a str,
    /// the semantics and the checker
    pub a: &'a Lib,
    pub b: &'a Lib,
    pub ns: &'a str,
    pub st: &'a Statement,
    /// the labelled sort, the level sort, the low level (rendered)
    pub key: &'a str,
    pub lvl: &'a str,
    pub lo: &'a str,
    /// the program's sort, the top cell's type
    pub pgm: &'a str,
    pub topt: &'a str,
    /// the checker's acceptance (`Levels.lean`'s name), its inversion lemmas, the other functions
    /// its equations call
    pub sec: &'a str,
    pub inversions: &'a [String],
    pub unfolds: &'a [String],
    /// the short name of `--store-ok` (its walk `Invariant.F_walk`)
    pub store_ok: &'a str,
    /// the theorem, under `(O : Open)`
    pub thm: &'a str,
}

struct Witness {
    name: String,
    program: Option<String>,
    /// the values of the configuration variables of each run, by name (`$` dropped)
    runs: [BTreeMap<String, P>; 2],
    /// the labelling: (key token, level constructor)
    lab: Vec<(String, String)>,
}

/// `Witnesses.lean`, and the witnesses' names.
pub(super) fn emit(cx: &Ctx) -> (String, Vec<String>) {
    let ws = read(cx);
    let (na, nb, ns, topt) = (&cx.a.ns, &cx.b.ns, cx.ns, cx.topt);
    let conv = crate::convert::Conv::new(&cx.a.m, &cx.a.def);
    let value = |p: &P, sort: &str, what: &str| {
        conv.value(p, sort)
            .unwrap_or_else(|e| fail(&format!("--witnesses: {what}: {e}")))
            .render()
    };
    let st = cx.st;
    let related: Vec<&super::Input> = st
        .inputs
        .iter()
        .filter(|i| matches!(i.kind, InputKind::Related(_)))
        .collect();
    let disc = st.disclosed.is_some();
    let store_obs = st.store_observed.is_some();
    let ks = crate::names::short_sort(cx.key);
    let trs = crate::terms::fsuffix(cx.key);
    let xk = format!("{na}.{}", cx.a.m.leaf_ctor("SortKItem", cx.key));
    let mut o = String::new();
    writeln!(
        o,
        "import {ns}.Proof\nimport {na}.Adequacy\nimport KPrelude.TwoStarts\n\n\
/-! Generated by `k2lean noninterference`; do not edit.\n\n\
Refutations by two runs (`--witnesses`). Each witness is a labelling, a program and two initial\n\
configurations, with\n\
- the checker accepting the program at the labelling (`witness.NAME.secure`);\n\
- the two configurations satisfying the statement's premises: one value of each public input{};\n\
- one run from each that ends{} with observations that differ (`witness.NAME.leaks`: the\n  \
runs found by a search in the elaborator, `k2l_two_starts`, and checked by the kernel).\n\
So the checker accepts a program that leaks: the theorem fails at the witness, and the open cases\n\
are not all true (`Open.refuted`). -/\n\n\
set_option maxHeartbeats 0\nset_option maxRecDepth 100000\nset_option linter.unusedSimpArgs false\n\n\
namespace {ns}\n\nopen KPrelude KPrelude.TwoRuns\n\n\
/-- A final configuration, as a test. -/\ndef fin (c : {topt}) : Bool := decide (kOf c = {na}.SortK.dotk)\n\n\
theorem final_of_fin {{c : {topt}}} (h : fin c = true) : Final c :=\n  of_decide_eq_true (p := kOf c = {na}.SortK.dotk) h\n",
        if related.is_empty() {
            ""
        } else {
            ",\n  the related inputs related (`witness.NAME.related`)"
        },
        if disc {
            ",\n  having disclosed the same values,"
        } else {
            ""
        },
    )
    .unwrap();
    if store_obs {
        writeln!(
            o,
            "/-- A key of the store that the labelling `G` makes low, as a test. -/\n\
def lowKey (G : Lab) (k : {na}.SortKItem) : Bool :=\n  match {na}.proj_KItem_{ks} k with\n  \
| some x => decide (levId G x = some {lo})\n  | none => false\n\n\
theorem lowKey_low (G : Lab) (k : {na}.SortKItem) (hk : lowKey G k = true) :\n    ∃ x, {xk} x = k ∧ Low G x := by\n  \
unfold lowKey at hk\n  split at hk\n  · rename_i x hx\n    \
exact ⟨x, {na}.inj_proj_KItem_{ks} hx, (lev_id G x).trans (of_decide_eq_true hk)⟩\n  · cases hk\n",
            lo = cx.lo
        )
        .unwrap();
    }
    let simps: Vec<String> = cx
        .inversions
        .iter()
        .cloned()
        .chain(std::iter::once("lev_id".to_string()))
        .chain(cx.unfolds.iter().cloned())
        .collect();
    let mut guard = vec![];
    for w in &ws {
        let id = crate::names::ident(&w.name);
        let wn = format!("witness.{id}");
        let program = match &w.program {
            Some(p) if p.lines().count() <= 12 && !p.contains("-/") => {
                format!(":\n```\n{p}\n```")
            }
            _ => String::new(),
        };
        writeln!(o, "/-! ## The witness `{}`{program} -/\n", w.name).unwrap();
        // the labelling: the checker's map from the labelled sort's keys to levels
        let entries: Vec<String> = w
            .lab
            .iter()
            .map(|(k, l)| {
                let kv = value(
                    &P::Dv(S::App(cx.key.to_string(), vec![]), k.clone()),
                    cx.key,
                    &format!("{}.lab", w.name),
                );
                format!(
                    "({nb}.{} (tr_{trs} {kv}), {nb}.{} {l})",
                    cx.b.m.leaf_ctor("SortKItem", cx.key),
                    cx.b.m.leaf_ctor("SortKItem", cx.lvl)
                )
            })
            .collect();
        let labdoc: Vec<String> = w
            .lab
            .iter()
            .map(|(k, l)| format!("{k} |-> {}", l.rsplit('.').next().unwrap_or(l)))
            .collect();
        writeln!(
            o,
            "/-- The labelling: `{}`. -/\ndef {wn}.lab : Lab :=\n  open {na} in KPrelude.MapHook.ofEntries [{}]\n",
            labdoc.join(" "),
            entries.join(", ")
        )
        .unwrap();
        let pgm_v = value(
            &w.runs[0]["PGM"],
            cx.pgm,
            &format!("{}.1.kore: $PGM", w.name),
        );
        writeln!(
            o,
            "/-- The program. -/\ndef {wn}.program : {na}.{} :=\n  open {na} in {pgm_v}\n",
            cx.pgm
        )
        .unwrap();
        let mut args: [String; 2] = [String::new(), String::new()];
        for i in &st.inputs {
            let sort = &i.ty;
            match i.kind {
                InputKind::Public => {
                    let v = value(&w.runs[0][&i.var], sort, &format!("{}: ${}", w.name, i.var));
                    writeln!(
                        o,
                        "/-- `${}`, public: one value for both runs. -/\ndef {wn}.{} : {na}.{sort} :=\n  open {na} in {v}\n",
                        i.var, i.stem
                    )
                    .unwrap();
                    for a in &mut args {
                        write!(a, " {wn}.{}", i.stem).unwrap();
                    }
                }
                _ => {
                    for (r, a) in args.iter_mut().enumerate() {
                        let sub = super::sub_digit(r + 1);
                        let v = value(
                            &w.runs[r][&i.var],
                            sort,
                            &format!("{}.{}.kore: ${}", w.name, r + 1, i.var),
                        );
                        writeln!(
                            o,
                            "/-- `${}` of the {} run. -/\ndef {wn}.{}{sub} : {na}.{sort} :=\n  open {na} in {v}\n",
                            i.var,
                            if r == 0 { "first" } else { "second" },
                            i.stem
                        )
                        .unwrap();
                        write!(a, " {wn}.{}{sub}", i.stem).unwrap();
                    }
                }
            }
        }
        writeln!(
            o,
            "/-- The checker accepts the program at the labelling. -/\ntheorem {wn}.secure : secure {wn}.lab {wn}.program := by\n  \
show {} {wn}.lab {wn}.program = some true\n  simp only [{wn}.program, {}] <;> decide\n",
            cx.sec,
            simps.join(", ")
        )
        .unwrap();
        guard.push(format!("{wn}.secure"));
        // the related store: both `Good`, equal once the keys at which they differ are removed
        for i in &related {
            let (s1, s2) = (format!("{wn}.{}₁", i.stem), format!("{wn}.{}₂", i.stem));
            let diff = differing_keys(cx, &w.runs[0][&i.var], &w.runs[1][&i.var], &w.name, &i.var);
            let xs: Vec<String> = diff
                .iter()
                .map(|k| {
                    value(
                        &P::Dv(S::App(cx.key.to_string(), vec![]), k.clone()),
                        cx.key,
                        &w.name,
                    )
                })
                .collect();
            let not_low = if xs.is_empty() {
                "(fun x hx => by simp at hx)".to_string()
            } else {
                format!(
                    "(by\n      intro x hx\n      simp only [List.mem_cons, List.mem_nil_iff, or_false] at hx\n      rcases hx with {}\n      all_goals exact fun hl => absurd ((lev_id _ _).symm.trans hl) (by decide))",
                    vec!["rfl"; xs.len()].join(" | ")
                )
            };
            let walk = format!("{na}.Invariant.{}", cx.store_ok);
            for (n, s) in [("₁", &s1), ("₂", &s2)] {
                writeln!(
                    o,
                    "theorem {wn}.good{n} : Good {s} :=\n  ({walk}_walk _).2 ⟨(MapHook.wfb_iff _).1 (by decide),\n    by unfold MapHook.EntriesOn {walk}_test; decide⟩\n"
                )
                .unwrap();
            }
            writeln!(
                o,
                "open {na} in\n/-- `${}`: the two stores are low-equal; they differ only at {}. -/\ntheorem {wn}.related : lowEq {wn}.lab {s1} {s2} :=\n  \
⟨{wn}.good₁, {wn}.good₂, MapHook.AgreeOn.of_removeKeys key_injective [{}] {wn}.good₁.wf {wn}.good₂.wf\n    (by decide) {not_low}⟩\n",
                i.var,
                if diff.is_empty() {
                    "no key".to_string()
                } else {
                    format!("`{}`, which the labelling does not make low", diff.join("`, `"))
                },
                xs.join(", ")
            )
            .unwrap();
            guard.push(format!("{wn}.related"));
        }
        // the conclusion, what separates two final configurations, and why that refutes it
        let mut concl = vec![];
        let mut apart = vec![];
        let mut happ = vec![];
        if store_obs {
            concl.push(format!("lowEq {wn}.lab (storeOf f₁) (storeOf f₂)"));
            apart.push(format!(
                "MapHook.lowApart (lowKey {wn}.lab) (storeOf a) (storeOf b)"
            ));
            happ.push(format!(
                "(fun h hl => MapHook.not_agreeOn_of_lowApart (lowKey_low {wn}.lab) h hl.2.2)"
            ));
        }
        if !st.pubs.is_empty() {
            concl.push("pubOf f₁ = pubOf f₂".into());
            apart.push("!decide (pubOf a = pubOf b)".into());
            happ.push("not_of_decide".into());
        }
        let (mut q, mut ap, mut ha) = (concl.join(" ∧ "), apart.join(" || "), happ[0].clone());
        if happ.len() == 2 {
            ap = format!("({}) || ({})", apart[0], apart[1]);
            ha = format!("not_and_of {} {}", happ[0], happ[1]);
        }
        if disc {
            q = format!("discOf f₁ = discOf f₂ → {q}");
            ap = format!("decide (discOf a = discOf b) && ({ap})");
            ha = format!("not_imp_of {ha}");
        }
        writeln!(
            o,
            "/-- One run from each configuration ends{}, and their observations differ. -/\n\
theorem {wn}.leaks :\n    ¬ RelatedFrom {na}.Step fin (fun f₁ f₂ => {q})\n      \
({na}.init {wn}.program{}) ({na}.init {wn}.program{}) := by\n  \
k2l_two_starts KPrelude.successors {na}.rules, {na}.successors_iff.mp,\n    (fun a b => {ap}), (fun _ _ => {ha})\n",
            if disc {
                ", the two disclosed the same values"
            } else {
                ""
            },
            args[0],
            args[1]
        )
        .unwrap();
        guard.push(format!("{wn}.leaks"));
    }
    let w0 = crate::names::ident(&ws[0].name);
    writeln!(
        o,
        "/-- The open cases are not all true: under them `{thm}` holds, which the two\nruns of `{}` refute. -/\n\
theorem Open.refuted : ¬ Open := fun O =>\n  witness.{w0}.leaks fun h₁ hf₁ h₂ hf₂{hd} =>\n    \
{thm} (G := witness.{w0}.lab) O witness.{w0}.secure{rel} h₁ (final_of_fin hf₁) h₂ (final_of_fin hf₂){hd}\n\n\
#k2l_assert_axioms {} Open.refuted\n\nend {ns}",
        ws[0].name,
        guard.join(" "),
        thm = cx.thm,
        hd = if disc { " hd" } else { "" },
        rel = if related.is_empty() {
            String::new()
        } else {
            format!(" witness.{w0}.related")
        },
    )
    .unwrap();
    (o, ws.iter().map(|w| w.name.clone()).collect())
}

/// The witnesses of `DIR`: per name, its two initial configurations read as `init` at values of
/// the configuration variables, the program agreed on and each public input, and its labelling.
fn read(cx: &Ctx) -> Vec<Witness> {
    let dir = cx.dir;
    let entries = std::fs::read_dir(dir).unwrap_or_else(|e| fail(&format!("{dir}: {e}")));
    let mut stems: BTreeMap<String, Option<std::path::PathBuf>> = BTreeMap::new();
    for e in entries {
        let path = e.unwrap_or_else(|e| fail(&format!("{dir}: {e}"))).path();
        let Some(f) = path.file_name().and_then(|s| s.to_str()) else {
            continue;
        };
        let Some((stem, ext)) = f.split_once('.') else {
            continue;
        };
        let slot = stems.entry(stem.to_string()).or_default();
        if !["1.kore", "2.kore", "1.vars", "2.vars", "lab"].contains(&ext) {
            *slot = Some(path.clone());
        }
    }
    let it = crate::init::of(&cx.a.def)
        .unwrap_or_else(|| fail("--witnesses: no initial configuration (topCellInitializer)"));
    let rd = |p: &std::path::Path| {
        std::fs::read_to_string(p).unwrap_or_else(|e| fail(&format!("{}: {e}", p.display())))
    };
    let lvls: Vec<(String, String)> =
        cx.b.m
            .sort(cx.lvl)
            .own
            .iter()
            .map(|c| {
                (
                    cx.b.m.ctors[c].klabel.clone(),
                    format!("{}.{}", cx.b.ns, cx.b.m.ctor_path(c)),
                )
            })
            .collect();
    let mut out = vec![];
    for (name, program) in stems {
        let d = std::path::Path::new(dir);
        let runs: Vec<BTreeMap<String, P>> = (1..=2)
            .map(|r| {
                let f = d.join(format!("{name}.{r}.kore"));
                if !f.exists() {
                    fail(&format!(
                        "--witnesses {dir}: `{name}` has no `{name}.{r}.kore` (an initial configuration, krust's `krun --depth 0`)"
                    ));
                }
                let pat = k_rust_kore::kore::parser::parse_pattern(rd(&f).trim())
                    .unwrap_or_else(|e| fail(&format!("{}: {e:?}", f.display())));
                let vals = crate::init::witnesses(&it, &crate::ir::pat(&pat), &cx.a.def)
                    .unwrap_or_else(|| {
                        fail(&format!(
                            "{}: not an initial configuration of the definition (`init` at some values of its configuration variables)",
                            f.display()
                        ))
                    });
                it.vars
                    .iter()
                    .zip(vals)
                    .map(|(v, p)| (v.name.trim_start_matches('$').to_string(), p))
                    .collect()
            })
            .collect();
        let runs: [BTreeMap<String, P>; 2] = [runs[0].clone(), runs[1].clone()];
        // the statement compares runs of one program from one value of each public input
        let mut shared = vec!["PGM".to_string()];
        shared.extend(
            cx.st
                .inputs
                .iter()
                .filter(|i| matches!(i.kind, InputKind::Public))
                .map(|i| i.var.clone()),
        );
        for v in &shared {
            if runs[0].get(v) != runs[1].get(v) {
                fail(&format!(
                    "--witnesses {dir}: `{name}`: the two configurations differ at ${v}, which the statement takes as one value for both runs"
                ));
            }
        }
        let lf = d.join(format!("{name}.lab"));
        if !lf.exists() {
            fail(&format!(
                "--witnesses {dir}: `{name}` has no `{name}.lab` (its labelling, `KEY |-> LEVEL` pairs)"
            ));
        }
        let text = rd(&lf);
        let toks: Vec<&str> = text.split_whitespace().collect();
        if !toks.len().is_multiple_of(3) || toks.chunks(3).any(|c| c[1] != "|->") {
            fail(&format!(
                "{}: a labelling is `KEY |-> LEVEL` pairs, separated by blanks",
                lf.display()
            ));
        }
        let lab = toks
            .chunks(3)
            .map(|c| {
                let lv = lvls
                    .iter()
                    .filter(|(k, _)| k == c[2] || k.starts_with(&format!("{}_", c[2])))
                    .map(|(_, l)| l.clone())
                    .collect::<Vec<_>>();
                match lv.as_slice() {
                    [l] => (c[0].to_string(), l.clone()),
                    _ => fail(&format!(
                        "{}: `{}` is not a level of the checker ({})",
                        lf.display(),
                        c[2],
                        lvls.iter()
                            .map(|(k, _)| k.as_str())
                            .collect::<Vec<_>>()
                            .join(", ")
                    )),
                }
            })
            .collect();
        out.push(Witness {
            name,
            program: program.map(|p| rd(&p).trim_end().to_string()),
            runs,
            lab,
        });
    }
    if out.is_empty() {
        fail(&format!(
            "--witnesses {dir}: no witness (`NAME.1.kore`, `NAME.2.kore`, `NAME.lab`)"
        ));
    }
    out
}

/// The keys at which two map values differ (bound in one only, or to different values), as
/// tokens of the labelled sort.
fn differing_keys(cx: &Ctx, m1: &P, m2: &P, name: &str, var: &str) -> Vec<String> {
    let hooks = &cx.a.m.hooks;
    fn entries<'p>(
        p: &'p P,
        hooks: &BTreeMap<String, String>,
        out: &mut Vec<(&'p P, &'p P)>,
    ) -> bool {
        match p {
            P::App(f, _, args) => match hooks.get(f).map(String::as_str) {
                Some("MAP.concat") => args.iter().all(|q| entries(q, hooks, out)),
                Some("MAP.element") if args.len() == 2 => {
                    out.push((&args[0], &args[1]));
                    true
                }
                Some("MAP.unit") => true,
                _ => false,
            },
            _ => false,
        }
    }
    let (mut e1, mut e2) = (vec![], vec![]);
    if !entries(m1, hooks, &mut e1) || !entries(m2, hooks, &mut e2) {
        fail(&format!(
            "--witnesses: `{name}`: ${var} is not a map of bindings"
        ));
    }
    let look = |es: &[(&P, &P)], k: &P| es.iter().find(|(x, _)| *x == k).map(|(_, v)| (*v).clone());
    let mut keys: Vec<&P> = e1.iter().chain(&e2).map(|(k, _)| *k).collect();
    keys.dedup();
    let mut out: Vec<String> = vec![];
    for k in keys {
        if look(&e1, k) == look(&e2, k) {
            continue;
        }
        let tok = match crate::soundness::as_inj(k) {
            Some((from, _, P::Dv(_, t))) if from == cx.key => t.clone(),
            _ => fail(&format!(
                "--witnesses: `{name}`: the two values of ${var} differ at a key that is not of the labelled sort {}",
                cx.key
            )),
        };
        if !out.contains(&tok) {
            out.push(tok);
        }
    }
    out
}
