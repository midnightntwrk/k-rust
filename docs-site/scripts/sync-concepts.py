#!/usr/bin/env python3
"""Generate the compact-tour concept data from the curriculum ledger."""

from __future__ import annotations

import json
import sys
import tomllib
from pathlib import Path


SITE = Path(__file__).resolve().parent.parent
ROOT = SITE.parent / "krs"
LEDGER = ROOT / "docs-plan" / "tour.toml"
OUTPUT = SITE / "src" / "generated" / "five-minute-concepts.ts"


def main() -> None:
    with LEDGER.open("rb") as source:
        ledger = tomllib.load(source)

    synthesis = next(
        item for item in ledger["synthesis"] if item["id"] == "five-minute-theory"
    )
    concepts = {item["id"]: item for item in ledger["concept"]}
    chapters = {item["id"]: item for item in ledger["chapter"]}
    generated = []
    for concept_id in synthesis["requires"]:
        concept = concepts[concept_id]
        generated.append(
            {
                "id": concept_id,
                "title": concept["title"],
                "gloss": concept["gloss"],
                "route": chapters[concept["chapter"]]["route"],
            }
        )

    source = (
        "// Generated by scripts/sync-concepts.py from docs-plan/tour.toml.\n"
        "// Do not edit this glossary by hand.\n"
        f"export const fiveMinuteConcepts = {json.dumps(generated, indent=2)} as const\n"
    )
    if "--write" in sys.argv:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(source, encoding="utf-8")
        print(f"updated {OUTPUT}")
        return
    if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != source:
        raise SystemExit(
            "generated five-minute concept data is stale; "
            "run `python3 scripts/sync-concepts.py --write`"
        )
    print("src/generated/five-minute-concepts.ts is current")


if __name__ == "__main__":
    main()
