#!/usr/bin/env python3
"""Generate the compact-tour concept data from the curriculum ledger."""

from __future__ import annotations

import json
import sys
from pathlib import Path


SITE = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(SITE / "plan"))
from ledger import Ledger  # noqa: E402

OUTPUT = SITE / "src" / "generated" / "five-minute-concepts.ts"


def main() -> None:
    ledger = Ledger.load()
    synthesis = next(
        item for item in ledger.rows("synthesis") if item["id"] == "five-minute-theory"
    )
    topics = {item["id"]: item for item in ledger.rows("topic")}
    generated = []
    for topic_id in synthesis["requires"]:
        topic = topics[topic_id]
        generated.append(
            {
                "id": topic_id,
                "title": topic["title"],
                "gloss": topic["gloss"],
                "route": ledger.destination(topic),
            }
        )

    source = (
        "// Generated by scripts/sync-concepts.py from plan/tour.toml.\n"
        "// Do not edit this glossary by hand.\n"
        f"export const fiveMinuteConcepts = {json.dumps(generated, indent=2)} as const\n"
    )
    if "--write" in sys.argv:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(source, encoding="utf-8")
        print(f"updated {OUTPUT}")
        return
    if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != source:
        raise SystemExit(
            "generated five-minute concept data is stale; "
            "run `python3 scripts/sync-concepts.py --write`"
        )
    print("src/generated/five-minute-concepts.ts is current")


if __name__ == "__main__":
    main()
