#!/usr/bin/env python3
"""Mirror k-rust's reader-facing docs (`docs/`) into the site's `/k-rust/` section,
and the normative module documentation of KRS crates into regions of site pages.

`--check` (the default) fails when a mirror differs from what its source gives;
`--write` regenerates the mirrors. The source stays the one to edit.
Each mirror escapes the characters MDX reads as markup (`<`, `{`, `}`) outside
code, shows K code blocks as text, and points a relative link at the mirrored
page it names or else at the file on GitHub.
A region mirror takes a Rust module's `//!` documentation from a heading to its
end, writes each intra-doc link (`[`Name`]`, or `[`Name`](crate::path)` with its target
written apart) as the code it shows, moves the
headings down to the page's level, and replaces the text between the region's
two marker comments on the page.
"""

from __future__ import annotations

from pathlib import Path, PurePosixPath
import posixpath
import re
import sys

SITE = Path(__file__).resolve().parent.parent
REPOSITORY = SITE.parent
PAGES = SITE / "src" / "pages" / "k-rust"
BLOB = "https://github.com/midnightntwrk/k-rust/blob/main/"
# Source (relative to the repository) -> mirrored page (relative to PAGES, without `.mdx`).
MIRRORS = {
    "docs/amendments.md": "amendments",
    "docs/compatibility.md": "compatibility",
    "docs/fuzzing.md": "fuzzing",
}
NOTICE = "{/* Generated by docs-site/scripts/sync-k-rust.py from {source}; edit the source and run `bun run sync:snippets`. */}\n\n"
# Module documentation mirrored into a region of a page (relative to `src/pages`): from the
# heading `start` to the end of the module's `//!` documentation, its headings `demote` levels down.
REGIONS = [
    {
        "source": "krs/crates/krs-exec/src/inputs.rs",
        "page": "reference/workflow.mdx",
        "start": "# The encoding",
        "demote": 2,
    },
]
REGION_BEGIN = "{/* Generated by docs-site/scripts/sync-k-rust.py from the module documentation of {source}; edit it there and run `bun run sync:snippets`. */}\n"
REGION_END = "{/* End of the text generated from {source}. */}\n"
INTRA_DOC_LINK = re.compile(r"\[(`[^`\]]+`)\](?![(\[])")
# An intra-doc link whose target is a Rust path written apart (`[`encode`](crate::encode())`).
PATH_LINK = re.compile(r"\[(`[^`\]]+`)\]\((?:crate|self|super)(?:::\w+)*(?:\(\)|!)?\)")
HEADING = re.compile(r"^(#+) ")

LINK = re.compile(r"\]\(([^)\s]+)\)")
INLINE_CODE = re.compile(r"(`+)(.+?)\1")
ESCAPES = {"<": "&lt;", "{": "&#123;", "}": "&#125;"}


def target(source: str, link: str) -> str:
    if link.startswith(("#", "http://", "https://", "mailto:")):
        return link
    path, _, anchor = link.partition("#")
    resolved = posixpath.normpath(posixpath.join(posixpath.dirname(source), path))
    if resolved in MIRRORS:
        page = f"/k-rust/{MIRRORS[resolved]}"
    elif resolved == source:
        page = ""
    else:
        page = BLOB + str(PurePosixPath(resolved))
    return page + (f"#{anchor}" if anchor else "")


def prose(source: str, text: str) -> str:
    text = LINK.sub(lambda match: f"]({target(source, match.group(1))})", text)
    return "".join(ESCAPES.get(character, character) for character in text)


def convert(source: str, text: str) -> str:
    return NOTICE.replace("{source}", source) + body(source, text)


def body(source: str, text: str) -> str:
    lines: list[str] = []
    fenced = False
    for line in text.splitlines(keepends=True):
        if line.lstrip().startswith("```"):
            fenced = not fenced
            # The site's highlighter has no K grammar.
            lines.append(re.sub(r"^(\s*```)k\s*$", r"\1text\n", line))
            continue
        if fenced:
            lines.append(line)
            continue
        pieces: list[str] = []
        position = 0
        for match in INLINE_CODE.finditer(line):
            pieces.append(prose(source, line[position:match.start()]))
            pieces.append(match.group(0))
            position = match.end()
        pieces.append(prose(source, line[position:]))
        lines.append("".join(pieces))
    return "".join(lines)


def module_documentation(source: str, start: str, demote: int) -> str:
    """The `//!` documentation of the Rust module `source` from the heading `start` on."""

    lines = []
    for line in (REPOSITORY / source).read_text(encoding="utf-8").splitlines():
        if not line.startswith("//!"):
            break
        lines.append(line.removeprefix("//!").removeprefix(" "))
    if start not in lines:
        raise SystemExit(f"{source}: the module documentation has no heading `{start}`")
    fenced = False
    converted = []
    for line in lines[lines.index(start):]:
        if line.lstrip().startswith("```"):
            fenced = not fenced
        elif not fenced:
            line = HEADING.sub(lambda match: "#" * (len(match.group(1)) + demote) + " ", line)
            line = PATH_LINK.sub(r"\1", line)
            line = INTRA_DOC_LINK.sub(r"\1", line)
        converted.append(line + "\n")
    return body(source, "".join(converted))


def region(entry: dict) -> tuple[Path, str]:
    """The page `entry` mirrors into, and the page's text with the region regenerated."""

    source = entry["source"]
    page = SITE / "src" / "pages" / entry["page"]
    text = page.read_text(encoding="utf-8")
    begin = REGION_BEGIN.replace("{source}", source)
    end = REGION_END.replace("{source}", source)
    if text.count(begin) != 1 or text.count(end) != 1 or text.index(begin) > text.index(end):
        raise SystemExit(f"{page.relative_to(SITE)}: expected one region marked\n  {begin}  ...\n  {end}")
    head, rest = text.split(begin)
    _, tail = rest.split(end)
    generated = module_documentation(source, entry["start"], entry["demote"])
    return page, head + begin + "\n" + generated + "\n" + end + tail


def main() -> int:
    mode = sys.argv[1:]
    if mode not in ([], ["--check"], ["--write"]):
        raise SystemExit("usage: sync-k-rust.py [--check | --write]")
    stale = []
    for source, page in MIRRORS.items():
        expected = convert(source, (REPOSITORY / source).read_text(encoding="utf-8"))
        mirror = PAGES / f"{page}.mdx"
        if mode == ["--write"]:
            mirror.parent.mkdir(parents=True, exist_ok=True)
            mirror.write_text(expected, encoding="utf-8")
        elif not mirror.is_file() or mirror.read_text(encoding="utf-8") != expected:
            stale.append(f"{mirror.relative_to(SITE)} (from {source})")
    for entry in REGIONS:
        page, expected = region(entry)
        if mode == ["--write"]:
            page.write_text(expected, encoding="utf-8")
        elif page.read_text(encoding="utf-8") != expected:
            stale.append(f"{page.relative_to(SITE)} (a region from {entry['source']})")
    if stale:
        print("stale k-rust mirrors; run `bun run sync:snippets`:\n  " + "\n  ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
