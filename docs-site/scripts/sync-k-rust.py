#!/usr/bin/env python3
"""Mirror k-rust's reader-facing docs (`docs/`) into the site's `/k-rust/` section.

`--check` (the default) fails when a mirror differs from what its source gives;
`--write` regenerates the mirrors. The source stays the one to edit.
Each mirror escapes the characters MDX reads as markup (`<`, `{`, `}`) outside
code, shows K code blocks as text, and points a relative link at the mirrored
page it names or else at the file on GitHub.
"""

from __future__ import annotations

from pathlib import Path, PurePosixPath
import posixpath
import re
import sys

SITE = Path(__file__).resolve().parent.parent
REPOSITORY = SITE.parent
PAGES = SITE / "src" / "pages" / "k-rust"
BLOB = "https://github.com/midnightntwrk/k-rust/blob/main/"
# Source (relative to the repository) -> mirrored page (relative to PAGES, without `.mdx`).
MIRRORS = {"docs/compatibility.md": "compatibility"}
NOTICE = "{/* Generated by docs-site/scripts/sync-k-rust.py from {source}; edit the source and run `bun run sync:snippets`. */}\n\n"

LINK = re.compile(r"\]\(([^)\s]+)\)")
INLINE_CODE = re.compile(r"(`+)(.+?)\1")
ESCAPES = {"<": "&lt;", "{": "&#123;", "}": "&#125;"}


def target(source: str, link: str) -> str:
    if link.startswith(("#", "http://", "https://", "mailto:")):
        return link
    path, _, anchor = link.partition("#")
    resolved = posixpath.normpath(posixpath.join(posixpath.dirname(source), path))
    if resolved in MIRRORS:
        page = f"/k-rust/{MIRRORS[resolved]}"
    elif resolved == source:
        page = ""
    else:
        page = BLOB + str(PurePosixPath(resolved))
    return page + (f"#{anchor}" if anchor else "")


def prose(source: str, text: str) -> str:
    text = LINK.sub(lambda match: f"]({target(source, match.group(1))})", text)
    return "".join(ESCAPES.get(character, character) for character in text)


def convert(source: str, text: str) -> str:
    lines: list[str] = []
    fenced = False
    for line in text.splitlines(keepends=True):
        if line.lstrip().startswith("```"):
            fenced = not fenced
            # The site's highlighter has no K grammar.
            lines.append(re.sub(r"^(\s*```)k\s*$", r"\1text\n", line))
            continue
        if fenced:
            lines.append(line)
            continue
        pieces: list[str] = []
        position = 0
        for match in INLINE_CODE.finditer(line):
            pieces.append(prose(source, line[position:match.start()]))
            pieces.append(match.group(0))
            position = match.end()
        pieces.append(prose(source, line[position:]))
        lines.append("".join(pieces))
    return NOTICE.replace("{source}", source) + "".join(lines)


def main() -> int:
    mode = sys.argv[1:]
    if mode not in ([], ["--check"], ["--write"]):
        raise SystemExit("usage: sync-k-rust.py [--check | --write]")
    stale = []
    for source, page in MIRRORS.items():
        expected = convert(source, (REPOSITORY / source).read_text(encoding="utf-8"))
        mirror = PAGES / f"{page}.mdx"
        if mode == ["--write"]:
            mirror.parent.mkdir(parents=True, exist_ok=True)
            mirror.write_text(expected, encoding="utf-8")
        elif not mirror.is_file() or mirror.read_text(encoding="utf-8") != expected:
            stale.append(f"{mirror.relative_to(SITE)} (from {source})")
    if stale:
        print("stale k-rust mirrors; run `bun run sync:snippets`:\n  " + "\n  ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
