//! A randomized differential oracle for the evaluation of `Unspecified` applications
//! (`simplify::simplify_root`, `UnspecifiedValues`).
//!
//! Each case is a small generated definition over `String`: applications `U_i =
//! substr("abc", 2 + i, 1)`, which the `STRING.substr` hook leaves `Unspecified` (reversed
//! indices), with one to three function equations each; ordinary `total` functions defined by an
//! equation and an `owise` one; and functions defined by `[simplification]` equations only. The
//! sides and `requires` of every equation mention other `U_j`, the functions, `keep(X, Y) = Y`,
//! `substr(X, 0, 0)` (`""` for every string `X`, which the hook computes only on a value) and
//! literals.
//!
//! The definition is generated from a model `M`: a value for every `U_i`, and every equation is
//! true in `M` (an `Unspecified` application's equations state `M(U_i)`, a function's equations
//! state the function `M` gives it, total and defined by guards that exclude each other). So no
//! two equations ever give different values, and a value the simplifier returns is `M` of its
//! input, whatever it is (soundness).
//!
//! Two shapes of definitions:
//! - *Determined*: every `U_i` has a value equation that mentions only `U_j` with `j < i` and
//!   functions over those, with a `requires` true in `M`; the other equations are arbitrary
//!   (true in `M`), so they may reach any application, also one whose attempt is open. With no
//!   attempt open, every application then has a value the evaluator finds whatever the order of
//!   the equations: an attempt fails only for want of a value an open attempt computes, and the
//!   value equation of the innermost such application needs none. So every input simplifies to
//!   `M` of it, in every order.
//! - *Undetermined*: some `U_i` have only equations whose result holds `U_i` itself (`U_i =
//!   U_i ++ ""`), which never give a value, so results may keep applications. When no priority
//!   group has two equations that may both give a result (`strict`), every order of the
//!   equations gives the same result; otherwise only the checks below that hold in every order
//!   apply (the documented residual: two equations of a group that both give a result, the
//!   results differing as terms).
//!
//! For every generated input and every sampled order of the equations within their priority
//! groups, the oracle checks:
//! 1. the result with the reuse of `Unspecified` evaluations turned off
//!    (`simplify::without_unspecified_reuse`) equals the result with it on: reuse is memoization;
//!    in particular, no result holds an application where the evaluation without reuse gave a
//!    value;
//! 2. a value is `M` of the input; for a determined definition every result is that value;
//! 3. for a strict definition, the result is the same in every order.
//!
//! A run whose budget ran out is skipped (the documented residual: a reused value saves work that
//! a fresh evaluation spends). The generator is seeded deterministically; the default run is a
//! few seconds, and `KRUST_UNSPECIFIED_ORACLE_CASES` (number of definitions) and
//! `KRUST_UNSPECIFIED_ORACLE_SEED` (first seed) set a longer one. Checked first, unless
//! `KRUST_UNSPECIFIED_ORACLE_NO_SHAPES` is set: fixed shapes that reviews found (`shapes`), the
//! generated definitions on which long runs found a weakened guard (`REGRESSION_SEEDS`), and the
//! shapes again with a record's reads bounded at no entry, so that a record keeps only the check
//! it keeps past its bound (`simplify::with_reads_bound`).

