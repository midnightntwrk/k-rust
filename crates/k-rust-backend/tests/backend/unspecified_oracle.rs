/// SplitMix64: a small deterministic generator, so that a case is reproduced by its seed.
struct Rng(u64);

impl Rng {
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9e37_79b9_7f4a_7c15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
        z ^ (z >> 31)
    }

    fn below(&mut self, bound: usize) -> usize {
        (self.next() % bound as u64) as usize
    }

    /// True with probability `numerator / denominator`.
    fn chance(&mut self, numerator: u64, denominator: u64) -> bool {
        self.next() % denominator < numerator
    }

    fn shuffle<T>(&mut self, items: &mut [T]) {
        for index in (1..items.len()).rev() {
            items.swap(index, self.below(index + 1));
        }
    }
}

#[derive(Clone, Debug)]
enum Expr {
    Lit(String),
    /// `U_i`.
    App(usize),
    /// The argument `X` of a function's equation.
    Arg,
    Concat(Box<Expr>, Box<Expr>),
    /// `keep(X, Y) = Y`.
    Keep(Box<Expr>, Box<Expr>),
    /// `substr(X, 0, 0)`, `""` for every string.
    Drop(Box<Expr>),
    Call(usize, Box<Expr>),
}

#[derive(Clone, Debug)]
enum Cond {
    True,
    LengthAbove(Expr, usize),
    LengthIs(Expr, usize),
    Is(Expr, String),
    Not(Box<Cond>),
    And(Box<Cond>, Box<Cond>),
    Or(Box<Cond>, Box<Cond>),
}

/// The head an equation defines.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
enum Head {
    App(usize),
    Function(usize),
}

#[derive(Clone, Debug)]
struct Equation {
    head: Head,
    rhs: Expr,
    requires: Cond,
    /// `[simplification]` rather than a function equation.
    simplification: bool,
    /// Priority 200, the `owise` group.
    owise: bool,
}

/// A function `f_i(X)`: defined by function equations (an equation and an `owise` one) or by
/// `[simplification]` equations only (two whose guards exclude each other).
#[derive(Clone, Debug)]
struct Function {
    /// The `U_j` its equations may mention are those with `j < level`.
    level: usize,
}

struct Case {
    /// The generator's seed, or the name of a fixed shape.
    name: String,
    seed: u64,
    determined: bool,
    strict: bool,
    model: Vec<String>,
    functions: Vec<Function>,
    equations: Vec<Equation>,
    inputs: Vec<Expr>,
}

struct Generator<'a> {
    rng: &'a mut Rng,
    model: Vec<String>,
    functions: Vec<Function>,
    equations: Vec<Equation>,
}

const LITERALS: [&str; 4] = ["", "a", "b", "ab"];

impl Generator<'_> {
    fn literal(&mut self) -> String {
        LITERALS[self.rng.below(LITERALS.len())].to_owned()
    }

    /// A random expression of at most `depth` levels mentioning the `U_j` with `j < apps`, the
    /// functions with an index below `functions` and a level up to `apps`, and `X` if `arg`.
    fn expr(&mut self, depth: usize, apps: usize, functions: usize, arg: bool) -> Expr {
        let callable = (0..functions)
            .filter(|&index| self.functions[index].level <= apps)
            .collect::<Vec<_>>();
        loop {
            let choice = if depth == 0 {
                self.rng.below(3)
            } else {
                self.rng.below(8)
            };
            return match choice {
                0 => Expr::Lit(self.literal()),
                1 if apps > 0 => Expr::App(self.rng.below(apps)),
                2 if arg => Expr::Arg,
                3 => Expr::Concat(
                    Box::new(self.expr(depth - 1, apps, functions, arg)),
                    Box::new(self.expr(depth - 1, apps, functions, arg)),
                ),
                4 => Expr::Keep(
                    Box::new(self.expr(depth - 1, apps, functions, arg)),
                    Box::new(self.expr(depth - 1, apps, functions, arg)),
                ),
                5 => Expr::Drop(Box::new(self.expr(depth - 1, apps, functions, arg))),
                6 | 7 if !callable.is_empty() => Expr::Call(
                    callable[self.rng.below(callable.len())],
                    Box::new(self.expr(depth - 1, apps, functions, arg)),
                ),
                _ => continue,
            };
        }
    }

    fn cond(&mut self, depth: usize, apps: usize, functions: usize, arg: bool) -> Cond {
        match self.rng.below(if depth == 0 { 5 } else { 8 }) {
            0 | 1 => Cond::True,
            2 => Cond::LengthAbove(self.expr(1, apps, functions, arg), self.rng.below(3)),
            3 => Cond::LengthIs(self.expr(1, apps, functions, arg), self.rng.below(3)),
            4 => {
                let literal = self.literal();
                Cond::Is(self.expr(1, apps, functions, arg), literal)
            }
            5 => Cond::Not(Box::new(self.cond(depth - 1, apps, functions, arg))),
            6 => Cond::And(
                Box::new(self.cond(depth - 1, apps, functions, arg)),
                Box::new(self.cond(depth - 1, apps, functions, arg)),
            ),
            _ => Cond::Or(
                Box::new(self.cond(depth - 1, apps, functions, arg)),
                Box::new(self.cond(depth - 1, apps, functions, arg)),
            ),
        }
    }

    fn model(&self) -> Model<'_> {
        Model {
            apps: &self.model,
            equations: &self.equations,
        }
    }

    /// An expression whose value in `M` is `value`, mentioning anything.
    fn target(&mut self, value: &str, apps: usize, functions: usize) -> Expr {
        for _ in 0..12 {
            let candidate = self.expr(2, apps, functions, false);
            if self.model().value(&candidate, None) == value {
                return candidate;
            }
        }
        let equal = (0..apps)
            .filter(|&index| self.model[index] == value)
            .collect::<Vec<_>>();
        if !equal.is_empty() && self.rng.chance(1, 2) {
            return Expr::App(equal[self.rng.below(equal.len())]);
        }
        Expr::Lit(value.to_owned())
    }

    /// An expression whose value in `M` is `value`, made by wrapping a random one so that its
    /// value does not count (`keep(r, t)`, `substr(r, 0, 0) ++ t`).
    fn wrapped(&mut self, value: &str, apps: usize, functions: usize) -> Expr {
        let inner = self.expr(2, apps, functions, false);
        let target = self.target(value, apps, functions);
        match self.rng.below(3) {
            0 => Expr::Keep(Box::new(inner), Box::new(target)),
            1 => Expr::Concat(Box::new(Expr::Drop(Box::new(inner))), Box::new(target)),
            _ => Expr::Concat(Box::new(target), Box::new(Expr::Drop(Box::new(inner)))),
        }
    }

    /// An expression whose value in `M` is `""`.
    fn empty(&mut self, apps: usize, functions: usize) -> Expr {
        match self.rng.below(4) {
            0 => Expr::Lit(String::new()),
            1 => Expr::Drop(Box::new(self.expr(2, apps, functions, false))),
            _ => self.target("", apps, functions),
        }
    }

    /// A function: an equation and an `owise` one, or two `[simplification]` equations whose
    /// guards exclude each other. Its equations mention the `U_j` below its level and the
    /// functions before it.
    fn function(&mut self, index: usize, apps: usize) {
        let level = self.rng.below(apps + 1);
        self.functions.push(Function { level });
        let head = Head::Function(index);
        let guard = self.cond(1, level, index, true);
        let first = self.expr(2, level, index, true);
        let second = self.expr(2, level, index, true);
        if self.rng.chance(1, 2) {
            self.equations.push(Equation {
                head,
                rhs: first,
                requires: guard,
                simplification: false,
                owise: false,
            });
            self.equations.push(Equation {
                head,
                rhs: second,
                requires: Cond::True,
                simplification: false,
                owise: true,
            });
        } else {
            self.equations.push(Equation {
                head,
                rhs: first,
                requires: guard.clone(),
                simplification: true,
                owise: false,
            });
            self.equations.push(Equation {
                head,
                rhs: second,
                requires: Cond::Not(Box::new(guard)),
                simplification: true,
                owise: false,
            });
        }
    }

    /// An equation of `U_i` whose result holds `U_i` on every path, true in `M`.
    fn holding(&mut self, index: usize, apps: usize, functions: usize) -> Equation {
        let own = Expr::App(index);
        let rhs = match self.rng.below(3) {
            0 => Expr::Concat(Box::new(own), Box::new(self.empty(apps, functions))),
            1 => Expr::Concat(Box::new(self.empty(apps, functions)), Box::new(own)),
            _ => Expr::Keep(
                Box::new(self.expr(2, apps, functions, false)),
                Box::new(own),
            ),
        };
        Equation {
            head: Head::App(index),
            rhs,
            requires: self.cond(1, apps, functions, false),
            simplification: false,
            owise: false,
        }
    }
}

/// The values the model gives expressions and conditions.
struct Model<'a> {
    apps: &'a [String],
    equations: &'a [Equation],
}

impl Model<'_> {
    fn value(&self, expr: &Expr, arg: Option<&str>) -> String {
        match expr {
            Expr::Lit(value) => value.clone(),
            Expr::App(index) => self.apps[*index].clone(),
            Expr::Arg => arg.expect("X only in a function's equation").to_owned(),
            Expr::Concat(left, right) => self.value(left, arg) + &self.value(right, arg),
            Expr::Keep(_, right) => self.value(right, arg),
            Expr::Drop(_) => String::new(),
            Expr::Call(function, argument) => self.call(*function, &self.value(argument, arg)),
        }
    }

    fn holds(&self, cond: &Cond, arg: Option<&str>) -> bool {
        match cond {
            Cond::True => true,
            Cond::LengthAbove(expr, bound) => self.value(expr, arg).chars().count() > *bound,
            Cond::LengthIs(expr, length) => self.value(expr, arg).chars().count() == *length,
            Cond::Is(expr, literal) => self.value(expr, arg) == *literal,
            Cond::Not(cond) => !self.holds(cond, arg),
            Cond::And(left, right) => self.holds(left, arg) && self.holds(right, arg),
            Cond::Or(left, right) => self.holds(left, arg) || self.holds(right, arg),
        }
    }

    /// The function's value on `argument`: its first equation (by priority) whose guard holds.
    fn call(&self, function: usize, argument: &str) -> String {
        let mut equations = self
            .equations
            .iter()
            .filter(|equation| equation.head == Head::Function(function))
            .collect::<Vec<_>>();
        equations.sort_by_key(|equation| equation.owise);
        let equation = equations
            .into_iter()
            .find(|equation| self.holds(&equation.requires, Some(argument)))
            .expect("every function is total");
        self.value(&equation.rhs, Some(argument))
    }
}

/// Fixed shapes the reviews found, checked by the oracle before the generated ones.
fn shapes() -> Vec<Case> {
    use Expr::{App, Call, Lit};
    let concat = |left: Expr, right: Expr| Expr::Concat(Box::new(left), Box::new(right));
    let keep = |left: Expr, right: Expr| Expr::Keep(Box::new(left), Box::new(right));
    let drop = |inner: Expr| Expr::Drop(Box::new(inner));
    let app = |head: usize, rhs: Expr, requires: Cond| Equation {
        head: Head::App(head),
        rhs,
        requires,
        simplification: false,
        owise: false,
    };
    let lit = |value: &str| Lit(value.to_owned());
    let length_is = |expr: Expr, length: usize| Cond::LengthIs(expr, length);
    let mut shapes = Vec::new();
    // Review 5 F1 (`ord1.k`): `A = U0 = A ++ X` gives no value; `X = U1` is `substr(A, 0, 0)`,
    // which fails for want of `A`, or `""`; `U = U2` fails through `keep(A, U)`, then is `X`.
    shapes.push(Case {
        name: "shape ord1".to_owned(),
        seed: 1,
        determined: false,
        strict: false,
        model: vec!["a".to_owned(), String::new(), String::new()],
        functions: Vec::new(),
        equations: vec![
            app(2, keep(App(0), App(2)), Cond::True),
            app(2, App(1), Cond::True),
            app(0, concat(App(0), App(1)), Cond::True),
            app(1, drop(App(0)), Cond::True),
            app(1, lit(""), Cond::True),
        ],
        inputs: vec![App(2), App(1), App(0)],
    });
    // Review 5 F1 (`hist.k`): `T1 = A ++ "|" ++ X` and `T2 = X ++ "|" ++ A` over the same `A`
    // and `X`.
    shapes.push(Case {
        name: "shape hist".to_owned(),
        seed: 2,
        determined: false,
        strict: false,
        model: vec![
            "a".to_owned(),
            String::new(),
            "a|".to_owned(),
            "|a".to_owned(),
        ],
        functions: Vec::new(),
        equations: vec![
            app(2, concat(App(0), concat(lit("|"), App(1))), Cond::True),
            app(3, concat(App(1), concat(lit("|"), App(0))), Cond::True),
            app(0, concat(App(0), App(1)), Cond::True),
            app(1, drop(App(0)), Cond::True),
            app(1, lit(""), Cond::True),
        ],
        inputs: vec![App(2), App(3), App(1)],
    });
    // Review 4 F-B with a `[simplification]` function (`st-simp-1.k`): `C = U0` is `k("")` or
    // `"c"`, `A = U1 = C`, and `k` is defined by simplification equations whose guard asks for
    // `A`: inside `A`'s attempt, `k("")` waits for `A`, so `C = k("")` fails and `C = "c"` gives
    // the value.
    let guard = length_is(App(1), 7);
    shapes.push(Case {
        name: "shape st-simp".to_owned(),
        seed: 3,
        determined: true,
        strict: false,
        model: vec!["c".to_owned(), "c".to_owned()],
        functions: vec![Function { level: 2 }],
        equations: vec![
            Equation {
                head: Head::Function(0),
                rhs: lit("z"),
                requires: guard.clone(),
                simplification: true,
                owise: false,
            },
            Equation {
                head: Head::Function(0),
                rhs: lit("c"),
                requires: Cond::Not(Box::new(guard)),
                simplification: true,
                owise: false,
            },
            app(0, Call(0, Box::new(lit(""))), Cond::True),
            app(0, lit("c"), Cond::True),
            app(1, App(0), Cond::True),
        ],
        inputs: vec![App(1), App(0)],
    });
    // A record's stack read below its deepest open attempt: `T = U4 = P ++ R` with `P = U2 =
    // keep(Q, "p")`, `Q = U1 = X ++ ""`, `X = U0 = drop(P) ++ keep(Q, "x")` and `R = U3 = Q ++
    // "r"`. Inside `P` and `Q`, `X` fails for want of `P`; inside `R` and `Q`, with the same
    // application `Q` at the same depth but `R` below it, `X` is `"x"`.
    shapes.push(Case {
        name: "shape stack-below".to_owned(),
        seed: 4,
        determined: false,
        strict: true,
        model: ["x", "x", "p", "xr", "pxr"].map(str::to_owned).to_vec(),
        functions: Vec::new(),
        equations: vec![
            app(4, concat(App(2), App(3)), Cond::True),
            app(2, keep(App(1), lit("p")), Cond::True),
            app(1, concat(App(0), lit("")), Cond::True),
            app(0, concat(drop(App(2)), keep(App(1), lit("x"))), Cond::True),
            app(3, concat(App(1), lit("r")), Cond::True),
        ],
        inputs: vec![App(4)],
    });
    // A value recorded for the first application of a lineage that took further steps reads
    // what those steps read. `T = U4 = A ++ X`, `A = U2 = B` and `B = U1 = X ++ ""`, so `A`'s
    // lineage steps on `B`, whose attempt is still open when the lineage ends; `X = U0` is `A ++
    // W` (with `W = U3`, which never gives a value) or `"x"`. In `T`, `A` is evaluated first and
    // `B`'s attempt finds `X` not open. Then `X`'s attempt on `A ++ W` reaches `A` with `X`
    // open: evaluated afresh, `B` fails for want of `X`, so `A` gets no value there and `X` is
    // `"x"`; `A`'s record, had it lost what `B`'s attempt read, would give `A` its value there
    // and `X` the value `"x" ++ W`.
    shapes.push(Case {
        name: "shape lineage-reads".to_owned(),
        seed: 5,
        determined: false,
        strict: false,
        model: ["x", "x", "x", "", "xx"].map(str::to_owned).to_vec(),
        functions: Vec::new(),
        equations: vec![
            app(4, concat(App(2), App(0)), Cond::True),
            app(0, concat(App(2), App(3)), Cond::True),
            app(0, lit("x"), Cond::True),
            app(1, concat(App(0), lit("")), Cond::True),
            app(2, App(1), Cond::True),
            app(3, concat(App(3), lit("")), Cond::True),
        ],
        inputs: vec![App(4)],
    });
    shapes
}

// The loops build several vectors indexed by application at once.
#[allow(clippy::needless_range_loop)]
fn generate(seed: u64) -> Case {
    let mut rng = Rng(seed);
    let apps = 2 + rng.below(4);
    let determined = rng.chance(1, 2);
    let mut generator = Generator {
        rng: &mut rng,
        model: Vec::new(),
        functions: Vec::new(),
        equations: Vec::new(),
    };
    let function_count = generator.rng.below(4);
    for index in 0..function_count {
        generator.function(index, apps);
    }
    // The value equations, lowest application first; an undetermined application gets a value of
    // the model at random and only equations that hold it.
    let mut undetermined = vec![false; apps];
    let mut value_equations = Vec::new();
    for index in 0..apps {
        if !determined && generator.rng.chance(2, 5) {
            undetermined[index] = true;
            let value = generator.literal();
            generator.model.push(value);
            continue;
        }
        let rhs = generator.expr(2, index, function_count, false);
        let value = generator.model().value(&rhs, None);
        generator.model.push(value);
        let mut requires = generator.cond(1, index, function_count, false);
        if !generator.model().holds(&requires, None) {
            requires = Cond::Not(Box::new(requires));
        }
        value_equations.push(Equation {
            head: Head::App(index),
            rhs,
            requires,
            simplification: false,
            owise: false,
        });
    }
    // Every application's other equations, now that the model is complete: those that hold the
    // application, and others that give its value of the model through anything. A strict
    // undetermined definition gives each application at most one equation that may give a
    // result.
    let strict = !determined && generator.rng.chance(1, 2);
    let mut app_equations = value_equations;
    for index in 0..apps {
        let extra = if undetermined[index] {
            1 + generator.rng.below(2)
        } else {
            generator.rng.below(3)
        };
        let has_productive = !undetermined[index];
        for count in 0..extra {
            let productive = if strict {
                !has_productive && count == 0 && generator.rng.chance(1, 3)
            } else {
                generator.rng.chance(1, 2)
            };
            let equation = if productive {
                let value = generator.model[index].clone();
                let rhs = if generator.rng.chance(1, 2) {
                    generator.target(&value, apps, function_count)
                } else {
                    generator.wrapped(&value, apps, function_count)
                };
                Equation {
                    head: Head::App(index),
                    rhs,
                    requires: generator.cond(1, apps, function_count, false),
                    simplification: false,
                    owise: false,
                }
            } else {
                generator.holding(index, apps, function_count)
            };
            app_equations.push(equation);
        }
    }
    let inputs = {
        let mut inputs = (0..apps).map(Expr::App).collect::<Vec<_>>();
        inputs.push(generator.expr(2, apps, function_count, false));
        inputs
    };
    let Generator {
        model,
        functions,
        mut equations,
        ..
    } = generator;
    equations.extend(app_equations);
    // Reduction aids for a reported case: drop the equations listed (by their label) and keep
    // only the input listed.
    if let Ok(dropped) = std::env::var("KRUST_UNSPECIFIED_ORACLE_DROP") {
        let dropped = dropped
            .split(',')
            .map(|label| label.trim().parse::<usize>().expect("an equation label"))
            .collect::<Vec<_>>();
        let mut index = 0;
        equations.retain(|_| {
            index += 1;
            !dropped.contains(&(index - 1))
        });
    }
    let inputs = match env_number("KRUST_UNSPECIFIED_ORACLE_INPUT") {
        Some(kept) => vec![inputs[kept as usize].clone()],
        None => inputs,
    };
    Case {
        name: format!("seed {seed}"),
        seed,
        determined,
        strict,
        model,
        functions,
        equations,
        inputs,
    }
}

const STRING: &str = r"SortString{}";

fn app_kore(index: usize) -> String {
    format!(
        r#"substr{{}}(\dv{{SortString{{}}}}("abc"), \dv{{SortInt{{}}}}("{}"), \dv{{SortInt{{}}}}("1"))"#,
        index + 2
    )
}

fn string_kore(value: &str) -> String {
    format!(r#"\dv{{SortString{{}}}}("{value}")"#)
}

fn expr_kore(expr: &Expr) -> String {
    match expr {
        Expr::Lit(value) => string_kore(value),
        Expr::App(index) => app_kore(*index),
        Expr::Arg => format!("X:{STRING}"),
        Expr::Concat(left, right) => {
            format!(
                "concatString{{}}({}, {})",
                expr_kore(left),
                expr_kore(right)
            )
        }
        Expr::Keep(left, right) => format!("keep{{}}({}, {})", expr_kore(left), expr_kore(right)),
        Expr::Drop(inner) => format!(
            r#"substr{{}}({}, \dv{{SortInt{{}}}}("0"), \dv{{SortInt{{}}}}("0"))"#,
            expr_kore(inner)
        ),
        Expr::Call(function, argument) => format!("f{function}{{}}({})", expr_kore(argument)),
    }
}

fn cond_kore(cond: &Cond) -> String {
    let int = |value: usize| format!(r#"\dv{{SortInt{{}}}}("{value}")"#);
    match cond {
        Cond::True => r#"\dv{SortBool{}}("true")"#.to_owned(),
        Cond::LengthAbove(expr, bound) => format!(
            "gtInt{{}}(lengthString{{}}({}), {})",
            expr_kore(expr),
            int(*bound)
        ),
        Cond::LengthIs(expr, length) => format!(
            "eqInt{{}}(lengthString{{}}({}), {})",
            expr_kore(expr),
            int(*length)
        ),
        Cond::Is(expr, literal) => format!(
            "eqString{{}}({}, {})",
            expr_kore(expr),
            string_kore(literal)
        ),
        Cond::Not(cond) => format!("notBool{{}}({})", cond_kore(cond)),
        Cond::And(left, right) => format!("andBool{{}}({}, {})", cond_kore(left), cond_kore(right)),
        Cond::Or(left, right) => format!("orBool{{}}({}, {})", cond_kore(left), cond_kore(right)),
    }
}

fn equation_kore(equation: &Equation, label: usize) -> String {
    // A function equation's left-hand side has variables only: the arguments of `U_i` are
    // matched through `\in` constraints before its `requires` is evaluated.
    let requires = format!(
        r#"\equals{{SortBool{{}}, R}}({}, \dv{{SortBool{{}}}}("true"))"#,
        cond_kore(&equation.requires)
    );
    let (lhs, arguments) = match equation.head {
        Head::App(index) => (
            r"substr{}(X0:SortString{}, X1:SortInt{}, X2:SortInt{})".to_owned(),
            format!(
                r#"\and{{R}}(\in{{SortString{{}}, R}}(X0:SortString{{}}, S:SortString{{}}), \and{{R}}(\in{{SortInt{{}}, R}}(X1:SortInt{{}}, \dv{{SortInt{{}}}}("{}")), \and{{R}}(\in{{SortInt{{}}, R}}(X2:SortInt{{}}, \dv{{SortInt{{}}}}("1")), \top{{R}}())))"#,
                index + 2
            ),
        ),
        Head::Function(index) => (format!("f{index}{{}}(X:{STRING})"), r"\top{R}()".to_owned()),
    };
    // Without argument constraints, the requires is the second conjunct's first.
    let antecedent = match equation.head {
        Head::App(_) => format!(r"\and{{R}}({requires}, {arguments})"),
        Head::Function(_) => format!(r"\and{{R}}(\top{{R}}(), \and{{R}}({requires}, {arguments}))"),
    };
    let mut attributes = format!(r#"label{{}}("e{label}")"#);
    if equation.simplification {
        attributes.push_str(", simplification{}()");
    }
    if equation.owise {
        attributes.push_str(r#", priority{}("200")"#);
    }
    format!(
        r#"
        axiom{{R}} \implies{{R}}(
            {antecedent},
            \equals{{SortString{{}}, R}}({lhs}, \and{{SortString{{}}}}({}, \top{{SortString{{}}}}()))
        ) [{attributes}]"#,
        expr_kore(&equation.rhs),
    )
}

/// The groups whose order an evaluation may depend on: the equations of one head, one theory and
/// one priority, as indices into `equations`, in the order generated.
fn groups(equations: &[Equation]) -> Vec<Vec<usize>> {
    let mut groups: Vec<((Head, bool, bool), Vec<usize>)> = Vec::new();
    for (index, equation) in equations.iter().enumerate() {
        let key = (equation.head, equation.simplification, equation.owise);
        match groups.iter_mut().find(|(group, _)| *group == key) {
            Some((_, members)) => members.push(index),
            None => groups.push((key, vec![index])),
        }
    }
    groups.into_iter().map(|(_, members)| members).collect()
}

fn definition_kore(case: &Case, order: &[Vec<usize>]) -> String {
    let mut source = String::from(
        r#"[]
        module MAIN
            hooked-sort SortBool{} [hook{}("BOOL.Bool"), hasDomainValues{}()]
            hooked-sort SortString{} [hook{}("STRING.String"), hasDomainValues{}()]
            hooked-sort SortInt{} [hook{}("INT.Int"), hasDomainValues{}()]
            hooked-symbol substr{}(SortString{}, SortInt{}, SortInt{}) : SortString{}
                [function{}(), total{}(), hook{}("STRING.substr")]
            hooked-symbol concatString{}(SortString{}, SortString{}) : SortString{}
                [function{}(), total{}(), hook{}("STRING.concat")]
            hooked-symbol lengthString{}(SortString{}) : SortInt{}
                [function{}(), total{}(), hook{}("STRING.length")]
            hooked-symbol eqString{}(SortString{}, SortString{}) : SortBool{}
                [function{}(), total{}(), hook{}("STRING.eq")]
            hooked-symbol gtInt{}(SortInt{}, SortInt{}) : SortBool{}
                [function{}(), total{}(), hook{}("INT.gt")]
            hooked-symbol eqInt{}(SortInt{}, SortInt{}) : SortBool{}
                [function{}(), total{}(), hook{}("INT.eq")]
            hooked-symbol andBool{}(SortBool{}, SortBool{}) : SortBool{}
                [function{}(), total{}(), hook{}("BOOL.and")]
            hooked-symbol orBool{}(SortBool{}, SortBool{}) : SortBool{}
                [function{}(), total{}(), hook{}("BOOL.or")]
            hooked-symbol notBool{}(SortBool{}) : SortBool{}
                [function{}(), total{}(), hook{}("BOOL.not")]
            symbol keep{}(SortString{}, SortString{}) : SortString{} [function{}(), total{}()]
            axiom{R} \implies{R}(
                \and{R}(\top{R}(), \and{R}(\top{R}(), \top{R}())),
                \equals{SortString{}, R}(
                    keep{}(X:SortString{}, Y:SortString{}),
                    \and{SortString{}}(Y:SortString{}, \top{SortString{}}())
                )
            ) [label{}("keep")]
"#,
    );
    for index in 0..case.functions.len() {
        writeln!(
            source,
            "            symbol f{index}{{}}(SortString{{}}) : SortString{{}} [function{{}}(), total{{}}()]"
        )
        .unwrap();
    }
    for group in order {
        for &index in group {
            source.push_str(&equation_kore(&case.equations[index], index));
        }
    }
    source.push_str("\n        endmodule []\n");
    source
}

/// What one simplification ended with.
#[derive(Debug, Eq, PartialEq)]
enum Outcome {
    Result {
        term: Term,
        constraints: Vec<Predicate>,
    },
    /// The iteration budget ran out: skipped (documented residual).
    Exhausted,
    Error(String),
}

/// The outcome of one simplification, and whether it met a rule condition already being
/// evaluated for the same term (`simplify::condition_reentries`): such a condition is left
/// undecided, which the documented residual covers.
fn simplify_once(definition: &BackendDefinition, input: &Term, reuse: bool) -> (Outcome, bool) {
    // Each simplification is cancelled after `limit()`: these definitions are small, so a longer
    // one is a cost out of proportion (an evaluation repeated without bound) and a failure.
    let token = CancellationToken::new();
    let before = snapshot();
    let reentries = condition_reentries();
    let (done, finished) = mpsc::channel::<()>();
    let watchdog = {
        let token = token.clone();
        thread::spawn(move || {
            if finished.recv_timeout(limit()) == Err(RecvTimeoutError::Timeout) {
                token.cancel();
            }
        })
    };
    let run = || {
        token.scope(|| {
            diagnostic::collect(|| {
                simplify::simplify(definition, input, SimplificationOptions::default())
            })
            .0
        })
    };
    let result = if reuse {
        run()
    } else {
        without_unspecified_reuse(run)
    };
    let _ = done.send(());
    watchdog.join().expect("the watchdog does not panic");
    let attempts = snapshot()
        .delta(&before)
        .get(Counter::SimplifyEquationAttempts);
    let reentered = condition_reentries() != reentries;
    let outcome = match result {
        Err(stop) => Outcome::Error(format!(
            "stopped after {attempts} equation attempts: {}",
            stop.into_cause()
        )),
        Ok(Err(SimplificationError::IterationLimit { .. })) => Outcome::Exhausted,
        Ok(Err(error)) => Outcome::Error(error.to_string()),
        Ok(Ok(simplification)) if simplification.exhausted.is_some() => Outcome::Exhausted,
        Ok(Ok(simplification)) => Outcome::Result {
            constraints: simplification.constraints().to_vec(),
            term: simplification.term,
        },
    };
    (outcome, reentered)
}

/// A short reading of a term, for reports.
fn show(term: &Term) -> String {
    match term.kind() {
        TermKind::DomainValue { value, .. } => format!("{value:?}"),
        TermKind::Application {
            symbol, arguments, ..
        } => {
            if &*symbol.name == "substr"
                && let [string, start, end] = arguments.as_slice()
                && let (
                    TermKind::DomainValue { value: string, .. },
                    TermKind::DomainValue { value: start, .. },
                    TermKind::DomainValue { value: end, .. },
                ) = (string.kind(), start.kind(), end.kind())
                && string.as_bytes() == b"abc"
                && end.as_bytes() == b"1"
                && let Ok(start) = start.as_utf8()
            {
                let index = start.parse::<usize>().expect("an index") - 2;
                return format!("U{index}");
            }
            let arguments = arguments.iter().map(show).collect::<Vec<_>>().join(", ");
            format!("{}({arguments})", symbol.name)
        }
        _ => format!("{term:?}"),
    }
}

fn show_outcome(outcome: &Outcome) -> String {
    match outcome {
        Outcome::Result { term, constraints } if constraints.is_empty() => show(term),
        Outcome::Result { term, constraints } => format!("{} with {constraints:?}", show(term)),
        Outcome::Exhausted => "budget exhausted".to_owned(),
        Outcome::Error(error) => error.clone(),
    }
}

fn show_expr(expr: &Expr) -> String {
    match expr {
        Expr::Lit(value) => format!("{value:?}"),
        Expr::App(index) => format!("U{index}"),
        Expr::Arg => "X".to_owned(),
        Expr::Concat(left, right) => format!("({} ++ {})", show_expr(left), show_expr(right)),
        Expr::Keep(left, right) => format!("keep({}, {})", show_expr(left), show_expr(right)),
        Expr::Drop(inner) => format!("drop({})", show_expr(inner)),
        Expr::Call(function, argument) => format!("f{function}({})", show_expr(argument)),
    }
}

fn show_cond(cond: &Cond) -> String {
    match cond {
        Cond::True => "true".to_owned(),
        Cond::LengthAbove(expr, bound) => format!("len({}) > {bound}", show_expr(expr)),
        Cond::LengthIs(expr, length) => format!("len({}) == {length}", show_expr(expr)),
        Cond::Is(expr, literal) => format!("{} == {literal:?}", show_expr(expr)),
        Cond::Not(cond) => format!("not({})", show_cond(cond)),
        Cond::And(left, right) => format!("({} and {})", show_cond(left), show_cond(right)),
        Cond::Or(left, right) => format!("({} or {})", show_cond(left), show_cond(right)),
    }
}

/// The case's model and equations in the given order, for reports.
fn show_case(case: &Case, order: &[Vec<usize>]) -> String {
    let mut text = format!(
        "  model {:?} (determined {}, strict {})\n",
        case.model, case.determined, case.strict
    );
    for group in order {
        for &index in group {
            let equation = &case.equations[index];
            let head = match equation.head {
                Head::App(index) => format!("U{index}"),
                Head::Function(index) => format!("f{index}(X)"),
            };
            let kind = match (equation.simplification, equation.owise) {
                (true, _) => " [simplification]",
                (_, true) => " [owise]",
                _ => "",
            };
            writeln!(
                text,
                "  e{index}: {head} = {} requires {}{kind}",
                show_expr(&equation.rhs),
                show_cond(&equation.requires)
            )
            .unwrap();
        }
    }
    text
}

fn is_value(term: &Term) -> bool {
    matches!(term.kind(), TermKind::DomainValue { .. })
}

/// The counts of a run.
#[derive(Default)]
struct Counts {
    definitions: u64,
    determined: u64,
    strict: u64,
    terms: u64,
    orders: u64,
    simplifications: u64,
    exhausted: u64,
    reentered: u64,
}

/// Check one case; a violation is returned with a description.
/// A failed check: its kind and a report.
struct Violation {
    kind: &'static str,
    text: String,
}

fn check(case: &Case, counts: &mut Counts) -> Result<(), Violation> {
    let mut rng = Rng(case.seed.wrapping_mul(0x2545_f491_4f6c_dd1d) ^ 0xa5a5_a5a5);
    let generated = groups(&case.equations);
    let mut orders = vec![generated.clone()];
    orders.push(
        generated
            .iter()
            .map(|group| group.iter().rev().copied().collect())
            .collect(),
    );
    for _ in 0..ORDERS {
        let mut order = generated.clone();
        for group in &mut order {
            rng.shuffle(group);
        }
        orders.push(order);
    }
    let definitions = orders
        .iter()
        .map(|order| {
            let source = definition_kore(case, order);
            let syntax = parse_definition(&source)
                .unwrap_or_else(|error| panic!("{}: {error}\n{source}", case.name));
            BackendDefinition::internalize(&syntax, "MAIN")
                .unwrap_or_else(|error| panic!("{}: {error:?}\n{source}", case.name))
        })
        .collect::<Vec<_>>();
    let model = Model {
        apps: &case.model,
        equations: &case.equations,
    };
    counts.definitions += 1;
    counts.determined += u64::from(case.determined);
    counts.strict += u64::from(case.strict);
    counts.orders += orders.len() as u64;
    for input in &case.inputs {
        counts.terms += 1;
        let expected = model.value(input, None);
        let mut first: Option<(usize, Outcome)> = None;
        let mut first_reentered = false;
        for (order_index, definition) in definitions.iter().enumerate() {
            let syntax = parse_pattern(&expr_kore(input)).expect("input parses");
            let term = definition
                .admit_unverified(&syntax, &[])
                .internalize_term()
                .expect("input internalizes");
            let value = parse_pattern(&string_kore(&expected)).expect("value parses");
            let value = definition
                .admit_unverified(&value, &[])
                .internalize_term()
                .expect("value internalizes");
            let (fresh, fresh_reentered) = simplify_once(definition, &term, false);
            let (reused, reused_reentered) = simplify_once(definition, &term, true);
            let reentered = fresh_reentered || reused_reentered;
            counts.simplifications += 2;
            counts.reentered += u64::from(reentered);
            let describe = |kind: &'static str, what: &str| Violation {
                kind,
                text: format!(
                    "{} input {} order {order_index}: {what}\n  without reuse: {}\n  with reuse: {}\n  model value {expected:?}\n{}",
                    case.name,
                    show_expr(input),
                    show_outcome(&fresh),
                    show_outcome(&reused),
                    show_case(case, &orders[order_index])
                ),
            };
            if fresh == Outcome::Exhausted || reused == Outcome::Exhausted {
                counts.exhausted += 1;
                continue;
            }
            for outcome in [&fresh, &reused] {
                match outcome {
                    Outcome::Error(error) => {
                        return Err(describe("error", &format!("error {error}")));
                    }
                    Outcome::Result { term, constraints } => {
                        if is_value(term) && (*term != value || !constraints.is_empty()) {
                            return Err(describe("unsound", "a value other than the model's"));
                        }
                        // A condition left undecided by its own re-entry is the documented
                        // residual.
                        if case.determined && *term != value && !reentered {
                            return Err(describe(
                                "determined",
                                "a determined input without its value",
                            ));
                        }
                    }
                    Outcome::Exhausted => unreachable!(),
                }
            }
            if let (
                Outcome::Result {
                    term: fresh_term, ..
                },
                Outcome::Result { term, .. },
            ) = (&fresh, &reused)
                && is_value(fresh_term)
                && !is_value(term)
            {
                return Err(describe(
                    "reuse",
                    "reuse kept an application where the evaluation without it gave a value",
                ));
            }
            if fresh != reused {
                return Err(describe("reuse", "reuse changed the result"));
            }
            if reentered {
                first_reentered = true;
            }
            match &first {
                None => first = Some((order_index, fresh)),
                Some((first_order, first_outcome)) => {
                    if case.strict && !first_reentered && *first_outcome != fresh {
                        return Err(describe(
                            "order",
                            &format!(
                                "the result differs from that of order {first_order}: {}",
                                show_outcome(first_outcome)
                            ),
                        ));
                    }
                }
            }
        }
    }
    Ok(())
}

fn env_number(name: &str) -> Option<u64> {
    std::env::var(name).ok().map(|value| {
        value
            .parse()
            .unwrap_or_else(|_| panic!("{name} must be a number, not {value:?}"))
    })
}

/// The oracle over generated definitions (module documentation). Reproduce a reported case with
/// `KRUST_UNSPECIFIED_ORACLE_SEED=<seed> KRUST_UNSPECIFIED_ORACLE_CASES=1`.
#[test]
fn unspecified_evaluation_agrees_with_and_without_reuse_in_every_order() {
    let first = env_number("KRUST_UNSPECIFIED_ORACLE_SEED").unwrap_or(0);
    let cases = env_number("KRUST_UNSPECIFIED_ORACLE_CASES").unwrap_or(DEFAULT_CASES);
    let mut counts = Counts::default();
    let max_failures = env_number("KRUST_UNSPECIFIED_ORACLE_FAILURES").unwrap_or(3);
    let mut failures: Vec<Violation> = Vec::new();
    let verbose = std::env::var_os("KRUST_UNSPECIFIED_ORACLE_VERBOSE").is_some();
    // The shapes, the regression seeds, and the shapes again with records bounded at no entry,
    // which checks a record past its bound (`simplify::with_reads_bound`); then the generated
    // definitions. Each with the bound of its run.
    let fixed = if std::env::var_os("KRUST_UNSPECIFIED_ORACLE_NO_SHAPES").is_some() {
        Vec::new()
    } else {
        let bounded = shapes().into_iter().map(|mut case| {
            case.name.push_str(", reads bounded at 0");
            (case, Some(0))
        });
        shapes()
            .into_iter()
            .map(|case| (case, None))
            .chain(
                REGRESSION_SEEDS
                    .into_iter()
                    .map(|seed| (generate(seed), None)),
            )
            .chain(bounded)
            .collect()
    };
    let generated = (first..first + cases).map(|seed| (generate(seed), None));
    for (case, bound) in fixed.into_iter().chain(generated) {
        if verbose {
            eprintln!("{}", case.name);
        }
        let checked = match bound {
            Some(bound) => with_reads_bound(bound, || check(&case, &mut counts)),
            None => check(&case, &mut counts),
        };
        if let Err(failure) = checked {
            eprintln!(
                "violation ({}): {}",
                failure.kind,
                failure.text.lines().next().unwrap_or_default()
            );
            failures.push(failure);
            if failures.len() as u64 >= max_failures {
                break;
            }
        }
    }
    eprintln!(
        "unspecified oracle: {} definitions ({} determined, {} strict), {} terms, {} orders, {} simplifications, {} skipped for the budget, {} runs with a re-entered condition",
        counts.definitions,
        counts.determined,
        counts.strict,
        counts.terms,
        counts.orders,
        counts.simplifications,
        counts.exhausted,
        counts.reentered
    );
    let mut kinds = std::collections::BTreeMap::<&str, usize>::new();
    for failure in &failures {
        *kinds.entry(failure.kind).or_default() += 1;
    }
    assert!(
        failures.is_empty(),
        "{} failures {kinds:?}:\n{}",
        failures.len(),
        failures
            .iter()
            .take(3)
            .map(|failure| failure.text.as_str())
            .collect::<Vec<_>>()
            .join("\n\n")
    );
}
