/// Compares every tour-minimal expansion with a native per-invocation
/// capture, token for token, as `fallback.rs` does for the support driver.
///
/// `KRS_NATIVE_CAPTURE` names a JSON Lines capture; the rows
/// of `krs_tour_minimal` with display file `src/lib.rs` (the `krs emit-k`
/// collector build) are compared after re-lexing rustc's text through
/// `proc_macro2`.
#[test]
#[ignore = "needs a native capture; set KRS_NATIVE_CAPTURE"]
fn tour_minimal_matches_the_native_capture() {
    let path = std::env::var("KRS_NATIVE_CAPTURE").expect("KRS_NATIVE_CAPTURE names a capture");
    let capture = std::fs::read_to_string(&path).expect("the native capture is readable");
    let mut rows = capture
        .lines()
        .map(|line| serde_json::from_str::<serde_json::Value>(line).expect("a JSON capture row"))
        .filter(|row| row["crate"] == "krs_tour_minimal" && row["file"] == "src/lib.rs")
        .collect::<Vec<_>>();
    rows.sort_by_key(|row| (row["line"].as_u64(), row["column"].as_u64()));
    let expansion = expand(TOUR_MINIMAL).expect("tour-minimal expands");
    assert_eq!(rows.len(), expansion.expansions.len());
    for (row, expansion) in rows.iter().zip(&expansion.expansions) {
        let native: TokenStream = row["output"]
            .as_str()
            .expect("a captured output")
            .parse()
            .expect("native output lexes");
        assert_eq!(
            native.to_string(),
            expansion.output.to_string(),
            "{} at {}:{}",
            expansion.kind,
            row["line"],
            row["column"]
        );
    }
}

/// Compares the whole-file expansion of every corpus crate whose native
/// capture rows carry display file `src/lib.rs` with those rows, token for
/// token (`KRS_NATIVE_CAPTURE`, as above).
///
/// This extends the tour-minimal token check to the other surfaces those
/// crates use; rows are matched by call-site position.
#[test]
#[ignore = "needs a native capture; set KRS_NATIVE_CAPTURE"]
fn corpus_matches_the_native_capture() {
    const CRATES: &[(&str, &str)] = &[
        ("krs_tour_imp", "tests/tour-imp/src/lib.rs"),
        ("krs_tour_negatives", "tests/tour-negatives/src/lib.rs"),
        (
            "krs_c7_associativity",
            "tests/c7/rust-definition/src/lib.rs",
        ),
        (
            "krs_expr_fixture",
            "crates/krs-expand/tests/fixtures/expr/src/lib.rs",
        ),
        ("m3b_calc", "tests/m3b/rust-definition/src/lib.rs"),
    ];
    let path = std::env::var("KRS_NATIVE_CAPTURE").expect("KRS_NATIVE_CAPTURE names a capture");
    let capture = std::fs::read_to_string(&path).expect("the native capture is readable");
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    for (crate_name, file) in CRATES {
        let mut rows = capture
            .lines()
            .map(|line| serde_json::from_str::<serde_json::Value>(line).unwrap())
            .filter(|row| row["crate"] == *crate_name && row["file"] == "src/lib.rs")
            .collect::<Vec<_>>();
        rows.sort_by_key(|row| (row["line"].as_u64(), row["column"].as_u64()));
        let source = std::fs::read_to_string(root.join(file)).unwrap();
        let module_path = vec![(*crate_name).to_owned()];
        let expansion = whole_file::expand_file(&FileRequest {
            display_file: "src/lib.rs",
            source: &source,
            generated_file: GENERATED_FILE,
            facade_alias: "k",
            facade_path: syn::parse_str("::k").unwrap(),
            module_path: &module_path,
            selection: &Selection::WholeFile,
        })
        .unwrap_or_else(|diagnostics| panic!("{crate_name}: {diagnostics:?}"));
        let map = &expansion.generated.map;
        let mut outputs = expansion
            .expansions
            .iter()
            .map(|expansion| {
                let start = map.invocations[expansion.id.0].call_site.start;
                let line = source[..start].matches('\n').count() + 1;
                let column = source[..start]
                    .rsplit('\n')
                    .next()
                    .map_or(0, |prefix| prefix.chars().count())
                    + 1;
                (
                    (line as u64, column as u64),
                    expansion.kind,
                    &expansion.output,
                )
            })
            .collect::<Vec<_>>();
        outputs.sort_by_key(|(position, _, _)| *position);
        assert_eq!(
            rows.len(),
            outputs.len(),
            "{crate_name}: one row per invocation"
        );
        for (row, (position, kind, output)) in rows.iter().zip(&outputs) {
            assert_eq!(
                (
                    row["line"].as_u64().unwrap(),
                    row["column"].as_u64().unwrap()
                ),
                *position,
                "{crate_name}: {kind}"
            );
            let native: TokenStream = row["output"].as_str().unwrap().parse().unwrap();
            assert_eq!(
                native.to_string(),
                output.to_string(),
                "{crate_name}: {kind} at {position:?}"
            );
        }
    }
}
