use crate::plan::{CollectorKind, CollectorPlan, KrsCfg, RegistrationMode, manifest_directory};
use sha2::{Digest, Sha256};
use std::error::Error;
use std::fmt;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

const MARKER: &str = "KRS generated collector package; safe to replace.\n";

/// Deterministic bytes for a generated collector package.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct GeneratedCollector {
    /// Generated `Cargo.toml` bytes.
    pub manifest: Vec<u8>,
    /// Generated `src/main.rs` bytes.
    pub main_source: Vec<u8>,
    /// Generated `.cargo/config.toml` bytes.
    pub cargo_config: Vec<u8>,
    /// Canonical selection JSON, which never contains manifest paths.
    pub canonical_selection: Vec<u8>,
}

impl GeneratedCollector {
    /// Generate a package from a validated plan without touching the filesystem.
    ///
    /// # Errors
    ///
    /// Returns [`GenerationError`] if a Cargo manifest path has no package
    /// directory or canonical selection serialization fails.
    pub fn from_plan(plan: &CollectorPlan) -> Result<Self, GenerationError> {
        let main_source = render_main(plan);
        let cargo_config = render_cargo_config(plan);
        let canonical_selection = plan
            .canonical_selection_json()
            .map_err(GenerationError::Serialization)?;
        let mut identity = Sha256::new();
        for bytes in [
            main_source.as_bytes(),
            cargo_config.as_bytes(),
            canonical_selection.as_slice(),
        ] {
            identity.update(bytes.len().to_le_bytes());
            identity.update(bytes);
        }
        let identity = format!("{:x}", identity.finalize());
        let package_name = format!("krs-generated-collector-{}", &identity[..32]);
        let manifest = render_manifest(plan, &package_name)?;
        Ok(Self {
            manifest: manifest.into_bytes(),
            main_source: main_source.into_bytes(),
            cargo_config: cargo_config.into_bytes(),
            canonical_selection,
        })
    }

    /// Write this generated package below a caller-selected directory.
    ///
    /// A non-empty directory is accepted only when it contains KRS's marker,
    /// preventing accidental replacement of an unrelated Cargo package.
    ///
    /// # Errors
    ///
    /// Returns [`GenerationError`] when the directory is not empty and marked
    /// as KRS-owned, or when a directory or file cannot be written.
    pub fn write_to(&self, output: &Path) -> Result<(), GenerationError> {
        if output.exists() {
            let marker = output.join(".krs-collector");
            let empty = fs::read_dir(output)
                .map_err(|source| GenerationError::io(output, source))?
                .next()
                .is_none();
            if !empty {
                let contents = fs::read_to_string(&marker)
                    .map_err(|_| GenerationError::UnsafeOutput(output.to_path_buf()))?;
                if contents != MARKER {
                    return Err(GenerationError::UnsafeOutput(output.to_path_buf()));
                }
            }
        }

        fs::create_dir_all(output.join("src"))
            .map_err(|source| GenerationError::io(output, source))?;
        fs::create_dir_all(output.join(".cargo"))
            .map_err(|source| GenerationError::io(output, source))?;
        write(&output.join(".krs-collector"), MARKER.as_bytes())?;
        write(&output.join("Cargo.toml"), &self.manifest)?;
        write(&output.join("src/main.rs"), &self.main_source)?;
        write(&output.join(".cargo/config.toml"), &self.cargo_config)?;
        write(
            &output.join("krs-selection.json"),
            &self.canonical_selection,
        )?;
        Ok(())
    }
}

fn render_manifest(plan: &CollectorPlan, package_name: &str) -> Result<String, GenerationError> {
    let package_name = toml_string(package_name);
    let mut output = format!(
        "# @generated by krs-cli; build-only paths below are intentionally host-local.\n\
         [package]\n\
         name = {package_name}\n\
         version = \"0.0.0\"\n\
         edition = \"2024\"\n\
         publish = false\n\n\
         [package.metadata.krs.collector]\n\
         schema = 1\n\
         host-only = true\n\n\
         [dependencies]\n"
    );
    for dependency in &plan.dependencies {
        let directory =
            manifest_directory(&dependency.manifest_path).map_err(GenerationError::InvalidPlan)?;
        output.push_str(&dependency.alias);
        output.push_str(" = { package = ");
        output.push_str(&toml_string(&dependency.package_name));
        output.push_str(", path = ");
        output.push_str(&toml_string(&directory.to_string_lossy()));
        output.push_str(", default-features = false");
        if !dependency.features.is_empty() {
            output.push_str(", features = [");
            for (index, feature) in dependency.features.iter().enumerate() {
                if index != 0 {
                    output.push_str(", ");
                }
                output.push_str(&toml_string(feature));
            }
            output.push(']');
        }
        output.push_str(" }\n");
    }
    if let CollectorKind::Production {
        runtime,
        registration,
    } = &plan.kind
    {
        render_runtime_dependency(
            &mut output,
            "__krs_host_runtime",
            "krs",
            &runtime.host_manifest,
            *registration == RegistrationMode::Explicit,
        )?;
        render_runtime_dependency(
            &mut output,
            "__krs_collector_runtime",
            "krs-collector",
            &runtime.collector_manifest,
            false,
        )?;
    }
    output.push_str("\n[workspace]\n");
    output.push_str("\n[profile.dev]\ndebug = 0\n");
    Ok(output)
}

fn render_runtime_dependency(
    output: &mut String,
    alias: &str,
    package: &str,
    manifest: &Path,
    no_default_features: bool,
) -> Result<(), GenerationError> {
    let directory = manifest_directory(manifest).map_err(GenerationError::InvalidPlan)?;
    output.push_str(alias);
    output.push_str(" = { package = ");
    output.push_str(&toml_string(package));
    output.push_str(", path = ");
    output.push_str(&toml_string(&directory.to_string_lossy()));
    if no_default_features {
        output.push_str(", default-features = false");
    }
    output.push_str(" }\n");
    Ok(())
}

fn render_main(plan: &CollectorPlan) -> String {
    let mut output = String::from(
        "// @generated by krs-cli. Stdout is reserved for descriptor protocol bytes.\n\n",
    );
    for dependency in plan
        .dependencies
        .iter()
        .filter(|dependency| dependency.semantics)
    {
        output.push_str("#[allow(unused_extern_crates)]\nextern crate ");
        output.push_str(&dependency.alias);
        output.push_str(" as _;\n");
    }
    match &plan.kind {
        CollectorKind::EntryPoint { alias, function } => {
            render_entrypoint_main(plan, output, alias.as_str(), function)
        }
        CollectorKind::Production { .. } => render_production_main(plan, output),
    }
}

fn render_entrypoint_main(
    plan: &CollectorPlan,
    mut output: String,
    alias: &str,
    function: &[String],
) -> String {
    output.push_str("\nconst SELECTED_FACETS: &[(&str, &str, &str, &str)] = &[\n");
    for facet in plan.facets() {
        output.push_str("    (");
        output.push_str(&rust_string(&facet.k_namespace));
        output.push_str(", ");
        output.push_str(&rust_string(&facet.definition));
        output.push_str(", ");
        output.push_str(&rust_string(&facet.root));
        output.push_str(", ");
        output.push_str(&rust_string(&facet.syntax_root));
        output.push_str("),\n");
    }
    output.push_str(
        "];

fn main() {
    let stdout = std::io::stdout();
    let mut output = stdout.lock();
    if let Err(error) = ",
    );
    output.push_str(alias);
    output.push_str("::");
    output.push_str(&function.join("::"));
    output.push_str(
        "(&mut output, SELECTED_FACETS) {
        eprintln!(\"KRS collector failed: {error}\");
        std::process::exit(1);
    }
}
",
    );
    output
}

fn render_production_main(plan: &CollectorPlan, mut output: String) -> String {
    output.push_str(
        "\nfn main() {\n    if let Err(error) = collect() {\n        eprintln!(\"KRS collector failed: {error}\");\n        std::process::exit(1);\n    }\n}\n\nfn collect() -> Result<(), Box<dyn std::error::Error>> {\n    let contexts = vec![\n",
    );
    for facet in plan.context_facets() {
        output.push_str("        __krs_collector_runtime::PackageContext::new(");
        for value in [
            facet.k_namespace.as_str(),
            facet.package_name.as_str(),
            facet.package_version.as_str(),
            facet.cargo_source.as_str(),
            facet.crate_root.as_str(),
        ] {
            output.push_str(&rust_string(value));
            output.push_str(", ");
        }
        output.push_str("std::path::Path::new(");
        output.push_str(&rust_string(&facet.manifest_path.to_string_lossy()));
        output.push_str("))?,\n");
    }
    output.push_str("    ];\n");
    let descriptors = match plan.registration() {
        RegistrationMode::Inventory => "__krs_host_runtime::host_descriptors()",
        RegistrationMode::Explicit => {
            output.push_str(
                "    let tables: &[&__krs_host_runtime::__private::RegistrationTable] = &[\n",
            );
            for dependency in plan
                .dependencies
                .iter()
                .filter(|dependency| dependency.semantics)
            {
                output.push_str("        &");
                output.push_str(&dependency.alias);
                output.push_str("::__KRS_REGISTRATIONS,\n");
            }
            output.push_str("    ];\n");
            "__krs_host_runtime::host_descriptors_from(tables)"
        }
    };
    // `run_collector` writes descriptor bytes to stdout and diagnostics and
    // opt-in measurements to the sidecars selected by `krs`.
    output.push_str("    __krs_collector_runtime::run_collector(\n        contexts,\n        || ");
    output.push_str(descriptors);
    output.push_str(",\n        __krs_host_runtime::builtin_registry,\n    )\n}\n");
    output
}

fn render_cargo_config(plan: &CollectorPlan) -> String {
    let mut output = String::from(
        "# @generated: an explicit host target prevents target-side collector execution.\n[build]\n",
    );
    output.push_str("target = ");
    output.push_str(&toml_string(plan.host_target()));
    output.push('\n');
    output.push_str("rustflags = [");
    let flags = plan
        .cfg()
        .iter()
        .map(check_cfg_flag)
        .chain(plan.cfg().iter().map(cfg_flag))
        .collect::<Vec<_>>();
    for (index, flag) in flags.iter().enumerate() {
        if index > 0 {
            output.push_str(", ");
        }
        output.push_str(&toml_string(flag));
    }
    output.push_str("]\n");
    output
}

fn check_cfg_flag(cfg: &KrsCfg) -> String {
    match &cfg.value {
        Some(value) => format!(
            "--check-cfg=cfg({},values({}))",
            cfg.key,
            rust_string(value)
        ),
        None => format!("--check-cfg=cfg({})", cfg.key),
    }
}

fn cfg_flag(cfg: &KrsCfg) -> String {
    match &cfg.value {
        Some(value) => format!("--cfg={}={}", cfg.key, rust_string(value)),
        None => format!("--cfg={}", cfg.key),
    }
}

fn rust_string(value: &str) -> String {
    proc_macro2::Literal::string(value).to_string()
}

fn toml_string(value: &str) -> String {
    toml_edit::Value::from(value).to_string()
}

fn write(path: &Path, bytes: &[u8]) -> Result<(), GenerationError> {
    match fs::read(path) {
        Ok(existing) if existing == bytes => return Ok(()),
        Ok(_) => {}
        Err(error) if error.kind() == io::ErrorKind::NotFound => {}
        Err(source) => return Err(GenerationError::io(path, source)),
    }
    fs::write(path, bytes).map_err(|source| GenerationError::io(path, source))
}

/// Failure while rendering or writing a generated collector package.
#[derive(Debug)]
pub enum GenerationError {
    /// The validated plan contained an unusable Cargo manifest path.
    InvalidPlan(crate::PlanningError),
    /// Canonical selection JSON serialization failed.
    Serialization(serde_json::Error),
    /// The output directory appears to belong to something else.
    UnsafeOutput(PathBuf),
    /// Filesystem operation failed.
    Io {
        /// Path whose filesystem operation failed.
        path: PathBuf,
        /// Underlying filesystem error.
        source: io::Error,
    },
}

impl GenerationError {
    fn io(path: &Path, source: io::Error) -> Self {
        Self::Io {
            path: path.to_path_buf(),
            source,
        }
    }
}

impl fmt::Display for GenerationError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::InvalidPlan(error) => write!(formatter, "invalid collector plan: {error}"),
            Self::Serialization(error) => {
                write!(
                    formatter,
                    "could not serialize canonical selection: {error}"
                )
            }
            Self::UnsafeOutput(path) => write!(
                formatter,
                "refusing to replace non-KRS output directory `{}`",
                path.display()
            ),
            Self::Io { path, source } => {
                write!(formatter, "could not write `{}`: {source}", path.display())
            }
        }
    }
}

impl Error for GenerationError {
    fn source(&self) -> Option<&(dyn Error + 'static)> {
        match self {
            Self::InvalidPlan(error) => Some(error),
            Self::Serialization(error) => Some(error),
            Self::UnsafeOutput(_) => None,
            Self::Io { source, .. } => Some(source),
        }
    }
}
