//! End-to-end command contracts over an independently built authored crate.

use std::fs;
use std::ops::Deref;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};
use std::sync::atomic::{AtomicU64, Ordering};

#[test]
fn commands_share_the_production_collection_and_definition_pipeline() {
    let temporary = temporary_directory();
    let target = temporary.join("target");
    let emitted = temporary.join("emitted");
    let manifest = materialize_fixture(&temporary);

    let expand = command(&target, &manifest, "expand", None);
    assert_success(&expand);
    let expanded = String::from_utf8(expand.stdout).unwrap();
    assert!(
        expanded.starts_with(
            "// @generated by `krs expand`; deterministic layer-2 reference surface.\n"
        )
    );
    assert!(expanded.contains("#[krs::rule]"));
    assert!(expanded.contains("pub fn foo_to_bar"));
    assert!(!expanded.contains("\"protocol_version\""));
    assert!(!expanded.contains("inventory"));

    let check = command(&target, &manifest, "check", None);
    assert_success(&check);
    assert_eq!(
        check.stdout,
        b"KRS check passed: 9 descriptors, 1 semantic modules\n"
    );

    let emit = command(&target, &manifest, "emit-k", Some(&emitted));
    assert_success(&emit);
    assert_eq!(
        emit.stdout,
        b"emitted descriptor-bundle.json, semantic-ir.json, definition-ir.json, definition.k, symbols.json, sources.json\n"
    );
    let descriptor_bundle = fs::read_to_string(emitted.join("descriptor-bundle.json")).unwrap();
    assert_ne!(descriptor_bundle, expanded);
    let descriptor: serde_json::Value = serde_json::from_str(&descriptor_bundle).unwrap();
    assert_eq!(descriptor["protocol_version"], 19);
    assert!(descriptor_bundle.contains("\"item_name\": \"Machine\""));
    for name in ["semantic-ir.json", "definition-ir.json"] {
        let document: serde_json::Value =
            serde_json::from_slice(&fs::read(emitted.join(name)).unwrap()).unwrap();
        assert_eq!(document["schema_version"], 12);
    }
    assert!(
        fs::read_to_string(emitted.join("definition.k"))
            .unwrap()
            .contains("rule foo => bar")
    );
    assert!(emitted.join("symbols.json").is_file());
    assert!(emitted.join("sources.json").is_file());
    assert!(emitted.join(".krs-artifacts").is_file());
    assert_eq!(
        fs::read_dir(&emitted)
            .unwrap()
            .map(|entry| entry.unwrap().file_name())
            .collect::<std::collections::BTreeSet<_>>(),
        [
            ".krs-artifacts",
            "definition-ir.json",
            "definition.k",
            "descriptor-bundle.json",
            "semantic-ir.json",
            "sources.json",
            "symbols.json",
        ]
        .map(Into::into)
        .into_iter()
        .collect()
    );

    let unsafe_output = temporary.join("user-owned");
    fs::create_dir_all(&unsafe_output).unwrap();
    fs::write(unsafe_output.join("definition.k"), "user contents\n").unwrap();
    let unsafe_emit = command(&target, &manifest, "emit-k", Some(&unsafe_output));
    assert!(!unsafe_emit.status.success());
    assert!(
        String::from_utf8(unsafe_emit.stderr)
            .unwrap()
            .contains("refusing to replace non-KRS artifact directory")
    );
    assert_eq!(
        fs::read_to_string(unsafe_output.join("definition.k")).unwrap(),
        "user contents\n"
    );

    let native = temporary.join("native");
    let build = command(&target, &manifest, "build", Some(&native));
    assert_success(&build);
    assert_eq!(
        build.stdout,
        b"built definition.kore, syntaxDefinition.kore, macros.kore\n"
    );
    assert!(native.join("definition.kore").is_file());
    assert!(native.join("syntaxDefinition.kore").is_file());
    assert!(native.join("macros.kore").is_file());
    assert!(native.join(".krs-artifacts").is_file());
}

fn command(target: &Path, manifest: &Path, command: &str, output: Option<&Path>) -> Output {
    let mut process = Command::new(env!("CARGO_BIN_EXE_krs"));
    process
        .arg(command)
        .args(["--manifest-path"])
        .arg(manifest)
        .args(["--package", "krs-cli-m2-fixture", "--definition", "main"])
        .env("CARGO_TARGET_DIR", target);
    if let Some(output) = output {
        process.arg("--output").arg(output);
    }
    process.output().unwrap()
}

fn materialize_fixture(temporary: &Path) -> PathBuf {
    let project = temporary.join("language");
    fs::create_dir_all(project.join("src")).unwrap();
    fs::write(
        project.join("src/lib.rs"),
        include_bytes!("fixtures/m2/src/lib.rs"),
    )
    .unwrap();
    let krs = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../krs")
        .canonicalize()
        .unwrap();
    let krs_literal = serde_json::to_string(krs.to_str().unwrap()).unwrap();
    let manifest = format!(
        "[package]\nname = \"krs-cli-m2-fixture\"\nversion = \"0.0.0\"\nedition = \"2024\"\npublish = false\n\n[dependencies]\nkrs = {{ path = {krs_literal} }}\n\n[package.metadata.krs]\nk-namespace = \"ORG-KRS-CLI-M2\"\n\n[package.metadata.krs.definitions.main]\nroot = \"crate\"\nsyntax-root = \"crate\"\n\n[workspace]\n"
    );
    fs::write(project.join("Cargo.toml"), manifest).unwrap();
    project.join("Cargo.toml")
}

fn assert_success(output: &Output) {
    assert!(
        output.status.success(),
        "command failed:\n{}",
        String::from_utf8_lossy(&output.stderr)
    );
}

struct TemporaryDirectory(PathBuf);

impl Deref for TemporaryDirectory {
    type Target = Path;

    fn deref(&self) -> &Self::Target {
        &self.0
    }
}

impl Drop for TemporaryDirectory {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

fn temporary_directory() -> TemporaryDirectory {
    static NEXT: AtomicU64 = AtomicU64::new(0);
    let unique = NEXT.fetch_add(1, Ordering::Relaxed);
    TemporaryDirectory(
        std::env::temp_dir().join(format!("krs-cli-commands-{}-{unique}", std::process::id())),
    )
}
