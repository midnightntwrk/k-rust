//! End-to-end command contracts over an independently built authored crate.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Output;

use krs_compiler::testing::assert_lowering_contract;
use krs_ir::testing::assert_canonical_contract;
use krs_ir::{DefinitionIr, DescriptorBundle, SemanticTheory};
use krs_test_support::{fixture_target, krs_command, temp_dir};
use sha2::{Digest, Sha256};

const FOO_BAR: &str = include_str!("fixtures/foo-bar/src/lib.rs");
const NESTED_FUNCTION_PATTERN: &str = include_str!("fixtures/nested-function-pattern/src/lib.rs");

#[test]
fn authored_fixtures_satisfy_ir_and_lowering_contracts() {
    let temporary = temp_dir();
    for (name, source) in [
        ("foo-bar", FOO_BAR),
        ("nested-function-pattern", NESTED_FUNCTION_PATTERN),
    ] {
        let manifest = materialize_fixture(temporary.path(), source);
        let target = fixture_target(&manifest, Some(temporary.path()));
        let emitted = temporary.path().join(format!("emitted-{name}"));
        let result = command(&target, &manifest, "emit-k", Some(&emitted), &[]);
        assert_success(&result);

        let bundle: DescriptorBundle =
            serde_json::from_slice(&fs::read(emitted.join("descriptor-bundle.json")).unwrap())
                .unwrap();
        let theory: SemanticTheory =
            serde_json::from_slice(&fs::read(emitted.join("semantic-ir.json")).unwrap()).unwrap();
        let definition: DefinitionIr =
            serde_json::from_slice(&fs::read(emitted.join("definition-ir.json")).unwrap()).unwrap();
        assert_canonical_contract(&bundle);
        assert_canonical_contract(&theory);
        assert_canonical_contract(&definition);
        let (lowered, _) = assert_lowering_contract(&theory);
        assert_eq!(lowered.definition(), &definition, "{name}");
    }
}

#[test]
fn build_accepts_rule_terms_nested_64_constructors_deep() {
    let temporary = temp_dir();
    let term = format!("{}Tick(0){}", "Wrap(".repeat(64), ")".repeat(64));
    let source = format!(
        r#"
use krs::KResult;
use krs::builtin::{{Int, KSequence}};

krs::sorts! {{ Step: krs::KItem; }}

#[krs::constructors(sort = Step, result = KResult)]
#[krs::precedence((Tick, Wrap))]
pub enum Op {{
    #[krs::syntax("tick ( {{value}} )")]
    Tick {{ value: Int }},
    #[krs::syntax("wrap ( {{inner}} )")]
    Wrap {{ inner: Step }},
}}

#[krs::configuration]
pub struct Machine {{
    #[krs::cell]
    pub k: KSequence,
}}

impl Machine {{
    #[krs::init]
    pub fn init(#[krs::config_var(name = "PGM", main)] program: KSequence) -> Self {{
        Self {{ k: krs::k![program] }}
    }}
}}

#[rustfmt::skip]
krs::rules! {{
    for Machine;
    use Op::*;
    deep: {{ k: [Tick(0), ..], }} => {{ k: [{term}, ..], }};
}}
"#
    );
    let manifest = materialize_fixture(temporary.path(), &source);
    let target = fixture_target(&manifest, Some(temporary.path()));
    let mut process = krs_command!();
    let output = process
        .args(["build", "--manifest-path"])
        .arg(manifest)
        .args([
            "--package",
            "krs-cli-foo-bar-fixture",
            "--definition",
            "main",
            "--output",
        ])
        .arg(temporary.path().join("built"))
        .env("CARGO_TARGET_DIR", target)
        .output()
        .unwrap();
    assert_success(&output);
    assert!(temporary.path().join("built/definition.kore").is_file());
}

#[test]
fn commands_share_the_production_collection_and_definition_pipeline() {
    let temporary = temp_dir();
    let emitted = temporary.path().join("emitted");
    let manifest = materialize_fixture(temporary.path(), FOO_BAR);
    let target = fixture_target(&manifest, Some(temporary.path()));

    let expand = command(&target, &manifest, "expand", None, &[]);
    assert_success(&expand);
    let expanded = String::from_utf8(expand.stdout).unwrap();
    assert!(
        expanded.starts_with(
            "// @generated by `krs expand`; deterministic layer-2 reference surface.\n"
        )
    );
    assert!(expanded.contains("#[krs::rule]"));
    assert!(expanded.contains("pub fn foo_to_bar"));
    assert!(!expanded.contains("\"protocol_version\""));
    assert!(!expanded.contains("inventory"));

    let check = command(&target, &manifest, "check", None, &[]);
    assert_success(&check);
    assert_eq!(
        check.stdout,
        b"KRS check passed: 9 descriptors, 1 semantic modules\n"
    );

    assert_check_measurement(temporary.path(), &target, &manifest, &check.stdout);

    let emit = command(&target, &manifest, "emit-k", Some(&emitted), &[]);
    assert_success(&emit);
    assert_eq!(
        emit.stdout,
        b"emitted descriptor-bundle.json, semantic-ir.json, definition-ir.json, definition.k, symbols.json, sources.json\n"
    );
    let descriptor_bundle = fs::read_to_string(emitted.join("descriptor-bundle.json")).unwrap();
    assert_ne!(descriptor_bundle, expanded);
    let descriptor: serde_json::Value = serde_json::from_str(&descriptor_bundle).unwrap();
    assert_eq!(
        descriptor["protocol_version"],
        krs_ir::SchemaVersion::CURRENT.0
    );
    assert!(descriptor_bundle.contains("\"item_name\": \"Machine\""));
    for name in ["semantic-ir.json", "definition-ir.json"] {
        let document: serde_json::Value =
            serde_json::from_slice(&fs::read(emitted.join(name)).unwrap()).unwrap();
        assert_eq!(document["schema_version"], krs_ir::SchemaVersion::CURRENT.0);
    }
    assert!(
        fs::read_to_string(emitted.join("definition.k"))
            .unwrap()
            .contains("rule foo => bar")
    );
    assert!(emitted.join("symbols.json").is_file());
    assert!(emitted.join("sources.json").is_file());
    assert!(emitted.join(".krs-artifacts").is_file());
    assert_eq!(
        fs::read_dir(&emitted)
            .unwrap()
            .map(|entry| entry.unwrap().file_name())
            .collect::<std::collections::BTreeSet<_>>(),
        [
            ".krs-artifacts",
            "definition-ir.json",
            "definition.k",
            "descriptor-bundle.json",
            "semantic-ir.json",
            "sources.json",
            "symbols.json",
        ]
        .map(Into::into)
        .into_iter()
        .collect()
    );

    let unsafe_output = temporary.path().join("user-owned");
    fs::create_dir_all(&unsafe_output).unwrap();
    fs::write(unsafe_output.join("definition.k"), "user contents\n").unwrap();
    let unsafe_emit = command(&target, &manifest, "emit-k", Some(&unsafe_output), &[]);
    assert!(!unsafe_emit.status.success());
    assert!(
        String::from_utf8(unsafe_emit.stderr)
            .unwrap()
            .contains("refusing to replace non-KRS artifact directory")
    );
    assert_eq!(
        fs::read_to_string(unsafe_output.join("definition.k")).unwrap(),
        "user contents\n"
    );

    let native = temporary.path().join("native");
    assert_build_measurement(temporary.path(), &target, &manifest, &native);
    assert!(native.join("definition.kore").is_file());
    assert!(native.join("syntaxDefinition.kore").is_file());
    assert!(native.join("macros.kore").is_file());
    assert!(native.join(".krs-artifacts").is_file());
}

#[test]
fn located_collector_failure_preserves_tokens_and_removes_scratch_files() {
    let temporary = temp_dir();
    let source = FOO_BAR.replace(
        "pub trait Obj: KResult {}",
        "pub trait Obj: KResult + Send {}",
    );
    let manifest = materialize_fixture(temporary.path(), &source);
    let target = fixture_target(&manifest, Some(temporary.path()));
    let scratch = temporary.path().join("scratch");
    fs::create_dir(&scratch).unwrap();
    let timings_path = temporary.path().join("timings.json");
    let mut process = krs_command!();
    let output = process
        .args(["check", "--manifest-path"])
        .arg(&manifest)
        .args([
            "--package",
            "krs-cli-foo-bar-fixture",
            "--definition",
            "main",
            "--timings",
        ])
        .arg(&timings_path)
        .env("CARGO_TARGET_DIR", target)
        .env("CARGO_NET_OFFLINE", "true")
        .env("RUSTUP_TOOLCHAIN", "stable")
        .env("TMPDIR", &scratch)
        .output()
        .unwrap();
    let stderr = String::from_utf8_lossy(&output.stderr);
    assert!(!output.status.success(), "{stderr}");
    let diagnostics = krs_cli::DiagnosticEnvelope::from_json_lines(&stderr).unwrap();
    assert_eq!(diagnostics.len(), 1, "{stderr}");
    let diagnostic = &diagnostics[0];
    assert_eq!(diagnostic.code, "krs::collect::unresolved-type-reference");
    assert_eq!(diagnostic.stage, krs_cli::DiagnosticStage::Analysis);
    let range = &diagnostic.authored_range;
    assert_eq!(range.file.package().k_namespace(), "ORG-KRS-CLI-FOO-BAR");
    assert_eq!(range.file.package_relative_path(), "src/lib.rs");
    assert_eq!(
        range.file.content_sha256(),
        &krs_ir::Sha256Digest::from_bytes(Sha256::digest(source.as_bytes()).into())
    );
    let start = source.find("Send").unwrap();
    assert_eq!(range.start_byte as usize, start);
    assert_eq!(range.end_byte as usize, start + "Send".len());
    assert!(output.stdout.is_empty());
    assert!(
        stderr.contains("Rust path `Send` does not resolve to a selected KRS type declaration"),
        "{stderr}"
    );
    let timings = read_json(&timings_path);
    assert_eq!(timings["failed_span"], "collector.run");
    let leftovers = fs::read_dir(&scratch)
        .unwrap()
        .map(|entry| entry.unwrap().file_name().to_string_lossy().into_owned())
        .filter(|name| {
            name.starts_with("krs-collector-read-set-")
                || name.starts_with("krs-collector-measure-")
                || name.starts_with("krs-collector-diagnostics-")
        })
        .collect::<Vec<_>>();
    assert!(
        leftovers.is_empty(),
        "collector scratch files remain: {leftovers:?}"
    );
}

/// `check --timings --counters` reports the whole pipeline and stable counters.
fn assert_check_measurement(temporary: &Path, target: &Path, manifest: &Path, stdout: &[u8]) {
    let timings_path = temporary.join("check-timings.json");
    let counters_path = temporary.join("check-counters.json");
    let measured = command(
        target,
        manifest,
        "check",
        None,
        &[
            "--no-reuse",
            "--timings",
            timings_path.to_str().unwrap(),
            "--counters",
            counters_path.to_str().unwrap(),
        ],
    );
    assert_success(&measured);
    assert_eq!(measured.stdout, stdout, "measurement changed stdout");
    let timings = read_json(&timings_path);
    assert_eq!(timings["schema"], "krs-timings/1");
    assert_eq!(timings["command"], "check");
    assert_eq!(timings["status"], "ok");
    assert!(timings["failed_span"].is_null());
    assert_eq!(
        span_ids(&timings),
        [
            ("cargo.metadata.input", 0),
            ("host.discover", 0),
            ("cargo.metadata.runtime", 0),
            ("collector.plan", 0),
            ("collector.generate", 0),
            ("collector.build", 0),
            ("collector.run", 0),
            ("collector.exec", 1),
            ("collector.factories", 1),
            ("collector.builtins", 1),
            ("collector.resolve", 1),
            ("collector.resolve.builtins", 2),
            ("collector.resolve.intake", 2),
            ("collector.resolve.tables", 2),
            ("collector.resolve.provenance", 2),
            ("collector.resolve.payload", 2),
            ("collector.resolve.bundle", 2),
            ("collector.serialize", 1),
            ("collector.write", 1),
            ("collector.release", 1),
            ("protocol.decode", 0),
            ("semantic.lower", 0),
            ("definition.lower", 0),
            ("check.adapt", 0),
            ("release", 0),
        ]
        .map(|(id, depth)| (id.to_owned(), depth))
    );
    assert_timing_invariants(&timings);
    let counters = read_json(&counters_path);
    assert_eq!(counters["schema"], "krs-counters/1");
    assert_eq!(counters["status"], "ok");
    let counters = &counters["counters"];
    assert_eq!(counters["result.reused"], 0);
    assert_eq!(counters["descriptors.total"], 9);
    assert_eq!(counters["semantic.modules"], 1);
    let bundle_bytes = counters["bundle.bytes"].as_u64().unwrap();
    let provenance_bytes = counters["bundle.provenance_bytes"].as_u64().unwrap();
    assert!(provenance_bytes > 0 && provenance_bytes < bundle_bytes);
    assert_eq!(
        counters["bundle.other_bytes"].as_u64().unwrap(),
        bundle_bytes - provenance_bytes
    );
    // Counters are deterministic: a second run writes the same bytes.
    let again_path = temporary.join("check-counters-again.json");
    assert_success(&command(
        target,
        manifest,
        "check",
        None,
        &["--no-reuse", "--counters", again_path.to_str().unwrap()],
    ));
    assert_eq!(
        fs::read(&counters_path).unwrap(),
        fs::read(&again_path).unwrap()
    );
}

/// `build --timings --counters` nests k-rust phases and counts KORE bytes.
fn assert_build_measurement(temporary: &Path, target: &Path, manifest: &Path, native: &Path) {
    let build_timings = temporary.join("build-timings.json");
    let build_counters = temporary.join("build-counters.json");
    let build = command(
        target,
        manifest,
        "build",
        Some(native),
        &[
            "--no-reuse",
            "--timings",
            build_timings.to_str().unwrap(),
            "--counters",
            build_counters.to_str().unwrap(),
        ],
    );
    assert_success(&build);
    let timings = read_json(&build_timings);
    assert_timing_invariants(&timings);
    let ids = span_ids(&timings);
    let top = ids
        .iter()
        .filter(|(_, depth)| *depth == 0)
        .map(|(id, _)| id.as_str())
        .skip_while(|id| *id != "definition.lower")
        .collect::<Vec<_>>();
    assert_eq!(
        top,
        [
            "definition.lower",
            "native.adapt",
            "native.prepare",
            "native.compile",
            "native.reparse.definition",
            "native.reparse.syntax",
            "native.provenance",
            "native.write",
            "release",
        ]
    );
    let compile = ids
        .iter()
        .position(|(id, _)| id == "native.compile")
        .unwrap();
    assert!(
        ids[compile + 1..]
            .iter()
            .take_while(|(_, depth)| *depth > 0)
            .any(|(id, depth)| id == "definition checks" && *depth == 1),
        "k-rust phases are not nested below native.compile: {ids:?}"
    );
    let counters = &read_json(&build_counters)["counters"];
    assert_eq!(counters["result.reused"], 0);
    assert_eq!(
        counters["native.bytes.definition.kore"].as_u64().unwrap(),
        fs::metadata(native.join("definition.kore")).unwrap().len()
    );
    assert_eq!(
        build.stdout,
        b"built definition.kore, syntaxDefinition.kore, macros.kore\n"
    );
}

fn read_json(path: &Path) -> serde_json::Value {
    serde_json::from_slice(&fs::read(path).unwrap()).unwrap()
}

fn span_ids(timings: &serde_json::Value) -> Vec<(String, u64)> {
    timings["spans"]
        .as_array()
        .unwrap()
        .iter()
        .map(|span| {
            (
                span["id"].as_str().unwrap().to_owned(),
                span["depth"].as_u64().unwrap(),
            )
        })
        .collect()
}

fn assert_timing_invariants(timings: &serde_json::Value) {
    let total = timings["total_wall_seconds"].as_f64().unwrap();
    let unattributed = timings["unattributed_seconds"].as_f64().unwrap();
    assert!(unattributed >= 0.0 && unattributed <= total, "{timings}");
    let spans = timings["spans"].as_array().unwrap();
    let mut previous_depth = 0;
    for span in spans {
        let depth = span["depth"].as_u64().unwrap();
        assert!(
            depth <= previous_depth + 1,
            "a span skips a level: {timings}"
        );
        assert!(span["seconds"].as_f64().unwrap() >= 0.0);
        previous_depth = depth;
    }
}

fn command(
    target: &Path,
    manifest: &Path,
    command: &str,
    output: Option<&Path>,
    arguments: &[&str],
) -> Output {
    let mut process = krs_command!();
    process
        .arg(command)
        .args(arguments)
        .args(["--manifest-path"])
        .arg(manifest)
        .args([
            "--package",
            "krs-cli-foo-bar-fixture",
            "--definition",
            "main",
        ])
        .env("CARGO_TARGET_DIR", target);
    if let Some(output) = output {
        process.arg("--output").arg(output);
    }
    process.output().unwrap()
}

fn materialize_fixture(temporary: &Path, source: &str) -> PathBuf {
    let project = temporary.join("language");
    fs::create_dir_all(project.join("src")).unwrap();
    fs::write(project.join("src/lib.rs"), source).unwrap();
    let krs = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../krs")
        .canonicalize()
        .unwrap();
    let krs_literal = serde_json::to_string(krs.to_str().unwrap()).unwrap();
    let manifest = format!(
        "[package]\nname = \"krs-cli-foo-bar-fixture\"\nversion = \"0.0.0\"\nedition = \"2024\"\npublish = false\n\n[dependencies]\nkrs = {{ path = {krs_literal} }}\n\n[package.metadata.krs]\nk-namespace = \"ORG-KRS-CLI-FOO-BAR\"\n\n[package.metadata.krs.definitions.main]\nroot = \"crate\"\nsyntax-root = \"crate\"\n\n[workspace]\n"
    );
    fs::write(project.join("Cargo.toml"), manifest).unwrap();
    project.join("Cargo.toml")
}

fn assert_success(output: &Output) {
    assert!(
        output.status.success(),
        "command failed:\n{}",
        String::from_utf8_lossy(&output.stderr)
    );
}

#[test]
fn native_rejection_reports_the_authored_rust_item_on_every_backend() {
    let temporary = temp_dir();
    let manifest = materialize_fixture(temporary.path(), NESTED_FUNCTION_PATTERN);
    let target = fixture_target(&manifest, Some(temporary.path()));
    let item = "twist_twice";
    let start = NESTED_FUNCTION_PATTERN.find("fn twist_twice(").unwrap() + "fn ".len();

    for backend in ["haskell", "llvm"] {
        let native = temporary.path().join(backend);
        let timings_path = temporary.path().join(format!("{backend}-timings.json"));
        let build = command(
            &target,
            &manifest,
            "build",
            Some(&native),
            &[
                "--backend",
                backend,
                "--timings",
                timings_path.to_str().unwrap(),
            ],
        );
        let timings = read_json(&timings_path);
        assert_eq!(timings["status"], "failed", "{backend}");
        assert_eq!(timings["failed_span"], "native.compile", "{backend}");
        assert_timing_invariants(&timings);
        assert!(
            span_ids(&timings)
                .iter()
                .any(|(id, depth)| id == "native.diagnostics" && *depth == 0)
        );
        let stderr = String::from_utf8(build.stderr).unwrap();
        assert!(!build.status.success(), "{backend} accepted:\n{stderr}");
        assert!(build.stdout.is_empty(), "{backend}");
        assert!(!native.exists(), "{backend} wrote artifacts");
        let lines = stderr.lines().collect::<Vec<_>>();
        assert_eq!(lines.len(), 1, "{backend}:\n{stderr}");
        let diagnostic: serde_json::Value = serde_json::from_str(lines[0]).unwrap();
        assert_eq!(diagnostic["schema_version"], 1, "{stderr}");
        assert_eq!(diagnostic["stage"], "native", "{stderr}");
        assert_eq!(diagnostic["code"], "IllegalFunctionOnLhs", "{stderr}");
        assert_eq!(diagnostic["severity"], "error", "{stderr}");
        let range = &diagnostic["authored_range"];
        assert_eq!(
            range["file"]["package"]["cargo_name"],
            "krs-cli-foo-bar-fixture"
        );
        assert_eq!(range["file"]["package_relative_path"], "src/lib.rs");
        assert_eq!(range["start_byte"], start, "{stderr}");
        assert_eq!(range["end_byte"], start + item.len(), "{stderr}");
    }
}
