//! JSON protocol of the expander module (schema 1).
//!
//! # Expansion
//!
//! The browser worker sends one UTF-8 JSON request per build:
//!
//! ```json
//! {
//!   "schema": 1,
//!   "mode": "whole-file",
//!   "file": {
//!     "virtual_path": "/workspace/tour-minimal/src/lib.rs",
//!     "display_file": "src/lib.rs",
//!     "source": "<complete UTF-8 source>"
//!   },
//!   "package": {
//!     "cargo_name": "krs-tour-minimal",
//!     "cargo_version": "0.0.0",
//!     "manifest_dir": "/workspace/tour-minimal",
//!     "crate_name": "krs_tour_minimal"
//!   },
//!   "module_path": ["krs_tour_minimal"],
//!   "facade": { "alias": "k", "path": "::k" },
//!   "generated_file": "/work/expanded/tour-minimal/src/lib.rs",
//!   "policy": { "editable_files": ["src/lib.rs"], "facade_alias": "k" }
//! }
//! ```
//!
//! - `mode` is `"whole-file"` or
//!   `{ "invocations": [{ "kind": "sorts", "replaced": [287, 320] }] }`, which
//!   expands only the listed outermost invocations (editor tooling and
//!   tests).
//! - `file.virtual_path` must equal `package.manifest_dir` joined with
//!   `file.display_file`, and `display_file` is the value rustc reports as
//!   `Span::file()` for the lesson, which enters factory names.
//! - `module_path` must start with `package.crate_name`.
//! - `facade.alias` must equal `policy.facade_alias`.
//! - `policy` is the lesson manifest's `[policy]` table
//!   (`krs_lesson_policy::LessonPolicy`); the policy runs first, and any
//!   policy diagnostic stops the request before expansion.
//!
//! `package` fields do not enter the generated text: generated factories keep
//! `env!("CARGO_…")` and `module_path!()`, and the rustc that compiles the
//! output supplies them.
//!
//! The response:
//!
//! ```json
//! {
//!   "schema": 1,
//!   "ok": true,
//!   "expanded": { "generated_file": "/work/expanded/tour-minimal/src/lib.rs", "text": "…" },
//!   "source_map": { "version": 1, "generated_file": "…", "authored_file": "src/lib.rs",
//!                   "authored_sha256": "…", "invocations": [], "segments": [] },
//!   "diagnostics": [],
//!   "registrations": [
//!     { "invocation": 0, "module_path": ["krs_tour_minimal"], "factory": "__krs_…", "cfg": [] }
//!   ],
//!   "requests_framework": true,
//!   "evidence": { "krs_expand_version": "0.1.0", "request_sha256": "…",
//!                 "authored_sha256": "…", "text_sha256": "…" }
//! }
//! ```
//!
//! `ok` is true exactly when `diagnostics` is empty; `expanded` and
//! `source_map` are present exactly then. A diagnostic is:
//!
//! ```json
//! { "origin": "expander", "code": null, "severity": "error", "message": "expected identifier",
//!   "class": "exact-authored", "file": "src/lib.rs", "authored": [19, 20], "invocation": 0,
//!   "notes": [] }
//! ```
//!
//! `origin` is `policy`, `expander`, or `protocol`. A renderer diagnostic
//! has `code: null`, as rustc reports `compile_error!` output; the expander's
//! own diagnostics use `krs::expand::*` codes and policy diagnostics
//! `krs::policy::*`. `authored` is a UTF-8 byte range in the authored file:
//! the exact range for `exact-authored`, the invocation's call site for
//! `invocation-level`, and `null` for `unmappable`.
//!
//! # Lookup
//!
//! A lookup request maps generated byte ranges (rustc diagnostic spans in
//! the generated file) through a source map this module returned:
//!
//! ```json
//! { "schema": 1, "authored_source": "<the authored source>",
//!   "text": "<expanded.text>", "source_map": { … }, "ranges": [[1200, 1205]] }
//! ```
//!
//! The response is `{ "schema": 1, "ok": true, "mappings": [ { "class": …,
//! "authored": [s, e] | null, "invocation": n | null } ], "diagnostics": [] }`
//! with one mapping per range, classified by `krs_expand::sink::lookup`.

use std::collections::BTreeMap;

use krs_expand::sink::{
    self, AuthoredFile, GeneratedSource, Invocation, InvocationId, Mapping, MappingClass, Segment,
    SourceMap,
};
use krs_expand::whole_file::{self, ExpandDiagnostic, FileRequest, SelectedInvocation, Selection};
use krs_lesson_policy::{LessonPolicy, PolicyDiagnostic};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

/// Protocol schema this module reads and writes.
pub const SCHEMA: u32 = 1;

/// The request is not a valid schema-1 request.
pub const PROTOCOL_ERROR: &str = {
    const CODE: &krs_diagnostic::Code = &krs_diagnostic::codes::expand::PROTOCOL_ERROR;
    CODE.as_str()
};

/// One expansion request.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Request {
    /// Must equal [`SCHEMA`].
    pub schema: u32,
    /// Which invocations to expand.
    pub mode: Mode,
    /// The authored file.
    pub file: File,
    /// The lesson package.
    pub package: Package,
    /// Module path of the file, starting with the crate name.
    pub module_path: Vec<String>,
    /// How authored and generated code name the `krs` facade.
    pub facade: Facade,
    /// Path of the generated file the browser rustc compiles.
    pub generated_file: String,
    /// The lesson manifest's `[policy]` table.
    pub policy: LessonPolicy,
}

/// Which invocations to expand.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(rename_all = "kebab-case", deny_unknown_fields)]
pub enum Mode {
    /// Every outermost KRS invocation.
    WholeFile,
    /// Only the listed outermost invocations.
    Invocations(Vec<Selected>),
}

/// One explicitly selected invocation.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Selected {
    /// The `krs-macros` entry-point name.
    pub kind: String,
    /// The authored byte range the expansion replaces.
    pub replaced: [usize; 2],
}

/// The authored file of a request.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct File {
    /// Absolute path of the authored file in the worker's file system.
    pub virtual_path: String,
    /// Package-relative display file (rustc `Span::file()`).
    pub display_file: String,
    /// The complete UTF-8 source.
    pub source: String,
}

/// The lesson package of a request.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Package {
    /// `CARGO_PKG_NAME`.
    pub cargo_name: String,
    /// `CARGO_PKG_VERSION`.
    pub cargo_version: String,
    /// `CARGO_MANIFEST_DIR`.
    pub manifest_dir: String,
    /// `CARGO_CRATE_NAME`.
    pub crate_name: String,
}

/// The facade names of a request.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Facade {
    /// The dependency name authored code uses, `k`.
    pub alias: String,
    /// The path generated code uses, `::k`.
    pub path: String,
}

/// One expansion response.
#[derive(Clone, Debug, Serialize)]
pub struct Response {
    /// Always [`SCHEMA`].
    pub schema: u32,
    /// True exactly when `diagnostics` is empty.
    pub ok: bool,
    /// The generated file, when `ok`.
    pub expanded: Option<Expanded>,
    /// The generated-to-authored map, when `ok`.
    pub source_map: Option<SourceMapJson>,
    /// Every diagnostic.
    pub diagnostics: Vec<Diagnostic>,
    /// Registered descriptor factories, in expansion order.
    pub registrations: Vec<RegistrationJson>,
    /// Whether the expansions request the framework sort descriptors.
    pub requests_framework: bool,
    /// Identity values for retained evidence.
    pub evidence: Evidence,
}

/// The generated file.
#[derive(Clone, Debug, Serialize)]
pub struct Expanded {
    /// Path of the generated file.
    pub generated_file: String,
    /// Its text.
    pub text: String,
}

/// One diagnostic.
#[derive(Clone, Debug, Serialize)]
pub struct Diagnostic {
    /// `policy`, `expander`, or `protocol`.
    pub origin: &'static str,
    /// Stable code, or `None` for a renderer diagnostic.
    pub code: Option<String>,
    /// Always `error`.
    pub severity: &'static str,
    /// The message.
    pub message: String,
    /// Mapping class ([`krs_expand::sink::MappingClass::name`]).
    pub class: &'static str,
    /// The file the diagnostic concerns.
    pub file: String,
    /// UTF-8 byte range in the authored file.
    pub authored: Option<[usize; 2]>,
    /// The invocation that reported it, numbered as in the source map.
    pub invocation: Option<usize>,
    /// Notes; none today.
    pub notes: Vec<String>,
}

/// One registered factory.
#[derive(Clone, Debug, Serialize)]
pub struct RegistrationJson {
    /// Outermost invocation id.
    pub invocation: usize,
    /// Module path of the factory.
    pub module_path: Vec<String>,
    /// Factory name.
    pub factory: String,
    /// `#[cfg]` attributes of the registration.
    pub cfg: Vec<String>,
}

/// Identity values of one run.
#[derive(Clone, Debug, Serialize)]
pub struct Evidence {
    /// `krs-expand-wasm` package version.
    pub krs_expand_version: &'static str,
    /// SHA-256 of the request bytes.
    pub request_sha256: String,
    /// SHA-256 of the authored source, when the request parsed.
    pub authored_sha256: Option<String>,
    /// SHA-256 of `expanded.text`, when `ok`.
    pub text_sha256: Option<String>,
}

/// The JSON form of [`SourceMap`], plus the authored hash.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct SourceMapJson {
    /// [`sink::SOURCE_MAP_VERSION`].
    pub version: u32,
    /// Path of the generated file.
    pub generated_file: String,
    /// Display file of the authored source.
    pub authored_file: String,
    /// SHA-256 of the authored source.
    pub authored_sha256: String,
    /// Expanded invocations by id.
    pub invocations: Vec<InvocationJson>,
    /// Classified generated ranges.
    pub segments: Vec<SegmentJson>,
}

/// The JSON form of [`Invocation`].
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct InvocationJson {
    /// Id.
    pub id: usize,
    /// Entry-point name.
    pub kind: String,
    /// Authored call-site range.
    pub call_site: [usize; 2],
    /// Authored replaced range.
    pub replaced: [usize; 2],
    /// Parent invocation.
    pub parent: Option<usize>,
}

/// The JSON form of [`Segment`].
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct SegmentJson {
    /// Generated range.
    pub generated: [usize; 2],
    /// Mapping class ([`krs_expand::sink::MappingClass::name`]).
    pub class: String,
    /// Authored range of an exact-authored segment.
    pub authored: Option<[usize; 2]>,
    /// Owning invocation.
    pub owner: Option<usize>,
    /// Authored span of a respanned token.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub respanned: Option<[usize; 2]>,
}

fn pair(range: &krs_expand::sink::ByteRange) -> [usize; 2] {
    [range.start(), range.end()]
}

fn range([start, end]: [usize; 2]) -> Result<krs_expand::sink::ByteRange, String> {
    krs_expand::sink::ByteRange::new(start, end).map_err(|error| error.to_string())
}

/// Lowercase hexadecimal SHA-256.
#[must_use]
pub fn sha256(bytes: &[u8]) -> String {
    krs_ir::lower_hex(&Sha256::digest(bytes))
}

impl SourceMapJson {
    /// The JSON form of `map` for an authored source with hash
    /// `authored_sha256`.
    #[must_use]
    pub fn new(map: &SourceMap, authored_sha256: String) -> Self {
        Self {
            version: map.version,
            generated_file: map.generated_file.clone(),
            authored_file: map.authored_file.clone(),
            authored_sha256,
            invocations: map
                .invocations
                .iter()
                .map(|invocation| InvocationJson {
                    id: invocation.id.0,
                    kind: invocation.kind.clone(),
                    call_site: pair(&invocation.call_site),
                    replaced: pair(&invocation.replaced),
                    parent: invocation.parent.map(|parent| parent.0),
                })
                .collect(),
            segments: map
                .segments
                .iter()
                .map(|segment| SegmentJson {
                    generated: pair(&segment.generated),
                    class: segment.class.name().to_owned(),
                    authored: segment.authored.as_ref().map(pair),
                    owner: segment.owner.map(|owner| owner.0),
                    respanned: segment.respanned.as_ref().map(pair),
                })
                .collect(),
        }
    }

    /// The [`SourceMap`] this JSON form describes.
    ///
    /// # Errors
    ///
    /// Returns a message for an unknown class name or reversed byte range.
    pub fn to_map(&self) -> Result<SourceMap, String> {
        let class = |name: &str| {
            [
                MappingClass::ExactAuthored,
                MappingClass::InvocationLevel,
                MappingClass::GeneratedOnly,
                MappingClass::Unmappable,
            ]
            .into_iter()
            .find(|class| class.name() == name)
            .ok_or_else(|| format!("unknown mapping class `{name}`"))
        };
        Ok(SourceMap {
            version: self.version,
            generated_file: self.generated_file.clone(),
            authored_file: self.authored_file.clone(),
            invocations: self
                .invocations
                .iter()
                .map(|invocation| {
                    Ok(Invocation {
                        id: InvocationId(invocation.id),
                        kind: invocation.kind.clone(),
                        call_site: range(invocation.call_site)?,
                        replaced: range(invocation.replaced)?,
                        parent: invocation.parent.map(InvocationId),
                    })
                })
                .collect::<Result<_, String>>()?,
            segments: self
                .segments
                .iter()
                .map(|segment| {
                    Ok(Segment {
                        generated: range(segment.generated)?,
                        class: class(&segment.class)?,
                        authored: segment.authored.map(range).transpose()?,
                        owner: segment.owner.map(InvocationId),
                        respanned: segment.respanned.map(range).transpose()?,
                    })
                })
                .collect::<Result<_, String>>()?,
        })
    }
}

impl Diagnostic {
    fn protocol(message: String) -> Self {
        Self {
            origin: "protocol",
            code: Some(PROTOCOL_ERROR.to_owned()),
            severity: "error",
            message,
            class: MappingClass::Unmappable.name(),
            file: String::new(),
            authored: None,
            invocation: None,
            notes: Vec::new(),
        }
    }

    fn policy(diagnostic: PolicyDiagnostic) -> Self {
        Self {
            origin: "policy",
            code: Some(diagnostic.code.to_owned()),
            severity: "error",
            message: diagnostic.message,
            class: diagnostic.class,
            file: diagnostic.file,
            authored: diagnostic.authored.as_ref().map(pair),
            invocation: None,
            notes: Vec::new(),
        }
    }

    fn expander(diagnostic: ExpandDiagnostic, file: &str) -> Self {
        Self {
            origin: "expander",
            code: diagnostic.code.map(str::to_owned),
            severity: "error",
            message: diagnostic.message,
            class: diagnostic.class.name(),
            file: file.to_owned(),
            authored: diagnostic.authored.as_ref().map(pair),
            invocation: diagnostic.invocation.map(|invocation| invocation.0),
            notes: Vec::new(),
        }
    }
}

impl Response {
    fn failed(diagnostics: Vec<Diagnostic>, evidence: Evidence) -> Self {
        Self {
            schema: SCHEMA,
            ok: false,
            expanded: None,
            source_map: None,
            diagnostics,
            registrations: Vec::new(),
            requests_framework: false,
            evidence,
        }
    }
}

/// Checks the request fields that must agree with each other.
fn validate(request: &Request) -> Result<syn::Path, String> {
    if request.schema != SCHEMA {
        return Err(format!(
            "request schema {} is not supported; expected {SCHEMA}",
            request.schema
        ));
    }
    let expected_path = format!(
        "{}/{}",
        request.package.manifest_dir.trim_end_matches('/'),
        request.file.display_file
    );
    if request.file.virtual_path != expected_path {
        return Err(format!(
            "file.virtual_path `{}` is not package.manifest_dir joined with file.display_file (`{expected_path}`)",
            request.file.virtual_path
        ));
    }
    if request.module_path.first() != Some(&request.package.crate_name) {
        return Err(format!(
            "module_path {:?} does not start with crate name `{}`",
            request.module_path, request.package.crate_name
        ));
    }
    if request.facade.alias != request.policy.facade_alias {
        return Err(format!(
            "facade.alias `{}` differs from policy.facade_alias `{}`",
            request.facade.alias, request.policy.facade_alias
        ));
    }
    syn::parse_str::<syn::Path>(&request.facade.path).map_err(|error| {
        format!(
            "facade.path `{}` is not a path: {error}",
            request.facade.path
        )
    })
}

/// Runs one expansion request.
#[must_use]
pub fn run(request_bytes: &[u8]) -> Response {
    let mut evidence = Evidence {
        krs_expand_version: env!("CARGO_PKG_VERSION"),
        request_sha256: sha256(request_bytes),
        authored_sha256: None,
        text_sha256: None,
    };
    let request = match serde_json::from_slice::<Request>(request_bytes) {
        Ok(request) => request,
        Err(error) => {
            return Response::failed(
                vec![Diagnostic::protocol(format!(
                    "malformed expansion request: {error}"
                ))],
                evidence,
            );
        }
    };
    evidence.authored_sha256 = Some(sha256(request.file.source.as_bytes()));
    let facade_path = match validate(&request) {
        Ok(path) => path,
        Err(message) => return Response::failed(vec![Diagnostic::protocol(message)], evidence),
    };

    let files = BTreeMap::from([(
        request.file.display_file.clone(),
        request.file.source.clone(),
    )]);
    let policy = krs_lesson_policy::check_request(&files, &request.policy);
    if !policy.is_empty() {
        return Response::failed(
            policy.into_iter().map(Diagnostic::policy).collect(),
            evidence,
        );
    }

    let selection = match &request.mode {
        Mode::WholeFile => Ok(Selection::WholeFile),
        Mode::Invocations(selected) => selected
            .iter()
            .map(|selected| {
                Ok(SelectedInvocation {
                    kind: selected.kind.clone(),
                    replaced: range(selected.replaced)?,
                })
            })
            .collect::<Result<_, String>>()
            .map(Selection::Invocations),
    };
    let selection = match selection {
        Ok(selection) => selection,
        Err(message) => return Response::failed(vec![Diagnostic::protocol(message)], evidence),
    };
    let expansion = whole_file::expand_file(&FileRequest {
        display_file: &request.file.display_file,
        source: &request.file.source,
        generated_file: &request.generated_file,
        facade_alias: &request.facade.alias,
        facade_path,
        module_path: &request.module_path,
        selection: &selection,
    });
    let expansion = match expansion {
        Ok(expansion) => expansion,
        Err(diagnostics) => {
            return Response::failed(
                diagnostics
                    .into_iter()
                    .map(|diagnostic| Diagnostic::expander(diagnostic, &request.file.display_file))
                    .collect(),
                evidence,
            );
        }
    };
    let text = expansion.generated.text;
    evidence.text_sha256 = Some(sha256(text.as_bytes()));
    let authored_sha256 = sha256(request.file.source.as_bytes());
    Response {
        schema: SCHEMA,
        ok: true,
        source_map: Some(SourceMapJson::new(
            &expansion.generated.map,
            authored_sha256,
        )),
        expanded: Some(Expanded {
            generated_file: request.generated_file,
            text,
        }),
        diagnostics: Vec::new(),
        registrations: expansion
            .registrations
            .into_iter()
            .map(|registration| RegistrationJson {
                invocation: registration.invocation.0,
                module_path: registration.module_path,
                factory: registration.factory,
                cfg: registration.cfg,
            })
            .collect(),
        requests_framework: expansion.requests_framework,
        evidence,
    }
}

/// Runs one expansion request given as JSON bytes and returns the JSON
/// response bytes.
///
/// It does not invalidate `proc_macro2`'s thread-local span map; the Wasm
/// ABI does after each call.
///
/// # Panics
///
/// Never in practice: a [`Response`] always serializes.
#[must_use]
pub fn run_json(request: &[u8]) -> Vec<u8> {
    serde_json::to_vec(&run(request)).expect("expansion responses always serialize")
}

/// The JSON expansion response for a protocol error raised before any
/// request bytes are read.
pub(crate) fn protocol_error_json(message: &str) -> Vec<u8> {
    let evidence = Evidence {
        krs_expand_version: env!("CARGO_PKG_VERSION"),
        request_sha256: sha256(&[]),
        authored_sha256: None,
        text_sha256: None,
    };
    let response = Response::failed(vec![Diagnostic::protocol(message.to_owned())], evidence);
    serde_json::to_vec(&response).expect("expansion responses always serialize")
}

/// One lookup request.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct LookupRequest {
    /// Must equal [`SCHEMA`].
    pub schema: u32,
    /// The authored source the map was made for.
    pub authored_source: String,
    /// The generated text (`expanded.text`).
    pub text: String,
    /// The map returned with `text`.
    pub source_map: SourceMapJson,
    /// Generated byte ranges to classify.
    pub ranges: Vec<[usize; 2]>,
}

/// One lookup response.
#[derive(Clone, Debug, Serialize)]
pub struct LookupResponse {
    /// Always [`SCHEMA`].
    pub schema: u32,
    /// True exactly when `diagnostics` is empty.
    pub ok: bool,
    /// One mapping per requested range.
    pub mappings: Vec<MappingJson>,
    /// Protocol diagnostics.
    pub diagnostics: Vec<Diagnostic>,
}

/// One classified range.
#[derive(Clone, Debug, Eq, PartialEq, Serialize)]
pub struct MappingJson {
    /// Mapping class ([`krs_expand::sink::MappingClass::name`]).
    pub class: &'static str,
    /// The exact authored range, or the invocation's call site.
    pub authored: Option<[usize; 2]>,
    /// The invocation the range belongs to.
    pub invocation: Option<usize>,
}

fn lookup_inner(request: &[u8]) -> Result<Vec<MappingJson>, String> {
    let request = serde_json::from_slice::<LookupRequest>(request)
        .map_err(|error| format!("malformed lookup request: {error}"))?;
    if request.schema != SCHEMA {
        return Err(format!(
            "request schema {} is not supported; expected {SCHEMA}",
            request.schema
        ));
    }
    if sha256(request.authored_source.as_bytes()) != request.source_map.authored_sha256 {
        return Err("authored_source does not match source_map.authored_sha256".to_owned());
    }
    let map = request.source_map.to_map()?;
    let (authored, _) = AuthoredFile::lex(&map.authored_file, &request.authored_source)
        .map_err(|error| format!("authored_source does not lex: {error}"))?;
    let source = GeneratedSource {
        text: request.text,
        map,
    };
    request
        .ranges
        .iter()
        .map(|&generated| {
            Ok(match sink::lookup(&source, &authored, range(generated)?) {
                Mapping::ExactAuthored { authored, owner } => MappingJson {
                    class: MappingClass::ExactAuthored.name(),
                    authored: Some(pair(&authored)),
                    invocation: owner.map(|owner| owner.0),
                },
                Mapping::InvocationLevel { owner, call_site } => MappingJson {
                    class: MappingClass::InvocationLevel.name(),
                    authored: Some(pair(&call_site)),
                    invocation: Some(owner.0),
                },
                Mapping::GeneratedOnly => MappingJson {
                    class: MappingClass::GeneratedOnly.name(),
                    authored: None,
                    invocation: None,
                },
                Mapping::Unmappable => MappingJson {
                    class: MappingClass::Unmappable.name(),
                    authored: None,
                    invocation: None,
                },
            })
        })
        .collect()
}

/// Runs one lookup request given as JSON bytes and returns the JSON response
/// bytes.
///
/// # Panics
///
/// Never in practice: a [`LookupResponse`] always serializes.
#[must_use]
pub fn lookup_json(request: &[u8]) -> Vec<u8> {
    let response = match lookup_inner(request) {
        Ok(mappings) => LookupResponse {
            schema: SCHEMA,
            ok: true,
            mappings,
            diagnostics: Vec::new(),
        },
        Err(message) => LookupResponse {
            schema: SCHEMA,
            ok: false,
            mappings: Vec::new(),
            diagnostics: vec![Diagnostic::protocol(message)],
        },
    };
    serde_json::to_vec(&response).expect("lookup responses always serialize")
}
