//! The escape tables of the generated parser's token literals, printed as a C header.
//!
//! A generated parser writes each token as the KORE string literal of the code points the
//! in-process frontend reads from it (`kompile::term_to_kore`): a `STRING.String` token's
//! characters after its K escapes, a `BYTES.Bytes` token's bytes as the code points of their
//! values, any other token's characters. `cparser/main.c` holds the one decoder and the one
//! encoder that do this; the escapes they read and write are the constants of
//! [`crate::kast::string`] (K literals) and [`crate::kore::string`] (KORE literals), printed
//! here, so the generated parser and the in-process route cannot read or write a different set.

use std::fmt::Write as _;

use crate::kast::string as k;
use crate::kore::string as kore;

/// The C header `cparser/main.c` includes as `krust_literals.h`.
pub(super) fn header() -> String {
    let mut output = String::from(
        "/* Generated by krust: the escapes of K token literals and of KORE string literals. */\n\
         #ifndef KRUST_LITERALS_H\n\
         #define KRUST_LITERALS_H\n\
         \n\
         /* An escape naming a code point by a letter. */\n\
         struct krust_named_escape {\n  char letter;\n  unsigned long code_point;\n};\n\
         \n\
         /* An escape giving a number in exactly `digits` hexadecimal digits. */\n\
         struct krust_hex_escape {\n  char letter;\n  int digits;\n};\n\n",
    );
    write_named(
        &mut output,
        "krust_k_named_escapes",
        k::NAMED_ESCAPES.iter().copied(),
    );
    write_hex(&mut output, "krust_k_hex_escapes", &k::HEX_ESCAPES);
    writeln!(
        output,
        "/* In a Bytes literal, a hexadecimal escape of at most this many digits gives one byte. */\n\
         #define KRUST_K_BYTE_DIGITS {}\n\
         /* A backslash and a decimal digit begin an escape of this many octal digits. */\n\
         #define KRUST_K_OCTAL_DIGITS {}\n",
        k::BYTE_DIGITS,
        k::OCTAL_DIGITS
    )
    .expect("writing to a string cannot fail");
    write_named(
        &mut output,
        "krust_kore_named_escapes",
        kore::NAMED_ESCAPES
            .iter()
            .map(|(code_point, letter)| (*letter, *code_point)),
    );
    write_hex(&mut output, "krust_kore_hex_escapes", &kore::HEX_ESCAPES);
    writeln!(
        output,
        "/* The code points a KORE literal writes as themselves, unless an escape names them. */\n\
         #define KRUST_KORE_UNESCAPED_FIRST 0x{:x}\n\
         #define KRUST_KORE_UNESCAPED_LAST 0x{:x}\n\
         \n\
         #define KRUST_ESCAPES(table) (sizeof table / sizeof *table)\n\
         \n\
         #endif",
        u32::from(*kore::UNESCAPED.start()),
        u32::from(*kore::UNESCAPED.end())
    )
    .expect("writing to a string cannot fail");
    output
}

/// A letter as a C character constant: its ASCII value, which needs no C escape.
fn c_letter(letter: char) -> String {
    assert!(letter.is_ascii(), "an escape letter is ASCII");
    format!("0x{:02x}", u32::from(letter))
}

fn write_named(output: &mut String, name: &str, escapes: impl Iterator<Item = (char, char)>) {
    let entries = escapes
        .map(|(letter, code_point)| {
            format!("{{{}, 0x{:x}}}", c_letter(letter), u32::from(code_point))
        })
        .collect::<Vec<_>>()
        .join(", ");
    writeln!(
        output,
        "static const struct krust_named_escape {name}[] = {{{entries}}};"
    )
    .expect("writing to a string cannot fail");
}

fn write_hex(output: &mut String, name: &str, escapes: &[(char, usize)]) {
    let entries = escapes
        .iter()
        .map(|(letter, digits)| format!("{{{}, {digits}}}", c_letter(*letter)))
        .collect::<Vec<_>>()
        .join(", ");
    writeln!(
        output,
        "static const struct krust_hex_escape {name}[] = {{{entries}}};"
    )
    .expect("writing to a string cannot fail");
}

#[cfg(test)]
mod tests {
    use super::header;

    #[test]
    fn the_header_prints_every_escape_of_both_literal_languages() {
        let header = header();
        assert!(header.contains(
            "krust_k_named_escapes[] = {{0x22, 0x22}, {0x5c, 0x5c}, {0x6e, 0xa}, {0x72, 0xd}, \
             {0x74, 0x9}, {0x66, 0xc}};"
        ));
        assert!(header.contains("krust_k_hex_escapes[] = {{0x78, 2}, {0x75, 4}, {0x55, 8}};"));
        assert!(header.contains("#define KRUST_K_BYTE_DIGITS 2"));
        assert!(header.contains("#define KRUST_K_OCTAL_DIGITS 3"));
        assert!(header.contains(
            "krust_kore_named_escapes[] = {{0x22, 0x22}, {0x5c, 0x5c}, {0x6e, 0xa}, {0x72, 0xd}, \
             {0x74, 0x9}, {0x66, 0xc}};"
        ));
        assert!(header.contains("krust_kore_hex_escapes[] = {{0x78, 2}, {0x75, 4}, {0x55, 8}};"));
        assert!(header.contains("#define KRUST_KORE_UNESCAPED_FIRST 0x20"));
        assert!(header.contains("#define KRUST_KORE_UNESCAPED_LAST 0x7e"));
    }
}
