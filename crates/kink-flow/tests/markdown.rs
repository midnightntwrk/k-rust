//! (flow F-10, README 6.1; deliverables 1-5, 7 and 8).
//!
//! The fixture is testdata/flow/markdown: spec.md (prose before, between and after the
//! fences, K-looking prose, a module split across two selected fences around a `ghost` fence
//! the selector does not select) and spec-view.k, its K view written out as a `.k` file.

