/// Deliverable 8 (e): a replacement that writes a Markdown fence line is refused before any
/// load; the envelope itself survives fence-like content lines by widening its fence.
#[test]
fn a_replacement_with_a_fence_line_is_markdown_envelope() {
    let md = Spec::at(&markdown().join("FLOW.toml"));
    for replace in ["+Int 1\\n```\\n", "+Int 1\\n  ~~~~\\n", "+Int 1\\n````k"] {
        let invalid = expect_invalid(
            md.resolve_edits(&format!(
                "[[mutation.edit]]\nrule = \"inc\"\nfind = \"+Int 1\"\nreplace = \"{replace}\"\n"
            )),
            Some(0),
            InvalidReason::MarkdownEnvelope,
        );
        assert!(invalid.detail.contains("fence"), "{}", invalid.detail);
    }
    // A replacement that ends in a multi-byte character passes the fence check; ending in a
    // comment, it leaves text after the rule's new end, which the span-shift check refuses
    // (only whitespace may follow a replaced rule).
    expect_invalid(
        md.resolve_edits(
            "[[mutation.edit]]\nrule = \"inc\"\nfind = \"+Int 1\"\nreplace = \"+Int 2 // é\"\n",
        ),
        Some(0),
        InvalidReason::SpanChanged,
    );
    // The same replacement in the `.k` view is K text and fails as K text.
    let k = Spec::at(&markdown().join("FLOW-view.toml"));
    expect_invalid(
        k.resolve_edits(
            "[[mutation.edit]]\nrule = \"inc\"\nfind = \"+Int 1\"\nreplace = \"+Int 1\\n```\\n\"\n",
        ),
        Some(0),
        InvalidReason::EditedLoadFailed,
    );
}

/// The envelope builder and the fence info search, directly.
#[test]
fn the_envelope_round_trips_through_k_rusts_extractor() {
    let view = fs::read_to_string(markdown().join("spec-view.k")).unwrap();
    let envelope = markdown_envelope(&view, "k").unwrap();
    // Re-pin R0a (finding E-09; k-rust 50c5812cb, bdad0af15, 760930379): the extractor keeps
    // each character of the fence line as a space, so the shift is the fence line's length
    // (`` ```k ``: 4; it was 0 at 927b9ce6, which dropped the fence line).
    assert_eq!(envelope.shift, 4);
    // The fence line carries the whitespace of the view's first line (prose there).
    let first = view.lines().next().unwrap();
    assert!(!first.is_empty());
    assert!(envelope.text.starts_with(&format!("```k{first}\n")));
    // The closing fence line is three spaces of the extraction too (a whitespace-only suffix).
    assert_eq!(envelope.extracted, format!("    {view}   "));
    // A view whose lines start with backtick runs (the content of a wider user fence) gets a
    // fence one backtick wider than the longest run, and still round trips.
    let fenced = "  \nrule a\n```\n   ````x\n    `````\nrule b";
    let envelope = markdown_envelope(fenced, "k").unwrap();
    assert!(envelope.text.starts_with("`````k  \n"), "{}", envelope.text);
    assert!(envelope.text.ends_with("\n`````"));
    // The six characters of the fence line `` `````k `` are spaces of the extraction (E-09).
    assert_eq!(envelope.extracted, format!("      {fenced}\n     "));
    assert_eq!(envelope.shift, 6);
    // A first line that holds code, or no line break, cannot be enveloped.
    assert!(markdown_envelope("rule a\n", "k").is_err());
    assert!(markdown_envelope("   ", "k").is_err());
    // The info string: the smallest set of the selector's tags that the extractor selects.
    assert_eq!(fence_info("k").unwrap(), "k");
    assert_eq!(fence_info(".k").unwrap(), "k");
    assert_eq!(fence_info("!ghost").unwrap(), "");
    assert_eq!(fence_info("k & extra").unwrap(), "{k extra}");
    assert_eq!(fence_info("ghost | k /* comment */").unwrap(), "ghost");
    assert!(fence_info("k & !k").is_err());
    // Several tags: every character of the fence line `` ```{k extra} `` is a space of the
    // extraction, so the extracted first line is twelve bytes longer than the view's. Re-pin R0a
    // (finding E-09): at 927b9ce6 only the space between the tags was kept (a shift of 1).
    let envelope = markdown_envelope("\n  rule a\n", "k & (extra | other)").unwrap();
    assert!(envelope.text.starts_with("```{k extra}\n"));
    assert_eq!(
        envelope.extracted,
        format!("{}\n  rule a\n   ", " ".repeat(12))
    );
    assert_eq!(envelope.shift, 12);
}

/// The commented-out-neighbour attack of review m1: rule c's replacement comments out rule d,
/// which follows on the same line, and writes an identical copy of it.
const NEIGHBOURS_K: &str = "module MAIN\n  imports INT\n  syntax Exp ::= Int | \"c\" | \"d\"\n  configuration <k> $PGM:Exp </k>\n  rule [c]: c => 3  rule [d]: d => 4\nendmodule\n";

/// Deliverable 8 (f): the attack is span-changed on a `.k` and on an `.md` source (F-04
/// accepted it); trailing whitespace left by a replacement is still accepted.
#[test]
fn the_commented_out_neighbour_attack_is_span_changed() {
    let dir = scratch("neighbours");
    write(&dir.join("main.k"), NEIGHBOURS_K);
    write(
        &dir.join("main.md"),
        &format!(
            "# Neighbours\n\nTwo rules share a line.\n\n```k\n{NEIGHBOURS_K}```\n\nThe end.\n"
        ),
    );
    write(
        &dir.join("FLOW-k.toml"),
        "[spec]\nentry = \"main.k\"\nmain_module = \"MAIN\"\n",
    );
    write(
        &dir.join("FLOW-md.toml"),
        "[spec]\nentry = \"main.md\"\nmain_module = \"MAIN\"\n",
    );
    for manifest in ["FLOW-k.toml", "FLOW-md.toml"] {
        let spec = Spec::at(&dir.join(manifest));
        for replace in [
            "=> 5 rule [d]: d => 4 //",
            "=> 5 rule [d]:   d   =>   4 //",
            "=> 5\\n  rule [d]: d => 4 //",
        ] {
            let invalid = expect_invalid(
                spec.resolve_edits(&format!(
                    "[[mutation.edit]]\nrule = \"c\"\nfind = \"=> 3\"\nreplace = \"{replace}\"\n"
                )),
                Some(0),
                InvalidReason::SpanChanged,
            );
            assert!(invalid.detail.contains("MAIN.c"), "{manifest}: {invalid}");
        }
        // Trailing whitespace at the end of a replaced rule is not text outside it.
        let resolved = spec
            .resolve_edits(
                "[[mutation.edit]]\nrule = \"c\"\nfind = \"=> 3\"\nreplace = \"=> 5   \"\n",
            )
            .unwrap();
        assert_eq!(resolved.rules[0].after.as_deref(), Some("rule [c]: c => 5"));
        // A deleted neighbour moves the next rule by exactly its length.
        let resolved = spec
            .resolve_edits(
                "[[mutation.edit]]\nrule = \"c\"\ndelete = true\n\
                 [[mutation.edit]]\nrule = \"d\"\nfind = \"=> 4\"\nreplace = \"=> 6\"\n",
            )
            .unwrap();
        assert_eq!(resolved.rules[1].after.as_deref(), Some("rule [d]: d => 6"));
    }
}

/// Deliverable 8 (g), review m2: `MODULE.x` addresses a `[label(x)]` rule (stored as the bare
/// `x`); a label written in both forms in one module stays ambiguous.
#[test]
fn a_module_qualified_label_addresses_a_label_attribute_rule() {
    let md = Spec::at(&markdown().join("FLOW.toml"));
    let dec = |rule: &str| {
        md.resolve_edits(&format!(
            "[[mutation.edit]]\nrule = \"{rule}\"\nfind = \"-Int 1\"\nreplace = \"-Int 2\"\n"
        ))
    };
    let qualified = dec("LIT.dec").unwrap();
    let bare = dec("dec").unwrap();
    assert_eq!(qualified.rules[0].label.as_deref(), Some("dec"));
    assert_eq!(qualified.digest, bare.digest);
    expect_invalid(dec("LIT-SYNTAX.dec"), Some(0), InvalidReason::UnknownLabel);
    expect_invalid(dec("OTHER.dec"), Some(0), InvalidReason::UnknownLabel);

    let dir = scratch("label-forms");
    write(
        &dir.join("main.k"),
        "module MAIN\n  imports INT\n  syntax Exp ::= Int | \"a\" | \"b\"\n  configuration <k> $PGM:Exp </k>\n  rule [q]: a => 1\n  rule b => 2 [label(q)]\nendmodule\n",
    );
    write(
        &dir.join("FLOW.toml"),
        "[spec]\nentry = \"main.k\"\nmain_module = \"MAIN\"\n",
    );
    let spec = Spec::at(&dir.join("FLOW.toml"));
    for rule in ["q", "MAIN.q"] {
        expect_invalid(
            spec.resolve_edits(&format!(
                "[[mutation.edit]]\nrule = \"{rule}\"\nfind = \"=>\"\nreplace = \"=>\"\n"
            )),
            Some(0),
            InvalidReason::AmbiguousLabel,
        );
    }
}

/// Deliverable 8 (i): a view that is not what k-rust parsed is refused. The specification is
/// loaded with the selector `k` and resolved with a selector that also selects the ghost fence.
#[test]
fn a_view_that_is_not_what_k_rust_parsed_is_refused() {
    let spec = Spec::at(&markdown().join("FLOW.toml"));
    let mut other = spec.manifest.clone();
    other.spec.md_selector = "k | ghost".to_owned();
    let list = MutationList::read(&markdown().join("MUTATIONS.toml")).unwrap();
    let invalid = expect_invalid(
        resolve(&other, &spec.loaded, &list.mutations[0]),
        Some(0),
        InvalidReason::SourceViewMismatch,
    );
    assert!(
        invalid.detail.contains("k-rust parsed other text"),
        "{invalid}"
    );
    // A selector spelled otherwise that extracts the same text is the same view.
    other.spec.md_selector = "k | nothing".to_owned();
    let same = resolve(&other, &spec.loaded, &list.mutations[0]).unwrap();
    let expected = resolve(&spec.manifest, &spec.loaded, &list.mutations[0]).unwrap();
    assert_eq!(same.digest, expected.digest);
}

/// A specification whose `ghost` fence, selected only by `k | ghost`, continues rule `a` of the
/// `k` fence before it: under `k` rule `a` is `a => 1`, under `k | ghost` it is
/// `a => 1 +Int 2`. The module has the same sentences under both selectors.
const GHOST_EDIT_MD: &str = "# Ghost\n\n```k\nmodule M\n  imports INT\n  syntax Exp ::= Int | \"a\" | \"b\"\n  configuration <k> $PGM:Exp </k>\n  rule [a]: a => 1\n```\n\nProse.\n\n```ghost\n    +Int 2\n```\n\n```k\n  rule [b]: b => 3\nendmodule\n```\n";

/// Re-pin R0a (finding E-09; k-rust 50c5812cb, bdad0af15, 760930379): at 501f18b9 every
/// extraction's offset map is the identity, so the source table no longer tells a view built
/// under another selector from the text k-rust parsed. A ghost fence that changes a sentence
/// without adding one (so no structure check fires) must still be refused as
/// source-view-mismatch, by View::read and by a resolution that edits another rule, for LF and
/// CRLF line breaks; the view under the load's own selector is accepted.
#[test]
fn a_ghost_fence_that_changes_a_sentence_is_a_source_view_mismatch() {
    for (case, newline) in [("lf", "\n"), ("crlf", "\r\n")] {
        let dir = scratch(&format!("ghost-edit-{case}"));
        write(&dir.join("m.md"), &GHOST_EDIT_MD.replace('\n', newline));
        write(
            &dir.join("FLOW.toml"),
            "[spec]\nentry = \"m.md\"\nmain_module = \"M\"\n",
        );
        let spec = Spec::at(&dir.join("FLOW.toml"));
        let own = spec.view("m.md");
        assert!(own.text.contains("rule [a]: a => 1"), "{case}");
        assert!(!own.text.contains("+Int 2"), "{case}");
        let ghost =
            extract_fenced_k_code_with_map(&GHOST_EDIT_MD.replace('\n', newline), "k | ghost")
                .unwrap()
                .text;
        assert!(
            ghost.contains("+Int 2"),
            "{case}: the ghost fence is in that view"
        );
        let mut other = spec.manifest.clone();
        other.spec.md_selector = "k | ghost".to_owned();
        let refused = View::read(&dir, &spec.loaded, &other.spec.md_selector, "m.md")
            .err()
            .unwrap_or_else(|| panic!("{case}: a view k-rust did not parse was accepted"));
        assert_eq!(
            refused.0,
            InvalidReason::SourceViewMismatch,
            "{case}: {}",
            refused.1
        );
        assert!(
            refused.1.contains("k-rust parsed other text"),
            "{case}: {}",
            refused.1
        );
        let list = MutationList::decode(
            "[[mutation]]\nid = \"m\"\n[[mutation.edit]]\nrule = \"b\"\nfind = \"=> 3\"\nreplace = \"=> 4\"\n",
        )
        .unwrap();
        let invalid = expect_invalid(
            resolve(&other, &spec.loaded, &list.mutations[0]),
            Some(0),
            InvalidReason::SourceViewMismatch,
        );
        assert!(
            invalid.detail.contains("k-rust parsed other text"),
            "{case}: {invalid}"
        );
        // The same mutation under the load's own selector resolves.
        resolve(&spec.manifest, &spec.loaded, &list.mutations[0])
            .unwrap_or_else(|invalid| panic!("{case}: {invalid}"));
    }
}

/// `kink-flow run` through the library, as the binary runs it.
fn search(manifest: &Path, mutations: &Path, only: &[&str]) -> (Value, bool) {
    let manifest = FlowManifest::read(manifest).unwrap();
    let list = MutationList::read(mutations).unwrap();
    run(
        &manifest,
        &list,
        &RunOptions {
            only: only.iter().map(|id| (*id).to_owned()).collect(),
            cache: None,
            // F-05's corpus order, so that the pinned calls and killers do not depend on host
            // timing (F-13's cost order: tests/usability.rs).
            order: ProgramOrder::Corpus,
        },
    )
}

fn copy_dir(from: &Path, to: &Path) {
    fs::create_dir_all(to).unwrap();
    for entry in fs::read_dir(from).unwrap() {
        let entry = entry.unwrap();
        let name = entry.file_name();
        if name == CACHE_DIRECTORY {
            continue;
        }
        if entry.file_type().unwrap().is_dir() {
            copy_dir(&entry.path(), &to.join(&name));
        } else {
            fs::copy(entry.path(), to.join(&name)).unwrap();
        }
    }
}

/// Deliverable 8 (h): `kink-flow run` on the Markdown fixture kills one mutation and reports
/// a survivor whose before and after texts are K text: the view's slice of the rule, and that
/// slice with the edit applied. Nothing in the document is Markdown.
#[test]
fn run_on_markdown_kills_and_reports_k_text() {
    let dir = scratch("run").join("markdown");
    copy_dir(&markdown(), &dir);
    let (document, ok) = search(
        &dir.join("FLOW.toml"),
        &dir.join("MUTATIONS.toml"),
        &["inc-adds-two", "twice-adds-two-at-once"],
    );
    assert!(ok, "{document:#}");
    let rows = document["mutations"].as_array().unwrap();
    let row = |id: &str| rows.iter().find(|m| m["id"] == id).unwrap();
    assert_eq!(
        (
            row("inc-adds-two")["status"].as_str(),
            row("inc-adds-two")["killer"].as_str()
        ),
        (Some("killed"), Some("inc"))
    );
    let survivor = row("twice-adds-two-at-once");
    assert_eq!(survivor["status"], "survived");
    assert_eq!(
        document["survivors"],
        serde_json::json!(["twice-adds-two-at-once"])
    );
    assert_eq!(survivor["reaching"], serde_json::json!(["twice"]));
    let rule = &survivor["rules"][0];
    let view = fs::read_to_string(dir.join("spec-view.k")).unwrap();
    let line = view.lines().nth(45).unwrap();
    let before = line.trim();
    assert_eq!(rule["file"], "spec.md");
    assert_eq!(
        (rule["start_line"].as_u64(), rule["end_line"].as_u64()),
        (Some(46), Some(46))
    );
    assert_eq!(rule["label"], "LIT.twice");
    assert_eq!(rule["before"], before);
    assert_eq!(before, "rule [twice]: twice I:Int => I +Int 1 +Int 1");
    assert_eq!(
        rule["after"],
        before.replace("I +Int 1 +Int 1", "I +Int 2").as_str()
    );
    let text = serde_json::to_string(&document).unwrap();
    for prose in ["```", "Closing prose", "ghost", "# Lit"] {
        assert!(!text.contains(prose), "{prose:?} in the run document");
    }
    // The user's Markdown file is untouched.
    assert_eq!(
        fs::read(dir.join("spec.md")).unwrap(),
        fs::read(markdown().join("spec.md")).unwrap()
    );
}
