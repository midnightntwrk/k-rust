fn flow(name: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../testdata/flow")
        .join(name)
}

fn markdown() -> PathBuf {
    flow("markdown")
}

/// A fresh directory for one test, under the target's temporary directory.
fn scratch(name: &str) -> PathBuf {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR"))
        .join(format!("kink-flow-markdown-{}", std::process::id()))
        .join(name);
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(&dir).unwrap();
    dir
}

fn write(path: &Path, text: &str) {
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, text).unwrap();
}

/// A specification loaded as kink-flow loads it (no compile).
struct Spec {
    manifest: FlowManifest,
    loaded: LoadedSource,
}

impl Spec {
    fn at(manifest: &Path) -> Self {
        let manifest = FlowManifest::read(manifest).unwrap();
        let loaded = load_source(&corpus_source(&manifest)).unwrap();
        Self { manifest, loaded }
    }

    fn resolve_edits(&self, edits: &str) -> Result<ResolvedMutation, InvalidMutation> {
        let list = MutationList::decode(&format!("[[mutation]]\nid = \"m\"\n{edits}")).unwrap();
        resolve(&self.manifest, &self.loaded, &list.mutations[0])
    }

    fn view(&self, name: &str) -> View {
        View::read(
            &self.manifest.directory,
            &self.loaded,
            &self.manifest.spec.md_selector,
            name,
        )
        .unwrap_or_else(|(reason, detail)| panic!("{name}: {} {detail}", reason.as_str()))
    }
}

#[track_caller]
fn expect_invalid(
    result: Result<ResolvedMutation, InvalidMutation>,
    edit: Option<usize>,
    reason: InvalidReason,
) -> InvalidMutation {
    match result {
        Ok(resolved) => panic!("expected {reason:?}, got a patch over {:?}", resolved.rules),
        Err(invalid) => {
            assert_eq!((invalid.edit, invalid.reason), (edit, reason), "{invalid}");
            invalid
        }
    }
}

/// The K view of a Markdown text under the selector `k`, as k-rust's loader extracts it.
fn k_view(markdown: &str) -> String {
    extract_fenced_k_code_with_map(markdown, "k").unwrap().text
}

/// Deliverable 7: spec-view.k is the K view of spec.md (generated by this helper; set
/// KINK_FLOW_WRITE_VIEW=1 to rewrite it after editing spec.md).
#[test]
fn spec_view_k_is_the_current_k_view_of_spec_md() {
    let source = fs::read_to_string(markdown().join("spec.md")).unwrap();
    let view = k_view(&source);
    let path = markdown().join("spec-view.k");
    if std::env::var_os("KINK_FLOW_WRITE_VIEW").is_some() {
        fs::write(&path, &view).unwrap();
    }
    assert_eq!(
        fs::read_to_string(&path).unwrap(),
        view,
        "spec-view.k is stale: rerun with KINK_FLOW_WRITE_VIEW=1"
    );
    // Lines are the Markdown file's lines; the prose, the fence lines and the ghost fence's
    // content are whitespace.
    assert_eq!(view.lines().count(), source.lines().count());
    assert!(view.lines().next().unwrap().trim().is_empty());
    for absent in ["ghost", "Lit:", "```", "I1 -Int I2", "Closing prose"] {
        assert!(!view.contains(absent), "{absent:?} is in the view");
    }
    for line in [31, 45, 46] {
        assert_eq!(
            view.lines().nth(line - 1),
            source.lines().nth(line - 1),
            "code line {line} keeps its text and columns"
        );
    }
}

/// Deliverable 1 and the premises of the stop rules: the source table holds an extraction of
/// spec.md equal to the recomputed view, every authored sentence's offsets index that view
/// and name the same bytes as its location, and slicing the raw Markdown with them (F-04's
/// defect, review M1) gives other text.
#[test]
fn the_k_view_is_what_k_rust_parsed_and_spans_index_it() {
    let spec = Spec::at(&markdown().join("FLOW.toml"));
    let view = spec.view("spec.md");
    assert!(view.markdown);
    assert_eq!(
        view.text,
        fs::read_to_string(markdown().join("spec-view.k")).unwrap()
    );
    assert_eq!(view.source_ids.len(), 1);
    let raw = fs::read_to_string(markdown().join("spec.md")).unwrap();
    let mut rules = 0;
    let mut raw_differs = 0;
    for (_, sentence) in spec.loaded.baseline.authored_sentences() {
        let attributes = sentence.attributes();
        if attributes.source() != Some("spec.md") {
            continue;
        }
        assert!(view.source_ids.contains(&attributes.source_id().unwrap()));
        let offset = |key| {
            attributes
                .value(key)
                .and_then(Value::as_u64)
                .map(|v| v as usize)
        };
        let span = offset(AttributeKey::SentenceStartOffset).unwrap()
            ..offset(AttributeKey::SentenceEndOffset).unwrap();
        assert_eq!(
            kink_flow::mutation::location_span(attributes.location().unwrap(), &view.text),
            Some(span.clone())
        );
        if matches!(sentence, k_rust::definition::Sentence::Rule { .. }) {
            rules += 1;
            assert!(view.text[span.clone()].starts_with("rule"));
            if raw.get(span.clone()) != Some(&view.text[span.clone()]) {
                raw_differs += 1;
            }
        }
    }
    assert_eq!(
        rules, 4,
        "inc, the unlabelled +, dec and twice; no ghost rule"
    );
    // Re-pin R0a (finding E-09; k-rust 50c5812cb, bdad0af15, 760930379): at 501f18b9 the
    // extraction turns prose into one space per byte, so its offset map is the identity and
    // raw-Markdown offsets name the same text as view offsets (at 927b9ce6: all 4 differed).
    assert_eq!(raw_differs, 0, "raw Markdown offsets name the view's text");
    assert!(
        spec.loaded
            .baseline
            .authored_sentences()
            .all(|(_, s)| s.attributes().string(AttributeKey::Label) != Some("LIT.ghost"))
    );
    // The `.k` view of the same text is its own file, unextracted.
    let k = Spec::at(&markdown().join("FLOW-view.toml"));
    let k_view = k.view("spec-view.k");
    assert!(!k_view.markdown);
    assert_eq!(k_view.text, view.text);
}

/// The outcome of a resolution, for the differential: the reason, or per edited rule its
/// address, label, lines, texts and the fingerprint of its replacement.
#[derive(Debug, PartialEq)]
enum Outcome {
    Invalid(Option<usize>, &'static str),
    Resolved(Vec<RuleOutcome>),
}

#[derive(Debug, PartialEq)]
struct RuleOutcome {
    at: SentenceRef,
    edits: Vec<usize>,
    label: Option<String>,
    lines: (u32, u32),
    before: String,
    after: Option<String>,
    replacement: Option<SentenceFingerprint>,
}

fn outcome(result: &Result<ResolvedMutation, InvalidMutation>) -> Outcome {
    match result {
        Err(invalid) => Outcome::Invalid(invalid.edit, invalid.reason.as_str()),
        Ok(resolved) => Outcome::Resolved(
            resolved
                .rules
                .iter()
                .map(|rule| RuleOutcome {
                    at: rule.at.clone(),
                    edits: rule.edits.clone(),
                    label: rule.label.clone(),
                    lines: (rule.start_line, rule.end_line),
                    before: rule.before.clone(),
                    after: rule.after.clone(),
                    replacement: resolved.patch.edits().iter().find_map(|edit| match edit {
                        Edit::ReplaceSentence { at, replacement } if *at == rule.at => {
                            Some(SentenceFingerprint::of(replacement).unwrap())
                        }
                        _ => None,
                    }),
                })
                .collect(),
        ),
    }
}

/// Deliverable 8 (a): every mutation of the fixture list resolves on spec.md and on its K view
/// spec-view.k to the same outcome; the outcomes themselves are pinned.
#[test]
fn every_fixture_mutation_resolves_alike_on_markdown_and_on_its_k_view() {
    let md = Spec::at(&markdown().join("FLOW.toml"));
    let k = Spec::at(&markdown().join("FLOW-view.toml"));
    let list = MutationList::read(&markdown().join("MUTATIONS.toml")).unwrap();
    let view = md.view("spec.md").text;
    let mut pinned = Vec::new();
    for mutation in &list.mutations {
        let on_md = resolve(&md.manifest, &md.loaded, mutation);
        let on_k = resolve(&k.manifest, &k.loaded, mutation);
        assert_eq!(outcome(&on_md), outcome(&on_k), "{}", mutation.id);
        if let Ok(resolved) = &on_md {
            // The shown texts are slices of the K view, and the edited view is the view with
            // the edits applied; the overlay is the only Markdown, and it extracts to it.
            for rule in &resolved.rules {
                assert!(view.contains(&rule.before), "{}", mutation.id);
                assert_eq!(rule.file, "spec.md");
            }
            let edited = &resolved.edited_views["spec.md"];
            assert_eq!(resolved.edited_sources, resolved.edited_views);
            assert_eq!(
                Some(edited),
                on_k.as_ref().unwrap().edited_views.get("spec-view.k")
            );
            let overlay = &resolved.overlay()["spec.md"];
            assert!(overlay.starts_with("```k"), "{overlay}");
            // Re-pin R0a (finding E-09; k-rust 50c5812cb, bdad0af15, 760930379): the envelope's
            // fence line `` ```k `` extracts to four spaces before the view's first line (the
            // envelope's shift), where 927b9ce6 dropped it.
            assert_eq!(
                k_view(overlay).trim_end(),
                format!("    {edited}").trim_end()
            );
            assert!(!edited.contains("```"));
        }
        pinned.push((
            mutation.id.as_str(),
            match &on_md {
                Ok(_) => "resolved",
                Err(invalid) => invalid.reason.as_str(),
            },
        ));
    }
    assert_eq!(
        pinned,
        [
            ("inc-adds-two", "resolved"),
            ("add-becomes-sub", "resolved"),
            ("dec-subtracts-two", "resolved"),
            ("twice-adds-two-at-once", "resolved"),
            ("add-swaps-operands", "resolved"),
            ("no-dec", "resolved"),
            ("twice-ambiguous", "find-ambiguous"),
            ("file-ambiguous", "find-ambiguous"),
            ("prose-only", "find-not-found"),
            ("ghost-rule", "unknown-label"),
        ]
    );
    let inc = resolve(&md.manifest, &md.loaded, &list.mutations[0]).unwrap();
    assert_eq!(
        (inc.rules[0].before.as_str(), inc.rules[0].after.as_deref()),
        (
            "rule [inc]: inc I:Int => I +Int 1",
            Some("rule [inc]: inc I:Int => I +Int 2")
        )
    );
}

/// The F-04 reviewer's file (handoffs/F-04-review-1.json M1): ten characters of prose and the
/// fence line put exactly fourteen dropped characters before rule `bb`, and `rule a => 1\n  `
/// is fourteen bytes, so raw-Markdown offsets would start at rule `a`.
const REVIEW_MD: &str = "xxxxxxxxxx\n\n```k\nmodule M\n  imports INT\n  syntax Exp ::= Int | \"a\" | \"b\" | Exp \"+\" Exp\n  configuration <k> $PGM:Exp </k>\n  rule a => 1\n  rule [bb]: b => 2 +Int 3 +Int 4 +Int 2\nendmodule\n```\n";

const REVIEW_FLOW_MD: &str = "[spec]\nentry = \"m.md\"\nmain_module = \"M\"\n";
const REVIEW_FLOW_K: &str = "[spec]\nentry = \"m.k\"\nmain_module = \"M\"\n";

/// Deliverable 8 (b): the review M1 attack is find-ambiguous on Markdown as on the
/// equivalent `.k`, and resolves to rule bb's own text when the find is unique.
#[test]
fn the_review_m1_attack_no_longer_resolves_silently() {
    let dir = scratch("review-m1");
    write(&dir.join("m.md"), REVIEW_MD);
    write(&dir.join("m.k"), &k_view(REVIEW_MD));
    write(&dir.join("FLOW.toml"), REVIEW_FLOW_MD);
    write(&dir.join("FLOW-k.toml"), REVIEW_FLOW_K);
    let md = Spec::at(&dir.join("FLOW.toml"));
    let k = Spec::at(&dir.join("FLOW-k.toml"));
    // The premise of the attack at 927b9ce6 was that the raw slice at bb's offsets started with
    // rule a. Re-pin R0a (finding E-09; k-rust 50c5812cb, bdad0af15, 760930379): the offset map
    // is now the identity, so the raw slice is rule bb's own text and the premise is gone; the
    // find rows below still pin that the resolution is in the K view.
    let (_, bb) = md
        .loaded
        .baseline
        .authored_sentences()
        .find(|(_, s)| s.attributes().string(AttributeKey::Label) == Some("M.bb"))
        .unwrap();
    let start = bb
        .attributes()
        .value(AttributeKey::SentenceStartOffset)
        .and_then(Value::as_u64)
        .unwrap() as usize;
    assert!(REVIEW_MD[start..].starts_with("rule [bb]: b => 2"));
    for edits in [
        "[[mutation.edit]]\nrule = \"bb\"\nfind = \"2\"\nreplace = \"5\"\n",
        "[[mutation.edit]]\nline = 9\nfind = \"2\"\nreplace = \"5\"\n",
    ] {
        let on_md = expect_invalid(
            md.resolve_edits(edits),
            Some(0),
            InvalidReason::FindAmbiguous,
        );
        let on_k = expect_invalid(
            k.resolve_edits(edits),
            Some(0),
            InvalidReason::FindAmbiguous,
        );
        assert_eq!(on_md.detail.replace("m.md", "m.k"), on_k.detail);
        assert!(on_md.detail.contains("occurs 2 times"), "{}", on_md.detail);
    }
    let resolved = md
        .resolve_edits(
            "[[mutation.edit]]\nrule = \"bb\"\nfind = \"+Int 2\"\nreplace = \"+Int 5\"\n",
        )
        .unwrap();
    assert_eq!(
        (
            resolved.rules[0].before.as_str(),
            resolved.rules[0].after.as_deref()
        ),
        (
            "rule [bb]: b => 2 +Int 3 +Int 4 +Int 2",
            Some("rule [bb]: b => 2 +Int 3 +Int 4 +Int 5")
        )
    );
    // Review m3: a find inside the rule is found in it (F-04 said edit-outside-rule).
    let find_alone = md
        .resolve_edits("[[mutation.edit]]\nfind = \"+Int 4\"\nreplace = \"+Int 6\"\n")
        .unwrap();
    assert_eq!(find_alone.rules[0].label.as_deref(), Some("M.bb"));
}

