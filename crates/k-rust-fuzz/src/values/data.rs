//! The constructor table of a data sort: constructor enumeration, argument classification and
//! inhabitation (ARCHITECTURE 3, R-20, T-10). Owner: FZ-09.
//!
//! The table is read from the internalized definition's signature
//! ([`BackendDefinition::symbols`], [`BackendDefinition::sorts`] and
//! [`BackendDefinition::sort_graph`]); inhabitation is re-derived here rather than read from the
//! backend, because what matters for generation is narrower than "the sort has a value": a value
//! must be *buildable by the generator*, from builtin values with a generator, empty collections
//! and the admissible constructors, without entering an excluded sort.
//!
//! An entry's values are:
//!
//! - applications of an admissible constructor whose result sort is the entry's sort or a
//!   subsort of it (injected to the entry's sort when it is a subsort);
//! - values of a subsort that is not a data sort: a builtin sort with a generator (`Int` in
//!   `syntax Val ::= Int`) or a collection sort, injected to the entry's sort.
//!
//! A constructor is admissible when it is a constructor (`SymbolType::Constructor`) whose head
//! role is free or an equation head (an `anywhere` constructor), with no sort parameters, no hook,
//! no collection role, not a macro or alias and not a binder, and not the injection. A function
//! builds no value of its own (its application denotes the value its equations compute), a
//! macro or alias does not survive preprocessing, a collection constructor builds a collection
//! value (generated by the collection's generator), and an injection is added by the table
//! itself, so none of them is a choice of the generator.
//!
//! An argument sort is classified as:
//!
//! - a builtin sort with a generator (`Int`, `Bool`, `String`, `Bytes`, `MInt{W}`, or one of them
//!   hooked under another name): a leaf the builtin generator draws;
//! - a collection sort (hooked `LIST.List`, `SET.Set`, `MAP.Map`): the definition does not state
//!   its element sorts (K collections hold `KItem`), so only its empty collection is drawn, which
//!   is a value of the sort whatever its element sorts are. The hole-sort rule (FZ-02) refuses a
//!   data sort that reaches a collection, so through `holes::resolve` this case is unreachable;
//!   it is kept for callers of [`super::TextSyntax::resolve`] and [`super::resolve_value_sort`];
//! - a data sort (no hook, no domain values) that is not excluded: another entry of the table
//!   (the exclusions apply only to data sorts: a builtin or collection sort the program grammar
//!   mentions, such as `Int`, stays a leaf, as ARCHITECTURE 2.4 exempts builtins);
//! - anything else (a token sort such as `Id`, a hooked sort without generator, `K`, `KItem`, an
//!   excluded program or cell sort, a parametric sort): unavailable, and a constructor with an
//!   unavailable argument is not admissible.
//!
//! Inhabitation is the least fixed point of: an entry with a non-data subsort is inhabited at
//! height 0; a constructor whose data arguments are all inhabited is inhabited at height one more
//! than the greatest of their heights; an entry is inhabited at the least height of its
//! constructors and subsorts. A constructor that never becomes inhabited is dropped, so a
//! generator that respects the heights always terminates: at remaining depth `d` it chooses only
//! alternatives of height at most `d`, and each data argument of such a constructor has height at
//! most `d - 1`.

use std::collections::BTreeMap;

use k_rust::{
    k_rust_backend::{
        definition::BackendDefinition,
        term::{
            DomainKind, HeadRole, MIntWidth, Sort as BackendSort, SortNode, Symbol, SymbolType,
        },
    },
    names::{BuiltinSort, MINT_SORT, WellKnownSymbol},
};

use super::{
    ArgumentSort, CollectionKind, DataConstructor, DataSort, DataSorts, EmptyCollection,
    MAX_INT_BITS, ValueSort, collection_symbols,
};
use crate::error::SortRefusal;

/// How an argument or subsort is generated, before inhabitation is known.
enum Class {
    Leaf(ArgumentSort),
    Data(String),
    Unavailable,
}

/// The constructor table of the data sort whose KORE name is `root`, with the sorts whose KORE
/// names `excluded` holds left out.
///
/// # Errors
///
/// [`SortRefusal::NoGenerator`] when no value of the sort can be built (no admissible
/// constructor or non-data subsort reaches it from inhabited sorts).
pub(super) fn data_table(
    root: &str,
    definition: &BackendDefinition,
    excluded: &dyn Fn(&str) -> bool,
) -> Result<DataSorts, SortRefusal> {
    let mut builder = Builder {
        definition,
        excluded,
        index: BTreeMap::new(),
        sorts: Vec::new(),
        pending: Vec::new(),
    };
    builder.entry(root);
    while let Some(index) = builder.pending.pop() {
        builder.fill(index);
    }
    let mut table = DataSorts {
        sorts: builder.sorts,
    };
    inhabit(&mut table);
    if table.sorts[0].height.is_none() {
        return Err(SortRefusal::NoGenerator);
    }
    Ok(table)
}

struct Builder<'a> {
    definition: &'a BackendDefinition,
    excluded: &'a dyn Fn(&str) -> bool,
    index: BTreeMap<String, usize>,
    sorts: Vec<DataSort>,
    pending: Vec<usize>,
}

/// A constructor whose data arguments are still named by KORE sort.
struct Candidate<'s> {
    symbol: &'s Symbol,
    arguments: Vec<Class>,
}

impl Builder<'_> {
    /// The index of the entry of `sort`, added (and queued for filling) on first use.
    fn entry(&mut self, sort: &str) -> usize {
        if let Some(index) = self.index.get(sort) {
            return *index;
        }
        let index = self.sorts.len();
        self.index.insert(sort.to_owned(), index);
        self.sorts.push(DataSort {
            kore_sort: sort.to_owned(),
            height: None,
            constructors: Vec::new(),
            subsorts: Vec::new(),
        });
        self.pending.push(index);
        index
    }

    /// Fill entry `index`: its admissible constructors and its non-data subsorts.
    fn fill(&mut self, index: usize) {
        let sort = self.sorts[index].kore_sort.clone();
        let target = BackendSort::application(sort.as_str(), Vec::new());
        let graph = self.definition.sort_graph();
        let below = |name: &str| {
            let sub = BackendSort::application(name, Vec::new());
            graph.check_subsort(&sub, &target).unwrap_or(false)
        };

        let mut candidates = Vec::new();
        for symbol in self.definition.symbols().values() {
            if !admissible(symbol) {
                continue;
            }
            let SortNode::Application { name, arguments } = symbol.result_sort.node() else {
                continue;
            };
            // The result sort must itself be a data sort that is not excluded: a production of a
            // token sort (`syntax Id ::= "main"`) or of a builtin builds no data value (T-9).
            if !arguments.is_empty()
                || !below(name)
                || !matches!(self.classify(&symbol.result_sort), Class::Data(_))
            {
                continue;
            }
            let arguments = symbol
                .argument_sorts
                .iter()
                .map(|argument| self.classify(argument))
                .collect::<Vec<_>>();
            if arguments
                .iter()
                .any(|argument| matches!(argument, Class::Unavailable))
            {
                continue;
            }
            candidates.push(Candidate {
                symbol: symbol.as_ref(),
                arguments,
            });
        }
        let mut constructors = Vec::with_capacity(candidates.len());
        for candidate in candidates {
            let SortNode::Application { name, .. } = candidate.symbol.result_sort.node() else {
                unreachable!("candidates have closed result sorts");
            };
            let arguments = candidate
                .arguments
                .into_iter()
                .map(|argument| match argument {
                    Class::Leaf(argument) => argument,
                    Class::Data(sort) => ArgumentSort::Data(self.entry(&sort)),
                    Class::Unavailable => unreachable!("dropped above"),
                })
                .collect();
            constructors.push(DataConstructor {
                symbol: candidate.symbol.name.to_string(),
                result_kore_sort: name.to_string(),
                height: None,
                arguments,
            });
        }

        let mut subsorts = Vec::new();
        for (name, info) in self.definition.sorts() {
            if name.as_ref() == sort.as_str() || !info.parameters.is_empty() || !below(name) {
                continue;
            }
            // Builtins and collections are classified before the exclusions (ARCHITECTURE 2.4
            // exempts builtins from the program-syntax rule); an excluded data subsort is
            // unavailable.
            if let Class::Leaf(leaf) =
                self.classify(&BackendSort::application(name.as_ref(), Vec::new()))
            {
                // Two subsorts with the same values (`Int` and a renamed `AInt`) would make a
                // value's KORE sort ambiguous: one is kept, the canonical builtin when there is
                // one (its literal reads back at its own sort), else the first in name order.
                match subsorts.iter().position(|kept| same_values(kept, &leaf)) {
                    None => subsorts.push(leaf),
                    Some(at) => {
                        let renamed = |leaf: &ArgumentSort| {
                            matches!(leaf, ArgumentSort::Value(ValueSort::Renamed { .. }))
                        };
                        if renamed(&subsorts[at]) && !renamed(&leaf) {
                            subsorts[at] = leaf;
                        }
                    }
                }
            }
        }
        let entry = &mut self.sorts[index];
        entry.constructors = constructors;
        entry.subsorts = subsorts;
    }

    /// How values of `sort` are generated as a constructor argument or a subsort. Builtins
    /// and collections are recognized before the exclusions are read: only a data sort can be
    /// excluded.
    fn classify(&self, sort: &BackendSort) -> Class {
        let SortNode::Application { name, arguments } = sort.node() else {
            return Class::Unavailable;
        };
        if let Some(builtin) = builtin_value_sort(sort, self.definition) {
            return Class::Leaf(ArgumentSort::Value(builtin));
        }
        let Some(info) = self.definition.sorts().get(name) else {
            return Class::Unavailable;
        };
        if !arguments.is_empty() || !info.parameters.is_empty() {
            return Class::Unavailable;
        }
        match info.hook.as_deref() {
            None if !info.has_domain_values && self.definition.domain_kind(sort).is_none() => {
                if (self.excluded)(name) {
                    Class::Unavailable
                } else {
                    Class::Data(name.to_string())
                }
            }
            Some(hook @ ("LIST.List" | "SET.Set" | "MAP.Map")) => {
                let (kind, namespace) = match hook {
                    "LIST.List" => (CollectionKind::List, "LIST"),
                    "SET.Set" => (CollectionKind::Set, "SET"),
                    _ => (CollectionKind::Map, "MAP"),
                };
                match collection_symbols(name, namespace, self.definition) {
                    Ok(symbols) => {
                        Class::Leaf(ArgumentSort::Empty(EmptyCollection { kind, symbols }))
                    }
                    Err(_) => Class::Unavailable,
                }
            }
            _ => Class::Unavailable,
        }
    }
}

/// Whether two leaf alternatives have the same values (and so the same printed forms).
fn same_values(left: &ArgumentSort, right: &ArgumentSort) -> bool {
    match (left, right) {
        (ArgumentSort::Value(left), ArgumentSort::Value(right)) => {
            core::mem::discriminant(left.generated()) == core::mem::discriminant(right.generated())
                && match (left.generated(), right.generated()) {
                    (ValueSort::MInt { width: left }, ValueSort::MInt { width: right }) => {
                        left == right
                    }
                    _ => true,
                }
        }
        (ArgumentSort::Empty(left), ArgumentSort::Empty(right)) => left.kind == right.kind,
        _ => false,
    }
}

/// Whether `symbol` may head a generated data value (see the module documentation).
fn admissible(symbol: &Symbol) -> bool {
    let attributes = &symbol.attributes;
    attributes.symbol_type == SymbolType::Constructor
        && matches!(
            attributes.head_role(),
            HeadRole::FreeConstructor | HeadRole::EquationHead
        )
        && symbol.sort_variables.is_empty()
        && attributes.hook.is_none()
        && attributes.collection.is_none()
        && !attributes.macro_or_alias
        && !attributes.binder
        && !symbol.is(WellKnownSymbol::Inj)
}

/// The builtin value sort of `sort` when it is one with a generator: `Int`, `Bool`, `String`,
/// `Bytes` and `MInt{W}`, read from its hook and domain values, and wrapped in
/// [`ValueSort::Renamed`] when the sort is hooked to one of them under another name.
pub(super) fn builtin_value_sort(
    sort: &BackendSort,
    definition: &BackendDefinition,
) -> Option<ValueSort> {
    let SortNode::Application { name, arguments } = sort.node() else {
        return None;
    };
    let (base, canonical) = match definition.domain_kind(sort)? {
        DomainKind::Int => (ValueSort::Int, sort.is_builtin(BuiltinSort::Int)),
        DomainKind::Bool => (ValueSort::Bool, sort.is_builtin(BuiltinSort::Bool)),
        DomainKind::String => (ValueSort::String, sort.is_builtin(BuiltinSort::String)),
        DomainKind::Bytes => (ValueSort::Bytes, sort.is_builtin(BuiltinSort::Bytes)),
        DomainKind::MInt(MIntWidth::Bits(width)) => (
            ValueSort::MInt {
                // A wider MInt is refused: its edge values alone would be too large to build.
                width: u32::try_from(width)
                    .ok()
                    .filter(|width| *width <= MAX_INT_BITS)?,
            },
            name.as_ref() == MINT_SORT,
        ),
        _ => return None,
    };
    if canonical {
        Some(base)
    } else if arguments.is_empty() {
        Some(ValueSort::Renamed {
            sort: kore_to_k_name(name),
            kore_sort: name.to_string(),
            base: Box::new(base),
        })
    } else {
        None
    }
}

/// The K name of a KORE sort name without arguments: `SortMyInt` is `MyInt`. Only used for
/// messages and the `sort` field of a renamed builtin reached as an argument; the KORE name is
/// what printing reads.
fn kore_to_k_name(name: &str) -> String {
    name.strip_prefix("Sort").unwrap_or(name).to_owned()
}

/// Compute every entry's and constructor's height by the least fixed point of the module
/// documentation, and drop the constructors that stay uninhabited.
fn inhabit(table: &mut DataSorts) {
    for entry in &mut table.sorts {
        if !entry.subsorts.is_empty() {
            entry.height = Some(0);
        }
    }
    loop {
        let mut changed = false;
        for index in 0..table.sorts.len() {
            for position in 0..table.sorts[index].constructors.len() {
                let constructor = &table.sorts[index].constructors[position];
                let mut height = 1u32;
                let mut inhabited = true;
                for argument in &constructor.arguments {
                    if let ArgumentSort::Data(child) = argument {
                        match table.sorts[*child].height {
                            Some(child) => height = height.max(child.saturating_add(1)),
                            None => inhabited = false,
                        }
                    }
                }
                if !inhabited || constructor.height.is_some_and(|known| known <= height) {
                    continue;
                }
                table.sorts[index].constructors[position].height = Some(height);
                let entry = &mut table.sorts[index];
                if entry.height.is_none_or(|known| height < known) {
                    entry.height = Some(height);
                }
                changed = true;
            }
        }
        if !changed {
            break;
        }
    }
    for entry in &mut table.sorts {
        entry
            .constructors
            .retain(|constructor| constructor.height.is_some());
        // Shrinking moves towards earlier alternatives: the lowest constructors come first.
        entry
            .constructors
            .sort_by_key(|constructor| constructor.height);
    }
}
