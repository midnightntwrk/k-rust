HERE = Path(__file__).resolve().parent
FIXTURE = HERE / "fixtures" / "foo-bar"
AMBIGUOUS = HERE / "fixtures" / "ambiguous"
PINS = HERE / "pins.json"
PACKAGE = "krs-cli-oracle-semantics"


def build_cli(results: Results) -> Path | None:
    try:
        executable("cargo")
    except GateError as error:
        results.add("tool_cargo", "FAIL", str(error))
        return None
    try:
        binary = build()
    except (GateError, OSError) as error:
        results.add("cli_binary", "FAIL", str(error))
        return None
    results.add("cli_binary", "PASS", f"built real CLI executable {binary}")
    return binary


def materialize(destination: Path) -> Path:
    shutil.copytree(FIXTURE, destination)
    template = destination / "Cargo.toml.in"
    manifest = template.read_text(encoding="utf-8").replace(
        "@KRS_CRATE_PATH@",
        json.dumps(str((ROOT / "crates" / "krs").resolve())),
    )
    (destination / "Cargo.toml").write_text(manifest, encoding="utf-8")
    template.unlink()
    return destination / "Cargo.toml"


def cli_command(
    binary: Path,
    command: str,
    manifest: Path,
    target: Path,
    *,
    package: str = PACKAGE,
    definition: str | None = "main",
    output: Path | None = None,
) -> subprocess.CompletedProcess[bytes]:
    extras = ["--output", str(output)] if output is not None else []
    arguments = Invocation(binary, manifest, package, definition).argv(command, *extras)
    environment = {
        "CARGO_TARGET_DIR": str(target),
        "CARGO_NET_OFFLINE": "true",
        "CARGO_TERM_COLOR": "never",
    }
    return run(arguments, cwd=manifest.parent, environment=environment, check=False, text=False)


def assert_no_leaks(name: str, raw: bytes, forbidden_paths: list[Path]) -> None:
    text = raw.decode("utf-8")
    forbidden_tokens = ("TypeId", "KCell::new")
    for token in forbidden_tokens:
        if token in text:
            raise ValueError(f"{name} leaks forbidden host token {token!r}")
    if re.search(r"\bSelf\b", text):
        raise ValueError(f"{name} leaks the Rust-only `Self` spelling")
    if re.search(r"(?<![A-Za-z])KCell(?![A-Za-z])", text):
        raise ValueError(f"{name} leaks the Rust wrapper `KCell` spelling")
    if re.search(r"\b0x[0-9a-fA-F]{6,}\b", text):
        raise ValueError(f"{name} appears to contain a pointer address")
    for path in forbidden_paths:
        if str(path) in text:
            raise ValueError(f"{name} leaks absolute path {path}")


def verify_expanded_source(raw: bytes, forbidden_paths: list[Path]) -> None:
    source = raw.decode("utf-8")
    required = (
        "// @generated by `krs expand`; deterministic layer-2 reference surface.",
        "#[krs::sort]\npub trait ObjectTerm: KResult {}",
        '#[krs::constructor(sort = ObjectTerm, syntax = "foo")]\npub struct Foo;',
        '#[krs::configuration(root = "machine")]\npub struct Machine {',
        "krs::configuration::KCell::new(krs::k![Foo])",
        "pub fn foo_to_bar(Foo: krs::Term<dyn ObjectTerm>) -> krs::Term<dyn ObjectTerm>",
    )
    missing = [fragment for fragment in required if fragment not in source]
    if missing:
        raise ValueError(f"expanded Rust source omits expected fragments: {missing}")
    for path in forbidden_paths:
        if str(path) in source:
            raise ValueError(f"expand.rs leaks absolute path {path}")


def verify_k_artifacts(directory: Path, forbidden_paths: list[Path], gate: Path) -> dict[str, bytes]:
    expected = json.loads((HERE / "definition-checks.json").read_bytes())
    with krs_gate.Session(gate, environment=z3_environment()) as session:
        files = session.ir_query(directory, {"kind": "files"})
        if files["actual"] != files["expected"] or not files["owned"] or files["has_claims"]:
            raise GateError(f"unexpected emit-k artifact set: {files}")
        absolute_strings = session.ir_query(directory, {"kind": "absolute_strings"})["rows"]
        if absolute_strings:
            raise GateError(f"emitted JSON artifacts contain absolute strings: {absolute_strings}")
        modules = session.ir_query(directory, {"kind": "modules"})
        if modules["main_module"] != expected["main_module"]:
            raise GateError(f"unexpected main module: {modules}")
        productions = session.ir_query(directory, {"kind": "productions", "sort": "ObjectTerm"})["rows"]
        facts = [{"symbol": row["symbol"], "terminals": row["terminals"]} for row in productions]
        if sorted(facts, key=lambda row: row["symbol"]) != expected["productions"]:
            raise GateError(f"unexpected ObjectTerm productions: {facts}")
        configurations = session.ir_query(directory, {"kind": "sentences", "sentence_kind": "configuration"})["rows"]
        if len(configurations) != 1 or configurations[0]["initializers"] != expected["initializer"]:
            raise GateError(f"unexpected foo initializer: {configurations}")
        rules = session.ir_query(directory, {"kind": "sentences", "sentence_kind": "rule"})["rows"]
        if not any(row["body"] == expected["rule_body"] for row in rules):
            raise GateError(f"canonical theory omits the foo-to-bar transition: {rules}")
        vocabulary = session.ir_query(directory, {"kind": "vocabulary"})
        for edge in expected["subsorts"]:
            if edge not in vocabulary["subsorts"]:
                raise GateError(f"missing subsort edge: {edge}")
    artifacts = {name: (directory / name).read_bytes() for name in files["expected"] if name != ".krs-artifacts"}
    for name, contents in artifacts.items():
        assert_no_leaks(name, contents, forbidden_paths)
    return artifacts


def positive_run(binary: Path, workspace: Path, results: Results, gate: Path) -> dict[str, bytes] | None:
    language = workspace / "language"
    manifest = materialize(language)
    target = workspace / "target"
    emitted = workspace / "emitted"
    native = workspace / "native"

    check = cli_command(binary, "check", manifest, target)
    expected_check = b"KRS check passed: 9 descriptors, 1 semantic modules\n"
    results.add(
        f"{workspace.name}_check",
        "PASS" if check.returncode == 0 and check.stdout == expected_check else "FAIL",
        "complete nine-descriptor theory validated" if check.returncode == 0 and check.stdout == expected_check else compact(check),
    )
    if check.returncode != 0:
        return None

    expand = cli_command(binary, "expand", manifest, target)
    try:
        if expand.returncode != 0:
            raise ValueError(compact(expand))
        verify_expanded_source(expand.stdout, [ROOT, workspace, language, target])
        results.add(f"{workspace.name}_expand", "PASS", f"canonical expanded Rust sha256={sha256_bytes(expand.stdout)}")
    except ValueError as error:
        results.add(f"{workspace.name}_expand", "FAIL", str(error))
        return None

    emit = cli_command(binary, "emit-k", manifest, target, output=emitted)
    expected_emit = b"emitted descriptor-bundle.json, semantic-ir.json, definition-ir.json, definition.k, symbols.json, sources.json\n"
    try:
        if emit.returncode != 0 or emit.stdout != expected_emit:
            raise ValueError(compact(emit))
        artifacts = verify_k_artifacts(emitted, [ROOT, workspace, language, target], gate)
        results.add(f"{workspace.name}_emit_k", "PASS", "exact owned canonical K artifact set")
    except (OSError, ValueError, GateError) as error:
        results.add(f"{workspace.name}_emit_k", "FAIL", str(error))
        return None

    build = cli_command(binary, "build", manifest, target, output=native)
    expected_build = b"built definition.kore, syntaxDefinition.kore, macros.kore\n"
    native_names = {
        ".krs-artifacts",
        "definition.kore",
        "macros.kore",
        "syntaxDefinition.kore",
    }
    observed_names = {path.name for path in native.iterdir()} if native.is_dir() else set()
    build_ok = (
        build.returncode == 0
        and build.stdout == expected_build
        and observed_names == native_names
        and all((native / name).stat().st_size > 0 for name in native_names)
    )
    results.add(
        f"{workspace.name}_build",
        "PASS" if build_ok else "FAIL",
        "structured k-rust compilation produced the exact native artifact set"
        if build_ok else compact(build),
    )
    if not build_ok:
        return None
    for name in sorted(native_names):
        artifacts[f"native/{name}"] = (native / name).read_bytes()
    artifacts["expand.rs"] = expand.stdout
    return artifacts


def verify_pins(results: Results, pins: Ledger, artifacts: dict[str, bytes]) -> None:
    fixture_actual = {
        "Cargo.toml.in": sha256_bytes((FIXTURE / "Cargo.toml.in").read_bytes()),
        "src/lib.rs": sha256_bytes((FIXTURE / "src" / "lib.rs").read_bytes()),
    }
    results.add(
        "fixture_pins",
        "PASS" if fixture_actual == pins["fixture_sha256"] else "FAIL",
        f"sha256={fixture_actual}",
    )
    actual = {name: sha256_bytes(data) for name, data in sorted(artifacts.items())}
    failures = []
    if not pins.record and set(actual) != set(pins.table("artifacts_sha256")):
        failures.append(f"artifact set differs from pins.json: {sorted(actual)}")
    for name, digest in actual.items():
        try:
            pins.expect(("artifacts_sha256", name), digest)
        except GateError as error:
            failures.append(str(error))
    if failures:
        results.add("artifact_pins", "FAIL", "; ".join(failures))
    else:
        status = "RECORDED" if pins.record else "PASS"
        results.add("artifact_pins", status, f"sha256={actual}", required=False)


def verify_relocation(results: Results, left: dict[str, bytes], right: dict[str, bytes]) -> None:
    names = sorted(set(left) | set(right))
    differences = [name for name in names if left.get(name) != right.get(name)]
    results.add(
        "clean_relocation",
        "MATCH" if not differences else "FAIL",
        "two clean, differently located workspaces produced byte-identical bundle/K/sidecars"
        if not differences else f"different artifacts: {differences}",
    )


def negative_cases(binary: Path, workspace: Path, results: Results) -> None:
    manifest = materialize(workspace / "missing-language")
    target = workspace / "negative-target"

    missing_option = cli_command(binary, "check", manifest, target, definition=None)
    option_ok = missing_option.returncode == 2 and b"missing --definition" in missing_option.stderr
    results.add("missing_facet_option", "PASS" if option_ok else "FAIL", "CLI rejects implicit facet selection" if option_ok else compact(missing_option))

    missing_facet = cli_command(binary, "check", manifest, target, definition="absent")
    facet_ok = missing_facet.returncode != 0 and b"declares no KRS definition facet `absent`" in missing_facet.stderr
    results.add("missing_facet", "PASS" if facet_ok else "FAIL", "planner rejects nonexistent explicit facet" if facet_ok else compact(missing_facet))

    ambiguous = workspace / "ambiguous"
    shutil.copytree(AMBIGUOUS, ambiguous)
    ambiguous_process = cli_command(
        binary,
        "expand",
        ambiguous / "Cargo.toml",
        workspace / "ambiguous-target",
        package="duplicated-semantics",
    )
    ambiguity_ok = ambiguous_process.returncode != 0 and b"matches 2 resolved packages" in ambiguous_process.stderr
    results.add("ambiguous_package", "PASS" if ambiguity_ok else "FAIL", "name selector rejects two resolved package identities" if ambiguity_ok else compact(ambiguous_process))

    broken_manifest = materialize(workspace / "broken-language")
    broken_source = broken_manifest.parent / "src" / "lib.rs"
    with broken_source.open("a", encoding="utf-8") as output:
        output.write('\ncompile_error!("KRS CLI oracle induced Cargo failure");\n')
    for command in ("check", "build"):
        broken = cli_command(
            binary,
            command,
            broken_manifest,
            workspace / "broken-target",
            output=workspace / "broken-output" if command == "build" else None,
        )
        diagnostics = krs_diagnostics(broken.stderr)
        source_bytes = broken_source.read_bytes()
        error_start = source_bytes.index(b"compile_error!")
        broken_ok = broken.returncode != 0 and any(
            diagnostic.schema_version == 1
            and diagnostic.stage == "rust-expansion"
            and diagnostic.code == "krs::rust-expansion::uncoded-error"
            and diagnostic.severity == "error"
            and "KRS CLI oracle induced Cargo failure" in diagnostic.message
            and diagnostic.authored_range is not None
            and diagnostic.authored_range.cargo_name == PACKAGE
            and diagnostic.authored_range.package_relative_path == "src/lib.rs"
            and error_start <= diagnostic.authored_range.start_byte
            < diagnostic.authored_range.end_byte
            <= len(source_bytes)
            for diagnostic in diagnostics
        )
        results.add(
            f"collector_build_failure_{command}",
            "PASS" if broken_ok else "FAIL",
            f"krs {command} reports an authored Rust diagnostic from the collector build" if broken_ok else compact(broken),
        )

    safe_manifest = materialize(workspace / "safe-language")
    unsafe_output = workspace / "unsafe-output"
    unsafe_output.mkdir()
    sentinel = b"do not overwrite\n"
    (unsafe_output / "definition.k").write_bytes(sentinel)
    (unsafe_output / "unrelated.txt").write_bytes(sentinel)
    unsafe = cli_command(binary, "emit-k", safe_manifest, workspace / "safe-target", output=unsafe_output)
    preserved = (
        unsafe.returncode != 0
        and b"refusing to replace non-KRS artifact directory" in unsafe.stderr
        and (unsafe_output / "definition.k").read_bytes() == sentinel
        and (unsafe_output / "unrelated.txt").read_bytes() == sentinel
        and {item.name for item in unsafe_output.iterdir()} == {"definition.k", "unrelated.txt"}
    )
    results.add("unsafe_output", "PASS" if preserved else "FAIL", "nonempty unowned output rejected without changing bytes" if preserved else compact(unsafe))


def reference_execution(results: Results, artifacts: dict[str, bytes], workspace: Path) -> None:
    missing = [name for name in ("kompile", "krun") if find_k_tool(name) is None]
    if missing:
        results.add("reference_execution", "UNAVAILABLE", f"missing {', '.join(missing)}; K compile/execution did not run", required=False)
        return
    try:
        executables = {name: k_tool(name, k_version()) for name in ("kompile", "krun")}
    except GateError as error:
        results.add("reference_execution", "MISMATCH", f"{error}; execution was refused")
        return

    workspace.mkdir(parents=True)
    source = workspace / "definition.k"
    source.write_bytes(artifacts["definition.k"])
    definition_ir = workspace / "definition-ir.json"
    definition_ir.write_bytes(artifacts["definition-ir.json"])
    try:
        gate = krs_gate.configured_or_build(workspace_debug_binary("krs").parents[1])
    except (GateError, OSError) as error:
        results.add("reference_execution", "FAIL", str(error))
        return
    main_module = krs_gate.ir_query(gate, workspace, {"kind": "modules"}, environment=z3_environment())["main_module"]
    definition = workspace / "compiled-definition"
    compile_process = run(
        [
            executables["kompile"],
            str(source),
            "--main-module",
            main_module,
            "--syntax-module",
            main_module,
            "--backend",
            "llvm",
            "--emit-json",
            "--output-definition",
            str(definition),
        ],
        timeout=240,
        check=False,
        text=False,
    )
    if compile_process.returncode != 0:
        results.add("reference_execution", "FAIL", compact(compile_process))
        return
    initial = run([executables["krun"], "--definition", str(definition), "--depth", "0", "--output", "kore"], timeout=60, check=False, text=False)
    final = run([executables["krun"], "--definition", str(definition), "--output", "kore"], timeout=60, check=False, text=False)
    if initial.returncode != 0 or final.returncode != 0:
        results.add("reference_execution", "FAIL", compact(initial if initial.returncode != 0 else final))
        return
    try:
        with krs_gate.Session(gate, environment=z3_environment()) as session:
            session.load(definition_ir, main_module)
            session.read(initial.stdout.decode("utf-8"), "initial")
            session.expect("initial", "k", text="foo ~> .K")
            session.read(final.stdout.decode("utf-8"), "final")
            session.expect("final", "k", text="bar ~> .K")
    except (GateError, OSError, UnicodeError) as error:
        results.add("reference_execution", "FAIL", str(error))
        return
    results.add("reference_execution", "PASS", f"K {k_version()} compiled canonical output and executed foo -> bar")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--record",
        action="store_true",
        help="run the oracle and rewrite the artifact pins it measured",
    )
    arguments = parser.parse_args()
    pins = Ledger(PINS, record=arguments.record)
    results = Results(width=11)
    binary = build_cli(results)
    if binary is None:
        return 1
    gate = krs_gate.configured_or_build(workspace_debug_binary("krs").parents[1])
    with tempfile.TemporaryDirectory(prefix="krs-cli-oracle-a-") as first_raw, tempfile.TemporaryDirectory(prefix="krs-cli-oracle-relocated-b-") as second_raw:
        first_root = Path(first_raw)
        second_root = Path(second_raw) / "different" / "depth"
        second_root.mkdir(parents=True)
        first = positive_run(binary, first_root / "run-a", results, gate)
        second = positive_run(binary, second_root / "run-b", results, gate)
        if first is not None and second is not None:
            verify_relocation(results, first, second)
            verify_pins(results, pins, first)
            reference_execution(results, first, first_root / "reference")
        else:
            results.add("clean_relocation", "FAIL", "positive command run did not complete")
        negative_cases(binary, first_root / "negative", results)
    if not results.failed:
        pins.finish("CLI acceptance oracle")
    print("\nCLI acceptance oracle:", "FAIL" if results.failed else "PASS")
    return int(results.failed)


if __name__ == "__main__":
    entry("CLI acceptance oracle", main)
