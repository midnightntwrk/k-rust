"""Shape-isolated synthetic KRS definitions for the scaling ladders.

Every shape is a function of one size parameter `n` that grows exactly one
aspect of a small base definition (one `Step` sort, an `Op` constructor enum,
a single-cell `k` configuration) while holding the rest fixed:

| Shape | Grows with `n` |
|---|---|
| `many-small-rules` | `n` one-token rules in one `k::rules!` block |
| `few-large-rules` | four rules whose right-hand `k` sequence has `n` items |
| `deep-terms` | four rules whose right-hand term nests `n` constructors deep |
| `wide-enums` | one constructor enum with `n` nullary variants |
| `sorts-deep` | a sort chain of length `n`, one leaf membership per chain sort |
| `sorts-dense` | `n` sorts in layers of four, each a subsort of the whole previous layer, one leaf membership per sort |
| `anchors-per-rule` | four rules whose right-hand integer expression is a balanced tree of `n` leaves |

`sorts-deep` and `sorts-dense` target the local-ancestor closure of
`k::sorts!` memberships: a membership into a sort with `a` local ancestors
expands to `a + 1` Rust marker impls, so both shapes have linear source and a
quadratic impl count.

A generated crate is written into scratch only (`write_crate`); nothing here
is committed as a fixture.
"""

from __future__ import annotations

from pathlib import Path
from typing import Callable

from support import ROOT

PACKAGE = "krs-perf-synth"
LIBRARY = "krs_perf_synth"
NAMESPACE = "KRS-PERF-SYNTH"
TEMPLATE = ROOT / "tests" / "tour-minimal"
"""The single-package workspace whose lock file (only the `krs` crates) the synthetic crate reuses."""

FIXED_RULES = 4


def _base(shape: str, n: int, *, sorts: str = "", declarations: str = "", rules: str) -> str:
    return f"""//! Synthetic KRS definition generated by tests/perf/synth.py: shape `{shape}`, n = {n}.

use k::KResult;
use k::builtin::{{Int, KSequence, int}};

k::sorts! {{
    Step: k::KItem;
{sorts}}}

#[k::constructors(sort = Step, result = KResult)]
#[k::precedence((Tick, Wrap, Done))]
pub enum Op {{
    #[k::syntax("tick ( {{value}} )")]
    Tick {{ value: Int }},
    #[k::syntax("wrap ( {{inner}} )")]
    Wrap {{ inner: Step }},
    #[k::syntax("done")]
    Done(),
}}
{declarations}
#[k::configuration]
pub struct Machine {{
    #[k::cell]
    pub k: KSequence,
}}

impl Machine {{
    #[k::init]
    pub fn init(#[k::config_var(name = "PGM", main)] program: KSequence) -> Self {{
        Self {{ k: k::k![program] }}
    }}
}}

#[rustfmt::skip]
k::rules! {{
    for Machine;
    use Op::*;

{rules}}}
"""


def _rule(name: str, left: str, right: str, where: str = "") -> str:
    clause = f"\n    where {where}" if where else ""
    return f"    {name}: {{\n        k: [{left}, ..],\n    }} => {{\n        k: [{right}, ..],\n    }}{clause};\n\n"


def _fixed_rules() -> str:
    return "".join(_rule(f"fixed_{j}", f"Tick({j})", f"Tick({j + 1})") for j in range(FIXED_RULES))


def many_small_rules(n: int) -> str:
    rules = "".join(_rule(f"step_{i}", f"Tick({i})", f"Tick({i + 1})") for i in range(n))
    return _base("many-small-rules", n, rules=rules)


def few_large_rules(n: int) -> str:
    right = ", ".join(f"Tick({i})" for i in range(n))
    rules = "".join(_rule(f"large_{j}", f"Tick({j})", right) for j in range(FIXED_RULES))
    return _base("few-large-rules", n, rules=rules)


def deep_terms(n: int) -> str:
    def nested(j: int) -> str:
        return "Wrap(" * n + f"Tick({j})" + ")" * n

    rules = "".join(_rule(f"deep_{j}", f"Tick({j})", nested(j)) for j in range(FIXED_RULES))
    return _base("deep-terms", n, rules=rules)


def wide_enums(n: int) -> str:
    names = [f"W{i}" for i in range(n)]
    variants = "".join(f'    #[k::syntax("w{i}")]\n    W{i}(),\n' for i in range(n))
    declarations = (
        f"\n#[k::constructors(sort = Wide, result = KResult)]\n"
        f"#[k::precedence(({', '.join(names)}))]\n"
        f"pub enum WideOp {{\n{variants}}}\n"
    )
    return _base("wide-enums", n, sorts="    Wide: k::KItem;\n", declarations=declarations, rules=_fixed_rules())


def sorts_deep(n: int) -> str:
    lines = []
    for i in range(n):
        lines.append(f"    Deep{i};" if i == 0 else f"    Deep{i}: Deep{i - 1};")
    for i in range(n):
        lines.append(f"    Leaf{i};")
        lines.append(f"    impl Deep{i} for Leaf{i};")
    return _base("sorts-deep", n, sorts="\n".join(lines) + "\n", rules=_fixed_rules())


DENSE_WIDTH = 4


def sorts_dense(n: int) -> str:
    if n % DENSE_WIDTH:
        raise ValueError(f"sorts-dense needs a multiple of {DENSE_WIDTH}, not {n}")
    layers = n // DENSE_WIDTH
    lines = []
    for layer in range(layers):
        for column in range(DENSE_WIDTH):
            name = f"Dense{layer}x{column}"
            if layer == 0:
                lines.append(f"    {name};")
            else:
                parents = " + ".join(f"Dense{layer - 1}x{c}" for c in range(DENSE_WIDTH))
                lines.append(f"    {name}: {parents};")
    for layer in range(layers):
        for column in range(DENSE_WIDTH):
            lines.append(f"    DenseLeaf{layer}x{column};")
            lines.append(f"    impl Dense{layer}x{column} for DenseLeaf{layer}x{column};")
    return _base("sorts-dense", n, sorts="\n".join(lines) + "\n", rules=_fixed_rules())


def _balanced(leaves: list[str]) -> str:
    if len(leaves) == 1:
        return leaves[0]
    middle = len(leaves) // 2
    return f"int::add({_balanced(leaves[:middle])}, {_balanced(leaves[middle:])})"


def anchors_per_rule(n: int) -> str:
    rules = ""
    for j in range(FIXED_RULES):
        leaves = ["value" if i % 2 == 0 else str(i) for i in range(max(n, 1))]
        left = "Wrap(" * (j + 1) + "Tick(value)" + ")" * (j + 1)
        rules += _rule(f"anchors_{j}", left, f"Tick({_balanced(leaves)})", "value: Int")
    return _base("anchors-per-rule", n, rules=rules)


SHAPES: dict[str, Callable[[int], str]] = {
    "many-small-rules": many_small_rules,
    "few-large-rules": few_large_rules,
    "deep-terms": deep_terms,
    "wide-enums": wide_enums,
    "sorts-deep": sorts_deep,
    "sorts-dense": sorts_dense,
    "anchors-per-rule": anchors_per_rule,
}


def generate(shape: str, n: int) -> str:
    if shape not in SHAPES:
        raise KeyError(f"unknown synthetic shape {shape!r}; known: {', '.join(SHAPES)}")
    if n < 1:
        raise ValueError(f"{shape}: n must be at least 1")
    return SHAPES[shape](n)


def manifest() -> str:
    """The synthetic crate's Cargo.toml: its own workspace, the local `krs` facade, no deny lints."""

    return f"""[package]
name = "{PACKAGE}"
description = "Synthetic KRS definition for compile-performance ladders (generated, scratch only)"
version = "0.0.0"
edition = "2024"
rust-version = "1.88"
publish = false

[lib]
name = "{LIBRARY}"
path = "src/lib.rs"

[dependencies]
k = {{ package = "krs", path = "{ROOT / 'crates' / 'krs'}" }}

[package.metadata.krs]
k-namespace = "{NAMESPACE}"

[package.metadata.krs.definitions.main]

[workspace]
resolver = "3"
"""


def write_crate(directory: Path, source: str) -> Path:
    """Write (or rewrite) the synthetic crate under `directory`; returns its manifest path."""

    (directory / "src").mkdir(parents=True, exist_ok=True)
    manifest_path = directory / "Cargo.toml"
    manifest_path.write_text(manifest(), encoding="utf-8")
    lock = (TEMPLATE / "Cargo.lock").read_text(encoding="utf-8")
    (directory / "Cargo.lock").write_text(
        lock.replace('name = "krs-tour-minimal"', f'name = "{PACKAGE}"'), encoding="utf-8")
    (directory / "src" / "lib.rs").write_text(source, encoding="utf-8")
    return manifest_path
