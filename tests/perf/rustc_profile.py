# The wrapper is POSIX sh so that it adds no interpreter start-up to the many
# rustc invocations it merely forwards. For the profiled crate it keeps argv,
# start and end times, and a copy of stderr (streamed, so Cargo still sees
# rustc's JSON artifact notifications as they happen and pipelining is
# unchanged) in a per-invocation directory, which is also the self-profile
# output directory. rustc's stdout, empty for an ordinary compilation, goes to
# a file so that `-Zunpretty` output does not flood Cargo's log.
WRAPPER = r"""#!/bin/sh
# @generated by tests/perf/rustc_profile.py: profile selected crates' rustc.
rustc=$1
shift
selected=
previous=
for argument in "$@"; do
    if [ "$previous" = --crate-name ]; then
        for crate in $KRS_PERF_PROFILE_CRATES; do
            [ "$argument" = "$crate" ] && selected=$crate
        done
    fi
    previous=$argument
done
if [ -z "$selected" ]; then
    exec "$rustc" "$@"
fi
directory=$KRS_PERF_PROFILE_DIR/$(date +%s%N)-$$
mkdir -p "$directory"
printf '%s\n' "$@" > "$directory/argv"
printf '%s\n' "$selected" > "$directory/crate"
date +%s.%N > "$directory/start"
{ RUSTC_BOOTSTRAP=1 "$rustc" "$@" $KRS_PERF_PROFILE_FLAGS "-Zself-profile=$directory" \
    2>&1 >"$directory/stdout"; echo $? > "$directory/status"; } | tee "$directory/stderr" >&2
date +%s.%N > "$directory/end"
exit "$(cat "$directory/status")"
"""


def crate_name(package: str) -> str:
    return package.replace("-", "_")


# --- measureme tools -----------------------------------------------------------------


def rustc_measureme_version(environment: Mapping[str, str]) -> str | None:
    """The measureme release linked into this rustc, from `librustc_driver`."""

    sysroot = subprocess.run(["rustc", "--print", "sysroot"], env=dict(environment), capture_output=True,
                             text=True, check=False).stdout.strip()
    return _measureme_version_in(sysroot)


@functools.lru_cache(maxsize=None)
def _measureme_version_in(sysroot: str) -> str | None:
    versions: Counter[str] = Counter()
    for library in Path(sysroot).glob("lib/librustc_driver-*.so") if sysroot else []:
        data = library.read_bytes()
        versions.update(match.decode() for match in re.findall(rb"measureme-(\d+\.\d+\.\d+)", data))
    return versions.most_common(1)[0][0] if versions else None


def tools_directory(version: str) -> Path:
    from support.tools import checkout_scratch

    return Path(os.environ.get("KRS_PERF_TOOLS", os.fspath(checkout_scratch() / "perf-tools"))) / f"measureme-{version}"


def measureme_tools(environment: Mapping[str, str], *, build: bool = True) -> dict[str, Any]:
    """Locate, or build into scratch, `summarize` and `crox` matching rustc.

    Returns `{status, version, bin, note}`; `status` is `available`,
    `built`, or `unavailable` (then `note` says why).
    """

    version = rustc_measureme_version(environment)
    if version is None:
        return {"status": "unavailable", "version": None, "bin": None,
                "note": "no measureme version found in librustc_driver"}
    root = tools_directory(version)
    binaries = root / "bin"
    if all((binaries / tool).is_file() for tool in ("summarize", "crox")):
        return {"status": "available", "version": version, "bin": os.fspath(binaries), "note": None}
    if not build:
        return {"status": "unavailable", "version": version, "bin": None, "note": f"not built in {root}"}
    print(f"building measureme {version} summarize and crox into {root}", flush=True)
    build_target = root / "build"
    install_environment = {key: value for key, value in environment.items() if key != "CARGO_NET_OFFLINE"}
    # measureme denies warnings that newer compilers raise; cap lints for this build only.
    install_environment.update({"RUSTFLAGS": "--cap-lints warn", "CARGO_TARGET_DIR": os.fspath(build_target)})
    completed = subprocess.run(
        ["cargo", "+stable", "install", "--locked", "--root", os.fspath(root), "--git", MEASUREME_GIT,
         "--tag", version, "summarize", "crox"],
        env=install_environment, capture_output=True, text=True, check=False, timeout=1800,
    )
    shutil.rmtree(build_target, ignore_errors=True)
    if completed.returncode != 0 or not all((binaries / tool).is_file() for tool in ("summarize", "crox")):
        return {"status": "unavailable", "version": version, "bin": None,
                "note": f"cargo install failed ({completed.returncode}): {completed.stderr.strip()[-600:]}"}
    return {"status": "built", "version": version, "bin": os.fspath(binaries), "note": None}


# --- parsers ----------------------------------------------------------------------------


_TIME_PASS = re.compile(
    r"^time:\s+([0-9.]+);\s+rss:\s+(\d+)MB\s+->\s+(\d+)MB\s+\(\s*[+-]?\d+MB\)\s*(\S+)\s*$")


def parse_time_passes(text: str) -> list[dict[str, Any]]:
    """`-Ztime-passes` lines in output order: `{pass, seconds, rss_start_mb, rss_end_mb}`."""

    passes = []
    for line in text.splitlines():
        match = _TIME_PASS.match(line.strip())
        if match:
            passes.append({"pass": match.group(4), "seconds": float(match.group(1)),
                           "rss_start_mb": int(match.group(2)), "rss_end_mb": int(match.group(3))})
    return passes


def _number(text: str) -> float:
    return float(text.replace("_", ""))


def _split_joined(token: str, uses: int) -> tuple[int, float] | None:
    """Split rustc's joined `Bytes` and `Avg Bytes` columns (`31_007_15910_335_719.7`).

    rustc pads the columns to a fixed width, so wide values run together.
    Every digit boundary is a candidate; the one where bytes / uses is
    closest to the average wins.
    """

    digits = token.replace("_", "")
    if "." not in digits:
        return None
    whole, _, fraction = digits.partition(".")
    best: tuple[float, int, float] | None = None
    for cut in range(1, len(whole)):
        total, average = int(whole[:cut]), float(f"{whole[cut:]}.{fraction}")
        if whole[cut] == "0" and len(whole) - cut > 1:
            continue
        error = abs(total / max(uses, 1) - average)
        if best is None or error < best[0]:
            best = (error, total, average)
    return None if best is None else (best[1], best[2])


def parse_macro_stats(text: str) -> list[dict[str, Any]]:
    """The `-Zmacro-stats` table: `{macro, uses, lines, bytes}` per macro.

    Long macro names are printed alone on one line with the numbers on the
    next; both layouts are accepted.
    """

    rows = []
    pending: str | None = None
    for raw in text.splitlines():
        if not raw.startswith("macro-stats"):
            continue
        body = raw[len("macro-stats"):].strip()
        if not body or body.startswith(("=", "-", "MACRO EXPANSION", "Macro Name")):
            pending = None
            continue
        fields = body.split()
        numeric = [field for field in fields if re.fullmatch(r"[0-9_]+(?:\.[0-9]+)?", field)]
        if len(fields) == 1 and not numeric:
            pending = fields[0]
            continue
        if pending is not None and len(fields) == len(numeric):
            name, values = pending, fields
        else:
            split = next((i for i, field in enumerate(fields) if re.fullmatch(r"[0-9_]+", field)), None)
            if split is None:
                continue
            name, values = " ".join(fields[:split]), fields[split:]
        pending = None
        try:
            uses, lines = int(_number(values[0])), int(_number(values[1]))
            if len(values) >= 5:
                size = int(_number(values[3]))
            else:
                joined = _split_joined(values[3], uses) if len(values) == 4 else None
                if joined is None:
                    continue
                size = joined[0]
        except (IndexError, ValueError):
            continue
        rows.append({"macro": name, "uses": uses, "lines": lines, "bytes": size})
    return rows


def _duration(value: Any) -> float:
    if isinstance(value, Mapping):
        return float(value.get("secs", 0)) + float(value.get("nanos", 0)) / 1e9
    return float(value or 0)


def parse_summarize(document: Mapping[str, Any]) -> dict[str, Any]:
    """measureme `summarize --json` as `{total_seconds, queries [...], artifact_sizes {}}`."""

    queries = []
    for row in document.get("query_data", []):
        queries.append({
            "label": row.get("label"),
            "self_seconds": round(_duration(row.get("self_time")), 6),
            "seconds": round(_duration(row.get("time")), 6),
            "invocations": row.get("invocation_count"),
            "cache_hits": row.get("number_of_cache_hits"),
            "incremental_load_seconds": round(_duration(row.get("incremental_load_time")), 6),
        })
    queries.sort(key=lambda row: -row["self_seconds"])
    return {
        "total_seconds": round(_duration(document.get("total_time")), 6),
        "queries": queries,
        "artifact_sizes": {row.get("label"): row.get("value") for row in document.get("artifact_sizes", [])},
    }


# --- trace events and the phase decomposition ------------------------------------------


_EVENT = re.compile(
    r'\{"name":"((?:[^"\\]|\\.)*)","cat":"(\w+)","ph":"X","ts":(\d+),"dur":(\d+),"pid":\d+,"tid":(\d+),'
    r'"args":(null|\{(?:"arg\d+":"(?:[^"\\]|\\.)*",?)*\})\}')
_ARG = re.compile(r'"arg\d+":"((?:[^"\\]|\\.)*)"')


def iter_trace_events(text: str) -> Iterator[dict[str, Any]]:
    """Complete events of a `crox` trace without materializing the whole JSON.

    crox writes one flat object per event; a full trace of a large crate is
    hundreds of megabytes, which `json.loads` would expand several-fold.
    """

    for match in _EVENT.finditer(text):
        arguments = match.group(6)
        yield {
            "name": json.loads(f'"{match.group(1)}"'),
            "cat": match.group(2),
            "ts": int(match.group(3)),
            "dur": int(match.group(4)),
            "tid": int(match.group(5)),
            "args": [json.loads(f'"{value}"') for value in _ARG.findall(arguments)] if arguments != "null" else [],
        }


def with_self_time(events: Iterable[dict[str, Any]]) -> list[dict[str, Any]]:
    """Events sorted per thread, each with `self` (duration minus direct children) and `parent` index."""

    ordered = sorted(events, key=lambda event: (event["tid"], event["ts"], -event["dur"]))
    stack: list[int] = []
    tid = None
    for index, event in enumerate(ordered):
        event["self"] = event["dur"]
        event["parent"] = None
        if event["tid"] != tid:
            stack, tid = [], event["tid"]
        while stack and ordered[stack[-1]]["ts"] + ordered[stack[-1]]["dur"] <= event["ts"]:
            stack.pop()
        if stack:
            parent = ordered[stack[-1]]
            event["parent"] = stack[-1]
            parent["self"] -= min(event["dur"], parent["ts"] + parent["dur"] - event["ts"])
        stack.append(index)
    return ordered


