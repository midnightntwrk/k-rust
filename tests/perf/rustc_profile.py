#!/usr/bin/env python3
"""rustc profiling modes for the compile-performance harness.

`bench.py --profile rustc` (and `rustc-trace`) profiles the semantics crate's
own rustc invocation inside an otherwise ordinary harness stage: the
`collector-build` stage (the collector's dev-profile, host-target build) and
the `cargo-check` stage (the host-target `cargo check` that `krs check` runs).

The mode installs a `RUSTC_WRAPPER` that forwards every rustc invocation
unchanged except the semantics crate's, which it runs with
`RUSTC_BOOTSTRAP=1 -Ztime-passes -Zmacro-stats -Zself-profile`. Dependencies
therefore compile exactly as in an unprofiled run (in particular proc-macro2's
build probe never sees `RUSTC_BOOTSTRAP`, which would otherwise switch on its
nightly span support), and the unstable flags reach one crate only.

After each measured run the mode parses, into the receipt's `rustc_profile`:

- the `-Ztime-passes` passes with their RSS;
- the `-Zmacro-stats` table (uses, lines, bytes per macro);
- self-profile query totals from measureme `summarize`, and a phase
  decomposition of the main thread from the `crox` trace, with nesting
  resolved by event intervals.

`summarize` and `crox` are built once into `<checkout scratch>/perf-tools/`
at the measureme version compiled into this rustc; when that fails the mode
records time-passes and macro-stats only. `rustc-trace` also keeps the Chrome
trace (for Perfetto) and the raw `.mm_profdata` beside the receipts.

    python3 tests/perf/rustc_profile.py tools            # build or locate summarize/crox
    python3 tests/perf/rustc_profile.py report PROFILED [--reference UNPROFILED]
"""

