// Derives the ticket's TOML evidence from a verify.ts output directory:
// timings.toml, vfs-listing.toml, rustc-args.toml.
//
//   bun test/summarize.ts DIR

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) throw new Error("usage: bun test/summarize.ts DIR");

const q = (value: unknown): string => JSON.stringify(value);
const num = (value: number | null | undefined) => (value === null || value === undefined ? "nan" : String(Math.round(value)));

interface Ev {
  type: string;
  stage?: string;
  state?: string;
  ms?: number;
  evidence?: {
    rustc: Record<string, { args: string[]; env: string[]; preopens: string[]; runMs: number; instantiateMs: number; memoryBytes: number | null; riwl: Record<string, number> | null }>;
    collector?: { args: string[]; env: string[]; preopens: string[]; compileMs: number; runMs: number; memoryBytes: number | null };
    vfs: { rustc: Array<{ path: string; bytes: number; sha256: string }>; collector: Array<{ path: string; bytes: number; sha256: string }> };
    artifacts: Record<string, { bytes: number; sha256: string }>;
  };
}
interface Run {
  host: string;
  scenario: string;
  wallMs: number;
  events: Ev[];
}

const runs: Run[] = [];
const hostMemory: string[] = [];
for (const host of ["bun", "node"]) {
  const data = JSON.parse(readFileSync(join(dir, `pipeline-${host}.json`), "utf8"));
  for (const r of data.records) runs.push({ host: data.host, scenario: r.scenario, wallMs: r.wallMs, events: r.events });
  hostMemory.push(
    `[[memory]]\nhost = ${q(data.host)}\nmethod = "process.memoryUsage().rss sampled every 50 ms, and /proc/self/status VmHWM"\n` +
      `peak_rss_sampled_mib = ${num(data.peakRssSampledBytes / 2 ** 20)}\nvm_hwm_mib = ${num(data.vmHwmBytes / 2 ** 20)}\n` +
      `load_and_verify_ms = ${num(data.loadAndVerifyMs)}\ncontext_ms = ${num(data.contextMs)}\n`,
  );
}
for (const browser of ["chromium", "firefox"]) {
  let record;
  try {
    record = JSON.parse(readFileSync(join(dir, `${browser}-record.json`), "utf8"));
  } catch {
    continue;
  }
  const lines = readFileSync(join(dir, `${browser}-events.jsonl`), "utf8").trim().split("\n").map((l) => JSON.parse(l));
  const init = lines.find((l) => l.step === "init")?.result ?? {};
  for (const line of lines) {
    if (line.result?.events) runs.push({ host: `${browser} ${record.browserVersion}`, scenario: line.step, wallMs: line.wallMs, events: line.result.events });
  }
  const phases = Object.entries(record.memory.byPhase as Record<string, { peakPssKb: number; peakRssKb: number }>)
    .map(([phase, v]) => `${q(phase)} = { peak_pss_mib = ${num(v.peakPssKb / 1024)}, peak_rss_mib = ${num(v.peakRssKb / 1024)} }`)
    .join("\n");
  hostMemory.push(
    `[[memory]]\nhost = ${q(`${browser} ${record.browserVersion}`)}\nmethod = ${q(record.memory.method)}\n` +
      `peak_pss_mib = ${num(record.memory.peakPss.pssKb / 1024)}\npeak_pss_phase = ${q(record.memory.peakPss.phase)}\n` +
      `peak_rss_mib = ${num(record.memory.peakRss.rssKb / 1024)}\n` +
      `page_fetch_verify_compile_ms = ${num(init.loadVerifyCompileMs)}\nworker_ready_ms = ${num(init.workerReadyMs)}\n` +
      `[memory.by_phase]\n${phases}\n`,
  );
}

// ---------------------------------------------------------------- timings.toml
const timing = runs.map((run) => {
  const stages = run.events.filter((e) => e.type === "progress" && e.state === "end").map((e) => `${q(e.stage)} = ${num(e.ms)}`);
  const terminal = run.events.filter((e) => ["success", "failure", "cancelled"].includes(e.type)).at(-1);
  const ev = terminal?.evidence;
  const out = [`[[run]]`, `host = ${q(run.host)}`, `scenario = ${q(run.scenario)}`, `outcome = ${q(terminal?.type ?? "none")}`, `wall_ms = ${num(run.wallMs)}`, `stage_ms = { ${stages.join(", ")} }`];
  for (const [name, r] of Object.entries(ev?.rustc ?? {})) {
    out.push(`rustc_${name} = { run_ms = ${num(r.runMs)}, instantiate_ms = ${num(r.instantiateMs)}, wasm_memory_mib = ${num((r.memoryBytes ?? 0) / 2 ** 20)}${r.riwl ? `, riwl_total_ms = ${num(r.riwl.total_ms)}` : ""} }`);
  }
  if (ev?.collector) out.push(`collector = { compile_ms = ${num(ev.collector.compileMs)}, run_ms = ${num(ev.collector.runMs)}, wasm_memory_mib = ${num((ev.collector.memoryBytes ?? 0) / 2 ** 20)} }`);
  return out.join("\n");
});
writeFileSync(
  join(dir, "timings.toml"),
  `# IR-15 per-stage wall time (ms) and memory, generated by browser/worker/test/summarize.ts from verify.ts output.\n` +
    `# stage_ms comes from the worker's progress events; rustc_* from the evidence records (debugEvidence).\n\n` +
    `${hostMemory.join("\n")}\n${timing.join("\n\n")}\n`,
);

// ---------------------------------------------------------------- vfs-listing.toml and rustc-args.toml
const reference = runs.find((r) => r.host.startsWith("chromium") && r.scenario === "tour-minimal") ?? runs.find((r) => r.scenario === "tour-minimal")!;
const ev = reference.events.at(-1)!.evidence!;
const entries = (list: Array<{ path: string; bytes: number; sha256: string }>) =>
  list.map((e) => `{ path = ${q(e.path)}, bytes = ${e.bytes}, sha256 = ${q(e.sha256)} }`).join(",\n  ");
writeFileSync(
  join(dir, "vfs-listing.toml"),
  `# Every file mounted for rustc.wasm and for the collector in the tour-minimal build (${reference.host}).\n\n` +
    `[rustc]\npreopens = ${q(ev.rustc.lesson!.preopens)}\nnote = "listed before the lesson compile; /work/out is empty then and receives the lesson rlib and collector.wasm"\n` +
    `files = [\n  ${entries(ev.vfs.rustc)},\n]\n\n` +
    `[collector]\npreopens = ${q(ev.collector!.preopens)}\nfiles = [\n  ${entries(ev.vfs.collector)},\n]\n\n` +
    `[artifacts]\n${Object.entries(ev.artifacts).map(([k, v]) => `${k} = { bytes = ${v.bytes}, sha256 = ${q(v.sha256)} }`).join("\n")}\n`,
);
const invocation = (name: string, r: { args: string[]; env: string[]; preopens: string[] }) =>
  `[${name}]\nargs = [\n  ${r.args.map(q).join(",\n  ")},\n]\nenv = ${q(r.env)}\npreopens = ${q(r.preopens)}\n`;
writeFileSync(
  join(dir, "rustc-args.toml"),
  `# Exact arguments and WASI environment of both rustc.wasm stages and the collector run (${reference.host}, tour-minimal).\n\n` +
    `${invocation("rustc_lesson", ev.rustc.lesson!)}\n${invocation("rustc_collector", ev.rustc.collector!)}\n${invocation("collector_run", ev.collector!)}`,
);
console.log(`wrote timings.toml, vfs-listing.toml, rustc-args.toml in ${dir}`);
