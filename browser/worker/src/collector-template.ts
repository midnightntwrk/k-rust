// Collector main.rs rendering: the program crates/krs-cli/src/generate.rs
// render_main + render_production_main emit in explicit registration mode,
// for one PackageContext: the lesson at <manifest_dir>/Cargo.toml.
// The `&<crate>::__KRS_REGISTRATIONS` table entry is also the strong reference
// to the lesson rlib: with only `extern crate <lesson> as _;` direct linking
// discards the rlib's object code and the collector finds no descriptors.

import type { LessonManifest } from "./protocol.ts";

/** krs-cli rust_string: a JSON string literal is a valid Rust string literal. */
function rustString(value: string): string {
  return JSON.stringify(value);
}

export function renderCollectorMain(lesson: LessonManifest): string {
  const p = lesson.package;
  const alias = p.crate_name;
  const context = [p.k_namespace, p.cargo_name, p.cargo_version, p.cargo_source, p.crate_name].map(rustString).join(", ");
  return (
    "// @generated by krs-cli. Stdout is reserved for descriptor protocol bytes.\n\n" +
    `#[allow(unused_extern_crates)]\nextern crate ${alias} as _;\n` +
    "\nfn main() {\n    if let Err(error) = collect() {\n        eprintln!(\"KRS collector failed: {error}\");\n        std::process::exit(1);\n    }\n}\n\n" +
    "fn collect() -> Result<(), Box<dyn std::error::Error>> {\n    let contexts = vec![\n" +
    `        __krs_compiler_runtime::PackageContext::new(${context}, std::path::Path::new(${rustString(`${p.manifest_dir}/Cargo.toml`)}))?,\n` +
    "    ];\n" +
    "    let tables: &[&__krs_host_runtime::__private::RegistrationTable] = &[\n" +
    `        &${alias}::__KRS_REGISTRATIONS,\n` +
    "    ];\n" +
    "    let builtins = __krs_host_runtime::builtin_registry();\n" +
    "    let bundle = __krs_compiler_runtime::collect_host_descriptors_with_builtins(\n        contexts,\n        __krs_host_runtime::host_descriptors_from(tables),\n        &builtins,\n    )?;\n" +
    "    use std::io::Write as _;\n" +
    "    std::io::stdout().lock().write_all(bundle.to_canonical_json()?.as_bytes())?;\n" +
    "    Ok(())\n}\n"
  );
}
