def build_cli(results: Results) -> Path | None:
    try:
        executable("cargo")
    except GateError as error:
        results.add("tool_cargo", "FAIL", str(error))
        return None
    try:
        binary = build()
    except (GateError, OSError) as error:
        results.add("cli_binary", "FAIL", str(error))
        return None
    results.add("cli_binary", "PASS", f"built real CLI executable {binary}")
    return binary


def materialize(destination: Path, fixture: Path = FIXTURE) -> Path:
    shutil.copytree(fixture, destination)
    template = destination / "Cargo.toml.in"
    manifest = template.read_text(encoding="utf-8").replace(
        "@KRS_CRATE_PATH@",
        json.dumps(str((ROOT / "crates" / "krs").resolve())),
    )
    (destination / "Cargo.toml").write_text(manifest, encoding="utf-8")
    template.unlink()
    return destination / "Cargo.toml"


def cli_command(
    binary: Path,
    command: str,
    manifest: Path,
    target: Path,
    *,
    package: str = PACKAGE,
    definition: str | None = "main",
    output: Path | None = None,
    extra: tuple[str, ...] = (),
) -> subprocess.CompletedProcess[bytes]:
    extras = ["--output", str(output)] if output is not None else []
    arguments = Invocation(binary, manifest, package, definition).argv(
        command, "--message-format=json", *extras, *extra
    )
    environment = {
        **z3_environment(),
        "CARGO_TARGET_DIR": str(target),
        "CARGO_NET_OFFLINE": "true",
        "CARGO_TERM_COLOR": "never",
    }
    return run(arguments, cwd=manifest.parent, environment=environment, check=False, text=False)


def assert_no_leaks(name: str, raw: bytes, forbidden_paths: list[Path]) -> None:
    text = raw.decode("utf-8")
    forbidden_tokens = ("TypeId", "KCell::new")
    for token in forbidden_tokens:
        if token in text:
            raise ValueError(f"{name} leaks forbidden host token {token!r}")
    if re.search(r"\bSelf\b", text):
        raise ValueError(f"{name} leaks the Rust-only `Self` spelling")
    if re.search(r"(?<![A-Za-z])KCell(?![A-Za-z])", text):
        raise ValueError(f"{name} leaks the Rust wrapper `KCell` spelling")
    if re.search(r"\b0x[0-9a-fA-F]{6,}\b", text):
        raise ValueError(f"{name} appears to contain a pointer address")
    for path in forbidden_paths:
        if str(path) in text:
            raise ValueError(f"{name} leaks absolute path {path}")


def verify_expanded_source(raw: bytes, forbidden_paths: list[Path]) -> None:
    source = raw.decode("utf-8")
    required = (
        "// @generated by `krs expand`; deterministic layer-2 reference surface.",
        "#[krs::sort(alias = ObjectTerm, parents = [krs::KResult])]\npub trait ObjectTermSort: krs::KResultSort {}",
        '#[krs::constructor(sort = ObjectTerm, syntax = "foo")]\npub struct Foo;',
        '#[krs::configuration(root = "machine")]\npub struct Machine {',
        "krs::configuration::KCell::new(krs::k![Foo])",
        "pub fn foo_to_bar(Foo: krs::Term<dyn ObjectTermSort>) -> krs::Term<dyn ObjectTermSort>",
    )
    missing = [fragment for fragment in required if fragment not in source]
    if missing:
        raise ValueError(f"expanded Rust source omits expected fragments: {missing}")
    for path in forbidden_paths:
        if str(path) in source:
            raise ValueError(f"expand.rs leaks absolute path {path}")


def verify_k_artifacts(directory: Path, forbidden_paths: list[Path], gate: Path) -> dict[str, bytes]:
    expected = json.loads((HERE / "definition-checks.json").read_bytes())
    with krs_gate.Session(gate, environment=z3_environment()) as session:
        files = session.ir_query(directory, {"kind": "files"})
        if files["actual"] != files["expected"] or not files["owned"] or files["has_claims"]:
            raise GateError(f"unexpected emit-k artifact set: {files}")
        absolute_strings = session.ir_query(directory, {"kind": "absolute_strings"})["rows"]
        if absolute_strings:
            raise GateError(f"emitted JSON artifacts contain absolute strings: {absolute_strings}")
        modules = session.ir_query(directory, {"kind": "modules"})
        if modules["main_module"] != expected["main_module"]:
            raise GateError(f"unexpected main module: {modules}")
        productions = session.ir_query(directory, {"kind": "productions", "sort": "ObjectTerm"})["rows"]
        facts = [{"symbol": row["symbol"], "terminals": row["terminals"]} for row in productions]
        if sorted(facts, key=lambda row: row["symbol"]) != expected["productions"]:
            raise GateError(f"unexpected ObjectTerm productions: {facts}")
        configurations = session.ir_query(directory, {"kind": "sentences", "sentence_kind": "configuration"})["rows"]
        if len(configurations) != 1 or configurations[0]["initializers"] != expected["initializer"]:
            raise GateError(f"unexpected foo initializer: {configurations}")
        rules = session.ir_query(directory, {"kind": "sentences", "sentence_kind": "rule"})["rows"]
        if not any(row["body"] == expected["rule_body"] for row in rules):
            raise GateError(f"canonical theory omits the foo-to-bar transition: {rules}")
        vocabulary = session.ir_query(directory, {"kind": "vocabulary"})
        for edge in expected["subsorts"]:
            if edge not in vocabulary["subsorts"]:
                raise GateError(f"missing subsort edge: {edge}")
    artifacts = {name: (directory / name).read_bytes() for name in files["expected"] if name != ".krs-artifacts"}
    for name, contents in artifacts.items():
        assert_no_leaks(name, contents, forbidden_paths)
    return artifacts


def positive_run(binary: Path, workspace: Path, results: Results, gate: Path) -> dict[str, bytes] | None:
    language = workspace / "language"
    manifest = materialize(language)
    target = workspace / "target"
    emitted = workspace / "emitted"
    native = workspace / "native"

    check = cli_command(binary, "check", manifest, target)
    expected_check = b"KRS check passed: 9 descriptors, 2 semantic modules\n"
    results.add(
        f"{workspace.name}_check",
        "PASS" if check.returncode == 0 and check.stdout == expected_check else "FAIL",
        "complete nine-descriptor theory validated" if check.returncode == 0 and check.stdout == expected_check else compact(check),
    )
    if check.returncode != 0:
        return None

    expand = cli_command(binary, "expand", manifest, target)
    try:
        if expand.returncode != 0:
            raise ValueError(compact(expand))
        verify_expanded_source(expand.stdout, [ROOT, workspace, language, target])
        results.add(f"{workspace.name}_expand", "PASS", f"canonical expanded Rust sha256={sha256_bytes(expand.stdout)}")
    except ValueError as error:
        results.add(f"{workspace.name}_expand", "FAIL", str(error))
        return None

    emit = cli_command(binary, "emit-k", manifest, target, output=emitted)
    expected_emit = b"emitted descriptor-bundle.json, semantic-ir.json, definition-ir.json, definition.k, symbols.json, sources.json\n"
    try:
        if emit.returncode != 0 or emit.stdout != expected_emit:
            raise ValueError(compact(emit))
        artifacts = verify_k_artifacts(emitted, [ROOT, workspace, language, target], gate)
        results.add(f"{workspace.name}_emit_k", "PASS", "exact owned canonical K artifact set")
    except (OSError, ValueError, GateError) as error:
        results.add(f"{workspace.name}_emit_k", "FAIL", str(error))
        return None

    build = cli_command(binary, "build", manifest, target, output=native)
    expected_build = b"built definition.kore, syntaxDefinition.kore, macros.kore\n"
    native_names = {
        ".krs-artifacts",
        "definition.kore",
        "macros.kore",
        "syntaxDefinition.kore",
    }
    observed_names = {path.name for path in native.iterdir()} if native.is_dir() else set()
    build_ok = (
        build.returncode == 0
        and build.stdout == expected_build
        and observed_names == native_names
        and all((native / name).stat().st_size > 0 for name in native_names)
    )
    results.add(
        f"{workspace.name}_build",
        "PASS" if build_ok else "FAIL",
        "structured k-rust compilation produced the exact native artifact set"
        if build_ok else compact(build),
    )
    if not build_ok:
        return None
    for name in sorted(native_names):
        artifacts[f"native/{name}"] = (native / name).read_bytes()
    artifacts["expand.rs"] = expand.stdout
    native_run = run_commands(binary, manifest, target, workspace, results)
    if native_run is None:
        return None
    artifacts.update(native_run)
    return artifacts


def run_commands(
    binary: Path, manifest: Path, target: Path, workspace: Path, results: Results
) -> dict[str, bytes] | None:
    """Run, trace, and parse the foo-bar theory natively; every output is pinned and relocation-stable.

    The init function takes no program, so `krs run` takes no FILE; `krs parse` parses at `ObjectTerm`.
    """

    program = workspace / "foo.prog"
    program.write_text("foo\n", encoding="utf-8")
    try:
        run_json = cli_command(binary, "run", manifest, target, extra=("--output", "json"))
        if run_json.returncode != 0:
            raise ValueError(compact(run_json))
        report = json.loads(run_json.stdout)
        if report.get("schema") != "krs-exec/1" or report["run"]["halt"] != "stuck" or report["run"]["steps"] != 1:
            raise ValueError(f"krs run report differs: {report}")
        if b"krs run: stuck after 1 step; <k> starts with `bar" not in run_json.stderr:
            raise ValueError(f"krs run status line differs: {run_json.stderr!r}")
        run_kore = cli_command(binary, "run", manifest, target, extra=("--output", "kore"))
        # The default output is grammar-directed (KF-017), as `krun --output pretty` prints the state;
        # the reference step requires it to equal krun's byte for byte.
        run_pretty = cli_command(binary, "run", manifest, target)
        if run_pretty.returncode != 0 or b"\n    bar ~> .K\n" not in run_pretty.stdout:
            raise ValueError(f"krs run pretty output differs: {compact(run_pretty)}")
        trace = cli_command(binary, "run", manifest, target, extra=("--trace", "--output", "none"))
        if run_kore.returncode != 0 or trace.returncode != 0 or trace.stdout:
            raise ValueError(compact(run_kore if run_kore.returncode != 0 else trace))
        # The fixture's `#[krs::rule] fn foo_to_bar` is unlabelled, so the step names its rule identity.
        if not re.match(rb"step 1  \S+   src/lib\.rs:\d+:\d+\nkrs run: stuck after 1 step", trace.stderr):
            raise ValueError(f"krs run --trace differs: {trace.stderr!r}")
        parse_kast = cli_command(
            binary, "parse", manifest, target, extra=("--sort", "ObjectTerm", "--output", "kast", str(program)),
        )
        parse_json = cli_command(
            binary, "parse", manifest, target, extra=("--sort", "ObjectTerm", "--output", "json", str(program)),
        )
        if parse_kast.returncode != 0 or parse_json.returncode != 0:
            raise ValueError(compact(parse_kast if parse_kast.returncode != 0 else parse_json))
        if json.loads(parse_json.stdout)["term"]["label"]["name"] != "foo":
            raise ValueError(f"krs parse --output json differs: {parse_json.stdout!r}")
        parse_program = cli_command(
            binary, "parse", manifest, target, extra=("--sort", "ObjectTerm", "--output", "program", str(program)),
        )
        if parse_program.returncode != 0 or parse_program.stdout != b"foo\n":
            raise ValueError(f"krs parse --output program differs: {compact(parse_program)}")
    except (KeyError, ValueError) as error:
        results.add(f"{workspace.name}_run", "FAIL", str(error))
        return None
    results.add(
        f"{workspace.name}_run", "PASS",
        "krs run (pretty, json, kore, trace) and krs parse (kast, json, program) reproduce foo -> bar natively",
    )
    return {
        "native-run/run.json": run_json.stdout,
        "native-run/final.kore": run_kore.stdout,
        "native-run/final.pretty": run_pretty.stdout,
        "native-run/parse.program": parse_program.stdout,
        "native-run/trace.txt": trace.stderr,
        "native-run/parse.kast": parse_kast.stdout,
        "native-run/parse.json": parse_json.stdout,
    }


def verify_pins(results: Results, pins: Ledger, artifacts: dict[str, bytes]) -> None:
    fixture_actual = {
        f"{prefix}{name}": sha256_bytes((fixture / name).read_bytes())
        for prefix, fixture in (("", FIXTURE), ("dollar-ids/", DOLLAR_IDS), ("claims/", CLAIMS))
        for name in ("Cargo.toml.in", "src/lib.rs")
    }
    results.add(
        "fixture_pins",
        "PASS" if fixture_actual == pins["fixture_sha256"] else "FAIL",
        f"sha256={fixture_actual}",
    )
    # A built definition's KORE is k-rust's output, which k-rust's own gates check;
    # the run and parse results below pin what it does.
    actual = {
        name: sha256_bytes(data)
        for name, data in sorted(artifacts.items())
        if not (name.startswith("native/") and name.endswith(".kore"))
    }
    failures = []
    if not pins.record and set(actual) != set(pins.table("artifacts_sha256")):
        failures.append(f"artifact set differs from pins.json: {sorted(actual)}")
    for name, digest in actual.items():
        try:
            pins.expect(("artifacts_sha256", name), digest)
        except GateError as error:
            failures.append(str(error))
    if failures:
        results.add("artifact_pins", "FAIL", "; ".join(failures))
    else:
        status = "RECORDED" if pins.record else "PASS"
        results.add("artifact_pins", status, f"sha256={actual}", required=False)


def verify_relocation(results: Results, left: dict[str, bytes], right: dict[str, bytes]) -> None:
    names = sorted(set(left) | set(right))
    differences = [name for name in names if left.get(name) != right.get(name)]
    results.add(
        "clean_relocation",
        "MATCH" if not differences else "FAIL",
        "two clean, differently located workspaces produced byte-identical bundle/K/sidecars"
        if not differences else f"different artifacts: {differences}",
    )


def negative_cases(binary: Path, workspace: Path, results: Results) -> None:
    manifest = materialize(workspace / "missing-language")
    target = workspace / "negative-target"

    missing_option = cli_command(binary, "check", manifest, target, definition=None)
    option_ok = missing_option.returncode == 2 and b"missing --definition" in missing_option.stderr
    results.add("missing_facet_option", "PASS" if option_ok else "FAIL", "CLI rejects implicit facet selection" if option_ok else compact(missing_option))

    missing_facet = cli_command(binary, "check", manifest, target, definition="absent")
    facet_ok = missing_facet.returncode != 0 and b"declares no KRS definition facet `absent`" in missing_facet.stderr
    results.add("missing_facet", "PASS" if facet_ok else "FAIL", "planner rejects nonexistent explicit facet" if facet_ok else compact(missing_facet))

    ambiguous = workspace / "ambiguous"
    shutil.copytree(AMBIGUOUS, ambiguous)
    ambiguous_process = cli_command(
        binary,
        "expand",
        ambiguous / "Cargo.toml",
        workspace / "ambiguous-target",
        package="duplicated-semantics",
    )
    ambiguity_ok = ambiguous_process.returncode != 0 and b"matches 2 resolved packages" in ambiguous_process.stderr
    results.add("ambiguous_package", "PASS" if ambiguity_ok else "FAIL", "name selector rejects two resolved package identities" if ambiguity_ok else compact(ambiguous_process))

    broken_manifest = materialize(workspace / "broken-language")
    broken_source = broken_manifest.parent / "src" / "lib.rs"
    with broken_source.open("a", encoding="utf-8") as output:
        output.write('\ncompile_error!("KRS CLI oracle induced Cargo failure");\n')
    for command in ("check", "build"):
        broken = cli_command(
            binary,
            command,
            broken_manifest,
            workspace / "broken-target",
            output=workspace / "broken-output" if command == "build" else None,
        )
        diagnostics = krs_diagnostics(broken.stderr)
        source_bytes = broken_source.read_bytes()
        error_start = source_bytes.index(b"compile_error!")
        broken_ok = broken.returncode != 0 and any(
            diagnostic.schema_version == 1
            and diagnostic.stage == "rust-expansion"
            and diagnostic.code == "krs::rust-expansion::uncoded-error"
            and diagnostic.severity == "error"
            and "KRS CLI oracle induced Cargo failure" in diagnostic.message
            and diagnostic.authored_range is not None
            and diagnostic.authored_range.cargo_name == PACKAGE
            and diagnostic.authored_range.package_relative_path == "src/lib.rs"
            and error_start <= diagnostic.authored_range.start_byte
            < diagnostic.authored_range.end_byte
            <= len(source_bytes)
            for diagnostic in diagnostics
        )
        results.add(
            f"collector_build_failure_{command}",
            "PASS" if broken_ok else "FAIL",
            f"krs {command} reports an authored Rust diagnostic from the collector build" if broken_ok else compact(broken),
        )

    human = run(
        Invocation(binary, broken_manifest, PACKAGE, "main").argv("check"),
        cwd=workspace,
        environment={
            **z3_environment(),
            "CARGO_TARGET_DIR": str(workspace / "broken-target"),
            "CARGO_NET_OFFLINE": "true",
            "CARGO_TERM_COLOR": "never",
        },
        check=False,
    )
    expected_path = broken_source.relative_to(workspace)
    human_ok = (
        human.returncode != 0
        and "error[krs::rust-expansion::uncoded-error]" in human.stderr
        and f"--> {expected_path}:" in human.stderr
    )
    results.add(
        "collector_build_failure_human_path",
        "PASS" if human_ok else "FAIL",
        "human diagnostic uses the source path relative to the CLI cwd" if human_ok else compact(human),
    )

    safe_manifest = materialize(workspace / "safe-language")
    unsafe_output = workspace / "unsafe-output"
    unsafe_output.mkdir()
    sentinel = b"do not overwrite\n"
    (unsafe_output / "definition.k").write_bytes(sentinel)
    (unsafe_output / "unrelated.txt").write_bytes(sentinel)
    unsafe = cli_command(binary, "emit-k", safe_manifest, workspace / "safe-target", output=unsafe_output)
    preserved = (
        unsafe.returncode != 0
        and b"refusing to replace non-KRS artifact directory" in unsafe.stderr
        and (unsafe_output / "definition.k").read_bytes() == sentinel
        and (unsafe_output / "unrelated.txt").read_bytes() == sentinel
        and {item.name for item in unsafe_output.iterdir()} == {"definition.k", "unrelated.txt"}
    )
    results.add("unsafe_output", "PASS" if preserved else "FAIL", "nonempty unowned output rejected without changing bytes" if preserved else compact(unsafe))

    run_manifest = materialize(workspace / "run-language")
    run_target = workspace / "run-target"
    unknown_variable = cli_command(binary, "run", run_manifest, run_target, extra=("-c", "ENV=.Map"))
    unknown_ok = (
        unknown_variable.returncode == 1
        and b"unknown configuration variable `ENV`" in unknown_variable.stderr
    )
    results.add(
        "run_unknown_variable", "PASS" if unknown_ok else "FAIL",
        "krs run rejects -c for an undeclared variable" if unknown_ok else compact(unknown_variable),
    )
    stray = cli_command(binary, "run", run_manifest, run_target, extra=("foo.prog",))
    stray_ok = stray.returncode == 2 and b"the init function takes no program (no $PGM); do not pass FILE" in stray.stderr
    results.add(
        "run_stray_file", "PASS" if stray_ok else "FAIL",
        "krs run rejects FILE when the init function takes no program" if stray_ok else compact(stray),
    )


def reference_execution(
    results: Results, artifacts: dict[str, bytes], workspace: Path, pins: Ledger, *, refresh: bool
) -> Snapshot | None:
    """Compile and execute the emitted K with Java K, replayed from the reference cache or live.

    The snapshot is keyed by the digest of the emitted `definition.k`; the
    caller finishes it only after every other check passed.
    """

    workspace.mkdir(parents=True)
    try:
        k = Snapshot(
            "cli/execution", Key(tools=REFERENCE_TOOLS), workspace=workspace, refresh=refresh,
            pin=Pin(pins, "execution"),
        )
    except GateError as error:
        results.add("reference_execution", "FAIL", str(error))
        return None
    source = workspace / "definition.k"
    source.write_bytes(artifacts["definition.k"])
    definition_ir = workspace / "definition-ir.json"
    definition_ir.write_bytes(artifacts["definition-ir.json"])
    try:
        gate = krs_gate.configured_or_build()
    except (GateError, OSError) as error:
        results.add("reference_execution", "FAIL", str(error))
        return None
    main_module = krs_gate.ir_query(gate, workspace, {"kind": "modules"}, environment=z3_environment())["main_module"]
    definition = workspace / "compiled-definition"
    try:
        compile_process, initial, final, pretty = reference_runs(k, source, main_module, definition)
    except GateError as error:
        results.add("reference_execution", "FAIL", str(error))
        return None
    if compile_process.returncode != 0:
        results.add("reference_execution", "FAIL", compact(compile_process))
        return None
    for process in (initial, final, pretty):
        if process.returncode != 0:
            results.add("reference_execution", "FAIL", compact(process))
            return None
    try:
        with krs_gate.Session(gate, environment=z3_environment()) as session:
            session.load(definition_ir, main_module)
            session.read(initial.stdout, "initial")
            session.expect("initial", "k", text="foo ~> .K")
            session.read(final.stdout, "final")
            session.expect("final", "k", text="bar ~> .K")
            # `krs run` follows the same single path natively; its final state agrees with krun's.
            session.read(artifacts["native-run/final.kore"].decode("utf-8"), "native")
            session.expect("native", "k", text="bar ~> .K")
            cells = ["k", "generatedCounter"]
            if session.observe("final", cells) != session.observe("native", cells):
                raise GateError("krs run and krun final states differ")
            # `krs run` prints the final state byte for byte as `krun --output pretty` does (KF-017).
            if artifacts["native-run/final.pretty"].decode("utf-8") != pretty.stdout:
                raise GateError(f"krs run and krun --output pretty differ: {pretty.stdout!r}")
    except (GateError, OSError, UnicodeError) as error:
        results.add("reference_execution", "FAIL", str(error))
        return None
    source_mode = "live" if k.live else "cached"
    results.add(
        "reference_execution", "PASS",
        f"{source_mode} K {k_version()} compiled canonical output and executed foo -> bar, as krs run does",
    )
    return k


def reference_runs(
    k: Snapshot, source: Path, main_module: str, definition: Path
) -> tuple[subprocess.CompletedProcess[str], ...]:
    """Compile the emitted K and run it to depth zero and to completion, as KORE and as `--output pretty`.

    Execution stops at a rejected compilation, whose result is then returned four times.
    """

    compile_process = k.run(
        "kompile/definition",
        "kompile",
        [
            str(source),
            "--main-module",
            main_module,
            "--syntax-module",
            f"{main_module}-SYNTAX",
            "--backend",
            "llvm",
            "--emit-json",
            "--output-definition",
            str(definition),
        ],
        timeout=240,
    )
    if compile_process.returncode != 0:
        return compile_process, compile_process, compile_process, compile_process
    initial = k.run(
        "krun/initial", "krun",
        ["--definition", str(definition), "--depth", "0", "--output", "kore"], timeout=60,
    )
    final = k.run("krun/final", "krun", ["--definition", str(definition), "--output", "kore"], timeout=60)
    pretty = k.run("krun/pretty", "krun", ["--definition", str(definition), "--output", "pretty"], timeout=60)
    return compile_process, initial, final, pretty


def dollar_id_claims(
    binary: Path, workspace: Path, results: Results, gate: Path, pins: Ledger, *, refresh: bool
) -> tuple[dict[str, bytes], Snapshot] | None:
    """Require K to read back emitted claims that name `$`-prefixed identifiers (C2-002).

    K's rule grammar has no lexical syntax for `Id` under `ID-SYNTAX`, so a bare
    `$x` stops `kprove` at its scanner; the emitted claims spell it
    `#token("$x","Id")`. The Haskell `kompile` of the emitted `definition.k` and
    `kprove --dry-run` of the emitted `spec.k`, with nothing upstream on the
    include path, form the reference snapshot `dollar-id-claims`, keyed by the
    digests of both files. The caller finishes the snapshot only after every
    other check passed.
    """

    manifest = materialize(workspace / "language", DOLLAR_IDS)
    emitted = workspace / "emitted"
    emit = cli_command(
        binary, "emit-k", manifest, workspace / "target", package=DOLLAR_IDS_PACKAGE, output=emitted,
    )
    if emit.returncode != 0 or not (emitted / "spec.k").is_file():
        results.add("dollar_id_claims", "FAIL", f"emit-k did not write spec.k: {compact(emit)}")
        return None
    artifacts = {f"dollar-ids/{name}": (emitted / name).read_bytes() for name in ("definition.k", "spec.k")}
    spec_text = artifacts["dollar-ids/spec.k"].decode("utf-8")
    if '#token("$x","Id")' not in spec_text or re.search(r"(?<!\")\$x\b", spec_text):
        results.add("dollar_id_claims", "FAIL", f"spec.k does not spell $x only as an Id #token:\n{spec_text}")
        return None
    main_module = krs_gate.ir_query(gate, emitted, {"kind": "modules"}, environment=z3_environment())["main_module"]
    spec_module = f"{main_module}-SPEC"
    try:
        k = Snapshot(
            "cli/dollar-id-claims", Key(tools=CLAIMS_REFERENCE_TOOLS), workspace=workspace, refresh=refresh,
            pin=Pin(pins, "dollar-id-claims"),
        )
        definition = workspace / "compiled-definition"
        krs_gate.require_route(gate, emitted, "java-haskell-reference", environment=z3_environment())
        compile_process = k.run(
            "kompile/definition", "kompile",
            [
                emitted / "definition.k", "--backend", "haskell", "--main-module", main_module,
                "--syntax-module", f"{main_module}-SYNTAX", "--output-definition", definition,
            ],
            timeout=240,
        )
        if compile_process.returncode != 0:
            raise GateError(f"kompile rejected the emitted definition: {compact(compile_process)}")
        spec_temp = workspace / "kprove-temp"
        spec_temp.mkdir()
        spec_kore = workspace / "dry-run" / "spec.kore"
        dry_run = k.run(
            "kprove/dry-run", "kprove",
            [
                emitted / "spec.k", "--definition", definition, "--spec-module", spec_module,
                "--dry-run", "--temp-dir", spec_temp,
            ],
            timeout=240,
            outputs=(Output(spec_kore, sorted_kore_claims, locate=lambda: dry_run_spec(spec_temp)),),
            streams={"stdout": reduce_kprove_temp},
        )
        if dry_run.returncode != 0 or not spec_kore.is_file():
            raise GateError(f"kprove --dry-run rejected the emitted claims: {compact(dry_run)}")
        claims = re.findall(r"(?m)^// claim ", spec_kore.read_text(encoding="utf-8"))
        if len(claims) != 1 or "assign-x" not in spec_kore.read_text(encoding="utf-8"):
            raise GateError(f"spec.kore does not hold exactly the assign-x claim: {len(claims)} claims")
    except (GateError, OSError) as error:
        results.add("dollar_id_claims", "FAIL", str(error))
        return None
    source_mode = "live" if k.live else "cached"
    results.add(
        "dollar_id_claims", "PASS",
        f"{source_mode} K {k_version()} kompile and kprove --dry-run read the emitted #token(\"$x\",\"Id\") claim",
    )
    return artifacts, k


def claims_proofs(
    binary: Path, workspace: Path, results: Results, pins: Ledger, *, refresh: bool
) -> tuple[dict[str, bytes], Snapshot] | None:
    """Prove the claims fixture natively with `krs prove` and require Java `kprove` to agree.

    `foo-reaches-bar` holds and `bar-reaches-foo` does not. Java K kompiles the emitted
    `definition.k` with the Haskell backend and proves each claim of the emitted `spec.k`;
    these runs form the reference snapshot `claims-prove`, keyed by the digests of both files.
    The fixture also carries the negatives that need a program: an unknown claim with its
    did-you-mean, and a program parse error with its location.
    """

    manifest = materialize(workspace / "language", CLAIMS)
    target = workspace / "target"
    emitted = workspace / "emitted"
    try:
        prove = cli_command(binary, "prove", manifest, target, package=CLAIMS_PACKAGE, extra=("--output", "json"))
        if prove.returncode != 1:
            raise GateError(f"krs prove did not report a disproved claim with status 1: {compact(prove)}")
        verdicts = {report["claim"]: report["verdict"] for report in json.loads(prove.stdout)["prove"]}
        if verdicts != CLAIM_VERDICTS:
            raise GateError(f"krs prove verdicts differ: {verdicts}")
        proven = cli_command(
            binary, "prove", manifest, target, package=CLAIMS_PACKAGE, extra=("--claim", "foo-reaches-bar"),
        )
        if proven.returncode != 0 or proven.stdout != b"ORG-KRS-CLI-CLAIMS-SPEC.foo-reaches-bar: proven\n":
            raise GateError(f"krs prove --claim foo-reaches-bar differs: {compact(proven)}")
        suggestion = cli_command(
            binary, "prove", manifest, target, package=CLAIMS_PACKAGE, extra=("--claim", "foo_reaches_bar"),
        )
        expected_suggestion = (
            b"no claim has label `foo_reaches_bar`; did you mean `ORG-KRS-CLI-CLAIMS-SPEC.foo-reaches-bar`?"
        )
        if suggestion.returncode != 1 or expected_suggestion not in suggestion.stderr:
            raise GateError(f"unknown-claim suggestion differs: {compact(suggestion)}")
        bad = workspace / "bad.prog"
        bad.write_text("fooo\n", encoding="utf-8")
        rejected = cli_command(binary, "run", manifest, target, package=CLAIMS_PACKAGE, extra=(str(bad),))
        expected_location = f"{bad}:1:4 does not parse at sort ObjectTerm".encode()
        if rejected.returncode != 1 or expected_location not in rejected.stderr:
            raise GateError(f"program parse error location differs: {compact(rejected)}")
        emit = cli_command(binary, "emit-k", manifest, target, package=CLAIMS_PACKAGE, output=emitted)
        if emit.returncode != 0 or not (emitted / "spec.k").is_file():
            raise GateError(f"emit-k did not write spec.k: {compact(emit)}")
        main_module = "ORG-KRS-CLI-CLAIMS"
        spec_module = f"{main_module}-SPEC"
        k = Snapshot(
            "cli/claims-prove", Key(tools=PROVE_REFERENCE_TOOLS), workspace=workspace, refresh=refresh,
            pin=Pin(pins, "claims-prove"),
        )
        definition = workspace / "compiled-definition"
        compile_process = k.run(
            "kompile/definition", "kompile",
            [
                emitted / "definition.k", "--backend", "haskell", "--main-module", main_module,
                "--syntax-module", main_module, "--output-definition", definition,
            ],
            timeout=240,
        )
        if compile_process.returncode != 0:
            raise GateError(f"kompile rejected the emitted definition: {compact(compile_process)}")
        java: dict[str, str] = {}
        for label in sorted(CLAIM_VERDICTS):
            local = label.rsplit(".", 1)[1]
            process = k.run(
                f"kprove/{local}", "kprove",
                [emitted / "spec.k", "--definition", definition, "--spec-module", spec_module, "--claims", label],
                timeout=240,
            )
            proved = process.returncode == 0 and process.stdout.strip() == "#Top"
            java[label] = "proven" if proved else "disproved"
            if not proved and process.returncode == 0:
                raise GateError(f"kprove {label} exited 0 without #Top: {compact(process)}")
        if java != CLAIM_VERDICTS:
            raise GateError(f"Java kprove verdicts differ from krs prove: java={java}, krs={verdicts}")
    except (GateError, OSError, KeyError, ValueError) as error:
        results.add("claims_prove", "FAIL", str(error))
        return None
    source_mode = "live" if k.live else "cached"
    results.add(
        "claims_prove", "PASS",
        f"krs prove and {source_mode} K {k_version()} kprove agree: foo-reaches-bar proven, bar-reaches-foo disproved",
    )
    artifacts = {f"claims/{name}": (emitted / name).read_bytes() for name in ("definition.k", "spec.k")}
    artifacts["claims/prove.json"] = prove.stdout
    return artifacts, k


def dry_run_spec(directory: Path) -> Path:
    """The one `spec.kore` that `kprove --dry-run` wrote below its `--temp-dir`, or a missing path."""

    found = sorted(directory.glob("*/spec.kore"))
    if len(found) > 1:
        raise GateError(f"kprove --dry-run wrote {len(found)} spec.kore files")
    return found[0] if found else directory / "spec.kore"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--record",
        action="store_true",
        help="run the oracle and rewrite the artifact pins it measured",
    )
    add_refresh_argument(parser)
    arguments = parser.parse_args()
    pins = Ledger(PINS, record=arguments.record)
    results = Results(width=11)
    binary = build_cli(results)
    if binary is None:
        return 1
    gate = krs_gate.configured_or_build()
    snapshots: list[Snapshot] = []
    with tempfile.TemporaryDirectory(prefix="krs-cli-oracle-a-") as first_raw, tempfile.TemporaryDirectory(prefix="krs-cli-oracle-relocated-b-") as second_raw:
        first_root = Path(first_raw)
        second_root = Path(second_raw) / "different" / "depth"
        second_root.mkdir(parents=True)
        first = positive_run(binary, first_root / "run-a", results, gate)
        second = positive_run(binary, second_root / "run-b", results, gate)
        if first is not None and second is not None:
            verify_relocation(results, first, second)
            claims = dollar_id_claims(
                binary, first_root / "dollar-ids", results, gate, pins, refresh=arguments.refresh_reference,
            )
            proofs = claims_proofs(
                binary, first_root / "claims", results, pins, refresh=arguments.refresh_reference,
            )
            if claims is not None and proofs is not None:
                claim_artifacts, claim_snapshot = claims
                proof_artifacts, proof_snapshot = proofs
                snapshots.extend((claim_snapshot, proof_snapshot))
                verify_pins(results, pins, {**first, **claim_artifacts, **proof_artifacts})
            snapshot = reference_execution(
                results, first, first_root / "reference", pins, refresh=arguments.refresh_reference,
            )
            if snapshot is not None:
                snapshots.append(snapshot)
        else:
            results.add("clean_relocation", "FAIL", "positive command run did not complete")
        negative_cases(binary, first_root / "negative", results)
    for snapshot in snapshots:
        if results.failed:
            break
        try:
            results.add("reference_snapshot", "PASS", snapshot.finish())
        except GateError as error:
            results.add("reference_snapshot", "FAIL", str(error))
    if not results.failed:
        pins.finish("CLI acceptance oracle")
    print("\nCLI acceptance oracle:", "FAIL" if results.failed else "PASS")
    return int(results.failed)


if __name__ == "__main__":
    entry("CLI acceptance oracle", main)
