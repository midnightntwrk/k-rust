//! The comments that make emitted K readable without its sidecars: the header of each
//! artifact and the `// KRS` line above each sentence written from a KRS item.
//!
//! A `// KRS <package>/<file>: <item>` line names the Rust item an agent greps for, never a
//! line, a column or a byte offset: an edit that only moves Rust lines leaves the emitted K
//! byte-identical, so a committed `definition.k` and every digest of it change only when an
//! item is added, removed, renamed or moved, or its K changes.
//! The lines are K comments outside every generated source-map range, so they change no
//! sentence and no range a sidecar records for one.

use std::{
    collections::{BTreeMap, BTreeSet},
    fmt,
};

use krs_ir::{ApplicationRef, OriginFrame, RangedOriginKind, SentenceKind, StableItemId};
use krs_ir_levels::{
    DefinitionIr, DefinitionSentence, DefinitionTerm, DefinitionTermKind, ModuleRole,
    ProductionSentence, RuleBodyRef, RuleSentence, SymbolId,
};

/// The header `emit_k` writes at the start of `definition.k` and `spec.k`, before one blank
/// line: what generated the file and from which packages (sorted, deduplicated Cargo names),
/// that it is not edited, and how its comments and default labels name the Rust sources.
///
/// It names no krs build, so it is constant for a package set.
#[must_use]
pub(crate) fn header(packages: &[&str]) -> String {
    let from = if packages.is_empty() {
        String::new()
    } else {
        format!(" from {}", packages.join(", "))
    };
    format!(
        "// Generated by `krs emit-k`{from}. Do not edit; edit the Rust sources and emit again.\n\
         // The `// KRS <package>/<file>: <item>` line above a sentence names the Rust item it comes from.\n\
         // A default label spells that item's path: `<namespace>--<module>--…--<item>`.\n\n"
    )
}

/// The Rust source of one emitted sentence, as the `// KRS` line above it names it.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct SentenceSource {
    package: String,
    file: String,
    item: String,
    branch: Option<String>,
    local_function: bool,
    claim_helper: bool,
}

impl SentenceSource {
    /// The Cargo package name of the sentence's authored file.
    #[must_use]
    pub fn package(&self) -> &str {
        &self.package
    }

    /// The authored file's package-relative path, slash-separated.
    #[must_use]
    pub fn file(&self) -> &str {
        &self.file
    }

    /// The Rust item the sentence comes from, spelled as the source writes it: a rule,
    /// equation, simplification, context or claim fn, a table row's label, the configuration
    /// struct, or the function of a shorthand equation or of a lifted local function.
    #[must_use]
    pub fn item(&self) -> &str {
        &self.item
    }

    /// The branch of a function-shorthand equation: its position (`3`, `2.1` for the first
    /// branch inside the second), or the name a `#[k::label]` arm gives it; `None` for any
    /// other sentence and for the one equation of a body that does not branch.
    #[must_use]
    pub fn branch(&self) -> Option<&str> {
        self.branch.as_deref()
    }

    /// Whether the sentence is an equation of a function KRS lifted out of `item` (a `let`
    /// block or a `k::matches!` there).
    #[must_use]
    pub const fn is_local_function(&self) -> bool {
        self.local_function
    }

    /// Whether the sentence is an equation of a function that, within the definition, only
    /// claims apply: no initializer term, no program syntax and no sentence a run can fire
    /// applies it. A run's input may still apply it, as a typed input may apply any function.
    #[must_use]
    pub const fn is_claim_helper(&self) -> bool {
        self.claim_helper
    }
}

/// `// KRS <package>/<file>: <item>[, branch <b>][, local function][ (claim helper: only
/// claims apply it)]`.
impl fmt::Display for SentenceSource {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            formatter,
            "// KRS {}/{}: {}",
            self.package, self.file, self.item
        )?;
        if let Some(branch) = &self.branch {
            write!(formatter, ", branch {branch}")?;
        }
        if self.local_function {
            formatter.write_str(", local function")?;
        }
        if self.claim_helper {
            formatter.write_str(" (claim helper: only claims apply it)")?;
        }
        Ok(())
    }
}

/// What naming the Rust source of one definition's sentences needs: its productions, to
/// recognize a function-shorthand equation by its head, and its claim helpers.
#[derive(Debug)]
pub struct SentenceSources<'a> {
    productions: BTreeMap<&'a SymbolId, &'a ProductionSentence>,
    claim_helpers: BTreeSet<SymbolId>,
}

impl<'a> SentenceSources<'a> {
    /// Indexes `definition` once for [`Self::source`].
    #[must_use]
    pub fn new(definition: &'a DefinitionIr) -> Self {
        let productions = definition
            .modules()
            .iter()
            .flat_map(krs_ir_levels::DefinitionModule::sentences)
            .filter_map(|sentence| match sentence {
                DefinitionSentence::Production(production) => {
                    Some((production.symbol().id(), production))
                }
                _ => None,
            })
            .collect();
        Self {
            productions,
            claim_helpers: claim_helpers(definition),
        }
    }

    /// The Rust source of `sentence` when it is a rule-like sentence (a rule, equation,
    /// simplification, alias, desugar, context or claim) or the configuration, and its
    /// origin names both its authored file and the item it was lowered from: the item of its
    /// Definition-IR frame, or, for the configuration, whose Definition-IR frame names none,
    /// of the latest earlier frame that does, the configuration struct. `None` otherwise,
    /// which leaves the line out rather than naming an item the sentence was not written at.
    #[must_use]
    pub fn source(&self, sentence: &DefinitionSentence) -> Option<SentenceSource> {
        if !matches!(
            sentence,
            DefinitionSentence::Rule(_) | DefinitionSentence::Configuration(_)
        ) {
            return None;
        }
        let (package, file) = authored_file(sentence)?;
        let id = match sentence {
            DefinitionSentence::Configuration(_) => {
                sentence.item().or_else(|| latest_item(sentence))?
            }
            _ => sentence.item()?,
        };
        let rule = match sentence {
            DefinitionSentence::Rule(rule) => Some(rule),
            _ => None,
        };
        let head = rule.and_then(equation_head);
        let claim_helper = head.is_some_and(|symbol| self.claim_helpers.contains(symbol));
        let mut source = SentenceSource {
            package,
            file,
            item: id.item_name().to_owned(),
            branch: None,
            local_function: false,
            claim_helper,
        };
        if id.is_generated_production() {
            local_function_host(sentence)?
                .item_name()
                .clone_into(&mut source.item);
            source.local_function = true;
            source.claim_helper |= krs_ir::lifted_from_claim(id);
        } else if let Some(rule) = rule
            && let Some(function) = self.shorthand_function(rule)
        {
            source.branch = branch(id.item_name(), &function);
            source.item = function;
        }
        Some(source)
    }

    /// The Rust name of the function a function-shorthand equation defines: the shorthand
    /// writes each equation's head at the function's own name, where its production is
    /// declared, so the head application's authored range is exactly the production's; a
    /// hand-written equation or a table row writes its head in its own pattern or header.
    fn shorthand_function(&self, rule: &RuleSentence) -> Option<String> {
        let RuleBodyRef::Term(rewrite) = rule.relational_body() else {
            return None;
        };
        let symbol = equation_head(rule)?;
        let production = self.productions.get(symbol)?;
        let head = rewrite.from().origin().origin().exact_authored_range()?;
        if production.origin().origin().exact_authored_range()? != head {
            return None;
        }
        production
            .symbol()
            .declaration()
            .and_then(|declaration| declaration.segments().last().cloned())
    }
}

/// The branch a shorthand equation named `item_name` is of the function `function`: none when
/// it is the function's one equation (`equation_name(function)`), its position when the name
/// spells one (`signed_less_2_1` is `2.1`), and otherwise the name itself, which a
/// `#[k::label]` arm gave it. The shorthand refuses a label that spells a position, so the
/// spelling tells which of the two the author wrote.
fn branch(item_name: &str, function: &str) -> Option<String> {
    match krs_syntax::branch_positions(function, item_name) {
        Some(positions) if positions.is_empty() => None,
        Some(positions) => Some(positions.join(".")),
        None => Some(item_name.to_owned()),
    }
}

/// The Cargo package and package-relative path of the sentence's authored file: the range of
/// its origin's first frame, which every origin stack begins with.
fn authored_file(sentence: &DefinitionSentence) -> Option<(String, String)> {
    match sentence.origin().origin().frames().first()? {
        OriginFrame::Ranged {
            kind: RangedOriginKind::Authored,
            range,
            ..
        } => Some((
            range.file.package().cargo_name().to_owned(),
            range.file.package_relative_path().to_owned(),
        )),
        _ => None,
    }
}

/// The item of the latest frame of `sentence`'s origin that names one.
fn latest_item(sentence: &DefinitionSentence) -> Option<&StableItemId> {
    sentence
        .origin()
        .origin()
        .frames()
        .iter()
        .rev()
        .find_map(|frame| match frame {
            OriginFrame::Ranged { item, .. } | OriginFrame::Transformation { item, .. } => {
                item.as_ref()
            }
            OriginFrame::Inserted { .. } => None,
        })
}

/// The item a lifted local function's equation was lifted out of: the item of the first macro
/// invocation of its origin, the host's.
fn local_function_host(sentence: &DefinitionSentence) -> Option<&StableItemId> {
    sentence
        .origin()
        .origin()
        .frames()
        .iter()
        .find_map(|frame| match frame {
            OriginFrame::Ranged {
                kind: RangedOriginKind::MacroInvocation,
                item: Some(item),
                ..
            } => Some(item),
            _ => None,
        })
}

/// The function an equation defines: the declared production at the root of its left-hand
/// side.
fn equation_head(rule: &RuleSentence) -> Option<&SymbolId> {
    if rule.kind() != SentenceKind::Equation {
        return None;
    }
    let RuleBodyRef::Term(rewrite) = rule.relational_body() else {
        return None;
    };
    match rewrite.from().kind() {
        DefinitionTermKind::Application {
            application: ApplicationRef::Declared(symbol),
            ..
        } => Some(symbol),
        _ => None,
    }
}

/// The functions only claims apply, `C \ R`:
///
/// - `R`, what a run can apply, holds every symbol applied anywhere in a production of the
///   program-syntax module (a program may write it), in the configuration's initializer, in a
///   context alias, and in every rule sentence that is neither a claim nor an equation, and is
///   closed under equations: when `F` is in `R`, every symbol applied anywhere in an equation
///   whose left-hand root is `F`, patterns and conditions included, is in `R`;
/// - `C` holds every symbol applied in a claim, closed the same way.
///
/// `R` over-approximates what the definition applies in a run, so a function outside it is
/// applied by no initializer term, no program syntax and no sentence any run can fire: within
/// the definition, only claims apply it. A run's input is outside that reach, since a typed
/// input may apply any function, which is why the mark says only what the claims do. A
/// definition with a `raw_k!` sentence has none, since its opaque text may apply anything.
#[must_use]
pub(crate) fn claim_helpers(definition: &DefinitionIr) -> BTreeSet<SymbolId> {
    let mut equations = BTreeMap::<&SymbolId, Vec<&RuleSentence>>::new();
    let mut reachable = BTreeSet::new();
    let mut claimed = BTreeSet::new();
    for module in definition.modules() {
        for sentence in module.sentences() {
            match sentence {
                DefinitionSentence::Raw(_) => return BTreeSet::new(),
                DefinitionSentence::Production(production)
                    if module.role() == ModuleRole::ProgramSyntax =>
                {
                    reachable.insert(production.symbol().id().clone());
                }
                DefinitionSentence::Configuration(configuration) => {
                    let mut pending = configuration.initializer().iter().collect::<Vec<_>>();
                    while let Some(cell) = pending.pop() {
                        match cell.content() {
                            krs_ir::FixedInitializerContent::Term { term } => {
                                applied(term, &mut reachable);
                            }
                            krs_ir::FixedInitializerContent::Children { children } => {
                                pending.extend(children);
                            }
                        }
                    }
                }
                DefinitionSentence::ContextAlias(alias) => {
                    for cell in alias.body().cells() {
                        applied(cell.pattern(), &mut reachable);
                    }
                }
                DefinitionSentence::Rule(rule) => {
                    if let Some(head) = equation_head(rule) {
                        equations.entry(head).or_default().push(rule);
                        continue;
                    }
                    let into = if rule.kind() == SentenceKind::Claim {
                        &mut claimed
                    } else {
                        &mut reachable
                    };
                    for term in crate::capability::sentence_terms(rule) {
                        applied(term, into);
                    }
                }
                _ => {}
            }
        }
    }
    let reachable = closed(reachable, &equations);
    closed(claimed, &equations)
        .difference(&reachable)
        .cloned()
        .collect()
}

/// `seeds` closed under `equations`: the symbols applied in every equation of a symbol in it.
fn closed(
    mut seeds: BTreeSet<SymbolId>,
    equations: &BTreeMap<&SymbolId, Vec<&RuleSentence>>,
) -> BTreeSet<SymbolId> {
    let mut pending = seeds.iter().cloned().collect::<Vec<_>>();
    while let Some(symbol) = pending.pop() {
        for equation in equations.get(&symbol).into_iter().flatten() {
            let mut found = BTreeSet::new();
            for term in crate::capability::sentence_terms(equation) {
                applied(term, &mut found);
            }
            for symbol in found {
                if seeds.insert(symbol.clone()) {
                    pending.push(symbol);
                }
            }
        }
    }
    seeds
}

/// Adds every declared symbol applied at or below `term` to `symbols`.
fn applied(term: &DefinitionTerm, symbols: &mut BTreeSet<SymbolId>) {
    let mut pending = vec![term];
    while let Some(term) = pending.pop() {
        if let DefinitionTermKind::Application {
            application: ApplicationRef::Declared(symbol),
            ..
        } = term.kind()
        {
            symbols.insert(symbol.clone());
        }
        pending.extend(term.children());
    }
}

#[cfg(test)]
mod tests {
    use super::{branch, header};

    #[test]
    fn the_header_names_the_packages_and_no_build() {
        let tail = "// The `// KRS <package>/<file>: <item>` line above a sentence names the Rust item it comes from.\n\
            // A default label spells that item's path: `<namespace>--<module>--…--<item>`.\n\n";
        assert_eq!(
            header(&["story-plus"]),
            format!(
                "// Generated by `krs emit-k` from story-plus. Do not edit; edit the Rust sources and emit again.\n{tail}"
            )
        );
        assert_eq!(
            header(&["a", "b-c"]),
            format!(
                "// Generated by `krs emit-k` from a, b-c. Do not edit; edit the Rust sources and emit again.\n{tail}"
            )
        );
        assert_eq!(
            header(&[]),
            format!(
                "// Generated by `krs emit-k`. Do not edit; edit the Rust sources and emit again.\n{tail}"
            )
        );
    }

    #[test]
    fn a_shorthand_equation_names_its_branch_by_position_or_label() {
        assert_eq!(branch("byte", "Byte"), None);
        assert_eq!(
            branch("interrupt_vector_3", "InterruptVector").as_deref(),
            Some("3")
        );
        assert_eq!(
            branch("signed_less_2_1", "SignedLess").as_deref(),
            Some("2.1")
        );
        assert_eq!(
            branch("vblank", "InterruptVector").as_deref(),
            Some("vblank")
        );
        assert_eq!(
            branch("vblank_1", "InterruptVector").as_deref(),
            Some("vblank_1")
        );
        assert_eq!(branch("hl_value_10", "HLValue").as_deref(), Some("10"));
        // A name that only starts like the function's is a label.
        assert_eq!(branch("byte_x", "Byte").as_deref(), Some("byte_x"));
        assert_eq!(branch("byte_", "Byte").as_deref(), Some("byte_"));
        assert_eq!(branch("byte_1_", "Byte").as_deref(), Some("byte_1_"));
        // A position has no leading zero, so these are labels too.
        assert_eq!(branch("byte_0", "Byte").as_deref(), Some("byte_0"));
        assert_eq!(branch("byte_01", "Byte").as_deref(), Some("byte_01"));
    }
}
