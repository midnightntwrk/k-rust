//! Whole-file expansion of tour-minimal and of small edge-case files.
//!
//! The tour-minimal checks compare the whole-file driver with the
//! independent test driver (`support`), which expands the same six
//! invocations by hand.

mod support;

use krs_expand::sink::{ByteRange, InvocationId, MappingClass};
use krs_expand::whole_file::{
    self, ExpandDiagnostic, FileExpansion, FileRequest, MacroUseKind, SelectedInvocation, Selection,
};
use krs_syntax::surface::{AttributeMacro, FunctionMacro};
use proc_macro2::TokenStream;
use sha2::{Digest, Sha256};
use support::{Expansion, TOUR_MINIMAL, expand_tour_minimal};

const GENERATED_FILE: &str = "/work/expanded/tour-minimal/src/lib.rs";

fn br(start: usize, end: usize) -> ByteRange {
    ByteRange::new(start, end).expect("fixture range is ordered")
}

fn module_path() -> Vec<String> {
    vec!["krs_tour_minimal".to_owned()]
}

fn expand_with(
    source: &str,
    selection: &Selection,
) -> Result<FileExpansion, Vec<ExpandDiagnostic>> {
    let module_path = module_path();
    whole_file::expand_file(&FileRequest {
        display_file: "src/lib.rs",
        source,
        generated_file: GENERATED_FILE,
        facade_alias: "k",
        facade_path: syn::parse_str("::k").unwrap(),
        module_path: &module_path,
        selection,
    })
}

fn expand(source: &str) -> Result<FileExpansion, Vec<ExpandDiagnostic>> {
    expand_with(source, &Selection::WholeFile)
}

fn sha256(bytes: &[u8]) -> String {
    use std::fmt::Write as _;
    Sha256::digest(bytes)
        .iter()
        .fold(String::new(), |mut text, byte| {
            let _ = write!(text, "{byte:02x}");
            text
        })
}

/// Every expansion of the support driver in pre-order.
fn support_outputs(expansions: &[Expansion], output: &mut Vec<(&'static str, String)>) {
    for expansion in expansions {
        output.push((expansion.kind, expansion.output.to_string()));
        for (_, _, nested) in &expansion.nested {
            support_outputs(std::slice::from_ref(nested), output);
        }
    }
}

fn table_start(expansion: &FileExpansion) -> usize {
    expansion
        .generated
        .text
        .find("\n// @generated by krs-expand")
        .expect("the registration table is appended")
}

#[test]
fn tour_minimal_matches_the_support_driver() {
    let expansion = expand(TOUR_MINIMAL).expect("tour-minimal expands");
    let (_, support) = expand_tour_minimal();
    let mut expected = Vec::new();
    support_outputs(&support, &mut expected);
    let actual = expansion
        .expansions
        .iter()
        .map(|expansion| (expansion.kind, expansion.output.to_string()))
        .collect::<Vec<_>>();
    assert_eq!(actual, expected);
    let invocations = &expansion.generated.map.invocations;
    let summary = invocations
        .iter()
        .map(|invocation| {
            (
                invocation.kind.as_str(),
                invocation.call_site,
                invocation.replaced,
                invocation.parent,
            )
        })
        .collect::<Vec<_>>();
    assert_eq!(
        summary,
        [
            ("sorts", br(287, 325), br(287, 325), None),
            ("constructors", br(327, 382), br(327, 501), None),
            ("configuration", br(503, 522), br(503, 582), None),
            ("init", br(603, 613), br(603, 709), None),
            ("k", br(672, 692), br(672, 692), Some(InvocationId(3))),
            ("rules", br(713, 869), br(713, 869), None),
        ]
    );
}

#[test]
fn tour_minimal_text_equals_the_reviewed_print_plus_the_table() {
    let expansion = expand(TOUR_MINIMAL).expect("tour-minimal expands");
    let text = &expansion.generated.text;
    let start = table_start(&expansion);
    expect_test::expect!["44640cb916e6bc9101918a89fd768cae73ef9bed4d6186d3c27791e3fda639b5"]
        .assert_eq(&sha256(&text.as_bytes()[..start]));
    let table = &text[start..];
    assert!(table.starts_with("\n// @generated by krs-expand"));
    assert!(table.contains("pub static __KRS_REGISTRATIONS: ::k::__private::RegistrationTable"));
    assert!(table.contains("requests_framework: true,"));
    let segments = &expansion.generated.map.segments;
    let last = segments.last().unwrap();
    assert_eq!(last.class, MappingClass::GeneratedOnly);
    assert_eq!(last.generated, br(start, text.len()));
    assert!(
        segments[..segments.len() - 1]
            .iter()
            .all(|segment| segment.class != MappingClass::GeneratedOnly)
    );
}

#[test]
fn tour_minimal_registers_seven_crate_root_factories() {
    let expansion = expand(TOUR_MINIMAL).expect("tour-minimal expands");
    assert!(expansion.requests_framework);
    let file = syn::parse_file(&expansion.generated.text).expect("the output parses");
    let functions = file
        .items
        .iter()
        .filter_map(|item| match item {
            syn::Item::Fn(function) => Some(function.sig.ident.to_string()),
            _ => None,
        })
        .collect::<Vec<_>>();
    let mut kinds = expansion
        .registrations
        .iter()
        .map(|registration| {
            assert_eq!(registration.module_path, module_path());
            assert!(registration.cfg.is_empty());
            let kind = expansion.generated.map.invocations[registration.invocation.0]
                .kind
                .clone();
            let factory = &registration.factory;
            assert!(functions.contains(factory), "{factory} is defined");
            assert!(
                expansion
                    .generated
                    .text
                    .contains(&format!("registrar.factory(crate::{factory});")),
                "{factory} is listed"
            );
            (kind, factory.split('_').nth(3).unwrap().to_owned())
        })
        .collect::<Vec<_>>();
    kinds.sort();
    assert_eq!(
        kinds,
        [
            ("configuration".to_owned(), "configuration".to_owned()),
            ("constructors".to_owned(), "enum".to_owned()),
            ("constructors".to_owned(), "enum".to_owned()),
            ("constructors".to_owned(), "enum".to_owned()),
            ("constructors".to_owned(), "enum".to_owned()),
            ("rules".to_owned(), "head".to_owned()),
            ("sorts".to_owned(), "sort".to_owned()),
        ]
    );
    // The native `krs emit-k` build (display file `src/lib.rs`) names the
    // rule's sort witness with this nonce.
    assert!(
        expansion
            .generated
            .text
            .contains("__krs_head_rule_sort_2cb94a8d9d940990")
    );
}

#[test]
fn text_outside_invocations_is_copied_unchanged() {
    let expansion = expand(TOUR_MINIMAL).expect("tour-minimal expands");
    let text = &expansion.generated.text;
    let mut covered = Vec::<ByteRange>::new();
    for segment in &expansion.generated.map.segments {
        if segment.owner.is_none() && segment.class == MappingClass::ExactAuthored {
            let authored = segment.authored.unwrap();
            assert_eq!(
                segment.generated.text(text).unwrap(),
                authored.text(TOUR_MINIMAL).unwrap()
            );
            covered.push(authored);
        }
    }
    covered.extend(
        expansion
            .generated
            .map
            .invocations
            .iter()
            .filter(|invocation| invocation.parent.is_none())
            .map(|invocation| invocation.replaced),
    );
    covered.sort_by_key(|range| range.start());
    let mut cursor = 0;
    for range in covered {
        assert_eq!(range.start(), cursor, "authored bytes are covered once");
        cursor = range.end();
    }
    assert_eq!(cursor, TOUR_MINIMAL.len());
}

#[test]
fn tour_minimal_output_invokes_no_krs_proc_macro() {
    let expansion = expand(TOUR_MINIMAL).expect("tour-minimal expands");
    let uses = whole_file::macro_uses(&expansion.generated.text).expect("the output parses");
    let entries = AttributeMacro::ALL
        .iter()
        .map(|entry| entry.name())
        .chain(FunctionMacro::ALL.iter().map(|entry| entry.name()))
        .collect::<Vec<_>>();
    for use_ in &uses {
        let last = use_.path.rsplit("::").next().unwrap();
        assert!(
            !entries.contains(&last),
            "KRS entry point still invoked: {use_:?}"
        );
        assert!(!use_.path.contains("rustversion"), "{use_:?}");
        assert!(
            !(use_.kind == MacroUseKind::Derive && (last == "Serialize" || last == "Deserialize")),
            "{use_:?}"
        );
    }
    assert!(
        uses.iter().any(|use_| use_.kind == MacroUseKind::Bang
            && use_.path == "::k::__register_host_descriptor")
    );
    let relexed: TokenStream = expansion.generated.text.parse().expect("the output lexes");
    assert!(!relexed.is_empty());
}

#[test]
fn invalid_sorts_block_reports_the_exact_token() {
    let source = "k::sorts! { ObjectTerm: ; }\n";
    let whole = expand(source).expect_err("the invalid block fails");
    let selected = expand_with(
        source,
        &Selection::Invocations(vec![SelectedInvocation {
            kind: "sorts".to_owned(),
            replaced: br(0, 27),
        }]),
    )
    .expect_err("the selected invalid block fails");
    for diagnostics in [whole, selected] {
        assert_eq!(
            diagnostics,
            [ExpandDiagnostic {
                code: krs_diagnostic::codes::syntax::RUST_SYNTAX,
                message: "expected identifier".to_owned(),
                class: MappingClass::ExactAuthored,
                authored: Some(br(24, 25)),
                invocation: Some(InvocationId(0)),
            }]
        );
    }
}

#[test]
fn selection_expands_only_the_listed_invocation() {
    let expansion = expand_with(
        TOUR_MINIMAL,
        &Selection::Invocations(vec![SelectedInvocation {
            kind: "sorts".to_owned(),
            replaced: br(287, 325),
        }]),
    )
    .expect("the selected block expands");
    assert_eq!(expansion.expansions.len(), 1);
    let text = &expansion.generated.text;
    assert!(!text.contains("k::sorts!"));
    assert!(text.contains("#[k::constructors(sort = ObjectTerm, result = KResult)]"));
    let missing = expand_with(
        TOUR_MINIMAL,
        &Selection::Invocations(vec![SelectedInvocation {
            kind: "rules".to_owned(),
            replaced: br(287, 325),
        }]),
    )
    .expect_err("a mismatched selection fails");
    assert_eq!(missing[0].code, whole_file::SELECTION);
}

#[test]
fn invocations_inside_standard_macros_are_expanded() {
    let source = "fn f() -> usize {\n    vec![k::anonymous!()].len()\n}\n";
    let expansion = expand(source).expect("the nested island expands");
    let [invocation] = expansion.generated.map.invocations.as_slice() else {
        panic!("one invocation");
    };
    assert_eq!(invocation.kind, "anonymous");
    assert_eq!(invocation.call_site, br(27, 42));
    assert!(!expansion.generated.text.contains("k::anonymous!"));
    assert!(expansion.generated.text.starts_with(
        "fn f() -> usize {\n    vec![:: core :: panic ! (\"anonymous! has no runtime value\")].len()\n}\n"
    ));
}

#[test]
fn attribute_order_and_form_are_checked() {
    let derive_first = "#[derive(Clone)]\n#[k::configuration]\npub struct M {}\n";
    let diagnostics = expand(derive_first).unwrap_err();
    assert_eq!(diagnostics[0].code, whole_file::ATTRIBUTE_ORDER);
    assert_eq!(diagnostics[0].authored, Some(br(17, 36)));

    let helper_first = "#[k::precedence((A))]\n#[k::constructors(sort = S, result = KResult)]\npub enum E { A() }\n";
    let diagnostics = expand(helper_first).unwrap_err();
    assert_eq!(diagnostics[0].code, whole_file::NOT_AN_ATTRIBUTE_MACRO);
    assert_eq!(diagnostics[0].authored, Some(br(2, 15)));

    let key_value = "#[k::configuration = 1]\npub struct M {}\n";
    let diagnostics = expand(key_value).unwrap_err();
    assert_eq!(diagnostics[0].code, whole_file::ATTRIBUTE_FORM);

    let doc_first =
        "/// Docs.\n#[k::configuration]\npub struct M {\n    #[k::cell]\n    pub k: u8,\n}\n";
    let expansion = expand(doc_first).expect("inert attributes may precede");
    assert_eq!(expansion.generated.map.invocations[0].replaced, br(0, 76));
    assert_eq!(expansion.generated.map.invocations[0].call_site, br(10, 29));
}

