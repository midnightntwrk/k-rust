#[test]
fn attribute_expressions_on_item_macros_expand_with_their_macro() {
    for (source, kind, call_site) in [
        (
            "#[doc = k::anonymous!()]\nk::sorts! { A; }\n",
            "sorts",
            br(25, 41),
        ),
        (
            "impl S {\n    #[doc = k::anonymous!()]\n    k::anonymous!();\n}\n",
            "anonymous",
            br(42, 57),
        ),
    ] {
        let expansion = expand(source).expect("the item macro and its attribute expand");
        let [invocation] = expansion.generated.map.invocations.as_slice() else {
            panic!("only the item macro is outermost in {source:?}");
        };
        assert_eq!(invocation.kind, kind);
        assert_eq!(invocation.call_site, call_site);
        assert!(!expansion.generated.text.contains("k::anonymous!"));
    }
}

#[test]
fn facade_attributes_on_item_macros_expand_before_the_macro() {
    let sort = expand("#[k::sort]\nk::sorts! { A; }\n").unwrap_err();
    assert_eq!(sort[0].message, "expected `trait`");
    assert_eq!(sort[0].authored, Some(br(11, 12)));

    let unknown = expand("#[k::unknown]\nk::sorts! { A; }\n").unwrap_err();
    assert_eq!(unknown[0].code, whole_file::NOT_AN_ATTRIBUTE_MACRO);
    assert_eq!(unknown[0].authored, Some(br(2, 12)));

    let derive_first = expand("#[derive(Clone)]\n#[k::sort]\nk::sorts! { A; }\n").unwrap_err();
    assert_eq!(derive_first[0].code, whole_file::ATTRIBUTE_ORDER);
    assert_eq!(derive_first[0].authored, Some(br(17, 27)));
}

